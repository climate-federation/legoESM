"""Voronoi (MPAS-style) mesh for legoESM.

Implements icosahedral SCVT mesh generation and all required
connectivity/geometry arrays for the TRiSK discretization.

The mesh is a centroidal Voronoi tessellation on the sphere,
generated by recursive bisection of an icosahedron followed by
Lloyd relaxation.

References
----------
- Ringler, T. D., Thuburn, J., Klemp, J. B., & Skamarock, W. C. (2010).
  A unified approach to energy conservation and potential vorticity dynamics
  for arbitrarily-structured C-grids. J. Comput. Phys., 229(9), 3065-3090.
- Thuburn, J., Ringler, T. D., Skamarock, W. C., & Klemp, J. B. (2009).
  Numerical representation of geostrophic modes on arbitrarily structured
  C-grids. J. Comput. Phys., 228(22), 8321-8335.
- Du, Q., Faber, V., & Gunzburger, M. (1999). Centroidal Voronoi
  tessellations. SIAM Review, 41(4), 637-676.
"""

from __future__ import annotations

from typing import NamedTuple

import numpy as np
import jax.numpy as jnp
from scipy.spatial import ConvexHull, SphericalVoronoi

from legoesm import constants


class VoronoiMesh(NamedTuple):
    """MPAS-style Voronoi mesh for TRiSK discretization.

    All arrays use 0-based indexing. Unused entries in variable-length
    connectivity arrays are padded with -1 (integers) or 0.0 (floats).
    """
    # --- Dimensions ---
    nCells: int
    nEdges: int
    nVertices: int
    maxEdges: int       # max edges per cell (6 for hex, 5 for pent)
    vertexDegree: int   # edges per vertex (always 3 for Delaunay dual)
    radius: float

    # --- Cell coordinates (Voronoi generators) ---
    latCell: jnp.ndarray    # (nCells,)
    lonCell: jnp.ndarray    # (nCells,)
    xCell: jnp.ndarray      # (nCells,) Cartesian
    yCell: jnp.ndarray
    zCell: jnp.ndarray

    # --- Edge coordinates (midpoints of Voronoi boundaries) ---
    latEdge: jnp.ndarray    # (nEdges,)
    lonEdge: jnp.ndarray    # (nEdges,)
    xEdge: jnp.ndarray
    yEdge: jnp.ndarray
    zEdge: jnp.ndarray

    # --- Vertex coordinates (Delaunay circumcenters) ---
    latVertex: jnp.ndarray  # (nVertices,)
    lonVertex: jnp.ndarray  # (nVertices,)
    xVertex: jnp.ndarray
    yVertex: jnp.ndarray
    zVertex: jnp.ndarray

    # --- Connectivity (0-indexed, padded with -1) ---
    cellsOnEdge: jnp.ndarray       # (2, nEdges)
    edgesOnCell: jnp.ndarray       # (maxEdges, nCells)
    verticesOnCell: jnp.ndarray    # (maxEdges, nCells)
    verticesOnEdge: jnp.ndarray    # (2, nEdges)
    edgesOnVertex: jnp.ndarray     # (vertexDegree, nVertices)
    cellsOnVertex: jnp.ndarray     # (vertexDegree, nVertices)
    cellsOnCell: jnp.ndarray       # (maxEdges, nCells)
    edgesOnEdge: jnp.ndarray       # (maxEdges2, nEdges)
    nEdgesOnCell: jnp.ndarray      # (nCells,)
    nEdgesOnEdge: jnp.ndarray      # (nEdges,)

    # --- Geometry ---
    areaCell: jnp.ndarray           # (nCells,)
    areaTriangle: jnp.ndarray       # (nVertices,)
    dcEdge: jnp.ndarray             # (nEdges,) dist between cell centers
    dvEdge: jnp.ndarray             # (nEdges,) dist between vertices
    angleEdge: jnp.ndarray          # (nEdges,) angle of normal from east

    # --- Weights and signs ---
    weightsOnEdge: jnp.ndarray      # (maxEdges2, nEdges)
    kiteAreasOnVertex: jnp.ndarray  # (vertexDegree, nVertices)
    fEdge: jnp.ndarray              # (nEdges,) Coriolis at edges
    fVertex: jnp.ndarray            # (nVertices,) Coriolis at vertices
    edgeSignOnCell: jnp.ndarray     # (maxEdges, nCells) ±1
    edgeSignOnVertex: jnp.ndarray   # (vertexDegree, nVertices) ±1
    meshDensity: jnp.ndarray        # (nCells,)

    # ------------------------------------------------------------------
    # GridProtocol properties
    # ------------------------------------------------------------------

    @property
    def grid_lat(self) -> jnp.ndarray:
        return self.latCell

    @property
    def grid_lon(self) -> jnp.ndarray:
        return self.lonCell

    @property
    def grid_area(self) -> jnp.ndarray:
        return self.areaCell

    @property
    def grid_total_area(self):
        return jnp.sum(self.areaCell)

    @property
    def grid_coriolis(self) -> jnp.ndarray:
        return 2.0 * 7.292e-5 * jnp.sin(self.latCell)

    @property
    def grid_radius(self) -> float:
        return self.radius

    @property
    def grid_n_columns(self) -> int:
        return self.nCells

    @property
    def grid_shape_2d(self) -> tuple[int, ...]:
        return (self.nCells,)

    def to_columns(self, field):
        return field

    def from_columns(self, cols):
        return cols


