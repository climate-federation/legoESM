# Icosahedral mesh generation
# ============================================================================

def _icosahedral_base():
    """12 vertices, 20 triangles of a regular icosahedron on the unit sphere."""
    phi = (1.0 + np.sqrt(5.0)) / 2.0
    verts = np.array([
        [-1, phi, 0], [1, phi, 0], [-1, -phi, 0], [1, -phi, 0],
        [0, -1, phi], [0, 1, phi], [0, -1, -phi], [0, 1, -phi],
        [phi, 0, -1], [phi, 0, 1], [-phi, 0, -1], [-phi, 0, 1],
    ], dtype=np.float64)
    verts /= np.linalg.norm(verts, axis=1, keepdims=True)
    hull = ConvexHull(verts)
    triangles = hull.simplices.copy()
    # Orient all triangles outward (normal pointing away from origin)
    for i, tri in enumerate(triangles):
        a, b, c = verts[tri[0]], verts[tri[1]], verts[tri[2]]
        normal = np.cross(b - a, c - a)
        if np.dot(normal, a) < 0:
            triangles[i] = [tri[0], tri[2], tri[1]]
    return verts, triangles


def _bisect_mesh(vertices, triangles, level):
    """Recursive edge-midpoint bisection of a triangular mesh on the sphere."""
    verts_list = list(vertices)
    for _ in range(level):
        edge_midpoints = {}
        new_triangles = []

        def get_midpoint(i, j):
            key = (min(i, j), max(i, j))
            if key in edge_midpoints:
                return edge_midpoints[key]
            mid = (verts_list[i] + verts_list[j]) * 0.5
            mid /= np.linalg.norm(mid)
            idx = len(verts_list)
            verts_list.append(mid)
            edge_midpoints[key] = idx
            return idx

        for tri in triangles:
            a, b, c = int(tri[0]), int(tri[1]), int(tri[2])
            ab = get_midpoint(a, b)
            bc = get_midpoint(b, c)
            ca = get_midpoint(c, a)
            new_triangles.extend([
                [a, ab, ca],
                [b, bc, ab],
                [c, ca, bc],
                [ab, bc, ca],
            ])
        triangles = np.array(new_triangles, dtype=np.int64)
    return np.array(verts_list, dtype=np.float64), triangles


def _lloyd_relaxation(points, n_iter=50):
    """Lloyd relaxation to produce a centroidal Voronoi tessellation (SCVT)."""
    pts = points.copy()
    for _ in range(n_iter):
        try:
            sv = SphericalVoronoi(pts, radius=1.0, center=np.zeros(3))
            sv.sort_vertices_of_regions()
        except Exception:
            break
        new_pts = np.empty_like(pts)
        for i, region in enumerate(sv.regions):
            if len(region) == 0:
                new_pts[i] = pts[i]
                continue
            poly_verts = sv.vertices[region]
            # Spherical centroid: area-weighted mean projected to sphere
            centroid = _spherical_polygon_centroid(poly_verts)
            new_pts[i] = centroid
        pts = new_pts
    return pts


def _spherical_polygon_centroid(vertices):
    """Centroid of a spherical polygon on the unit sphere."""
    n = len(vertices)
    if n < 3:
        c = vertices.mean(axis=0)
        return c / np.linalg.norm(c)
    # Decompose into triangles from v0 and compute area-weighted centroid
    v0 = vertices[0]
    total_area = 0.0
    centroid = np.zeros(3)
    for i in range(1, n - 1):
        v1, v2 = vertices[i], vertices[i + 1]
        # True spherical triangle area via spherical excess
        area = _spherical_triangle_area(v0, v1, v2, radius=1.0)
        tri_center = (v0 + v1 + v2) / 3.0
        centroid += area * tri_center
        total_area += area
    if total_area > 0:
        centroid /= total_area
    else:
        centroid = vertices.mean(axis=0)
    norm = np.linalg.norm(centroid)
    if norm > 1e-15:
        centroid /= norm
    return centroid


