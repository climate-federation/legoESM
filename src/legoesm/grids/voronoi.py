def create_voronoi_mesh(
    subdivision_level: int,
    radius: float = constants.R_earth,
    lloyd_iterations: int = 50,
    omega: float = constants.Omega,
) -> VoronoiMesh:
    """Create a centroidal Voronoi tessellation (SCVT) on the sphere.

    Starts from an icosahedral triangulation, bisects to the desired
    level, applies Lloyd relaxation, then builds the full MPAS-compatible
    mesh with all connectivity and geometric arrays.

    Parameters
    ----------
    subdivision_level : int
        Number of bisection levels. nCells = 10*4^level + 2.
        level=3: 642 cells, level=4: 2562, level=5: 10242.
    radius : float
        Sphere radius [m]. Default: Earth radius.
    lloyd_iterations : int
        Number of Lloyd relaxation iterations. Default: 50.
    omega : float
        Rotation rate [rad/s]. Default: Earth rotation.

    Returns
    -------
    VoronoiMesh
    """
    if subdivision_level > 8:
        n_cells = 10 * 4 ** subdivision_level + 2
        raise ValueError(
            f"subdivision_level={subdivision_level} would create {n_cells:.2e} cells. "
            f"Maximum supported level is 8 (655,362 cells). "
            f"For higher resolutions, use load_mpas_mesh() with a pre-built mesh file."
        )

    # Step 1: Icosahedral base
    verts, triangles = _icosahedral_base()

    # Step 2: Bisect to desired resolution
    if subdivision_level > 0:
        verts, triangles = _bisect_mesh(verts, triangles, subdivision_level)

    # Step 3: Lloyd relaxation for SCVT
    if lloyd_iterations > 0 and subdivision_level > 0:
        cell_points = _lloyd_relaxation(verts, n_iter=lloyd_iterations)
    else:
        cell_points = verts

    # Step 4: Build complete mesh
    mesh = _build_mesh_from_generators(cell_points, radius, omega)
    return mesh


def load_mpas_mesh(path: str) -> VoronoiMesh:
    """Load an MPAS mesh from a NetCDF file.

    Parameters
    ----------
    path : str
        Path to MPAS mesh NetCDF file.

    Returns
    -------
    VoronoiMesh
    """
    import netCDF4 as nc

    ds = nc.Dataset(path, 'r')

    def read_var(name):
        return np.array(ds.variables[name][:])

    nCells = len(ds.dimensions['nCells'])
    nEdges = len(ds.dimensions['nEdges'])
    nVertices = len(ds.dimensions['nVertices'])
    maxEdges = len(ds.dimensions['maxEdges'])
    vertexDegree = len(ds.dimensions['vertexDegree'])

    # Read and convert from 1-indexed to 0-indexed
    def read_int_var(name):
        return np.array(ds.variables[name][:], dtype=np.int32) - 1

    radius = float(ds.sphere_radius) if hasattr(ds, 'sphere_radius') else 6371229.0

    import jax
    try:
        from legoesm.core.precision import get_policy
        _fdtype = get_policy().storage
    except Exception:
        _fdtype = jnp.float64 if jax.config.jax_enable_x64 else jnp.float32

    mesh_data = {
        'nCells': nCells, 'nEdges': nEdges, 'nVertices': nVertices,
        'maxEdges': maxEdges, 'vertexDegree': vertexDegree, 'radius': radius,
    }

    # Coordinates
    for name in ['latCell', 'lonCell', 'latEdge', 'lonEdge',
                 'latVertex', 'lonVertex']:
        mesh_data[name] = jnp.array(read_var(name), dtype=_fdtype)

    for prefix in ['Cell', 'Edge', 'Vertex']:
        for coord in ['x', 'y', 'z']:
            name = f'{coord}{prefix}'
            mesh_data[name] = jnp.array(read_var(name), dtype=_fdtype)

    # Connectivity (transpose to match our (maxEdges, nCells) convention)
    conn_names = {
        'cellsOnEdge': (2, nEdges),
        'verticesOnEdge': (2, nEdges),
        'edgesOnCell': (maxEdges, nCells),
        'verticesOnCell': (maxEdges, nCells),
        'cellsOnVertex': (vertexDegree, nVertices),
        'edgesOnVertex': (vertexDegree, nVertices),
        'cellsOnCell': (maxEdges, nCells),
    }
    for name, shape in conn_names.items():
        data = read_int_var(name)
        if data.ndim == 2:
            data = data.T if data.shape[0] != shape[0] else data
        mesh_data[name] = jnp.array(data, dtype=jnp.int32)

    # Geometry
    for name in ['areaCell', 'areaTriangle', 'dcEdge', 'dvEdge', 'angleEdge',
                 'fEdge', 'fVertex', 'meshDensity']:
        if name in ds.variables:
            mesh_data[name] = jnp.array(read_var(name), dtype=_fdtype)

    # Weights
    maxEdges2 = 2 * maxEdges - 2
    if 'weightsOnEdge' in ds.variables:
        woe = read_var('weightsOnEdge')
        eoe = read_int_var('edgesOnEdge')
        if woe.ndim == 2:
            woe = woe.T if woe.shape[0] != maxEdges2 else woe
            eoe = eoe.T if eoe.shape[0] != maxEdges2 else eoe
        mesh_data['weightsOnEdge'] = jnp.array(woe, dtype=_fdtype)
        mesh_data['edgesOnEdge'] = jnp.array(eoe, dtype=jnp.int32)
    else:
        mesh_data['weightsOnEdge'] = jnp.zeros((maxEdges2, nEdges))
        mesh_data['edgesOnEdge'] = jnp.full((maxEdges2, nEdges), -1,
                                             dtype=jnp.int32)

    if 'kiteAreasOnVertex' in ds.variables:
        ka = read_var('kiteAreasOnVertex')
        if ka.ndim == 2:
            ka = ka.T if ka.shape[0] != vertexDegree else ka
        mesh_data['kiteAreasOnVertex'] = jnp.array(ka, dtype=_fdtype)
    else:
        mesh_data['kiteAreasOnVertex'] = jnp.zeros((vertexDegree, nVertices))

    if 'edgeSignOnCell' not in mesh_data:
        mesh_data['edgeSignOnCell'] = jnp.zeros((maxEdges, nCells))
    if 'edgeSignOnVertex' not in mesh_data:
        mesh_data['edgeSignOnVertex'] = jnp.zeros((vertexDegree, nVertices))

    mesh_data['nEdgesOnCell'] = jnp.array(
        read_var('nEdgesOnCell'), dtype=jnp.int32)
    if 'nEdgesOnEdge' in ds.variables:
        mesh_data['nEdgesOnEdge'] = jnp.array(
            read_var('nEdgesOnEdge'), dtype=jnp.int32)
    else:
        mesh_data['nEdgesOnEdge'] = jnp.zeros(nEdges, dtype=jnp.int32)

    ds.close()
    return VoronoiMesh(**mesh_data)
