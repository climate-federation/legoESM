"""Loader for the vendored official CMIP6 CMOR tables.

Why
---
The CMOR variable metadata that ``cmor_output.py`` stamps onto every
NetCDF variable used to live in ~9 hand-typed Python dicts.  Hand-typed
metadata drifts away from the official tables, and it did: an audit
against PCMDI/cmip6-cmor-tables found

* ``positive`` missing on all 15 flux variables,
* ``cell_methods`` wrong on 29 of 35 ``Amon`` variables
  (``"time: mean"`` where CMIP6 requires ``"area: time: mean"``),
* ``units`` wrong on ``cli``/``clw`` (``"1"`` instead of ``"kg kg-1"``),
* ``cell_measures`` missing everywhere,
* no ``type`` (CMIP6 wants ``real``, i.e. float32, not double).

Every one of those is mechanical if the metadata is READ from the table
rather than retyped.  This module is that reader.

The tables are vendored (trimmed, ~80 kB) under ``cmor_tables/`` and are
regenerated by ``scripts/data/build_cmor_table_subset.py``.  Nothing here
touches the network.

Public surface
--------------
``load_table(table_id)``       -> ``{var: entry}`` for one table
``CMOR_TABLES``                -> ``{table_id: {var: entry}}`` (all tables)
``load_cv()``                  -> vendored CMIP6 controlled-vocabulary subset
``table_header(table_id)``     -> the table's ``Header`` block
``coordinate_axis(name)``      -> one ``axis_entry`` (plev19, height2m, ...)

Each entry is the official table entry plus a normalized ``dimensions``
tuple in legoESM's internal axis names, e.g.
``"longitude latitude plev19 time"`` -> ``("time", "plev", "lat", "lon")``.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

_TABLE_DIR = Path(__file__).resolve().parent / "cmor_tables"

# Official CMIP6 table IDs legoESM writes into.
CMIP6_TABLE_IDS: Tuple[str, ...] = (
    "Amon", "day", "CFday", "fx", "Lmon", "Omon", "Ofx", "SImon",
)

# Legacy table aliases kept so pre-existing callers/tests keep working.
# NONE of these is a valid CMIP6 table id for the variables it exposes:
#   ``Aday``  -- CMIP5 spelling; the CMIP6 CV value is ``day``.
#   ``Oyr``   -- a REAL CMIP6 table, but it holds ocean-biogeochemistry
#                annual fields, NOT thetao/so/uo/...; using it for those
#                is a legacy legoESM invention.
#   ``SIyr``  -- does not exist in CMIP6 at all (checked against all 48
#                official tables).
# Output written under these ids is NOT publishable; the compliance test
# refuses to certify them.
LEGACY_TABLE_ALIASES: Dict[str, str] = {
    "Aday": "day",
    "Oyr": "Omon",
    "SIyr": "SImon",
}

# Variables legoESM emits that exist in NO CMIP6 table (verified against
# all 48 official tables at the pinned ref).  They are kept so existing
