def _angle_from_east(x, y, z, dx, dy, dz):
    """Angle of direction vector (dx,dy,dz) relative to local east at (x,y,z).

    Returns angle in radians, measured counterclockwise from east.
    """
    # Local east: (-sin(lon), cos(lon), 0)
    r_horiz = np.sqrt(x**2 + y**2)
    if r_horiz < 1e-15:
        return 0.0
    east = np.array([-y / r_horiz, x / r_horiz, 0.0])
    # Local north: (-sin(lat)*cos(lon), -sin(lat)*sin(lon), cos(lat))
    lat = np.arcsin(np.clip(z, -1.0, 1.0))
    lon = np.arctan2(y, x)
    north = np.array([
        -np.sin(lat) * np.cos(lon),
        -np.sin(lat) * np.sin(lon),
        np.cos(lat),
    ])
    # Project direction onto tangent plane
    de = np.dot(dx * np.array([1, 0, 0]) + dy * np.array([0, 1, 0]) +
                dz * np.array([0, 0, 1]), east)
    dn = np.dot(dx * np.array([1, 0, 0]) + dy * np.array([0, 1, 0]) +
                dz * np.array([0, 0, 1]), north)
    d_vec = np.array([dx, dy, dz])
    de = np.dot(d_vec, east)
    dn = np.dot(d_vec, north)
    return np.arctan2(dn, de)


def _order_indices_ccw(center_xyz, neighbor_xyz):
    """Order neighbor indices counterclockwise around center on the sphere."""
    # Build local tangent plane basis
    c = center_xyz / np.linalg.norm(center_xyz)
    # Choose an arbitrary perpendicular direction
    if abs(c[2]) < 0.9:
        up = np.array([0.0, 0.0, 1.0])
    else:
        up = np.array([1.0, 0.0, 0.0])
    east = np.cross(up, c)
    east /= np.linalg.norm(east)
    north = np.cross(c, east)

    # Project neighbors to tangent plane and compute angles
    offsets = neighbor_xyz - c[None, :]
    x_proj = np.dot(offsets, east)
    y_proj = np.dot(offsets, north)
    angles = np.arctan2(y_proj, x_proj)
    return np.argsort(angles)


