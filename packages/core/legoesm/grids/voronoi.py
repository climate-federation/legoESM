# ============================================================================
# Mesh disk cache (avoids redundant per-rank SCVT rebuild under MPI)
# ============================================================================
#
# create_voronoi_mesh runs Lloyd relaxation (scipy SphericalVoronoi) which is
# DETERMINISTIC in (subdivision_level, radius, lloyd_iterations, omega) when
# density_fn is None, and slow (~10^2 s at level>=6).  Under MPI every rank
# rebuilds the SAME mesh; at 32 ranks/node the redundant builds contend for
# cores and exceed the job walltime (the multi-node "hang" was this, not an MPI
# fault: a surviving rank reported mesh=105.4 s while its peers timed out).
# Caching the built mesh to a shared-filesystem .npz lets the first process
# build once and every other process (this run or a later one) load it in
# O(1 s).  Pre-warm once before an MPI launch (prewarm_voronoi_cache) so all
# ranks only load.

_MESH_CACHE_ENV = "LEGOESM_MESH_CACHE_DIR"
_MESH_CACHE_DISABLE_ENV = "LEGOESM_MESH_CACHE_DISABLE"

# Big-mesh policy (codex round-19, issue: subdiv-8 cap blocked 128-GPU MPAS).
# Levels <= ROUTINE build freely (cheap). ROUTINE+1 .. MAX are
# cache-or-prewarm ONLY: a hit loads; a miss raises unless this process is
# the designated single builder (env below + exclusive lockfile — the
# opt-in alone would be a thundering herd across an MPI launch). > MAX is
# hard-refused (42M+ cells; the scipy SphericalVoronoi path does not scale
# there). Build cost measured 2026-07-29: one Lloyd iteration = 21.6 s at
# subdiv-7, 87.1 s at subdiv-8 (~4x per level).
_BIG_MESH_ROUTINE_LEVEL = 8
_BIG_MESH_MAX_LEVEL = 10
_BIG_MESH_BUILD_ENV = "LEGOESM_ALLOW_BIG_MESH_BUILD"
_BIG_MESH_LOCK_STALE_S = 7200.0   # lloyd=50 at subdiv-9 ~ 5 h; lloyd=0 ~ min
# Bump whenever the SCVT/connectivity/geometry construction changes VALUES for
# unchanged args (e.g. edits to _lloyd_relaxation / _build_mesh_from_generators).
# The schema check below only catches FIELD changes; a value-changing algorithm
# edit must invalidate old caches via this token.
_MESH_CACHE_VERSION = 1


def _voronoi_cache_disabled() -> bool:
    """True when LEGOESM_MESH_CACHE_DISABLE is set to a truthy value."""
    return os.environ.get(_MESH_CACHE_DISABLE_ENV, "").strip().lower() in (
        "1", "true", "yes", "on")


def _voronoi_cache_dir() -> str:
    """Cache directory (LEGOESM_MESH_CACHE_DIR or ~/.cache/legoesm/voronoi)."""
    d = os.environ.get(_MESH_CACHE_ENV, "").strip()
    if not d:
        d = os.path.join(
            os.path.expanduser("~"), ".cache", "legoesm", "voronoi")
    return d


def _voronoi_cache_path(
    subdivision_level: int, radius: float, lloyd_iterations: int, omega: float
) -> str:
    """Deterministic cache filename keyed on every parameter that changes the mesh.

    Includes the active x64 flag because the stored dtypes (and a fresh rebuild)
    depend on it — a float32-built mesh must never be served to an x64 run.
    ``radius``/``omega`` use ``repr`` (round-trippable for Python floats).
    """
    x64 = bool(jax.config.read("jax_enable_x64"))
    name = (
        f"scvt_v{_MESH_CACHE_VERSION}_lvl{subdivision_level}"
        f"_r{radius!r}_omega{omega!r}_lloyd{lloyd_iterations}"
        f"_x64{int(x64)}.npz"
    )
    return os.path.join(_voronoi_cache_dir(), name)


def _load_voronoi_cache(path: str):
    """Reconstruct a VoronoiMesh from *path*, or None on miss/corruption/schema drift."""
    if not os.path.exists(path):
        return None
    try:
        with np.load(path) as data:
            if set(data.files) != set(VoronoiMesh._fields):
                # Stale schema (fields added/removed) -> ignore, rebuild.
                return None
            fields = {}
            for field_name in VoronoiMesh._fields:
                arr = data[field_name]
                if arr.ndim == 0:
                    fields[field_name] = arr.item()        # scalar (nCells, radius, ...)
                else:
                    fields[field_name] = jnp.asarray(arr)  # respects current x64
        return VoronoiMesh(**fields)
    except Exception as exc:  # corrupt / truncated cache file -> rebuild
        warnings.warn(
            f"Ignoring unreadable Voronoi mesh cache {path!r}: {exc}",
            RuntimeWarning, stacklevel=2)
        return None


def _save_voronoi_cache(path: str, mesh: "VoronoiMesh") -> None:
    """Atomically write *mesh* to *path* (tmp + os.replace; safe under the N-rank race)."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    arrays = {field_name: np.asarray(getattr(mesh, field_name))
              for field_name in mesh._fields}
    tmp = f"{path}.tmp.{os.getpid()}"
    try:
        with open(tmp, "wb") as f:
            np.savez(f, **arrays)  # file handle -> no .npz extension munging
        os.replace(tmp, path)      # atomic on same filesystem; last writer wins
    except Exception as exc:  # never let a cache-write failure break generation
        warnings.warn(
            f"Could not write Voronoi mesh cache {path!r}: {exc}",
            RuntimeWarning, stacklevel=2)
        try:
            if os.path.exists(tmp):
                os.remove(tmp)
        except OSError:
            pass


def prewarm_voronoi_cache(
    subdivision_level: int,
    radius: float = constants.R_earth,
    lloyd_iterations: int = 50,
    omega: float = constants.Omega,
) -> str:
    """Build (if absent) and cache the uniform SCVT mesh; return the cache path.

    Call ONCE from a single process before an MPI launch so every rank loads the
    mesh instead of redundantly rebuilding it.  Cheap no-op when already cached
    (create_voronoi_mesh returns the cached mesh without rebuilding).
    """
    if _voronoi_cache_disabled():
        raise RuntimeError(
            f"{_MESH_CACHE_DISABLE_ENV} is set; cannot pre-warm a disabled cache.")
    path = _voronoi_cache_path(subdivision_level, radius, lloyd_iterations, omega)
    create_voronoi_mesh(
        subdivision_level, radius=radius,
        lloyd_iterations=lloyd_iterations, omega=omega)
    return path


def create_voronoi_mesh(
    subdivision_level: int,
    radius: float = constants.R_earth,
    lloyd_iterations: int = 50,
    omega: float = constants.Omega,
    density_fn=None,
) -> VoronoiMesh:
    """Create a centroidal Voronoi tessellation (SCVT) on the sphere.

    Starts from an icosahedral triangulation, bisects to the desired
    level, applies Lloyd relaxation, then builds the full MPAS-compatible
    mesh with all connectivity and geometric arrays.

    Parameters
    ----------
    subdivision_level : int
        Number of bisection levels. nCells = 10*4^level + 2.
        level=3: 642 cells, level=4: 2562, level=5: 10242.
    radius : float
        Sphere radius [m]. Default: Earth radius.
    lloyd_iterations : int
        Number of Lloyd relaxation iterations. Default: 50.
    omega : float
        Rotation rate [rad/s]. Default: Earth rotation.
    density_fn : callable(lat, lon) -> float, optional
        Relative mesh-density function (``lat``, ``lon`` in radians; larger =>
        finer cells).  When provided, the Lloyd relaxation is **density-weighted**
        (Du–Faber–Gunzburger SCVT): generators concentrate where the density is
        high, yielding a VARIABLE-RESOLUTION mesh refined over the high-density
        region (the MPAS variable-resolution capability).  Cell area relaxes toward
        ``~ 1/density`` (weighting by ``density**2``), so a region with relative
        density ``d`` gets roughly ``d`` x smaller cells.  ``None`` (default) =>
        the uniform quasi-uniform SCVT (unchanged).  Host-side mesh generation —
        the callable is plain NumPy, never traced.  NOTE: Lloyd relaxation converges
        linearly, so the achieved refinement contrast grows with
        ``lloyd_iterations``; for strong/precise variable resolution prefer a
        JIGSAW-built mesh loaded via :func:`load_mpas_mesh`.

    Returns
    -------
    VoronoiMesh
    """
    if subdivision_level > _BIG_MESH_MAX_LEVEL:
        n_cells = 10 * 4 ** subdivision_level + 2
        raise ValueError(
            f"subdivision_level={subdivision_level} would create {n_cells:.2e} "
            f"cells — unsupported (hard cap {_BIG_MESH_MAX_LEVEL}; the scipy "
            f"SphericalVoronoi build path does not scale there). For higher "
            f"resolutions, use load_mpas_mesh() with a pre-built mesh file."
        )
    # Levels above the routine cap are CACHE-OR-PREWARM only (codex round-19
    # design): a valid cache hit is always admissible; a MISS is refused
    # unless this process is the designated prewarmer — otherwise an N-rank
    # MPI launch would have every rank silently rebuild for hours (build is
    # ~87 s/Lloyd-iteration at subdiv-8, ~4x that at 9). The prewarm path is
    # single-builder: an exclusive lockfile serialises concurrent opt-ins.
    _big = subdivision_level > _BIG_MESH_ROUTINE_LEVEL

    # Disk cache: a uniform SCVT mesh is deterministic in these args, so skip the
    # expensive rebuild on a hit.  density_fn meshes are NOT cached (a callable
    # has no stable key); the env switch lets a run force a fresh build.
    use_cache = density_fn is None and not _voronoi_cache_disabled()
    cache_path = None
    if use_cache:
        cache_path = _voronoi_cache_path(
            subdivision_level, radius, lloyd_iterations, omega)
        cached = _load_voronoi_cache(cache_path)
        if cached is not None:
            return cached

    _lock_path = None
    if _big:
        if not use_cache:
            raise ValueError(
                f"subdivision_level={subdivision_level} needs the mesh disk "
                f"cache (density_fn=None and {_MESH_CACHE_DISABLE_ENV} unset)"
                f" — an uncached big-mesh build would repeat per rank.")
        if os.environ.get(_BIG_MESH_BUILD_ENV, "") != "1":
            raise ValueError(
                f"subdivision_level={subdivision_level}: no cached mesh at "
                f"{cache_path} and this process is not the designated "
                f"prewarmer. Build the cache ONCE via scripts/data/"
                f"prewarm_voronoi_mesh.py (or set {_BIG_MESH_BUILD_ENV}=1 in "
                f"a SINGLE-process job), then rerun.")
        # Single-builder lock (codex round-19: the opt-in alone is a
        # thundering herd — N authorized ranks could all miss). O_EXCL
        # lockfile beside the cache; losers wait for the winner's atomic
        # os.replace to land and then load it. Stale locks (builder died)
        # are stolen after _BIG_MESH_LOCK_STALE_S with a warning.
        _lock_path = f"{cache_path}.lock"
        import time as _time
        while True:
            try:
                _fd = os.open(_lock_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                os.write(_fd, str(os.getpid()).encode())
                os.close(_fd)
                break                      # we are the builder
            except FileExistsError:
                for _ in range(int(_BIG_MESH_LOCK_STALE_S)):
                    _time.sleep(1.0)
                    cached = _load_voronoi_cache(cache_path)
                    if cached is not None:
                        return cached      # winner finished; use its mesh
                    if not os.path.exists(_lock_path):
                        break              # lock released without a cache?!
                else:
                    try:                   # stale: builder likely died
                        os.unlink(_lock_path)
                    except FileNotFoundError:
                        pass
                    import warnings
                    warnings.warn(
                        f"stale big-mesh lock {_lock_path} removed after "
                        f"{_BIG_MESH_LOCK_STALE_S}s; taking over the build.")

    # Step 1: Icosahedral base
    verts, triangles = _icosahedral_base()

    # Step 2: Bisect to desired resolution
    if subdivision_level > 0:
        verts, triangles = _bisect_mesh(verts, triangles, subdivision_level)

    # Step 3: Lloyd relaxation for SCVT (density-weighted when density_fn given)
    if lloyd_iterations > 0 and subdivision_level > 0:
        cell_points = _lloyd_relaxation(
            verts, n_iter=lloyd_iterations, density_fn=density_fn)
    elif density_fn is not None:
        raise ValueError(
            "density_fn requires lloyd_iterations > 0 and subdivision_level > 0 "
            "(the variable-resolution mesh is produced by density-weighted Lloyd "
            "relaxation; with no relaxation the icosahedral seed stays uniform)."
        )
    else:
        cell_points = verts

    # Step 4: Build complete mesh
    mesh = _build_mesh_from_generators(cell_points, radius, omega)
    if use_cache and cache_path is not None:
        _save_voronoi_cache(cache_path, mesh)
    if _lock_path is not None:
        # Release AFTER the atomic cache save: waiters poll the cache, so
        # the lock's job is done once the mesh is loadable.
        try:
            os.unlink(_lock_path)
        except FileNotFoundError:
            pass
    return mesh


