# --- E3SM v3.0.1 orographic-only settings (gw_drag.F90) ---
_ALPHA_ORO_ONLY_PER_S = 1.0e-6   # gw_drag.F90:341 orographic_only Newtonian alpha [1/s]
_EFFGW = 1.0                     # efficiency as the audit's oracle ran it (no scaling) [1]


def lindzen_gwd(
    u: jax.Array,
    v: jax.Array,
    T: jax.Array,
    p_full: jax.Array,
    p_half: jax.Array,
    z_full: jax.Array,
    z_half: jax.Array,
    rho: jax.Array,
    lat: jax.Array,
    dt: float,
    config: LindzenConfig,
    h_topo_col: jax.Array | None = None,
) -> GWDOutput:
    """Lindzen-saturation orographic GWD tendencies (E3SM v3.0.1 orographic-only).

    Parameters
    ----------
    u, v, T, p_full, p_half, z_full, z_half, rho, lat, dt, config
        Standard GWD backend signature; column arrays (ncol, nlev), k = 0 top.
        ``z_full`` is height above the surface (E3SM ``zm``); ``rho`` and
        ``z_half`` only feed the ``eps_gwd`` diagnostic; ``lat`` is unused
        (no polar taper on the orographic source).
    h_topo_col : (ncol,) or None
        Subgrid orographic standard deviation ``sgh`` [m]; None = the scalar
        ``config.h_topo`` in every column.
    """
    ncol, nlev = u.shape
    g = constants.g
    R_d = constants.R_d
    c_pd = constants.c_pd
    cfg = E3SMCAMConfig(
        kwv=config.k_wave, fcrit2=config.fcrit2, umcfac=config.umcfac,
        alpha_newtonian=_ALPHA_ORO_ONLY_PER_S,
    )

    # Layer geometry as the e3sm_cam driver builds it.
    pmid = p_full
    pint = p_half
    dpm = jnp.maximum(jnp.abs(pint[:, 1:] - pint[:, :-1]), 1.0)
    rdpm = 1.0 / dpm
    piln = jnp.log(jnp.maximum(pint, 1.0))

    rhoi, ti, nm, ni = gw_prof(T, pmid, pint, c_pd, R_d, g, cfg.n2min)

    if h_topo_col is None:
        sgh = jnp.full((ncol,), config.h_topo, dtype=u.dtype)
    else:
        sgh = jnp.clip(jnp.asarray(h_topo_col), 0.0, None).astype(u.dtype)
    tau0, src_level, tend_level, xv, yv, c, ubm, ubi = gw_oro_src(
        u, v, T, sgh, pmid, pint, dpm, z_full, nm, R_d, cfg.kwv, cfg.fcrit2,
        cfg.orographic.oro_min_h, cfg.orographic.oro_min_wind,
    )
    _tau, du_dt, dv_dt, _gwut, _tau_sat = gw_drag_prof(
        tau0, c, src_level, tend_level, T, ti, piln, rhoi, nm, ni,
        ubm, ubi, xv, yv, dpm, rdpm, lat, _EFFGW, dt, cfg,
        orographic_only=True,
        softmin_sharpness=config.Fr_sharpness,
        crit_level_sharpness=config.crit_level_sharpness,
        crit_level_floor=config.crit_level_floor,
        tndmax_per_day=config.tndmax_per_day,
    )

    # E3SM driver discrete-KE heating (gw_drag.F90:908-913; ttgw = 0 for the
    # orographic ngwv = 0 call).
    dT_dt = -(du_dt * (u + 0.5 * dt * du_dt) + dv_dt * (v + 0.5 * dt * dv_dt)) / c_pd

    # Column KE dissipation diagnostic (unchanged definition, GWDOutput): the
    # instantaneous rate, NOT the discrete heat above (see module docstring).
    dz = jnp.clip(jnp.abs(z_half[:, :-1] - z_half[:, 1:]), 1.0, None)
    eps_gwd = -jnp.sum(rho * (u * du_dt + v * dv_dt) * dz, axis=1)

    return GWDOutput(du_dt=du_dt, dv_dt=dv_dt, dT_dt=dT_dt, eps_gwd=eps_gwd)
