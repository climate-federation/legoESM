"""CAM6 orographic gravity-wave drag (McFarlane 1987; CAM ``gw_oro``).

A JAX port of the CAM6 (ESCOMP/CAM ``cam_cesm2_1_rel_60``) orographic branch
of ``gw_tend`` (gw_drag.F90:1743-1807): ``gw_prof`` + land-fraction scaling +
``gw_oro_src`` + ``gw_drag_prof`` (single stationary wave, ``c = 0``) with the
gravity-wave eddy diffusion of dry static energy and constituents
(``gw_ediff`` / ``gw_diff_tend``).  Oracle-matched to max relative error
<= 1e-10 in fp64 with the smoothing fields below at their hard-switch limit
(``tests/atmosphere/hydrostatic/unit/test_gw_oro_cam6_oracle.py``, fixture
generated by running the CAM Fortran: ``scripts/validate/oracle/gw_oro_cam6``).

Algorithm (k = 0 model top; interface k sits above midpoint k)
-------------------------------------------------------------
1. ``gw_prof``: interface T, density ``rhoi = pint/(R_d*ti)`` and buoyancy
   frequency from ``dT/dp`` between midpoints, ``ni = sqrt(max(n2min, N^2))``
   with ``n2min = 5e-5 s^-2``; ``nm`` = midpoint average of ``ni``.  Midpoint
   pressure is the arithmetic interface mean (CAM ``Coords1D(pint)``).
2. Land scaling (``gw_lndscl_sgh``): ``effgw = effgw_oro*landfrac`` and
   ``sgh/sqrt(landfrac)`` where ``landfrac >= epsilon(1._r8)``, both zero
   elsewhere (``McFarlaneConfig.effgw_oro``, default 0.125).
3. ``gw_oro_src``: displacement ``hdsp = 2*sgh``; dp-weighted source averages
   of ``rho = pmid/(R_d*T)``, ``u``, ``v``, ``nm`` over every midpoint the
   mountain penetrates (full column, shared ``depth_averaged_oro_source``);
   launch ``tau0 = 0.5*k*min(hdsp^2, fcrit2*(U/N)^2)*rho*N*U`` only where
   ``U > 2 m/s`` and ``hdsp > 10 m``.  No upper clip on ``tau0``.
4. ``gw_drag_prof``: ``tau`` held at ``tau0`` up to the source interface, then
   upward ``tau(k) = min(taudmp, tausat)`` with Newtonian + background damping
   ``taudmp = tau(k+1)*exp(-2*mi*R_d/g*T*dln p)``, ``mi = ni/(2*k*ubmc2) *
   (alpha + ni^2/ubmc2*dback)`` (``alpha`` = CAM's Wehrbein & Leovy table on
   the reference interface pressures), saturation ``tausat = k*fcrit2*rhoi*
   |ubi|^3/(2*ni)`` zeroed where ``ubi`` changes sign across the layer
   (critical level: the residual stress is DEPOSITED there), both zeroed
   below ``taumin = 1e-10 Pa``.  Then ``tau *= effgw``.
5. Tendency, top down: ``ubt = g*dtau/dp`` limited to ``umcfac*|ubm|/dt``,
   signed against ``ubm``, scaled to ``|ubt| <= tndmax`` (400 m/s/day); the
   stress the limiter removed is carried to the layer below by resetting
   ``tau(k+1) = tau(k) + |ubt|*dp/g``.
6. Heating ``-ubm*ubt`` (frictional) plus the implicit gravity-wave eddy
   diffusion (``egwdff = prndl*0.5*|ubt*ubm|/nm^2``, ``prndl = 0.25``,
   zero-flux top/bottom) of ``dse = c_pd*T + g*z`` and of every tracer passed.

Smoothing (differentiability).  The existing sharpness/width fields each
reduce to the CAM hard switch at their limit: ``min_wind_sharpness`` (the
``U > 2 m/s`` launch gate, applied as ``sigmoid*U``), ``softmin_sharpness``
(p of the p-norm smooth min ``(taudmp^-p + tausat^-p)^(-1/p)`` of
``min(taudmp, tausat)``, the Lindzen form: C-infinity, never above either
stress, ``2^(-1/50)`` = 0.986 of both where they are equal at the default
p = 50), ``crit_level_sharpness`` / ``crit_level_floor``
(the sign-agreement test of ``ubi`` across the layer; CAM's ``c = 0`` is
``crit_level_floor -> 0``).  The ``hdsp > 10 m`` gate, ``n2min``, ``taumin``,
``ubmc2mn`` and the limiters are hard, as in CAM (piecewise smooth; finite
gradients).  The production smoothing values are NOT the hard limit.
KNOWN DIFFERENCE at the defaults (vs the CAM6 oracle, 14 columns, pinned per
column in the oracle test): field max-norm relative 3.5e-3 in du/dt, 4.2e-3 in
dT/dt, 1.3e-4 in dq/dt; per column up to 2.9e-2 in du/dt and 2.7e-2 in dT/dt
(column 11).  Measured 2026-10-29 when the smooth min became the p-norm
(#2241); the earlier sigmoid blend, not C1 at taudmp = tausat, gave field
max-norm 1.2e-2 in du/dt.  The hard limit is every sharpness -> inf (1e12)
with ``crit_level_floor = 0``.

Departures kept from the shared signature, not from the oracle:
``use_e3sm_hdsp`` / ``use_depth_averaged_source`` keep their
legacy opt-outs (the production-resolved values are the CAM path).  Without a
``land_frac_col`` the scheme runs CAM's ``gw_lndscl_sgh = .false.`` path
(``effgw = effgw_oro``, unscaled ``sgh``).  ``gw_oro_south_fac = 1`` (CAM6
default) is not modelled.

References
----------
- McFarlane, N. A. (1987). J. Atmos. Sci., 44, 1775-1800.
- ESCOMP/CAM cam_cesm2_1_rel_60 (a03b84b7): gw_drag.F90 (gw_init alpha
  table :416-519, gw_tend orographic branch :1743-1807), gw_oro.F90,
  gw_common.F90 (gw_prof, gw_drag_prof), gw_diffusion.F90.
- Wehrbein, W. M. and Leovy, C. B. (1982). J. Atmos. Sci., 39, 1532-1544.
"""

