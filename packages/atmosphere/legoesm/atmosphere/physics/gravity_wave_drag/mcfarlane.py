def _mcfarlane_launch_stress(
    rho_sfc: jax.Array,
    N_sfc: jax.Array,
    U_activated: jax.Array,
    h_topo_sq: jax.Array,
    config: McFarlaneConfig,
) -> jax.Array:
    """Froude-capped orographic launch stress ``tau_0`` [Pa] (gw_oro.F90:166-168).

    ``tau_0 = G_0 * rho * N * k * min(h_disp^2, fcrit2 * (U / N)^2) * U`` with
    ``G_0 = 0.5`` (CAM ``0.5*kwv``) and the displacement ``h_disp = 2*h``
    (CAM ``hdsp = 2*sgh``) when the resolved ``use_e3sm_hdsp`` is True, else
    the legacy ``h``.  Returned BEFORE ``directional_spread`` and the
    ``hdsp > 10 m`` gate.  ``h_topo_sq`` is the (land-scaled) ``sgh**2``.
    """
    froude_h_sq = config.fcrit2 * safe_divide(
        U_activated ** 2, N_sfc ** 2, eps=1e-30,
    )
    # ``is True``: mcfarlane_gwd resolves the tri-state flag ("auto" -> bool)
    # before this is reached; the strict identity test keeps a DIRECT caller
    # passing an unresolved ``"auto"`` (truthy) config on the legacy branch
    # instead of silently doubling.
    h_disp_sq = 4.0 * h_topo_sq if config.use_e3sm_hdsp is True else h_topo_sq
    h_eff_sq = jnp.minimum(h_disp_sq, froude_h_sq)
    return config.G_0 * rho_sfc * N_sfc * config.k_wave * h_eff_sq * U_activated


def mcfarlane_gwd(
    u: jax.Array,
    v: jax.Array,
    T: jax.Array,
    p_full: jax.Array,
    p_half: jax.Array,
    z_full: jax.Array,
    z_half: jax.Array,
    rho: jax.Array,
    lat: jax.Array,
    dt: float,
    config: McFarlaneConfig,
    h_topo_col: jax.Array | None = None,
    *,
    p_ref_half: jax.Array | None = None,
    land_frac_col: jax.Array | None = None,
    tracers: dict | None = None,
    return_stress: bool = False,
) -> GWDOutput | tuple[GWDOutput, jax.Array]:
    """CAM6 orographic gravity-wave drag tendencies.

    Parameters
    ----------
    u, v, T, p_full, p_half, z_full, z_half, rho, lat, dt, config
        Standard GWD backend signature; column arrays (ncol, nlev), k = 0 top.
        ``z_full`` is height above the surface (CAM ``zm``); ``rho`` and
        ``z_half`` only feed the ``eps_gwd`` diagnostic; ``p_full`` and
        ``lat`` are unused (CAM's midpoint is the interface mean; south
        factor 1).
    h_topo_col : (ncol,) or None
        Subgrid orographic standard deviation ``sgh`` [m]; None = scalar
        ``config.h_topo`` with the legacy displacement (see ``use_e3sm_hdsp``).
    p_ref_half : (nlev+1,)
        REQUIRED reference interface pressures [Pa] (CAM ``pref_edge``: the
        vertical coordinate at surface pressure 1e5 Pa) on which the
        Newtonian-cooling profile is interpolated.
    land_frac_col : (ncol,) or None
        Land fraction (CAM ``cam_in%landfrac``).  None = CAM's
        ``gw_lndscl_sgh = .false.`` path.
    tracers : dict[str, (ncol, nlev)] or None
        Per-mass mixing ratios diffused by the gravity-wave eddy diffusion;
        their tendencies are returned in ``GWDOutput.dq_dt`` (same keys).
    return_stress : bool
        Static flag, default False.  True returns ``(GWDOutput, tau)`` where
        ``tau`` (ncol, nlev+1) [Pa] is CAM's ``tau`` out of ``gw_drag_prof``
        (``lapply_effgw``): the propagated profile times ``effgw``, with
        each interface below the top redetermined from the limited
        tendency.  Interface k = 0 is the model top; ``tau[:, -1]`` is the
        bottom-interface stress, equal to the launch stress ``effgw*tau0``
        whenever no limiter binds.  Diagnostic only: the tendencies are the
        same either way.
    """
    _hdsp = config.use_e3sm_hdsp
    # Identity (not equality) for the bool arms: ``1 == True`` would otherwise
    # slip through membership and then silently resolve as legacy at the
    # ``is True`` reads — an int/float "flag" must raise, not downgrade.
    if not (_hdsp is True or _hdsp is False or _hdsp == "auto"):
        raise ValueError(
            f"McFarlaneConfig.use_e3sm_hdsp={_hdsp!r} is not a valid "
            "displacement convention; expected one of False | True | 'auto'."
        )
    if _hdsp is True and h_topo_col is None:
        raise ValueError(
            "McFarlaneConfig.use_e3sm_hdsp=True requires a per-column "
            "h_topo_col (wire grid.subgrid_topo_stddev or pass h_topo_col "
            "explicitly): the E3SM hdsp=2*sgh displacement quadruples the "
            "below-cap launch, and applying it to the uniform scalar "
            "config.h_topo fallback would quadruple drag over ocean "
            "columns.  Use 'auto' to keep the legacy displacement on the "
            "scalar fallback instead."
        )
    if p_ref_half is None:
        raise ValueError(
            "mcfarlane_gwd needs p_ref_half (reference interface pressures, "
            "CAM pref_edge): the CAM6 Newtonian-cooling damping profile is "
            "interpolated on them.  The GWD factories pass "
            "sigma_coord.pressure_at_half(constants.p_ref)."
        )
    config = config._replace(
        use_e3sm_hdsp=(_hdsp is True)
        or (_hdsp == "auto" and h_topo_col is not None),
    )
    ncol, nlev = u.shape
    g = constants.g
    R_d = constants.R_d
    c_pd = constants.c_pd

    # ---- gw_prof (gw_common.F90): CAM Coords1D(pint) midpoints ----
    pint = p_half
    pmid = 0.5 * (pint[:, :-1] + pint[:, 1:])
    dp = pint[:, 1:] - pint[:, :-1]
    piln = jnp.log(pint)
    rhoi, _ti, nm, ni = gw_prof(T, pmid, pint, c_pd, R_d, g, _N2MIN)

    # ---- landfrac scaling (gw_drag.F90:1757-1771) ----
    if h_topo_col is None:
        sgh = jnp.full((ncol,), config.h_topo, dtype=u.dtype)
    else:
        sgh = jnp.clip(jnp.asarray(h_topo_col), 0.0, None).astype(u.dtype)
    if land_frac_col is None:
        effgw = jnp.full((ncol,), config.effgw_oro, dtype=u.dtype)
    else:
        lf = jnp.asarray(land_frac_col).astype(u.dtype)
        on_land = lf >= _LANDFRAC_MIN
        effgw = jnp.where(on_land, config.effgw_oro * lf, 0.0)
        sgh = jnp.where(on_land, sgh / jnp.sqrt(jnp.where(on_land, lf, 1.0)), 0.0)
    # ``is True``: flag already resolved above.
    hdsp = sgh * (2.0 if config.use_e3sm_hdsp is True else 1.0)

    # ---- gw_oro_src (gw_oro.F90) ----
    rho_mid = pmid / (R_d * T)
    if config.use_depth_averaged_source:
        rsrc, usrc, vsrc, nsrc, src_level = depth_averaged_oro_source(
            u, v, rho_mid, hdsp, pint, dp, z_full, nm, full_column=True,
        )
    else:
        # Legacy opt-out: bottom-midpoint source, stress computed from the
        # bottom interface up (deposition allowed in the bottom layer).
        rsrc, usrc, vsrc, nsrc = rho_mid[:, -1], u[:, -1], v[:, -1], nm[:, -1]
        src_level = jnp.full((ncol,), nlev, dtype=jnp.int32)
    # CAM get_unit_vector (zero direction for a calm source), gradient-safe.
    U_ll, xv, yv = source_direction(usrc, vsrc)
    ubm = u * xv[:, None] + v * yv[:, None]
    ubi = jnp.concatenate(
        [ubm[:, :1], 0.5 * (ubm[:, :-1] + ubm[:, 1:]), U_ll[:, None]], axis=1,
    )
    # Smooth ``ubi(pver+1) > orovmin`` gate (hard at min_wind_sharpness -> inf).
    U_activated = jax.nn.sigmoid(
        config.min_wind_sharpness * (U_ll - config.min_wind)) * U_ll
    tau0 = _mcfarlane_launch_stress(rsrc, nsrc, U_activated, sgh ** 2, config)
    tau0 = tau0 * config.directional_spread
    tau0 = jnp.where(hdsp > _OROHMIN_M, tau0, 0.0)

    # ---- gw_drag_prof stress profile (gw_common.F90), bottom -> top ----
    alpha = newtonian_alpha_profile(
        jnp.asarray(p_ref_half, dtype=u.dtype)[None, :],
        alpha0_per_day=_ALPHA0_CAM6_PER_DAY, palph_hpa=_PALPH_CAM6_HPA,
    )[0]
    kwv = config.k_wave
    floor = config.crit_level_floor

    def stress_step(tau_below, j):
        ub = ubi[:, j]
        # Critical level: tausat = 0 unless ubi has the same sign at the top
        # and bottom of the layer (gw_common.F90:485, c = 0).  Smooth XNOR of
        # the two sign tests, exact at the hard limit with floor -> 0.
        s_top = jax.nn.sigmoid(config.crit_level_sharpness * (ub - floor))
        s_bot = jax.nn.sigmoid(config.crit_level_sharpness * (ubi[:, j + 1] - floor))
        agree = s_top * s_bot + (1.0 - s_top) * (1.0 - s_bot)
        tausat = (config.efficiency * config.fcrit2 * kwv * rhoi[:, j]
                  * jnp.abs(ub) ** 3 / (ni[:, j] * config.envelope_scale)) * agree
        ubmc2 = jnp.maximum(ub ** 2, _UBMC2MN)
        mi = ni[:, j] / (2.0 * kwv * ubmc2) * (alpha[j] + ni[:, j] ** 2 / ubmc2 * _DBACK)
        taudmp = tau_below * jnp.exp(
            -2.0 * mi * (R_d / g) * T[:, j] * (piln[:, j + 1] - piln[:, j]))
        tausat = jnp.where(tausat <= _TAUMIN_PA, 0.0, tausat)
        taudmp = jnp.where(taudmp <= _TAUMIN_PA, 0.0, taudmp)
        # Smooth min(taudmp, tausat): p-norm, p = softmin_sharpness (the
        # Lindzen form, #2241); exact min at softmin_sharpness -> inf.
        tau_new = pnorm_smooth_min(taudmp, tausat, config.softmin_sharpness, _TAUMIN_PA)
        tau_new = jnp.where(tausat > 0.0, tau_new, 0.0)
        # Interfaces at and below src_level hold tau0 (gw_oro.F90 source hold).
        tau_new = jnp.where(j < src_level, tau_new, tau_below)
        return tau_new, tau_new

    _, tau_up = jax.lax.scan(stress_step, tau0, jnp.arange(nlev - 1, -1, -1))
    tau = jnp.concatenate([tau_up[::-1].T, tau0[:, None]], axis=1)  # (ncol, nlev+1)
    tau = tau * effgw[:, None]

    # ---- gw_drag_prof tendency, top -> bottom (lapply_effgw = .true.) ----
    tndmax = config.tndmax_per_day / 86400.0

    def tend_step(tau_top, j):
        ubtl = g * (tau[:, j + 1] - tau_top) / dp[:, j]
        ubtl = jnp.minimum(ubtl, config.umcfac * jnp.abs(0.0 - ubm[:, j]) / dt)
        gwut = jnp.where((0.0 - ubm[:, j]) >= 0.0, jnp.abs(ubtl), -jnp.abs(ubtl))
        over = jnp.abs(gwut) > tndmax
        gwut = gwut * jnp.where(over, tndmax / jnp.where(over, jnp.abs(gwut), 1.0), 1.0)
        # The limited stress divergence is carried to the layer below
        # (CAM "redetermine the effective stress on the interface below").
        tau_below = tau_top + jnp.abs(gwut) * dp[:, j] / g
        return tau_below, (gwut, tau_below)

    _, (ubt, tau_lim) = jax.lax.scan(tend_step, tau[:, 0], jnp.arange(nlev))
    ubt = ubt.T                                               # (ncol, nlev)
    du_dt = ubt * xv[:, None]
    dv_dt = ubt * yv[:, None]
    dttke = -(ubm - 0.0) * ubt                                # [J/kg/s]

    # ---- gw_ediff + gw_diff_tend (gw_diffusion.F90), ktop..kbot = all ----
    egwdffi = gw_ediff(
        ubt[:, :, None], ubm, nm, jnp.zeros((ncol, 1), dtype=u.dtype), rhoi,
        pmid, 1.0 / dp, jnp.full((ncol,), nlev, dtype=jnp.int32), dt, g, R_d,
        0, nlev, _PRNDL, jnp.inf,
    )
    a, b, c = gw_diff_tridiag_coeffs(egwdffi, rhoi, pmid, 1.0 / dp, dt, g, 0, nlev)
    dse = c_pd * T + g * z_full
    dttdf = gw_diff_tend(dse, a, b, c, dt)
    dq_dt = None
    if tracers is not None:
        dq_dt = {k: gw_diff_tend(q, a, b, c, dt) for k, q in tracers.items()}

    dT_dt = (dttke + dttdf) / c_pd

    # Column KE dissipation diagnostic (unchanged definition, GWDOutput).
    dz = jnp.clip(jnp.abs(z_half[:, :-1] - z_half[:, 1:]), 1.0, None)
    eps_gwd = -jnp.sum(rho * (u * du_dt + v * dv_dt) * dz, axis=1)

    out = GWDOutput(du_dt=du_dt, dv_dt=dv_dt, dT_dt=dT_dt, eps_gwd=eps_gwd,
                    dq_dt=dq_dt)
    if not return_stress:
        return out
    # CAM's output tau: top interface as propagated, every interface below
    # redetermined from the limited tendency (tend_level = pver for gw_oro).
    return out, jnp.concatenate([tau[:, :1], tau_lim.T], axis=1)
