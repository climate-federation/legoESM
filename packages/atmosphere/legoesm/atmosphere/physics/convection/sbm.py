"""Simplified Betts-Miller (SBM) convection: a port of Isca's
``qe_moist_convection`` (``convection_scheme = 'SIMPLE_BETTS_MILLER'``).

Oracle
------
ExeClim/Isca tag ``v1.0`` (commit 5868cfd863b41823a3eeb30754ce06feba7528ec),
``src/atmos_param/qe_moist_convection/qe_moist_convection.F90``: Frierson (2007)
with the "shallower" shallow-convection scheme and the O'Gorman & Schneider
(2008) virtual-temperature / exact vapour-pressure modifications.  Every
routine below names the Fortran routine it ports; operation order follows the
Fortran so the port reproduces the RUNNING oracle to round-off
(``tests/atmosphere/test_sbm_qe_oracle.py``; fixture generated by
``scripts/validate/oracle/sbm_qe/``).

Thermodynamics: the oracle's ``escomp`` is ``legoesm.thermo``'s Tetens curve
and its constants are ``legoesm.constants`` (the fixture was produced with the
oracle compiled against exactly these, tier-2 audit variant L1).  The oracle's
own ``mixing_ratio`` (hard ``e -> r``) and ``virtual_temp`` are ported as is.

Algorithm (``SBM_convection_scheme``), per column:

1. ``CAPE_calculation``: lift the lowest-level parcel with its actual mixing
   ratio -- saturated: first-order wring-out at the lowest level; unsaturated:
   dry adiabat to the LCL, whose temperature comes from the scheme's
   ``lcl_temp_table`` (Newton-solved at init, linearly interpolated), then
   moist ascent by RK2 in ``ln p``.  CAPE (virtual temperature, ``ln p_half``
   weights) and the level of zero buoyancy ``kLZB``.  A parcel colder than
   ``Tmin`` before it has CAPE ends the ascent with no convection.
2. ``CAPE > 0``: reference profiles on ``kLZB..surface`` -- ``T_ref`` = parcel,
   ``q_ref`` from ``e_ref = rhbm * e(parcel saturation)`` -- and the relaxation
   increments ``dT = -(T - T_ref) dt/tau``, ``dq = -(q - q_ref) dt/tau``.
3. ``Pq`` (precipitation from drying) and ``Pt`` (latent equivalent of the
   heating) decide the branch:
   * ``Pq > 0`` and ``Pt > 0`` (deep): ``Pq > Pt`` -> scale ``dq`` by
     ``Pt/Pq`` (``do_change_time_scale_deepconv``); else shift ``dT``
     uniformly to conserve enthalpy (``do_change_Tref_deepconv``).
   * ``Pt > 0`` only (shallow, "shallower"): cut the convecting layer from the
     top until the remaining drying is positive, scale the cut level so the
     column precipitation is exactly 0, shift ``dT`` to conserve enthalpy
     (``do_shallow_convection``); no such level -> no convection.
   * ``Pt <= 0``: no convection.
4. Precipitation = ``Pq`` (= column drying in every branch).

Interface notes
---------------
* Tendencies are scaled by the existing smooth CAPE trigger
  ``cape_trigger(CAPE, cape_threshold, smooth_trigger_sharpness)``.  With
  ``cape_threshold = 0`` and ``smooth_trigger_sharpness -> inf`` the trigger is
  the oracle's ``CAPE > 0`` and the scheme IS the oracle; at the default
  (0 J/kg, 0.1) it is the oracle's threshold with the smooth trigger.
* The column precipitation ``Pq`` is handed out as the existing per-level
  condensate source ``dq_c_conv_dt`` (local drying rescaled so its column
  integral equals ``Pq``), as before.
* ``SBMConfig.cloud_mask_sharpness`` belonged to the replaced per-level
  ``T_moist >= T`` layer mask, which the oracle does not have; it is inert and
  a non-default value raises.
* Conditions on which the oracle stops with FATAL (LCL lookup value outside the
  table) or indexes outside its arrays (a parcel still buoyant at the model
  top, ``kLZB = 0`` with CAPE > 0) return NaN for that column.
* CIN, ``kLZBs``, ``convflag`` and the relaxation-timescale diagnostics of the
  oracle are not part of ``ConvectionOutput`` and are not computed.
* Differentiability: piecewise differentiable (``jnp.where`` on the oracle's
  hard switches); the LCL temperature is piecewise linear in the parcel state.

References
----------
- Frierson, D. M. W. (2007). The Dynamics of Idealized Convection Schemes and
  Their Effect on the Zonally Averaged Tropical Circulation. J. Atmos. Sci.,
  64, 1959-1976.
- O'Gorman, P. A., & Schneider, T. (2008). The hydrological cycle over a wide
  range of climates simulated with an idealized GCM. J. Climate, 21,
  3815-3832.
- Betts, A. K., & Miller, M. J. (1986). Q. J. R. Meteorol. Soc., 112, 693-709.
"""

