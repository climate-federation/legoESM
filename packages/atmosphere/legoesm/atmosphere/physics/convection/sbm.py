# --- Isca v1.0 qe_moist_convection module parameters (qe_moist_convection.F90
# l.67-76 namelist defaults; l.1088-1089 lcl_temp) ---
_T_MIN_K = 173.0                 # Tmin: lowest LCL temperature of the lookup table; parcel cutoff [K]
_T_MAX_K = 335.0                 # Tmax: highest LCL temperature of the lookup table [K]
_LCL_VAL_INC = 0.01              # val_inc: table increment of log(e_s / T**(1/kappa))
_LCL_NEWTON_PRECISION_K = 1.0e-7  # lcl_temp: Newton stops when |dT| <= precision [K]
_LCL_NEWTON_MAX_ITER = 100       # lcl_temp: max_iter
_SMALL = 1.0e-10                 # small: "to avoid division by 0 in dry limit" (added to L_v)


def _mixing_ratio(vapor_pressure, pressure):
    """qe ``mixing_ratio``: rdgas*e/rvgas/(p - e)."""
    return constants.R_d * vapor_pressure / constants.R_v / (pressure - vapor_pressure)


def _virtual_temp(temp, r):
    """qe ``virtual_temp``: T*(1 + q*(rvgas/rdgas - 1)), q = r/(1 + r)."""
    q = r / (1.0 + r)
    return temp * (1.0 + q * (constants.R_v / constants.R_d - 1.0))


@functools.lru_cache(maxsize=1)
def _lcl_temp_table():
    """qe ``get_val_min_max`` + ``generate_lcl_table`` (qe_moist_convection_init).

    Returns ``(val_min, val_max, table)`` as float64 numpy arrays, built once
    in float64 whatever the run precision (the oracle's 1e-7 K Newton stop is
    below float32 resolution).  The Newton iteration (``lcl_temp``) starts each
    entry from the previous entry's solution, as the oracle does, so the table
    is the oracle's to round-off.  A non-converged entry is the oracle's FATAL.
    """
    dt = np.float64
    kappa = constants.kappa
    with jax.enable_x64(True), jax.ensure_compile_time_eval():
        tmin = jnp.asarray(_T_MIN_K, dtype=dt)
        tmax = jnp.asarray(_T_MAX_K, dtype=dt)
        val_min = jnp.log(saturation_vapor_pressure(tmin) / (tmin ** (1.0 / kappa)))
        val_max = jnp.log(saturation_vapor_pressure(tmax) / (tmax ** (1.0 / kappa)))
        n = int(math.ceil((float(val_max) - float(val_min)) / _LCL_VAL_INC))

        def lcl_temp(guess, value):
            def cond(c):
                _, dT, it = c
                return (jnp.abs(dT) > _LCL_NEWTON_PRECISION_K) & (it < _LCL_NEWTON_MAX_ITER)

            def body(c):
                T, _, it = c
                diff = value - jnp.log(saturation_vapor_pressure(T) * T ** (-1.0 / kappa))
                ddiff = 1.0 / kappa * T ** -1 - constants.L_v / constants.R_v * T ** -2
                dT = diff / ddiff
                return T - dT, dT, it + 1

            T, dT, _ = jax.lax.while_loop(
                cond, body, (guess, jnp.asarray(_LCL_NEWTON_PRECISION_K + 1.0, dt), 0))
            return T, dT

        def step(guess, k):
            T, dT = lcl_temp(guess, val_min + k * _LCL_VAL_INC)
            return T, (T, dT)

        _, (table, last_dT) = jax.lax.scan(step, tmin, jnp.arange(n, dtype=dt))
        table = np.asarray(table)
        if not np.all(np.asarray(last_dT) < _LCL_NEWTON_PRECISION_K):
            raise RuntimeError("qe_moist_convection lcl_temp: LCL calculation did not converge")
    table.setflags(write=False)  # shared lru_cache object
    return np.asarray(val_min), np.asarray(val_max), table


def _get_lcl_temp(value, val_min, val_max, table):
    """qe ``get_lcl_temp``; ``bad`` flags the oracle's FATAL / out-of-table read."""
    n = table.shape[0]
    iv0 = jnp.floor((value - val_min) / _LCL_VAL_INC)          # iv_floor - 1
    w_floor = val_min + iv0 * _LCL_VAL_INC
    w_ceil = (value - w_floor) / _LCL_VAL_INC
    i = jnp.clip(iv0, 0, n - 2).astype(jnp.int32)
    tlcl = table[i + 1] * w_ceil - table[i] * (w_ceil - 1.0)
    bad = (value < val_min) | (value > val_max) | (iv0 < 0) | (iv0 > n - 2)
    return tlcl, bad


def _times_log_ratio(x, dlog):
    """``x * dlog``; where ``dlog`` is infinite (a zero top interface pressure,
    as the oracle would evaluate it) the forward value is the oracle's and no
    gradient flows through the infinite factor."""
    finite = jnp.isfinite(dlog)
    return jnp.where(finite, x * jnp.where(finite, dlog, 0.0),
                     jax.lax.stop_gradient(x) * dlog)


def _seq_cumsum(init, terms):
    """Running sum in level order (k = 0..nlev-1), as the Fortran loops add."""
    def f(c, t):
        c = c + t
        return c, c
    return jax.lax.scan(f, init, terms)[1]


def _cape_calculation(T, r, pf, ph, table_vals):
    """qe ``CAPE_calculation`` (+ ``CAPE_below_LCL`` / ``CAPE_above_LCL``) for
    one column.  Returns parcel ``Tp``, ``rp``, ``CAPE``, ``kLZB`` (1-based,
    0 = none, as in the oracle) and the FATAL flag."""
    val_min, val_max, table = table_vals
    Rd, Rv, cp, Lv = constants.R_d, constants.R_v, constants.c_pd, constants.L_v
    kappa, pref = constants.kappa, constants.p_ref
    nlev = T.shape[0]
    ks = nlev - 1
    Tv_env = _virtual_temp(T, r)
    T0 = T[ks]
    r0 = r[ks]
    rs = _mixing_ratio(saturation_vapor_pressure(T0), pf[ks])
    saturated = r0 >= rs
    # saturated lowest level: first-order wring-out of the excess vapour
    Tp_sat = T0 + (r0 - rs) / ((cp / (Lv + _SMALL)) + (Lv * rs) / Rv / T0 ** 2)
    rp_sat = _mixing_ratio(saturation_vapor_pressure(Tp_sat), pf[ks])
    # unsaturated: LCL from the lookup table
    theta0 = T[ks] * (pref / pf[ks]) ** kappa
    skip = (~saturated) & (r0 <= 0.0)
    r0_safe = jnp.where(r0 > 0.0, r0, 1.0)
    value = jnp.log(theta0 ** (-1.0 / kappa) * pref * r0_safe / (Rd / Rv + r0_safe))
    tlcl_tab, lut_bad = _get_lcl_temp(value, val_min, val_max, table)
    plcl_tab = pref * (tlcl_tab / theta0) ** (1.0 / kappa)
    lcl_above_top = plcl_tab < pf[0]
    pLCL = jnp.where(lcl_above_top, pf[0], plcl_tab)
    TLCL = jnp.where(lcl_above_top, theta0 * (pLCL / pref) ** kappa, tlcl_tab)
    # kLCL: first level, upward from the surface, with p_full <= pLCL
    n_dry = jnp.sum(jnp.cumprod((pf > pLCL)[::-1].astype(jnp.int32)))
    kLCL = jnp.where(saturated, ks, ks - n_dry)
    # log(p_half(k+1)/p_half(k)); +inf (as the oracle evaluates it) where the
    # top interface pressure is 0, with no gradient through that constant
    top_open = ph[:-1] > 0
    ratio = jnp.where(top_open, ph[1:] / jnp.where(top_open, ph[:-1], 1.0), 1.0)
    dlogph = jnp.where(top_open, jnp.log(ratio), jnp.inf)
    pf_below = jnp.concatenate([pf[1:], pf[-1:]])
    t_min = jnp.asarray(_T_MIN_K, T.dtype)

    def level(carry, k):
        Tp1, rp1, nocape, active, cape, klzb, reset = carry
        below = (~saturated) & (~skip) & (k > kLCL)
        at = (~skip) & (k == kLCL)
        rk = active & (((~saturated) & at) | ((~skip) & (k < kLCL)))
        # dry adiabat below the LCL
        T_dry = theta0 * (pf[k] / pref) ** kappa
        r_dry = _mixing_ratio(saturation_vapor_pressure(T_dry), pf[k])
        # RK2 in ln p from the LCL (at kLCL) or from the level below
        Ts = jnp.where(at, TLCL, Tp1)
        rs_ = jnp.where(at, r0, rp1)
        p_prev = jnp.where(at, pLCL, pf_below[k])
        lr = jnp.log(pf[k] / p_prev)
        a = kappa * Ts + (Lv / cp) * rs_
        b = (Lv ** 2) * rs_ / (cp * Rv * Ts ** 2)
        Th = Ts + a / (1.0 + b) * lr / 2
        rph = _mixing_ratio(saturation_vapor_pressure(Th), (pf[k] + p_prev) / 2)
        a = kappa * Th + (Lv / cp) * rph
        b = (Lv ** 2) * rph / (cp * Rv * Th ** 2)
        Tf = Ts + a / (1.0 + b) * lr
        rpf = _mixing_ratio(saturation_vapor_pressure(Tf), pf[k])
        Tvp = _virtual_temp(Tf, rpf)
        fail = rk & nocape & ((Th < t_min) | (Tf < t_min))
        not_buoyant = Tvp < Tv_env[k]
        buoyant = rk & ~fail & ~not_buoyant
        at_lzb = rk & ~fail & not_buoyant & ~nocape
        cape = jnp.where(buoyant, cape + _times_log_ratio(Rd * (Tvp - Tv_env[k]), dlogph[k]), cape)
        Tp_k = jnp.where(below, T_dry, jnp.where(at & saturated, Tp_sat,
                                                 jnp.where(rk, Tf, T[k])))
        rp_k = jnp.where(below, r_dry, jnp.where(at & saturated, rp_sat,
                                                 jnp.where(rk, rpf, r[k])))
        carry = (Tp_k, rp_k, nocape & ~buoyant, active & ~fail & ~at_lzb, cape,
                 jnp.where(at_lzb, k + 2, klzb), reset | fail)
        return carry, (Tp_k, rp_k)

    zero = jnp.zeros((), T.dtype)
    init = (T0, r0, jnp.asarray(True), jnp.asarray(True), zero,
            jnp.asarray(0, jnp.int32), jnp.asarray(False))
    (_, _, _, _, cape, klzb, reset), (Tp, rp) = jax.lax.scan(
        level, init, jnp.arange(ks, -1, -1, dtype=jnp.int32))
    Tp = Tp[::-1]
    rp = rp[::-1]
    none = reset | skip                          # set_values_if_nocape
    Tp = jnp.where(none, T, Tp)
    rp = jnp.where(none, r, rp)
    cape = jnp.where(none, zero, cape)
    klzb = jnp.where(none, 0, klzb)
    fatal = (~saturated) & (~skip) & lut_bad
    return Tp, rp, cape, klzb, fatal


def _sbm_column(T, q, pf, ph, dt, tau_bm, rhbm, table_vals):
    """qe ``SBM_convection_scheme`` for one column: increments over ``dt``,
    precipitation ``Pq`` [kg/m2 per step] and CAPE."""
    Rd, Rv, cp, Lv, g = (constants.R_d, constants.R_v, constants.c_pd,
                         constants.L_v, constants.g)
    nlev = T.shape[0]
    ks = nlev - 1
    lev = jnp.arange(nlev, dtype=jnp.int32)
    zero = jnp.zeros((), T.dtype)
    r = q / (1.0 - q)
    Tp, rp, cape, klzb, fatal = _cape_calculation(T, r, pf, ph, table_vals)
    conv = cape > 0
    kl0 = klzb - 1                                # 0-based LZB level
    in_layer = conv & (lev >= kl0)
    # set_reference_profiles
    eref = rhbm * pf * rp / (rp + (Rd / Rv))
    rref = _mixing_ratio(eref, pf)
    qref = rref / (1.0 + rref)
    top = lev < jnp.maximum(klzb - 1, 1)          # levels 1..max(kLZB-1,1) take model values
    Tref = jnp.where(top, T, Tp)
    qref = jnp.where(top, q, qref)
    # Pq_calculation / Pt_calculation
    dq = jnp.where(in_layer, -(q - qref) * dt / tau_bm, zero)
    dT = jnp.where(in_layer, -(T - Tref) * dt / tau_bm, zero)
    dph_up = ph[:-1] - ph[1:]                     # p_half(k) - p_half(k+1)
    dph = ph[1:] - ph[:-1]                        # p_half(k+1) - p_half(k)
    Pq = _seq_cumsum(zero, jnp.where(in_layer, dq * dph_up, zero))[-1] / g
    Pt = _seq_cumsum(zero, jnp.where(in_layer, (cp / (Lv + _SMALL)) * dT * dph, zero))[-1] / g
    deep = conv & (Pq > 0) & (Pt > 0)
    qts = deep & (Pq > Pt)
    tsh = deep & ~(Pq > Pt)
    shallow = conv & ~deep & (Pt > 0)
    # deep, do_change_time_scale_deepconv
    invtau_q = Pt / jnp.where(qts, Pq, 1.0) / tau_bm
    dq_qts = jnp.where(in_layer, tau_bm * invtau_q * dq, dq)
    # deep, do_change_Tref_deepconv
    i_lzb = jnp.clip(kl0, 0, ks)
    dk = -_seq_cumsum(zero, jnp.where(in_layer, (dT + (Lv / cp) * dq) * dph, zero))[-1]
    dk = dk / (ph[ks + 1] - ph[i_lzb])
    dT_tsh = jnp.where(in_layer, dT + dk, dT)
    # shallow: level_of_zero_precip
    S = _seq_cumsum(Pq, jnp.where(in_layer, -(dq * dph_up / g), zero))
    first = jnp.argmax(in_layer & ~(S < 0)).astype(jnp.int32)
    started = Pq < 0
    k_top = jnp.where(~started, kl0 - 1,
                      jnp.where(jnp.any(in_layer & ~(S < 0)), first, ks))
    i_top = jnp.clip(k_top, 0, ks)
    S_top = jnp.where(~started, Pq, S[i_top])
    found = S_top > 0
    dT_sh = jnp.where((lev >= kl0) & (lev <= k_top - 1) & (k_top > kl0), zero, dT)
    dq_sh = jnp.where((lev >= kl0) & (lev <= k_top - 1) & (k_top > kl0), zero, dq)
    # found: change_Tref_LZB_shallowconv
    den = dq_sh[i_top] * (ph[i_top + 1] - ph[i_top])
    c = S_top * g / jnp.where(shallow & found, den, 1.0)
    at_top = lev == k_top
    dq_f = jnp.where(at_top, dq_sh * c, dq_sh)
    dT_f = jnp.where(at_top, dT_sh * c, dT_sh)
    dk_s = _seq_cumsum(zero, jnp.where(lev >= k_top, dT_f * dph_up, zero))[-1]
    dk_s = dk_s / (ph[ks + 1] - ph[i_top])
    dT_f = jnp.where((lev >= k_top) & (k_top != ks), dT_f + dk_s, dT_f)
    # not found: set_profiles_to_full_model_values
    clear = jnp.where(k_top == kl0, lev == ks, (lev >= kl0) & (lev <= k_top))
    dT_nf = jnp.where(clear, zero, dT_sh)
    dq_nf = jnp.where(clear, zero, dq_sh)
    dT_out = jnp.where(qts, dT, jnp.where(tsh, dT_tsh, jnp.where(
        shallow, jnp.where(found, dT_f, dT_nf), zero)))
    dq_out = jnp.where(qts, dq_qts, jnp.where(tsh, dq, jnp.where(
        shallow, jnp.where(found, dq_f, dq_nf), zero)))
    precip = jnp.where(qts, Pt, jnp.where(tsh, Pq, zero))
    # the oracle stops (FATAL) or reads outside its arrays: NaN, not a value
    poison = fatal | (conv & (klzb == 0))
    nan = jnp.asarray(jnp.nan, T.dtype)
    return (jnp.where(poison, nan, dT_out), jnp.where(poison, nan, dq_out),
            jnp.where(poison, nan, precip), jnp.where(poison, nan, cape))


def sbm_convection(
    T: jax.Array,
    q_v: jax.Array,
    p_full: jax.Array,
    p_half: jax.Array,
    dt: float,
    config: SBMConfig = SBMConfig(),
) -> ConvectionOutput:
    """Simplified Betts-Miller convection tendencies (Isca qe_moist_convection).

    Parameters
    ----------
    T : jax.Array
        Temperature at full levels [K], shape (ncol, nlev), level 0 = top.
    q_v : jax.Array
        Water vapour specific humidity [kg/kg], shape (ncol, nlev).
    p_full : jax.Array
        Pressure at full levels [Pa], shape (ncol, nlev).
    p_half : jax.Array
        Pressure at half levels [Pa], shape (ncol, nlev+1).
    dt : float
        Model time step [s] (the oracle's increments are formed over ``dt``
        and returned per second).
    config : SBMConfig
        ``tau_c`` = ``tau_bm``, ``rh_ref`` = ``rhbm``; ``cape_threshold`` and
        ``smooth_trigger_sharpness`` set the CAPE trigger (oracle: 0, hard).
        Scalars or per-column arrays of shape (ncol,).

    Returns
    -------
    ConvectionOutput
    """
    sharp = config.cloud_mask_sharpness
    sharp_default = SBMConfig._field_defaults["cloud_mask_sharpness"]
    if (not isinstance(sharp, jax.core.Tracer)
            and np.any(np.asarray(sharp) != sharp_default)):
        raise ValueError(
            "SBMConfig.cloud_mask_sharpness belonged to the replaced per-level "
            "T_moist >= T layer mask; the Isca qe_moist_convection port has no such "
            "mask (its layer is kLZB..surface), so the field is inert and must stay "
            f"at its default {SBMConfig._field_defaults['cloud_mask_sharpness']}")
    ncol, nlev = T.shape
    dtype = jnp.result_type(T, q_v, p_full, p_half)
    T, q_v, p_full, p_half = (jnp.asarray(x, dtype) for x in (T, q_v, p_full, p_half))
    tau = jnp.broadcast_to(jnp.asarray(config.tau_c, dtype), (ncol,))
    rh = jnp.broadcast_to(jnp.asarray(config.rh_ref, dtype), (ncol,))
    val_min, val_max, table = _lcl_temp_table()
    table_vals = (jnp.asarray(val_min, dtype), jnp.asarray(val_max, dtype),
                  jnp.asarray(table, dtype))
    dT, dq, precip, cape = jax.vmap(
        lambda t, qq, pf, ph, ta, rr: _sbm_column(t, qq, pf, ph, dt, ta, rr, table_vals)
    )(T, q_v, p_full, p_half, tau, rh)
    if isinstance(sharp, jax.core.Tracer):
        # traced config (jit argument): the check above cannot raise, so a
        # non-default value poisons the outputs instead of being ignored
        cape = jnp.where(jnp.any(sharp != sharp_default), jnp.nan, cape)
    trigger = cape_trigger(cape, config.cape_threshold, config.smooth_trigger_sharpness)
    dT_dt = trigger[:, None] * (dT / dt)
    dq_v_dt = trigger[:, None] * (dq / dt)
    precip_rate = trigger * (precip / dt)            # [kg/m2/s]
    # Condensate source: local drying rescaled so its column integral is the
    # oracle precipitation (AD-safe divide, issue #249).
    dp = p_half[:, 1:] - p_half[:, :-1]
    local_cond = jnp.maximum(-dq_v_dt, 0.0)
    col_local_cond = jnp.sum(local_cond * dp / constants.g, axis=1, keepdims=True)
    dq_c_conv_dt = local_cond * safe_divide(precip_rate[:, None], col_local_cond, eps=1e-20)
    return ConvectionOutput(
        dT_dt=dT_dt,
        dq_v_dt=dq_v_dt,
        dq_c_conv_dt=dq_c_conv_dt,
        cape=cape,
        convective_mask=trigger,
        precip_frozen_sfc=jnp.zeros_like(cape),  # oracle snow = 0 (liquid only)
    )
