# 2. core MOST kernel, large_yeager vs aerobulk ncar
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("heights", ["zt10_zu10", "zt2_zu10"])
def test_core_large_yeager_matches_aerobulk_ncar(oracle, heights):
    d, inp = oracle["d"], oracle["inp"]
    if heights == "zt10_zu10":
        theta, rho, kw = oracle["theta10"], oracle["rho10"], {}
    else:
        theta, rho = oracle["theta2"], oracle["rho2"]
        kw = dict(z_t=2.0, z_q=2.0)
    tau_x, tau_y, sh, lh, _ = compute_most_fluxes(
        jnp.asarray(inp["u"]), jnp.asarray(inp["v"]), jnp.asarray(theta),
        jnp.asarray(inp["q_air"]), jnp.asarray(oracle["theta_s"]),
        jnp.asarray(oracle["ssq"]), jnp.asarray(rho), z_ref=10.0,
        scheme="large_yeager", n_iter=5,
        L_latent=jnp.asarray(oracle["L_sst"]), **kw)
    tag = f"ncar_{heights}"
    m = oracle["ly_mask"]
    # legoESM core convention: heat positive-up => compare to -aerobulk.
    _gate(f"ly {heights} tau_x", tau_x, -d[f"{tag}_taux"], _FLOOR_TAU,
          5e-3, 2e-2, 1e-1, m)
    _gate(f"ly {heights} tau_y", tau_y, -d[f"{tag}_tauy"], _FLOOR_TAU,
          5e-3, 2e-2, 1e-1, m)
    _gate(f"ly {heights} sh", sh, -d[f"{tag}_qh"], _FLOOR_HEAT,
          3e-2, 6e-2, 1e-1, m)
    _gate(f"ly {heights} lh", lh, -d[f"{tag}_ql"], _FLOOR_HEAT,
          1e-2, 7e-2, 2e-1, m)


