# 4. Non-vacuity self-test (guardrail doctrine: every gate ships a
#    synthetic-violation check proving it can actually fail).
# ---------------------------------------------------------------------------

def test_gate_fails_on_synthetic_violation(oracle):
    d = oracle["d"]
    ref = -d["coare3p0_zt10_zu10_taux"]
    corrupted = ref * 1.10  # a 10% systematic bias must trip the median gate
    with pytest.raises(AssertionError):
        _gate("synthetic", corrupted, ref, _FLOOR_TAU,
              5e-3, 3e-2, 1e-1, np.ones_like(ref, dtype=bool))


