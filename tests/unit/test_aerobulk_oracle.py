# 1. OMIP NEMO-port ncar vs aerobulk ncar
# ---------------------------------------------------------------------------

def test_omip_ncar_matches_aerobulk(oracle):
    d, inp = oracle["d"], oracle["inp"]
    out = air_sea_fluxes(
        u10=jnp.asarray(inp["u"]), v10=jnp.asarray(inp["v"]),
        T_air_K=jnp.asarray(inp["t_air"]), q_air=jnp.asarray(inp["q_air"]),
        T_sfc_K=jnp.asarray(inp["sst"]), slp_Pa=jnp.asarray(inp["slp"]))
    allpts = np.ones_like(oracle["W"], dtype=bool)
    # OMIP port keeps NEMO conventions: heat positive-down (= aerobulk),
    # stress = ocean reaction (-aerobulk), evap positive when evaporating
    # (aerobulk negative).
    _gate("omip tau_x", out[0], -d["ncar_zt10_zu10_taux"], _FLOOR_TAU,
          1e-3, 1e-3, 5e-2, allpts)
    _gate("omip tau_y", out[1], -d["ncar_zt10_zu10_tauy"], _FLOOR_TAU,
          1e-3, 1e-3, 5e-2, allpts)
    _gate("omip sh", out[2], d["ncar_zt10_zu10_qh"], _FLOOR_HEAT,
          2e-2, 3e-2, 6e-2, allpts)
    _gate("omip lh", out[3], d["ncar_zt10_zu10_ql"], _FLOOR_HEAT,
          5e-3, 1e-2, 4e-2, allpts)
    _gate("omip evap", out[4], -d["ncar_zt10_zu10_evap"], 1e-6,
          1e-3, 1e-3, 3e-2, allpts)


