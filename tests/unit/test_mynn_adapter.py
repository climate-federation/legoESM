"""turbulence=mynn25 host adapter for the WRF v4.8.0 MYNN-EDMF port.

The oracle fixture (tests/atmosphere/oracle_fixtures/mynn25.npz, generated by
running WRF's module_bl_mynnedmf.F90) is rebuilt in the HOST layout (top-down,
T instead of theta, packed (qke, qsq, el) carry) and must come back through the
adapter at the oracle test's tolerance and metric (votes N1, N5, N9, N11).
"""
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from legoesm.atmosphere.physics.turbulence.config import (
    MYNN25Config, SurfaceLayerConfig)
from legoesm.atmosphere.physics.turbulence.mynn_wrf_adapter import (
    cold_start_carry, mynn_wrf_columns, mynn_wrf_turbulence)
from legoesm.atmosphere.physics.turbulence.mynnedmf_wrf import mynnedmf_column
from legoesm.atmosphere.physics.turbulence.surface_layer import (
    compute_surface_fluxes, surface_fluxes_at_lowest_level,
    surface_moisture_flux)
from legoesm.atmosphere.physics._shared import (
    compute_heights_from_sigma, compute_rho, exner_function)

jax.config.update("jax_enable_x64", True)

TOL = 1.0e-10  # the oracle test's tolerance (vote N11)
FIXTURE = (Path(__file__).resolve().parents[1] / "atmosphere" / "oracle_fixtures"
           / "mynn25.npz")
GROUPS = ("l32", "l65")


@pytest.fixture(scope="module")
def fx():
    return dict(np.load(FIXTURE))


def _err(ours, ref):
    # the oracle test's metric: max |ours - ref| / max |ref| (codex N11)
    ref = np.asarray(ref, np.float64)
    ours = np.asarray(ours, np.float64).reshape(ref.shape)
    assert np.all(np.isfinite(ours)) and np.all(np.isfinite(ref))
    return float(np.max(np.abs(ours - ref)) / max(np.max(np.abs(ref)), 1e-300))


def _down(a):
    return jnp.asarray(a)[:, ::-1]


def _host(fx, g, s):
    """Fixture inputs in host layout (top-down level arrays)."""
    p = f"{g}_s{s}_in_"
    L = {k: _down(fx[p + k]) for k in
         "dz u v w tk p exner rho sqv sqc sqi qke qsq el".split()}
    S = {k: jnp.asarray(fx[p + k][:, 0]) for k in
         "xland ps ts ust hfx qfx wspd dt dx".split()}
    carry = jnp.stack([L["qke"], L["qsq"], L["el"]], axis=1)
    return L, S, carry


def _run(fx, g, s, *, no_ice=False):
    L, S, carry = _host(fx, g, s)
    return mynn_wrf_columns(
        L["dz"], L["u"], L["v"], L["w"], L["tk"], L["p"], L["exner"],
        L["rho"], L["sqv"], L["sqc"], None if no_ice else L["sqi"], carry,
        S["xland"], S["ps"], S["ts"], S["ust"], S["hfx"], S["qfx"],
        S["wspd"], S["dt"], S["dx"], initflag=(s == 1))


@pytest.mark.parametrize("g", GROUPS)
@pytest.mark.parametrize("s", (1, 3))
def test_adapter_reproduces_oracle_in_host_layout(fx, g, s):
    m, carry = _run(fx, g, s)
    o = f"{g}_s{s}_out_"
    exner = fx[f"{g}_s{s}_in_exner"]
    pairs = {
        "du": (m["du"], fx[o + "du"]), "dv": (m["dv"], fx[o + "dv"]),
        "dqv": (m["dqv"], fx[o + "dqv"]), "dqc": (m["dqc"], fx[o + "dqc"]),
        "dqi": (m["dqi"], fx[o + "dqi"]), "km": (m["km"], fx[o + "km"]),
        "kh": (m["kh"], fx[o + "kh"]),
        # M9: dT/dt = dth/dt * exner
        "dT": (m["dT"], fx[o + "dth"] * exner),
        "qke": (carry[:, 0], fx[o + "qke"]), "qsq": (carry[:, 1], fx[o + "qsq"]),
        "el": (carry[:, 2], fx[o + "el"]),
    }
    worst = {k: _err(np.asarray(a)[:, ::-1], ref) for k, (a, ref) in pairs.items()}
    worst["pblh"] = _err(m["pblh"], fx[o + "pblh"][:, 0])
    assert max(worst.values()) <= TOL, worst


def test_no_ice_lane_drops_an_exactly_zero_ice_tendency(fx):
    """N6: without an ice tracer sqi = 0 and dqi is dropped; that is only
    lossless because the port's ice tendency is exactly 0 at zero ice."""
    for g in GROUPS:
        m, _ = _run(fx, g, 3, no_ice=True)
        assert m["dqi"] is None
        p = f"{g}_s3_in_"
        args = [jnp.asarray(fx[p + k]) for k in
                "dz u v w th tk p exner rho sqv sqc".split()]
        args.append(jnp.zeros_like(args[-1]))
        args += [jnp.asarray(fx[p + k]) for k in ("qke", "qsq", "el")]
        args += [jnp.asarray(fx[p + k][:, 0]) for k in
                 "xland ps ts ust hfx qfx wspd dt dx".split()]
        out = mynnedmf_column(*args)
        assert np.all(np.asarray(out.dqi) == 0.0)


