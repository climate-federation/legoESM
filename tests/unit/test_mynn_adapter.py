# --- the lane kernel: one bulk exchange feeds the port (M4/M5/M6/M11/N5) ---

def _lane_column(fx, g="l32", s=3):
    """A host column on a pure sigma grid built from the fixture state."""
    L, S, carry = _host(fx, g, s)
    T, q_v = L["tk"], L["sqv"]
    p_s = S["ps"]
    nlev = T.shape[1]
    # half-level pressures between the fixture's full levels (top-down)
    p = L["p"]
    p_mid = 0.5 * (p[:, 1:] + p[:, :-1])
    p_half = jnp.concatenate(
        [0.5 * p[:, :1], p_mid, p_s[:, None]], axis=1)
    z_full, z_half = compute_heights_from_sigma(T, p_half, q_v=q_v)
    rho = compute_rho(T, p, q_v=q_v)
    assert z_half.shape == (T.shape[0], nlev + 1)
    return L, S, carry, p_half, z_full, z_half, rho


def _kernel(fx, cfg, **kw):
    L, S, carry, p_half, z_full, z_half, rho = _lane_column(fx)
    args = dict(w=L["w"], q_c=L["sqc"], q_i=L["sqi"],
                cell_area=S["dx"] ** 2, land_frac=(S["xland"] < 1.5) * 1.0,
                initflag=False)
    args.update(kw)
    q_sfc = L["sqv"][:, -1] * 1.1
    return (mynn_wrf_turbulence(
        L["u"], L["v"], L["tk"], L["sqv"], carry, L["p"], p_half, z_full,
        z_half, S["ts"], q_sfc, rho, 60.0, cfg, **args),
        (L, S, carry, p_half, z_full, z_half, rho, q_sfc))


@pytest.mark.parametrize("scheme", ("constant", "coare3"))
def test_kernel_feeds_the_port_one_bulk_exchange(fx, scheme):
    cfg = MYNN25Config(surface=SurfaceLayerConfig(bulk_scheme=scheme))
    (out, carry_new), (L, S, carry, p_half, z_full, z_half, rho, q_sfc) = (
        _kernel(fx, cfg))
    _, _, shf, lhf, ust, wspd = surface_fluxes_at_lowest_level(
        L["u"][:, -1], L["v"][:, -1], L["tk"][:, -1], L["sqv"][:, -1],
        S["ts"], q_sfc, rho[:, -1], cfg.surface,
        z_full[:, -1] - z_half[:, -1], return_wind_speed=True)
    qfx = surface_moisture_flux(cfg.surface, lhf, S["ts"])
    exner = exner_function(L["p"])
    m, c_ref = mynn_wrf_columns(
        z_half[:, :-1] - z_half[:, 1:], L["u"], L["v"], L["w"], L["tk"],
        L["p"], exner, rho, L["sqv"], L["sqc"], L["sqi"], carry,
        jnp.asarray(S["xland"]), p_half[:, -1], S["ts"], ust, shf, qfx, wspd,
        60.0, S["dx"], initflag=False)
    np.testing.assert_array_equal(out.dT_dt, m["dT"])
    np.testing.assert_array_equal(out.dq_c_dt, m["dqc"])
    np.testing.assert_array_equal(out.dq_i_dt, m["dqi"])
    np.testing.assert_array_equal(carry_new, c_ref)
    np.testing.assert_array_equal(out.ustar, ust)
    np.testing.assert_array_equal(out.evap_sfc, qfx)
    np.testing.assert_array_equal(out.h_pbl, m["pblh"])
    # the fixture has both land and water columns: the xland map is exercised
    assert set(np.unique(np.asarray(S["xland"]))) == {1.0, 2.0}


def test_kernel_without_land_fraction_is_all_water(fx):
    cfg = MYNN25Config(surface=SurfaceLayerConfig())
    (o_none, _), _ = _kernel(fx, cfg, land_frac=None)
    (o_water, _), (_, S, *_r) = _kernel(
        fx, cfg, land_frac=jnp.zeros_like(fx["l32_s3_in_ts"][:, 0]))
    np.testing.assert_array_equal(o_none.dT_dt, o_water.dT_dt)


@pytest.mark.parametrize("missing", ("w", "q_c", "cell_area"))
def test_kernel_refuses_missing_inputs(fx, missing):
    cfg = MYNN25Config(surface=SurfaceLayerConfig())
    with pytest.raises(ValueError, match=missing):
        _kernel(fx, cfg, **{missing: None})


def test_kernel_refuses_a_prescribed_stress(fx):
    """N8: a prescribed stress rebuilds u* apart from the bulk wind speed."""
    cfg = MYNN25Config(surface=SurfaceLayerConfig(prescribed_tau_x_pa=0.1))
    with pytest.raises(ValueError, match="prescribed surface stress"):
        _kernel(fx, cfg)


# --- return_wind_speed leaves every default path unchanged (N7) ---

@pytest.mark.parametrize("scheme", ("constant", "most", "coare3",
                                    "large_yeager", "large_yeager_cesm"))
def test_return_wind_speed_appends_only(scheme):
    n = 5
    u = jnp.linspace(-8.0, 9.0, n)
    v = jnp.linspace(3.0, -2.0, n)
    T = jnp.full(n, 290.0)
    q = jnp.full(n, 8e-3)
    Ts = jnp.linspace(288.0, 294.0, n)
    qs = jnp.full(n, 1.2e-2)
    rho = jnp.full(n, 1.2)
    cfg = SurfaceLayerConfig(bulk_scheme=scheme)
    kw = {"t_bot": T} if scheme == "large_yeager_cesm" else {}
    base = compute_surface_fluxes(u, v, T, q, Ts, qs, rho, cfg, **kw)
    more = compute_surface_fluxes(u, v, T, q, Ts, qs, rho, cfg,
                                  return_wind_speed=True, **kw)
    assert len(base) == 5 and len(more) == 6
    for a, b in zip(base, more[:5]):
        np.testing.assert_array_equal(a, b)
    wspd = np.asarray(more[5])
    assert np.all(wspd >= np.sqrt(np.asarray(u) ** 2 + np.asarray(v) ** 2) - 1e-12)
    if scheme == "constant":
        # the pair belongs to one exchange: u* = sqrt(Cd) * wspd
        np.testing.assert_allclose(more[4], np.sqrt(cfg.Cd_neutral) * wspd,
                                   rtol=1e-14)
