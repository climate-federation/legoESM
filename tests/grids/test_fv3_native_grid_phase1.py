# 4. CD-grid metric family follows provenance (no aspect-ratio inference)
# ---------------------------------------------------------------------------
class TestCDGridProvenance:
    def test_cdgrid_auto_follows_ed_provenance_at_n2(self):
        # n=2 is the case the old aspect-ratio inference could NOT distinguish
        # (both forms have aspect ~1.0 there) — provenance must decide.
        g_ed = create_cubed_sphere(2, dtype=np.float64, gnomonic="ed")
        cd_auto = create_cubed_sphere_cdgrid(g_ed, metric_dtype=np.float64)
        cd_expl = create_cubed_sphere_cdgrid(
            g_ed, metric_dtype=np.float64, gnomonic="ed")
        assert np.array_equal(
            np.asarray(cd_auto.dxc), np.asarray(cd_expl.dxc))
        assert np.array_equal(
            np.asarray(cd_auto.rarea_c), np.asarray(cd_expl.rarea_c))

    def test_cdgrid_auto_distinguishes_forms_at_n2(self):
        g_ed = create_cubed_sphere(2, dtype=np.float64, gnomonic="ed")
        g_eq = create_cubed_sphere(2, dtype=np.float64)
        cd_ed = create_cubed_sphere_cdgrid(g_ed, metric_dtype=np.float64)
        cd_eq = create_cubed_sphere_cdgrid(g_eq, metric_dtype=np.float64)
        assert not np.allclose(
            np.asarray(cd_ed.dxc), np.asarray(cd_eq.dxc), rtol=1e-12)

    def test_cdgrid_contradicting_request_raises(self):
        g_ed = create_cubed_sphere(4, dtype=np.float64, gnomonic="ed")
        g_eq = create_cubed_sphere(4, dtype=np.float64)
        with pytest.raises(ValueError, match="provenance"):
            create_cubed_sphere_cdgrid(g_ed, gnomonic="equiangular")
        with pytest.raises(ValueError, match="provenance"):
            create_cubed_sphere_cdgrid(g_eq, gnomonic="ed")


