"""Phase 1 of the FV3-native cubed-sphere effort: explicit ED grid selection.

Pins the three phase-1 guarantees:

1. ORACLE — the Python ``gnomonic_grids(im, grid_type=0)`` face panel matches
   the verbatim-extracted FV3 Fortran ``gnomonic_grids`` output (quad-precision
   ENABLE_QUAD_PRECISION build) at C8 and C36 to near machine precision.
   Fixture: ``tests/grids/fixtures/fv3_gnomonic_ed_oracle.npz`` regenerated by
   ``scripts/validate/fv3_native/gen_oracle.sh`` from
   ``fv3_gnomonic_oracle.f90`` (source-derived, not hand-tuned).

2. PROVENANCE — ``CubedSphereGrid`` carries immutable, static grid provenance
   (``gnomonic_form``, ``fv3_grid_type``) as pytree aux_data (never a traced
   leaf, never inferred from dx/dy aspect ratios), the FV3-native factory
   ``create_fv3_native_cubed_sphere`` selects gnomonic_ed (FV3 grid_type=0),
   and ``create_cubed_sphere_cdgrid`` derives its metric family from that
   provenance — including at n=2 where the old aspect-ratio inference was
   provably blind.

3. LEGACY — the historic equiangular grid remains the untouched default of
   ``create_cubed_sphere`` and stays geometrically distinct from ED
   (~231 km max cell-centre separation at C36 per the fidelity audit).

Phase 1 does NOT claim full FV3 fidelity: metrics (phase 2), duogrid halos
(phase 3), and the forward-backward SW core (phase 4) remain non-native.
"""
from __future__ import annotations

import pathlib
import warnings

import numpy as np
import pytest

jax = pytest.importorskip("jax")
jax.config.update("jax_enable_x64", True)

from legoesm.grids.cubed_sphere import (  # noqa: E402
    CubedSphereGrid,
    create_cubed_sphere,
    gnomonic_grids,
)
from legoesm.grids.cubed_sphere_cdgrid import (  # noqa: E402
    create_cubed_sphere_cdgrid,
)
from legoesm import constants  # noqa: E402

R = float(constants.R_earth)

_FIXTURE = pathlib.Path(__file__).parent / "fixtures" / "fv3_gnomonic_ed_oracle.npz"


def _angdiff(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """Angular difference |a-b| folded into [0, pi] (robust at the 0/2pi seam)."""
    d = np.abs(np.asarray(a) - np.asarray(b)) % (2.0 * np.pi)
    return np.minimum(d, 2.0 * np.pi - d)


# ---------------------------------------------------------------------------
# 1. Source-derived oracle: Python port == FV3 Fortran gnomonic_grids
# ---------------------------------------------------------------------------
class TestFV3SourceOracle:
    @pytest.mark.parametrize("im", [8, 36])
    def test_gnomonic_ed_matches_fv3_fortran(self, im):
        d = np.load(_FIXTURE)
        lon_ref = d[f"lon_c{im}"]
        lat_ref = d[f"lat_c{im}"]
        lon, lat = gnomonic_grids(im, grid_type=0)
        lon = np.asarray(lon)
        lat = np.asarray(lat)
        assert lon.shape == (im + 1, im + 1)
        assert _angdiff(lon, lon_ref).max() < 1e-13
        assert np.abs(lat - lat_ref).max() < 1e-13

    def test_gnomonic_ed_c1_degenerate_corners(self):
        # C1 exercises the empty-interior-loop edge of the construction.
        d = np.load(_FIXTURE)
        lon, lat = gnomonic_grids(1, grid_type=0)
        assert _angdiff(np.asarray(lon), d["lon_c1"]).max() < 1e-13
        assert np.abs(np.asarray(lat) - d["lat_c1"]).max() < 1e-13

    @pytest.mark.parametrize("im", [1, 8, 36])
    def test_make_fv3_native_grid_matches_fv3_mirror_grid(self, im):
        # The full 6-face assembly (gnomonic_grids + mirror_grid pipeline of
        # fv_grid_tools init_grid) — not just the face-1 panel — must match
        # the Fortran oracle in FV3 face numbering, face by face.  C1 (npx=2,
        # even) exercises the no-pole/dateline-forcing branch; C8/C36 (odd
        # npx) exercise the forcing masks.  Longitudes are compared RAW (not
        # mod 2π) away from the exact poles, pinning the FV3 [-π, π] atan2
        # range contract of mirror_grid_faces — an unintended renormalization
        # must fail here.
        from legoesm.grids.cubed_sphere import make_fv3_native_grid

        d = np.load(_FIXTURE)
        lon6, lat6 = make_fv3_native_grid(im, grid_type=0)
        lon6 = np.asarray(lon6)
        lat6 = np.asarray(lat6)
        assert lon6.shape == (6, im + 1, im + 1)
        # longitude is meaningless at the exact poles — mask |lat|=pi/2 nodes
        pole = np.abs(np.abs(d[f"lat6_c{im}"]) - np.pi / 2) < 1e-12
        dlon_raw = np.abs(lon6 - d[f"lon6_c{im}"])
        assert np.where(pole, 0.0, dlon_raw).max() < 1e-13
        assert np.abs(lat6 - d[f"lat6_c{im}"]).max() < 1e-13

    @pytest.mark.parametrize("im", [8, 36])
    def test_factory_centres_match_fv3_agrid_cloud(self, im):
        # End-to-end: the PUBLIC factory's cell centres must be the FV3
        # cell_center2 A-grid centres.  legoESM renumbers/rotates faces into
        # create_cubed_sphere's layout, so compare as a global point cloud
        # (bijective nearest-neighbour match on the unit sphere).
        from scipy.spatial import cKDTree

        from legoesm.grids.cubed_sphere import create_fv3_native_cubed_sphere

        d = np.load(_FIXTURE)
        g = create_fv3_native_cubed_sphere(im, dtype=np.float64)

        def cloud(lon, lat):
            lon = np.asarray(lon, dtype=np.float64).ravel()
            lat = np.asarray(lat, dtype=np.float64).ravel()
            return np.stack([
                np.cos(lat) * np.cos(lon),
                np.cos(lat) * np.sin(lon),
                np.sin(lat),
            ], axis=1)

        ours = cloud(g.lon, g.lat)
        ref = cloud(d[f"agrid_lon_c{im}"], d[f"agrid_lat_c{im}"])
        assert ours.shape == ref.shape
        dist_fwd, idx = cKDTree(ref).query(ours)
        assert dist_fwd.max() < 1e-12
        # bijection: every reference centre is hit exactly once
        assert len(np.unique(idx)) == len(ref)


