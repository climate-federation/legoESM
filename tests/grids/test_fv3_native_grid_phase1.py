# 5. Legacy equiangular stays distinct and default
# ---------------------------------------------------------------------------
class TestLegacyDistinct:
    def test_c36_centres_differ_by_hundreds_of_km(self):
        g_eq = create_cubed_sphere(36, dtype=np.float64)
        g_ed = create_cubed_sphere(36, dtype=np.float64, gnomonic="ed")
        lon_a, lat_a = np.asarray(g_eq.lon), np.asarray(g_eq.lat)
        lon_b, lat_b = np.asarray(g_ed.lon), np.asarray(g_ed.lat)
        # great-circle separation of matching cell centres
        s = np.sin(lat_a) * np.sin(lat_b) + np.cos(lat_a) * np.cos(lat_b) * np.cos(lon_a - lon_b)
        sep_km = R * np.arccos(np.clip(s, -1.0, 1.0)) / 1e3
        # audit: up to ~231 km at C36; require the same order, not the exact value
        assert sep_km.max() > 100.0
        assert sep_km.max() < 400.0

    def test_c8_coordinates_distinct(self):
        g_eq = create_cubed_sphere(8, dtype=np.float64)
        g_ed = create_cubed_sphere(8, dtype=np.float64, gnomonic="ed")
        assert not np.allclose(np.asarray(g_eq.lat), np.asarray(g_ed.lat), atol=1e-6)


