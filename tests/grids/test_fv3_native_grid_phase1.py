# 3. FV3-native factory entry point
# ---------------------------------------------------------------------------
class TestFV3NativeFactory:
    def test_factory_exists_and_selects_ed(self):
        from legoesm.grids.cubed_sphere import create_fv3_native_cubed_sphere

        g = create_fv3_native_cubed_sphere(8, dtype=np.float64)
        assert isinstance(g, CubedSphereGrid)
        assert g.gnomonic_form == "ed"
        assert g.fv3_grid_type == 0
        # identical coordinates to the explicit gated path
        g_ref = create_cubed_sphere(8, dtype=np.float64, gnomonic="ed")
        assert np.array_equal(np.asarray(g.lon), np.asarray(g_ref.lon))
        assert np.array_equal(np.asarray(g.lat), np.asarray(g_ref.lat))

    def test_factory_rejects_schmidt_stretch(self):
        # Schmidt/stretch args are deliberately NOT in the FV3-native factory
        # signature (unsupported on the ED path) — passing one fails loudly.
        from legoesm.grids.cubed_sphere import create_fv3_native_cubed_sphere

        with pytest.raises(TypeError):
            create_fv3_native_cubed_sphere(8, stretch_fac=3.0)

    def test_gated_path_still_rejects_schmidt_on_ed(self):
        with pytest.raises(ValueError):
            create_cubed_sphere(8, gnomonic="ed", stretch_fac=3.0)


