# 2. Static provenance on the grid object
# ---------------------------------------------------------------------------
class TestGridProvenance:
    def test_default_grid_is_equiangular_with_provenance(self):
        g = create_cubed_sphere(8, dtype=np.float64)
        assert g.gnomonic_form == "equiangular"
        assert g.fv3_grid_type == 2

    def test_ed_grid_carries_fv3_grid_type_0(self):
        g = create_cubed_sphere(8, dtype=np.float64, gnomonic="ed")
        assert g.gnomonic_form == "ed"
        assert g.fv3_grid_type == 0

    def test_provenance_is_aux_data_not_leaf(self):
        g = create_cubed_sphere(8, dtype=np.float64, gnomonic="ed")
        leaves = jax.tree_util.tree_leaves(g)
        assert not any(isinstance(leaf, str) for leaf in leaves)
        # tree round-trip preserves provenance (aux_data path)
        g2 = jax.tree_util.tree_map(lambda x: x, g)
        assert g2.gnomonic_form == "ed"
        assert g2.fv3_grid_type == 0

    def test_provenance_participates_in_treedef(self):
        g_ed = create_cubed_sphere(8, dtype=np.float64, gnomonic="ed")
        g_eq = create_cubed_sphere(8, dtype=np.float64)
        td_ed = jax.tree_util.tree_structure(g_ed)
        td_eq = jax.tree_util.tree_structure(g_eq)
        assert td_ed != td_eq  # distinct static signature -> no silent mixing

    def test_replace_preserves_provenance(self):
        g = create_cubed_sphere(8, dtype=np.float64, gnomonic="ed")
        g2 = g._replace(radius=2.0 * g.radius)
        assert g2.gnomonic_form == "ed"
        assert g2.fv3_grid_type == 0

    def test_single_face_panel_forwards_ed_provenance(self):
        # ED request makes this non-vacuous: the field defaults would report
        # equiangular/2 if the panel builder failed to forward provenance.
        from legoesm.grids.cubed_sphere import create_cubed_sphere_panel

        panel = create_cubed_sphere_panel(8, dtype=np.float64, gnomonic="ed")
        assert panel.gnomonic_form == "ed"
        assert panel.fv3_grid_type == 0
        # legacy default unchanged
        panel_eq = create_cubed_sphere_panel(8, dtype=np.float64)
        assert panel_eq.gnomonic_form == "equiangular"

    def test_small_earth_scaling_preserves_ed_provenance(self):
        # codex P1: the small-Earth rebuild silently returned an equiangular
        # grid for an ED input (coordinates AND provenance both wrong).
        from legoesm.grids.cubed_sphere import apply_small_earth_scaling

        g_ed = create_cubed_sphere(8, dtype=np.float64, gnomonic="ed")
        g_small = apply_small_earth_scaling(g_ed, 10.0)
        assert g_small.gnomonic_form == "ed"
        assert g_small.fv3_grid_type == 0
        # ED node distribution actually survives (not just the label):
        # lon/lat are radius-independent, so they must match the unscaled grid.
        assert np.allclose(
            np.asarray(g_small.lat), np.asarray(g_ed.lat), atol=1e-12)


