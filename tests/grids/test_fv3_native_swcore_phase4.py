def _compute_slices(res, ng, shape):
    """Fortran compute-domain slices for a (cell|node)-shaped axis."""
    def sl(nlen):
        extra = nlen - (res + 2 * ng)   # 0 cell axis, 1 node axis
        return slice(ng, ng + res + extra)
    return tuple(sl(s) for s in shape)


