@pytest.mark.parametrize("field", ["delpc", "ptc", "uc", "vc",
                                   "ut", "vt", "ua", "va", "divg_d"])
def test_c_sw_matches_fortran_compute_domain(csw_result, oracle,
                                             inputs, field):
    got = csw_result[field]
    want = oracle[field]
    res, ng = int(inputs["res"]), int(inputs["ng"])
    sl = _compute_slices(res, ng, want.shape)
    g, w = got[sl], want[sl]
    assert np.isfinite(w).all()
    scale = np.maximum(np.abs(w).max(), 1e-30)
    err = np.abs(g - w).max() / scale
    assert err < 1e-13, f"{field}: rel err {err:.3e}"


