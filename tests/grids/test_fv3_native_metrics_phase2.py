# 2. Factory-level: ED cdgrid carries the exact FV3 metrics (create layout)
# ---------------------------------------------------------------------------
class TestCDGridExactMetrics:
    @pytest.mark.parametrize("im", [8, 36])
    def test_ed_cdgrid_metrics_match_remapped_oracle(self, im):
        ref = _load(im)
        g = create_cubed_sphere(im, dtype=np.float64, gnomonic="ed")
        cd = create_cubed_sphere_cdgrid(g, metric_dtype=np.float64)

        area_c_ref = _remap_square(ref["area_c"])
        got = np.asarray(cd.area_corner)
        rel = np.abs(got - area_c_ref) / area_c_ref.max()
        # 5e-12: spherical-excess angle-ulp floor (see TestBuilderOracle)
        assert rel.max() < 5e-12, f"area_c: {rel.max():.3e}"

        dxc_ref, dyc_ref = _remap_staggered_pair(ref["dxc"], ref["dyc"])
        rel = np.abs(np.asarray(cd.dxc) - dxc_ref) / dxc_ref.max()
        assert rel.max() < 1e-13, f"dxc: {rel.max():.3e}"
        rel = np.abs(np.asarray(cd.dyc) - dyc_ref) / dyc_ref.max()
        assert rel.max() < 1e-13, f"dyc: {rel.max():.3e}"

        # CDGrid stores only the reciprocals rdxa/rdya — compare through them
        dxa_ref, dya_ref = _remap_staggered_pair(ref["dxa"], ref["dya"])
        got_dxa = 1.0 / np.asarray(cd.rdxa)
        rel = np.abs(got_dxa - dxa_ref) / dxa_ref.max()
        assert rel.max() < 1e-13, f"dxa (1/rdxa): {rel.max():.3e}"
        got_dya = 1.0 / np.asarray(cd.rdya)
        rel = np.abs(got_dya - dya_ref) / dya_ref.max()
        assert rel.max() < 1e-13, f"dya (1/rdya): {rel.max():.3e}"

    def test_ed_cdgrid_reciprocals_consistent(self):
        g = create_cubed_sphere(8, dtype=np.float64, gnomonic="ed")
        cd = create_cubed_sphere_cdgrid(g, metric_dtype=np.float64)
        assert np.allclose(
            np.asarray(cd.rdxc) * np.asarray(cd.dxc), 1.0, atol=1e-12)
        assert np.allclose(
            np.asarray(cd.rdyc) * np.asarray(cd.dyc), 1.0, atol=1e-12)
        assert np.allclose(
            np.asarray(cd.rarea_c) * np.asarray(cd.area_corner), 1.0, atol=1e-12)


