"""Oracle match: two-stream gray radiation vs Isca v1.0 B_FRIERSON, RUN as Fortran.

Oracle: ExeClim/Isca v1.0 (5868cfd863b41823a3eeb30754ce06feba7528ec)
``two_stream_gray_rad.F90``, compiled standalone with minimal FMS stubs and driven
through its public init/down/up entry points.  Fixture ``oracle_fixtures/gray_isca.npz``
generated by scripts/validate/oracle/gray_isca/{build.sh,make_fixture.py}.

Scope = the matched subset (see ``gray.py`` Faithfulness): dry LW, lw_diff_factor
mapped (E2: Isca ir_tau = D*tau), sfc_emissivity = 1, the oracle's pstd_mks set to
each column's p_s (ours uses sigma = p/p_s; Isca's p/101325 is a documented
departure, not tested here).  Ours is fed the oracle's own P2 insolation.

Metric: per column, max|ours - ref| / max|ref| (0 when both are identically zero),
worst column returned.
"""

from __future__ import annotations

from pathlib import Path

import jax

jax.config.update("jax_enable_x64", True)

import jax.numpy as jnp
import numpy as np
import pytest

from legoesm.atmosphere.physics.radiation.config import GrayRadiationConfig
from legoesm.atmosphere.physics.radiation.gray import gray_radiation

FIXTURE = Path(__file__).parent / "oracle_fixtures" / "gray_isca.npz"
_TOL = 1e-10  # user-approved oracle-match tolerance (max relative error, fp64)

_BASE = GrayRadiationConfig()
_ISCA = _BASE._replace(tau_equator=6.0, tau_pole=1.5, linear_frac=0.1, lw_diff_factor=1.0,
                       sw_exponent=4.0, sfc_emissivity=1.0)
CONFIGS = {
    "E0_isca_defaults": _ISCA._replace(sw_tau_0=0.0),
    "E1_isca_atmabs022": _ISCA._replace(sw_tau_0=0.22),
    "E2_production_mapped": _BASE,
}


def _rel(ours, ref):
    ref = np.asarray(ref, np.float64)
    ref = ref.reshape(ref.shape[0], -1)
    ours = np.asarray(ours, np.float64).reshape(ref.shape)
    assert np.all(np.isfinite(ours)) and np.all(np.isfinite(ref))
    num, den = np.max(np.abs(ours - ref), axis=1), np.max(np.abs(ref), axis=1)
    return float(np.max(np.where(den > 0, num / np.where(den > 0, den, 1.0), num)))


@pytest.fixture(scope="module")
def fix():
    return np.load(FIXTURE)


def _ours(z, tag):
    ph = jnp.asarray(z["p_half"])
    pf = 0.5 * (ph[:, 1:] + ph[:, :-1])   # unused by gray_radiation's numerics
    o = gray_radiation(jnp.asarray(z["T"]), pf, ph, jnp.asarray(z["T_sfc"]),
                       jnp.asarray(z["lat"]), None, jnp.asarray(z[f"{tag}/scal"][:, 0]),
                       CONFIGS[tag], sfc_albedo=jnp.asarray(z["albedo"]))
    return {k: np.asarray(getattr(o, k)) for k in
            ("lw_flux_up", "lw_flux_down", "sw_flux_up", "sw_flux_down",
             "heating_rate", "sw_heating_rate", "lw_heating_rate")}


@pytest.mark.parametrize("tag", list(CONFIGS))
def test_gray_matches_isca(fix, tag):
    z, o = fix, _ours(fix, tag)
    r = {k: z[f"{tag}/{k}"] for k in ("lw_up", "lw_down", "sw_up", "sw_down", "tdt_rad",
                                     "tdt_solar", "scal")}
    errs = {
        "lw_up": _rel(o["lw_flux_up"], r["lw_up"]),
        "lw_down": _rel(o["lw_flux_down"], r["lw_down"]),
        "sw_up": _rel(o["sw_flux_up"], r["sw_up"]),
        "sw_down": _rel(o["sw_flux_down"], r["sw_down"]),
        "heating": _rel(o["heating_rate"], r["tdt_rad"]),
        "heating_sw": _rel(o["sw_heating_rate"], r["tdt_solar"]),
        "olr": _rel(o["lw_flux_up"][:, :1], r["scal"][:, 3:4]),
        "sfc_net_sw": _rel(o["sw_flux_down"][:, -1:] - o["sw_flux_up"][:, -1:], r["scal"][:, 1:2]),
        "sfc_lw_down": _rel(o["lw_flux_down"][:, -1:], r["scal"][:, 2:3]),
    }
    bad = {k: v for k, v in errs.items() if not v <= _TOL}
    assert not bad, bad
