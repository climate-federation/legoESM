"""MLS ozone vs the RUNNING gSAM tracesini.

Fixture ``oracle_fixtures/ozone_mls.npz`` was generated by RUNNING gSAM 1.8.8
``SRC/RAD_RRTM/rad.f90`` ``tracesini`` (lines 1219-1431 compiled verbatim,
-fdefault-real-8; tarball sha256 0e9ea4a37f4daca5051cc4018cc95bbc5583159c7c27d7d05d1104fae4ed270c)
on ``RUNDATA/rrtmg_lw.nc``, via scripts/validate/oracle/ozone_mls/{build.sh,make_fixture.py}
(provenance in the npz ``meta``).  Grids: gSAM RCEMIP 74 levels, CAM6 L32, IFS 137
(ecRad meridian column 16) with and without a 0 Pa model top.

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64.
Relative error is ``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0), the
metric of the merged tier-1 oracle tests.  No smoothing knob: hard limit =
production.
"""
from __future__ import annotations

import json
from pathlib import Path

import jax

jax.config.update("jax_enable_x64", True)

import jax.numpy as jnp  # noqa: E402
import numpy as np  # noqa: E402
import pytest  # noqa: E402

from legoesm.atmosphere.physics.radiation.ozone_mls import mls_ozone_layer_vmr  # noqa: E402

FIXTURE = Path(__file__).parent / "oracle_fixtures" / "ozone_mls.npz"
TOL = 1.0e-10
GRIDS = ("rcemip74", "caml32", "ifs137", "ifs137_top0")


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


@pytest.fixture(scope="module")
def fx():
    return dict(np.load(FIXTURE))


def test_fixture_provenance(fx):
    meta = json.loads(str(fx["meta"]))
    assert meta["rrtmg_lw_nc_sha256"].startswith("4458c778dd66")
    assert "tracesini" in meta["oracle"]


@pytest.mark.parametrize("grid", GRIDS)
def test_layer_means_match_gsam(fx, grid):
    ph = jnp.asarray(fx[f"{grid}/p_half"])[None, :]
    lay, above = mls_ozone_layer_vmr(ph)
    err = float(_rel(lay[0], fx[f"{grid}/o3_oracle"]).max())
    assert err <= TOL, (grid, err)
    ref_above = fx[f"{grid}/o3_above_oracle"]
    if np.isfinite(ref_above):
        e2 = float(_rel(above[0], ref_above).max())
        assert e2 <= TOL, (grid, "above-top layer", e2)
    else:                                   # 0 Pa model top: degenerate extra layer
        assert grid == "ifs137_top0" and not np.isfinite(float(above[0]))


def test_columns_are_independent(fx):
    """Several columns in one call give each column's own answer."""
    ph = np.stack([fx["ifs137/p_half"], fx["ifs137/p_half"] * 0.9])
    lay, above = mls_ozone_layer_vmr(jnp.asarray(ph))
    for c in range(ph.shape[0]):
        one, one_above = mls_ozone_layer_vmr(jnp.asarray(ph[c:c + 1]))
        np.testing.assert_array_equal(np.asarray(lay[c]), np.asarray(one[0]))
        np.testing.assert_array_equal(np.asarray(above[c]), np.asarray(one_above[0]))
    assert not np.array_equal(np.asarray(lay[0]), np.asarray(lay[1]))


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
@pytest.mark.parametrize("grid", ("rcemip74", "ifs137_top0"))
def test_gradient_is_finite(fx, grid, dtype):
    ph = jnp.asarray(fx[f"{grid}/p_half"], dtype)[None, :]
    g = jax.grad(lambda p: jnp.sum(mls_ozone_layer_vmr(p)[0]))(ph)
    assert np.all(np.isfinite(np.asarray(g)))


def test_jit_parity(fx):
    ph = jnp.asarray(fx["caml32/p_half"])[None, :]
    a = mls_ozone_layer_vmr(ph)[0]
    b = jax.jit(mls_ozone_layer_vmr)(ph)[0]
    assert float(_rel(a, b).max()) <= TOL
