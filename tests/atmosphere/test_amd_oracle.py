"""AMD SGS eddy viscosity vs the RUNNING AMR-Wind v4.2.0 amd_muvel.

Fixture ``tests/atmosphere/oracle_fixtures/amd.npz`` was generated by RUNNING AMR-Wind
v4.2.0 (0ee09c22b9afeca06231e4910276c0ba05fb52dd) ``src/turbulence/LES/AMD.H::amd_muvel``
compiled verbatim (g++ 8.5 -O0, amrex type stubs; beta = 0, i.e. pure shear) with
``bash scripts/validate/oracle/amd/build.sh <amr-wind> <dir>`` then
``python scripts/validate/oracle/amd/make_fixture.py <dir>/amd_oracle <les dir> amd.npz``.
Points: the Vreman fixture's set (jax-alfa LES oracle CBL/NBL/SBL tensors, every 17th
grid point, plus 246 synthetic edge tensors).  C = 0.3.

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64.  Relative
error is ``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0); no floor.

RULE 5 (user decisions 2026-10-28 and 2026-10-31): the output floor is a softplus
floor of width ``floor_width`` (default 1e-8 m2/s) and the denominator floor one of
width ``denom_floor_width`` (default 10 eps s^-2).  The oracle match is asserted at
the hard limit (both widths 0); at the defaults the signed per-point gap (ours - oracle) is pinned
against ``oracle_fixtures/amd_default_gap.npz`` (1e-6 relative, 1e-12 absolute).
Regenerate it after a change to a smooth form or a default width with
``python tests/atmosphere/test_amd_oracle.py``.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from jax.test_util import check_grads

from legoesm.atmosphere.physics.turbulence.amd import (AMD_DENOM_FLOOR_WIDTH,
                                                        AMD_FLOOR_WIDTH, amd_nu_t)

jax.config.update("jax_enable_x64", True)

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests/atmosphere/oracle_fixtures/amd.npz"
GENERATOR = ROOT / "scripts/validate/oracle/amd/make_fixture.py"
GAP_FILE = ROOT / "tests/atmosphere/oracle_fixtures/amd_default_gap.npz"
TOL = 1.0e-10
HARD = dict(floor_width=0.0, denom_floor_width=0.0)


def _fx():
    return dict(np.load(FIXTURE))


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


def _ours(fx, dtype=jnp.float64, **kw):
    a = [jnp.asarray(x, dtype) for x in fx["a"]]
    h = [jnp.asarray(x, dtype) for x in fx["h"]]
    return amd_nu_t(*a, *h, float(json.loads(str(fx["meta"]))["c_amd"]), **kw)


def _default_gap(fx):
    return np.asarray(_ours(fx)) - fx["nu"]


def test_fixture_provenance_and_edge_inputs_reproduce():
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    assert meta["oracle_sha"] == "0ee09c22b9afeca06231e4910276c0ba05fb52dd"
    assert meta["c_amd"] == 0.3
    spec = importlib.util.spec_from_file_location("amd_make_fixture", GENERATOR)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    gen = mod.load_points_module()
    a_edge, h_edge = gen.edge_tensors()
    edge = fx["case_id"] == len(gen.CASES)
    np.testing.assert_array_equal(fx["a"][:, edge], a_edge)
    np.testing.assert_array_equal(fx["h"][:, edge], h_edge)


def test_amd_matches_amr_wind():
    fx = _fx()
    rel = _rel(_ours(fx, **HARD), fx["nu"])
    assert rel.max() <= TOL, (rel.max(), int(np.argmax(rel)))
    # the fixture exercises the oracle's outer 10*eps floor (N <= 0) and the
    # active branch
    floor = 10.0 * np.finfo(np.float64).eps
    assert np.sum(fx["nu"] == floor) > 100 and np.sum(fx["nu"] > floor) > 1000


def test_eager_jit_parity():
    """Hard limit (both widths 0): relative parity, no floor."""
    fx = _fx()
    c = float(json.loads(str(fx["meta"]))["c_amd"])
    f = lambda a, h: amd_nu_t(*a, *h, c, **HARD)  # noqa: E731
    a, h = jnp.asarray(fx["a"]), jnp.asarray(fx["h"])
    assert _rel(jax.jit(f)(a, h), f(a, h)).max() <= TOL


def test_eager_jit_parity_at_default():
    """Default width: where num/denom is ~0 its round-off differs eager vs jit
    (measured 3.3e-17 absolute on 6.9e-9), so the parity carries RULE 5's
    1e-12 absolute floor."""
    fx = _fx()
    c = float(json.loads(str(fx["meta"]))["c_amd"])
    f = lambda a, h: amd_nu_t(*a, *h, c)  # noqa: E731
    a, h = jnp.asarray(fx["a"]), jnp.asarray(fx["h"])
    np.testing.assert_allclose(np.asarray(jax.jit(f)(a, h)), np.asarray(f(a, h)),
                               rtol=TOL, atol=1e-12)


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_gradient_finite_on_fixture(dtype):
    fx = _fx()
    c = float(json.loads(str(fx["meta"]))["c_amd"])
    a = jnp.asarray(fx["a"], dtype)
    h = [jnp.asarray(x, dtype) for x in fx["h"]]
    g = jax.grad(lambda aa: jnp.sum(amd_nu_t(*aa, *h, c)))(a)
    assert g.dtype == dtype and bool(jnp.all(jnp.isfinite(g)))


def test_default_width_is_the_recorded_one():
    from legoesm.atmosphere.dynamics.gcm.compressible_euler import CompressibleEulerConfig
    assert AMD_FLOOR_WIDTH == 1.0e-8
    assert CompressibleEulerConfig().amd_floor_width == AMD_FLOOR_WIDTH
    assert AMD_DENOM_FLOOR_WIDTH == 10.0 * np.finfo(np.float64).eps
    assert CompressibleEulerConfig().amd_denom_floor_width == AMD_DENOM_FLOOR_WIDTH


def test_negative_denominator_width_raises():
    z = jnp.zeros(2)
    with pytest.raises(ValueError, match="denom_floor_width"):
        amd_nu_t(*([z] * 9), 1.0, 1.0, 1.0, 0.3, denom_floor_width=-1.0)


def test_default_smoothing_gap_per_point():
    """RULE 5 KNOWN DIFFERENCE: at the default width each fixture point's signed
    gap to AMR-Wind equals the stored measurement."""
    fx = _fx()
    stored = np.load(GAP_FILE)["gap"]
    np.testing.assert_allclose(_default_gap(fx), stored, rtol=1e-6, atol=1e-12)
    assert np.abs(stored).max() > 1e-9   # the smoothing does move floored points


def test_check_grads_through_the_softplus_floor_at_default():
    """RULE 5 gradient test: synthetic points whose unfloored viscosity x sits
    within a few widths of the floor (compressive normal strain a11 < 0 gives
    x = C dx^2 |a11|, so a11 sets x directly); a scalar scale s on the
    gradients keeps the finite-difference step inside the band."""
    # a pure a11 strain gives x = -C dx^2 a11; dx = 0.01 m keeps a11^2 above the
    # (hard) denominator floor, so only the output floor is exercised.
    w, c, dx = AMD_FLOOR_WIDTH, 0.3, 0.01
    x = jnp.asarray([-3.0, -1.0, 0.5, 1.0, 3.0]) * w     # unfloored nu around the floor
    a11 = -x / (c * dx * dx)
    z = jnp.zeros_like(a11)

    def f(s):   # one scale per point, so the derivative is per point
        return amd_nu_t(a11 * s, z, z, z, z, z, z, z, z, dx, dx, dx, c)

    s0 = jnp.ones_like(a11)
    check_grads(lambda s: jnp.sum(f(s)), (s0,), order=2, modes=("fwd", "rev"), eps=1e-5)
    d = np.asarray(jax.grad(lambda s: jnp.sum(f(s)))(s0))
    # below the floor (x = -3w, -w) the hard limit's derivative is exactly 0
    assert np.all(d != 0.0), d


def test_check_grads_through_the_denominator_floor_at_default():
    """RULE 5 gradient test for the denominator floor: a compressive a11 strain
    with a11^2 = r * 10 eps, r around 1.  With the hard floor (a11^2 floored at
    10 eps) nu = C dx^2 |a11|^3 / (10 eps), so d ln(nu)/d ln(s) = 3 below the
    floor and 1 above it; the smooth floor gives a value strictly between.
    dx = 1e3 m keeps nu (~1e-2 m2/s) far above the output floor."""
    F = 10.0 * np.finfo(np.float64).eps
    c, dx = 0.3, 1.0e3
    r = jnp.asarray([0.3, 1.0, 3.0])
    a11 = -jnp.sqrt(r * F)
    z = jnp.zeros_like(a11)

    def lognu(logs):   # one log-scale per point
        return jnp.log(amd_nu_t(a11 * jnp.exp(logs), z, z, z, z, z, z, z, z,
                                dx, dx, dx, c))

    l0 = jnp.zeros_like(a11)
    check_grads(lambda l: jnp.sum(lognu(l)), (l0,), order=2, modes=("fwd", "rev"),
                eps=1e-6)
    d = np.asarray(jax.grad(lambda l: jnp.sum(lognu(l)))(l0))
    # hard limit: exactly 3 (r < 1), 3 or 1 (r = 1), 1 (r > 1)
    assert np.all(d > 1.01) and np.all(d < 2.99), d
    # the softplus floor's own value: 3 - 2 r sigmoid(r - 1) / (1 + softplus(r - 1))
    rr = np.asarray(r)
    sig = 1.0 / (1.0 + np.exp(-(rr - 1.0)))
    np.testing.assert_allclose(d, 3.0 - 2.0 * rr * sig / (1.0 + np.log1p(np.exp(rr - 1.0))),
                               rtol=1e-6)


