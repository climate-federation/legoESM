"""Vreman SGS eddy viscosity vs the RUNNING author's reference Fortran.

Fixture ``tests/atmosphere/oracle_fixtures/vreman.npz`` was generated by RUNNING
A.W. Vreman's own implementation (http://www.vremanresearch.nl/Vreman_Subgridmodel_Fortran.txt,
sha256 8a7efd8c..., downloaded 2026-10-19; anisotropic form d_i = h_i**2 per the author's
comment), compiled with gfortran 8.5 -O0, with
``bash scripts/validate/oracle/vreman/build.sh <txt> <dir>`` then
``python scripts/validate/oracle/vreman/make_fixture.py <dir>/vreman_oracle <les dir> vreman.npz``.
Points: velocity-gradient tensors from the jax-alfa LES oracle's own CBL/NBL/SBL fields
(every 17th grid point) plus 246 synthetic edge tensors.

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64.  Relative
error is ``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0); no floor.

RULE 5 (user decision 2026-10-28): the author's ``Bbeta < 1e-12`` zero-guard is a
C1 smoothstep of half-width ``bbeta_guard_width`` (default 1e-13 m4/s4).  The
oracle match is asserted at the hard limit (width 0); at the default the signed
per-point gap (ours - oracle) is pinned against
``oracle_fixtures/vreman_default_gap.npz`` (1e-6 relative, 1e-12 absolute).
Regenerate it after a change to the smooth form or its default width with
``python tests/atmosphere/test_vreman_oracle.py``.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from jax.test_util import check_grads

from legoesm.atmosphere.physics.turbulence.vreman import (
    VREMAN_BBETA_GUARD_WIDTH, vreman_nu_t)

jax.config.update("jax_enable_x64", True)

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests/atmosphere/oracle_fixtures/vreman.npz"
GENERATOR = ROOT / "scripts/validate/oracle/vreman/make_fixture.py"
GAP_FILE = ROOT / "tests/atmosphere/oracle_fixtures/vreman_default_gap.npz"
_GUARD = 1.0e-12
TOL = 1.0e-10


def _fx():
    return dict(np.load(FIXTURE))


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


def _ours(fx, dtype=jnp.float64, **kw):
    a = [jnp.asarray(x, dtype) for x in fx["a"]]
    h = [jnp.asarray(x, dtype) for x in fx["h"]]
    return vreman_nu_t(*a, *h, float(json.loads(str(fx["meta"]))["c_vreman"]), **kw)


def _bbeta(fx):
    a, h = fx["a"], fx["h"]
    d = h ** 2
    b = [[sum(d[m] * a[3 * i + m] * a[3 * j + m] for m in range(3)) for j in range(3)]
         for i in range(3)]
    return (b[0][0] * b[1][1] - b[0][1] ** 2 + b[0][0] * b[2][2] - b[0][2] ** 2
            + b[1][1] * b[2][2] - b[1][2] ** 2)


def _default_gap(fx):
    return np.asarray(_ours(fx)) - fx["nu"]


def test_fixture_provenance_and_edge_inputs_reproduce():
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    assert meta["oracle_sha256"].startswith("8a7efd8c")
    assert meta["c_vreman"] == 0.07
    spec = importlib.util.spec_from_file_location("vreman_make_fixture", GENERATOR)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    a_edge, h_edge = gen.edge_tensors()
    edge = fx["case_id"] == len(gen.CASES)
    np.testing.assert_array_equal(fx["a"][:, edge], a_edge)
    np.testing.assert_array_equal(fx["h"][:, edge], h_edge)


def test_vreman_matches_reference_fortran():
    fx = _fx()
    rel = _rel(_ours(fx, bbeta_guard_width=0.0), fx["nu"])
    assert rel.max() <= TOL, (rel.max(), int(np.argmax(rel)))
    # the fixture exercises the author's zero-guard (oracle exactly 0 at
    # quiescent points where 0 < Bbeta < 1e-12) and the active branch
    assert np.sum(fx["nu"] == 0.0) > 100 and np.sum(fx["nu"] > 0.0) > 1000


def test_eager_jit_parity():
    fx = _fx()
    c = float(json.loads(str(fx["meta"]))["c_vreman"])
    f = lambda a, h: vreman_nu_t(*a, *h, c)  # noqa: E731
    a, h = jnp.asarray(fx["a"]), jnp.asarray(fx["h"])
    assert _rel(jax.jit(f)(a, h), f(a, h)).max() <= TOL


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_gradient_finite_on_fixture(dtype):
    fx = _fx()
    c = float(json.loads(str(fx["meta"]))["c_vreman"])
    a = jnp.asarray(fx["a"], dtype)
    h = [jnp.asarray(x, dtype) for x in fx["h"]]
    g = jax.grad(lambda aa: jnp.sum(vreman_nu_t(*aa, *h, c)))(a)
    assert g.dtype == dtype and bool(jnp.all(jnp.isfinite(g)))


def test_default_width_is_the_recorded_one():
    from legoesm.atmosphere.dynamics.gcm.compressible_euler import CompressibleEulerConfig
    from legoesm.atmosphere.dynamics.les.pseudo_incompressible_plane import (
        PseudoIncompressibleConfig)
    from legoesm.atmosphere.dynamics.les.spectral_les_plane import SpectralLESConfig
    assert VREMAN_BBETA_GUARD_WIDTH == 1.0e-13
    for cfg in (SpectralLESConfig, PseudoIncompressibleConfig, CompressibleEulerConfig):
        assert cfg._field_defaults["vreman_bbeta_guard_width"] == VREMAN_BBETA_GUARD_WIDTH


def test_default_smoothing_gap_per_point():
    """RULE 5 KNOWN DIFFERENCE: at the default width each fixture point's signed
    gap to the author's Fortran equals the stored measurement."""
    fx = _fx()
    gap = _default_gap(fx)
    stored = np.load(GAP_FILE)["gap"]
    np.testing.assert_allclose(gap, stored, rtol=1e-6, atol=1e-12)
    assert np.abs(stored).max() > 1e-6   # the smoothing does move points


def test_check_grads_through_the_smoothstep_at_default():
    """RULE 5 gradient test: three fixture points from the band
    [1e-12 - w, 1e-12 + w], rescaled (Bbeta ~ s^4) so Bbeta = 1e-12 exactly,
    i.e. ON the author's switch.  A scalar scale s on the nine gradients;
    eps = 1e-5 (JAX's default 1e-4 fails from finite-difference truncation of
    the ramp's curvature; tolerances stay JAX's).  At width 0 the step crosses
    the jump and this fails."""
    fx = _fx()
    w = VREMAN_BBETA_GUARD_WIDTH
    bb = _bbeta(fx)
    band = np.flatnonzero((bb > _GUARD - w) & (bb < _GUARD + w))[:3]
    assert band.size == 3
    c = float(json.loads(str(fx["meta"]))["c_vreman"])
    a = jnp.asarray(fx["a"][:, band] * (_GUARD / bb[band]) ** 0.25)
    h = [jnp.asarray(x[band]) for x in fx["h"]]

    def f(s):
        return jnp.sum(vreman_nu_t(*(a * s), *h, c))

    check_grads(f, (jnp.asarray(1.0),), order=2, modes=("fwd", "rev"), eps=1e-5)
    assert float(jax.grad(f)(jnp.asarray(1.0))) != 0.0


@pytest.mark.parametrize("w", [1.0e-12, 2.0e-12, -1.0e-13])
def test_width_at_or_above_guard_or_negative_raises(w):
    """User decision N7: a band reaching Bbeta = 0 (w >= 1e-12) gives NaN at
    rest, so it is refused, as is a negative width."""
    z = jnp.zeros(3)
    with pytest.raises(ValueError, match="bbeta_guard_width"):
        vreman_nu_t(*([z] * 9), 1.0, 1.0, 1.0, 0.07, bbeta_guard_width=w)


if __name__ == "__main__":
    np.savez_compressed(GAP_FILE, gap=_default_gap(_fx()),
                        width=VREMAN_BBETA_GUARD_WIDTH)
    print("wrote", GAP_FILE)
