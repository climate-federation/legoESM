"""Vreman SGS eddy viscosity vs the RUNNING author's reference Fortran.

Fixture ``tests/atmosphere/oracle_fixtures/vreman.npz`` was generated by RUNNING
A.W. Vreman's own implementation (http://www.vremanresearch.nl/Vreman_Subgridmodel_Fortran.txt,
sha256 8a7efd8c..., downloaded 2026-10-19; anisotropic form d_i = h_i**2 per the author's
comment), compiled with gfortran 8.5 -O0, with
``bash scripts/validate/oracle/vreman/build.sh <txt> <dir>`` then
``python scripts/validate/oracle/vreman/make_fixture.py <dir>/vreman_oracle <les dir> vreman.npz``.
Points: velocity-gradient tensors from the jax-alfa LES oracle's own CBL/NBL/SBL fields
(every 17th grid point) plus 246 synthetic edge tensors.

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64.  Relative
error is ``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0); no floor.  Vreman has
no sharpness field, so the hard limit is the production setting.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from legoesm.atmosphere.physics.turbulence.vreman import vreman_nu_t

jax.config.update("jax_enable_x64", True)

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests/atmosphere/oracle_fixtures/vreman.npz"
GENERATOR = ROOT / "scripts/validate/oracle/vreman/make_fixture.py"
TOL = 1.0e-10


def _fx():
    return dict(np.load(FIXTURE))


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


def _ours(fx, dtype=jnp.float64):
    a = [jnp.asarray(x, dtype) for x in fx["a"]]
    h = [jnp.asarray(x, dtype) for x in fx["h"]]
    return vreman_nu_t(*a, *h, float(json.loads(str(fx["meta"]))["c_vreman"]))


def test_fixture_provenance_and_edge_inputs_reproduce():
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    assert meta["oracle_sha256"].startswith("8a7efd8c")
    assert meta["c_vreman"] == 0.07
    spec = importlib.util.spec_from_file_location("vreman_make_fixture", GENERATOR)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    a_edge, h_edge = gen.edge_tensors()
    edge = fx["case_id"] == len(gen.CASES)
    np.testing.assert_array_equal(fx["a"][:, edge], a_edge)
    np.testing.assert_array_equal(fx["h"][:, edge], h_edge)


def test_vreman_matches_reference_fortran():
    fx = _fx()
    rel = _rel(_ours(fx), fx["nu"])
    assert rel.max() <= TOL, (rel.max(), int(np.argmax(rel)))
    # the fixture exercises the author's zero-guard (oracle exactly 0 at
    # quiescent points where 0 < Bbeta < 1e-12) and the active branch
    assert np.sum(fx["nu"] == 0.0) > 100 and np.sum(fx["nu"] > 0.0) > 1000


def test_eager_jit_parity():
    fx = _fx()
    c = float(json.loads(str(fx["meta"]))["c_vreman"])
    f = lambda a, h: vreman_nu_t(*a, *h, c)  # noqa: E731
    a, h = jnp.asarray(fx["a"]), jnp.asarray(fx["h"])
    assert _rel(jax.jit(f)(a, h), f(a, h)).max() <= TOL


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_gradient_finite_on_fixture(dtype):
    fx = _fx()
    c = float(json.loads(str(fx["meta"]))["c_vreman"])
    a = jnp.asarray(fx["a"], dtype)
    h = [jnp.asarray(x, dtype) for x in fx["h"]]
    g = jax.grad(lambda aa: jnp.sum(vreman_nu_t(*aa, *h, c)))(a)
    assert g.dtype == dtype and bool(jnp.all(jnp.isfinite(g)))
