"""Oracle match: Rayleigh upper sponge vs Isca v1.0 damping_driver, RUN as Fortran.

Oracle: ExeClim/Isca v1.0 (5868cfd863b41823a3eeb30754ce06feba7528ec)
``src/atmos_param/damping_driver/damping_driver.f90`` compiled unmodified with minimal
FMS stubs, called through its public ``damping_driver`` with ``do_rayleigh`` and
``do_conserve_energy``; compared output = the sponge ``udt`` / ``vdt`` / ``tdt``.
Fixture ``oracle_fixtures/rayleigh_sponge_isca.npz`` generated by
scripts/validate/oracle/sponge_isca/{build.sh,make_fixture.py}.

Ours = ``rayleigh_gwd`` with the HS94 low-level drag off (``k_max = 0``: not part of
damping_driver), the fixture's ``sponge_pbottom_Pa`` and Isca's hard cutoff
(``sponge_sharpness = inf``).  Two column sets: 13 CAM L32 columns at 1000 Pa and 7
synthetic L60 columns (top 1 Pa) at the 50 Pa default, one with p_s = 30 kPa so the
level cap excludes levels with p < p_sb.

Metric: per column, max|ours - ref| / max|ref| (0 when both are identically zero),
worst column returned.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import jax

jax.config.update("jax_enable_x64", True)

import jax.numpy as jnp
import numpy as np
import pytest

from legoesm.atmosphere.physics.gravity_wave_drag.config import RayleighConfig
from legoesm.atmosphere.physics.gravity_wave_drag.rayleigh import rayleigh_gwd

FIXTURE = Path(__file__).parent / "oracle_fixtures" / "rayleigh_sponge_isca.npz"
_TOL = 1e-12  # user-approved oracle bar (max relative error, fp64)
_KEYS = ("u", "v", "T", "p_full", "p_half", "z_full", "z_half", "rho", "lat")


def _rel(ours, ref):
    ref = np.asarray(ref, np.float64)
    ref = ref.reshape(ref.shape[0], -1)
    ours = np.asarray(ours, np.float64).reshape(ref.shape)
    assert np.all(np.isfinite(ours)) and np.all(np.isfinite(ref))
    num, den = np.max(np.abs(ours - ref), axis=1), np.max(np.abs(ref), axis=1)
    return float(np.max(np.where(den > 0, num / np.where(den > 0, den, 1.0), num)))


@pytest.fixture(scope="module")
def fix():
    return np.load(FIXTURE)


@pytest.mark.parametrize("cset", ["l32", "l60"])
def test_rayleigh_sponge_matches_isca(fix, cset):
    z = fix
    meta = json.loads(str(z["meta"]))
    cfg = RayleighConfig(k_max=0.0, sponge_k=meta["sponge_k_per_s"],
                         sponge_pbottom_Pa=float(z[f"{cset}_p_sb"]),
                         sponge_sharpness=math.inf)
    j = {k: jnp.asarray(z[f"{cset}_{k}"]) for k in _KEYS}
    o = rayleigh_gwd(j["u"], j["v"], j["T"], j["p_full"], j["p_half"], j["z_full"],
                     j["z_half"], j["rho"], j["lat"], meta["dt"], cfg)
    assert np.any(z[f"{cset}_udt"] != 0.0) and np.any(z[f"{cset}_udt"] == 0.0)
    errs = {"du_dt": _rel(o.du_dt, z[f"{cset}_udt"]),
            "dv_dt": _rel(o.dv_dt, z[f"{cset}_vdt"]),
            "dT_dt": _rel(o.dT_dt, z[f"{cset}_tdt"])}
    assert max(errs.values()) <= _TOL, errs
