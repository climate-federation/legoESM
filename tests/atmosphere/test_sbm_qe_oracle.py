jax.config.update("jax_enable_x64", True)

FIXTURE = Path(__file__).resolve().parent / "oracle_fixtures" / "sbm_qe.npz"
TOL = 1.0e-10
HARD = SBMConfig(cape_threshold=0.0, smooth_trigger_sharpness=1.0e12)


@pytest.fixture(scope="module")
def fx():
    z = dict(np.load(FIXTURE))
    z["meta"] = json.loads(str(z["meta"]))
    return z


def _run(fx, cfg, dtype=jnp.float64, fn=sbm_convection):
    args = [jnp.asarray(fx[k], dtype) for k in ("T", "q", "p_full", "p_half")]
    return fn(*args, float(fx["meta"]["dt"]), cfg)


def _precip(out, fx):
    dp = np.diff(fx["p_half"], axis=1)
    return np.sum(np.asarray(out.dq_c_conv_dt) * dp / constants.g, axis=1)


def _err(a, b):
    a = np.asarray(a, np.float64)
    b = np.asarray(b, np.float64)
    if not (np.all(np.isfinite(a)) and np.all(np.isfinite(b))):
        return np.inf
    return float(np.max(np.abs(a - b)) / max(np.max(np.abs(b)), 1e-300))


def test_fixture_provenance(fx):
    m = fx["meta"]
    assert m["tag"] == "v1.0"
    assert m["sha"] == "5868cfd863b41823a3eeb30754ce06feba7528ec"
    assert (m["dt"], m["tau_bm"], m["rhbm"]) == (1800.0, HARD.tau_c, HARD.rh_ref)
    # every branch of SBM_convection_scheme is on the fixture
    flag, pr = fx["ora_flag"], fx["ora_precip"]
    assert np.any(flag == 0) and np.any(flag == 1) and np.any(flag == 2)
    assert np.any((flag == 1) & np.any(fx["ora_dT"] != 0, axis=1))      # shallower
    assert np.any((flag == 1) & np.all(fx["ora_dT"] == 0.0, axis=1))  # CAPE but Pt <= 0
    assert np.all(pr[flag != 2] == 0.0) and np.all(pr[flag == 2] > 0.0)


def test_matches_isca_oracle_at_hard_trigger(fx):
    out = _run(fx, HARD)
    errs = {"dT_dt": _err(out.dT_dt, fx["ora_dT"]),
            "dq_v_dt": _err(out.dq_v_dt, fx["ora_dq"]),
            "precip": _err(_precip(out, fx), fx["ora_precip"]),
            "cape": _err(out.cape, fx["ora_cape"])}
    print("SBM vs Isca max rel err", errs)
    assert max(errs.values()) <= TOL, errs


def test_column_budgets_close(fx):
    """Column water closes in every column (precipitation = column drying), and
    column moist enthalpy closes in every branch as in the oracle: the deep
    T-shift by construction, the deep time-scale change through Pq = Pt, the
    shallower scheme through int(dq) = int(dT) = 0."""
    out = _run(fx, HARD)
    dp = np.diff(fx["p_half"], axis=1)
    dT, dq, dqc = (np.asarray(x) for x in (out.dT_dt, out.dq_v_dt, out.dq_c_conv_dt))
    water = np.sum((dq + dqc) * dp, axis=1) / constants.g
    assert np.max(np.abs(water)) <= TOL * np.max(np.abs(fx["ora_precip"]))
    mse = np.sum((constants.c_pd * dT + constants.L_v * dq) * dp, axis=1)
    scale = np.max(np.sum(constants.c_pd * np.abs(dT) * dp, axis=1))
    assert scale > 0.0 and np.max(np.abs(mse)) <= TOL * scale
    shallow = (fx["ora_flag"] == 1) & np.any(fx["ora_dT"] != 0, axis=1)
    assert np.any(shallow)
    assert np.max(np.abs(np.sum(dT * dp, axis=1)[shallow])) <= TOL * scale / constants.c_pd


def test_gradients_finite_fp64_and_fp32(fx):
    for dtype in (jnp.float64, jnp.float32):
        args = [jnp.asarray(fx[k], dtype) for k in ("T", "q", "p_full", "p_half")]

        def loss(T, q):
            o = sbm_convection(T, q, args[2], args[3], 1800.0, SBMConfig())
            return jnp.sum(o.dT_dt) + 1.0e3 * jnp.sum(o.dq_c_conv_dt)

        gT, gq = jax.grad(loss, argnums=(0, 1))(args[0], args[1])
        assert bool(jnp.all(jnp.isfinite(gT))) and bool(jnp.all(jnp.isfinite(gq))), dtype
        assert float(jnp.max(jnp.abs(gT))) > 0.0

        def loss_p(tau, rh):
            o = sbm_convection(*args, 1800.0, SBMConfig(tau_c=tau, rh_ref=rh))
            return jnp.sum(o.dT_dt) + 1.0e3 * jnp.sum(o.dq_c_conv_dt)

        g = jax.grad(loss_p, argnums=(0, 1))(jnp.asarray(7200.0, dtype), jnp.asarray(0.7, dtype))
        assert all(bool(jnp.isfinite(x)) and float(x) != 0.0 for x in g), (dtype, g)


def test_gradient_finite_with_zero_top_interface_pressure(fx):
    """Model tops at p = 0: log(p_half(2)/p_half(1)) is +inf as in the oracle,
    but gradients w.r.t. the state and the pressures stay finite."""
    T, q, pf, ph = (jnp.asarray(fx[k]) for k in ("T", "q", "p_full", "p_half"))
    ph = ph.at[:, 0].set(0.0)

    def loss(T, q, ph):
        o = sbm_convection(T, q, pf, ph, 1800.0, SBMConfig())
        return jnp.sum(o.dT_dt) + 1.0e3 * jnp.sum(o.dq_c_conv_dt)

    for g in jax.grad(loss, argnums=(0, 1, 2))(T, q, ph):
        assert bool(jnp.all(jnp.isfinite(g)))


def test_eager_jit_parity(fx):
    a = _run(fx, SBMConfig())
    b = _run(fx, SBMConfig(), fn=jax.jit(sbm_convection, static_argnums=(4, 5)))
    for x, y in zip((a.dT_dt, a.dq_v_dt, a.dq_c_conv_dt, a.cape),
                    (b.dT_dt, b.dq_v_dt, b.dq_c_conv_dt, b.cape)):
        assert _err(y, x) <= TOL


def test_inert_cloud_mask_sharpness_rejects_non_default(fx):
    with pytest.raises(ValueError, match="cloud_mask_sharpness"):
        _run(fx, SBMConfig(cloud_mask_sharpness=50.0))
    # a traced config (jit argument) cannot raise: the outputs are NaN instead
    args = [jnp.asarray(fx[k]) for k in ("T", "q", "p_full", "p_half")]
    f = jax.jit(lambda c: sbm_convection(*args, 1800.0, c))
    assert bool(jnp.all(jnp.isnan(f(SBMConfig(cloud_mask_sharpness=jnp.asarray(50.0))).dT_dt)))
    assert bool(jnp.all(jnp.isfinite(f(SBMConfig(cloud_mask_sharpness=jnp.asarray(5.0))).dT_dt)))


def test_column_the_oracle_rejects_is_nan():
    """Isca stops with FATAL 'get_lcl_temp: value to low' on a parcel whose LCL
    lies below the lookup table (here q = 1e-12 at 250 K; the oracle binary
    was run on this column, 2026-10-19); the port returns NaN for that column
    instead of a value, and leaves the other column alone."""
    nlev = 12
    sh = jnp.linspace(0.0, 1.0, nlev + 1)
    ph = jnp.stack([sh * 1.0e5] * 2)
    pf = 0.5 * (ph[:, 1:] + ph[:, :-1])
    T = jnp.full((2, nlev), 250.0)
    q = jnp.stack([jnp.full(nlev, 1.0e-12), jnp.zeros(nlev)])
    out = sbm_convection(T, q, pf, ph, 1800.0, SBMConfig())
    assert bool(jnp.all(jnp.isnan(out.dT_dt[0])))
    assert bool(jnp.all(out.dT_dt[1] == 0.0))


