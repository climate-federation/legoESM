"""Oracle match: HS94 low-level Rayleigh friction vs Isca v1.0 hs_forcing, RUN as Fortran.

Oracle: ExeClim/Isca v1.0 (5868cfd863b41823a3eeb30754ce06feba7528ec)
``src/atmos_param/hs_forcing/hs_forcing.F90`` compiled unmodified with minimal FMS
stubs, called through its public ``hs_forcing``; compared output = the Rayleigh
damping ``udt`` / ``vdt``.  Fixture ``oracle_fixtures/rayleigh_hs_isca.npz``
generated by scripts/validate/oracle/hs_isca/{build.sh,make_fixture.py}.

Ours = ``rayleigh_gwd`` with the upper sponge switched off (``sponge_k = 0``: the
sponge is not HS94 and has no oracle) and the fixture's ``sigma_b`` / ``k_max``.
Only the momentum tendencies are compared: Isca's ``tdt`` mixes Newtonian damping
with the dissipative heating.

Metric: per column, max|ours - ref| / max|ref| (0 when both are identically zero),
worst column returned.
"""

from __future__ import annotations

import json
from pathlib import Path

import jax

jax.config.update("jax_enable_x64", True)

import jax.numpy as jnp
import numpy as np
import pytest

from legoesm.atmosphere.physics.gravity_wave_drag.config import RayleighConfig
from legoesm.atmosphere.physics.gravity_wave_drag.rayleigh import rayleigh_gwd

FIXTURE = Path(__file__).parent / "oracle_fixtures" / "rayleigh_hs_isca.npz"
_TOL = 1e-10  # user-approved oracle-match tolerance (max relative error, fp64)


def _rel(ours, ref):
    ref = np.asarray(ref, np.float64)
    ref = ref.reshape(ref.shape[0], -1)
    ours = np.asarray(ours, np.float64).reshape(ref.shape)
    assert np.all(np.isfinite(ours)) and np.all(np.isfinite(ref))
    num, den = np.max(np.abs(ours - ref), axis=1), np.max(np.abs(ref), axis=1)
    return float(np.max(np.where(den > 0, num / np.where(den > 0, den, 1.0), num)))


@pytest.fixture(scope="module")
def fix():
    return np.load(FIXTURE)


def test_rayleigh_hs_matches_isca(fix):
    z = fix
    meta = json.loads(str(z["meta"]))
    cfg = RayleighConfig(k_max=meta["kf_per_s"], sigma_b=meta["sigma_b"], sponge_k=0.0)
    j = {k: jnp.asarray(z[k]) for k in ("u", "v", "T", "p_full", "p_half", "z_full",
                                        "z_half", "rho", "lat")}
    o = rayleigh_gwd(j["u"], j["v"], j["T"], j["p_full"], j["p_half"], j["z_full"],
                     j["z_half"], j["rho"], j["lat"], meta["dt"], cfg)
    errs = {"du_dt": _rel(o.du_dt, z["udt"]),
            "dv_dt": _rel(o.dv_dt, z["vdt"])}
    bad = {k: v for k, v in errs.items() if not v <= _TOL}
    assert not bad, bad
