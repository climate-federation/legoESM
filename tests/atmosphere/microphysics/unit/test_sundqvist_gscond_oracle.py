"""Sundqvist condensation (Zhao-Carr gscond port) vs the RUNNING oracle.

Fixture ``tests/atmosphere/oracle_fixtures/sundqvist_zhao_carr_gscond.npz`` was
generated by RUNNING NCAR/ccpp-physics v7.0.1
(da75531bf90a799e4c0dcb988cc591d82bd024de) ``zhaocarr_gscond_run``, compiled
unmodified (-fdefault-real-8) with legoESM's Tetens curve as ``fpvs``, by
``scripts/validate/oracle/sundqvist_zhao_carr_gscond/make_fixture.py`` (metadata
in the npz ``meta``).

Bar (standing oracle bar): per field ``max|ours - oracle| / max|oracle|`` at most
1e-12, or the oracle's own 20-seed 1-ulp spread if larger, in fp64 at the hard
limit (``smooth_frac = 0``).
"""
from __future__ import annotations

import json
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

jax.config.update("jax_enable_x64", True)

ROOT = Path(__file__).resolve().parents[4]
FIXTURE = ROOT / "tests/atmosphere/oracle_fixtures/sundqvist_zhao_carr_gscond.npz"
BAR = 1.0e-12
FIELDS = ("t", "q", "cwm", "tp", "qp")


def _fx():
    return dict(np.load(FIXTURE))


def _keys(fx):
    meta = json.loads(str(fx["meta"]))
    return [(r, t) for r in ("A", "B") for t in meta["tendencies"]]


def _ours(fx, run, tend, smooth_frac=0.0, dtype=jnp.float64):
    from legoesm.atmosphere.physics.microphysics.sundqvist import zhao_carr_gscond
    dt, u = (float(x) for x in fx[f"run_{run}"])
    key = f"{run}_{tend}"
    a = lambda x: jnp.asarray(x, dtype)  # noqa: E731
    r = zhao_carr_gscond(
        a(fx["col_T"]), a(fx["col_q_v"]), a(fx["col_q_c"]), a(fx["col_p_full"]),
        a(fx["col_p_half"][:, -1]), a(fx[f"prev_{key}_tp"]), a(fx[f"prev_{key}_qp"]),
        a(fx[f"prev_{key}_psp"]), dt, u, smooth_frac)
    return dict(t=r.T, q=r.q_v, cwm=r.cwm, tp=r.T_store, qp=r.q_v_store)


def _err(ours, ref):
    return float(np.max(np.abs(np.asarray(ours) - ref)) / np.max(np.abs(ref)))


@pytest.mark.parametrize("run,tend", [(r, t) for r in ("A", "B")
                                      for t in ("moisten", "dry", "mixed")])
def test_gscond_matches_oracle(run, tend):
    fx = _fx()
    key = f"{run}_{tend}"
    ours = _ours(fx, run, tend)
    spread = dict(zip(FIELDS, fx[f"spread_{key}"]))
    for k in FIELDS:
        err = _err(ours[k], fx[f"ora_{key}_{k}"])
        assert err <= max(BAR, spread[k]), (key, k, err, spread[k])


def test_fixture_exercises_every_branch():
    """Condensation, cloud evaporation and the ice latent heat all occur."""
    fx = _fx()
    n_cond = n_evap = 0
    for run, tend in _keys(fx):
        dcwm = fx[f"ora_{run}_{tend}_cwm"] - fx["col_q_c"]
        n_cond += int(np.sum(dcwm > 0))
        n_evap += int(np.sum(dcwm < 0))
    assert n_cond > 50 and n_evap > 10, (n_cond, n_evap)
    # Ice id: latent heat per kg differs from L_v somewhere (heating / condensed).
    from legoesm import constants as C
    key = "A_moisten"
    dq = fx["col_q_v"] - fx[f"ora_{key}_q"]
    dT = fx[f"ora_{key}_t"] - fx["col_T"]
    m = np.abs(dq) > 1e-9
    L = C.c_pd * dT[m] / dq[m]
    assert np.any(np.abs(L / (C.L_v + C.L_f) - 1) < 1e-9)  # latent-ok: ice-id check
    assert np.any(np.abs(L / C.L_v - 1) < 1e-9)  # latent-ok: liquid check


def test_smooth_default_close_and_differentiable():
    """At the production width the port stays near the oracle and its
    gradient is finite and matches a central difference."""
    from legoesm.atmosphere.physics.microphysics.config import SundqvistConfig
    from legoesm.atmosphere.physics.microphysics.sundqvist import zhao_carr_gscond
    fx = _fx()
    frac = SundqvistConfig().gscond_smooth_frac
    ours = _ours(fx, "A", "mixed", smooth_frac=frac)
    assert _err(ours["t"], fx["ora_A_mixed_t"]) < 1e-3
    key = "A_mixed"
    a = lambda x: jnp.asarray(x, jnp.float64)  # noqa: E731

    def f(T):
        r = zhao_carr_gscond(
            T, a(fx["col_q_v"]), a(fx["col_q_c"]), a(fx["col_p_full"]),
            a(fx["col_p_half"][:, -1]), a(fx[f"prev_{key}_tp"]), a(fx[f"prev_{key}_qp"]),
            a(fx[f"prev_{key}_psp"]), 600.0, 0.8, frac)
        return jnp.sum(r.cwm * 1e3) + jnp.sum(r.T)

    T0 = a(fx["col_T"])
    g = jax.grad(f)(T0)
    assert bool(jnp.all(jnp.isfinite(g)))
    v = jnp.asarray(np.random.default_rng(0).standard_normal(T0.shape))
    h = 1e-4
    fd = (f(T0 + h * v) - f(T0 - h * v)) / (2 * h)
    assert abs(float(jnp.vdot(g, v)) - float(fd)) <= 1e-5 * max(1.0, abs(float(fd)))


@pytest.mark.parametrize("smooth_frac", [0.0, 0.01])
def test_rh_crit_one_is_finite(smooth_frac):
    """rh_crit = 1 (inside the declared bounds): the oracle never forms
    1/(1-u); neither may the port's value or gradient."""
    from legoesm.atmosphere.physics.microphysics.sundqvist import zhao_carr_gscond
    from legoesm.thermo import saturation_specific_humidity
    T = jnp.full((1, 3), 280.0)
    p = jnp.full((1, 3), 8.0e4)
    ps = jnp.full((1,), 1.0e5)

    def f(q):
        r = zhao_carr_gscond(T, q, jnp.full((1, 3), 1e-4), p, ps, T, 0.99 * q, ps,
                             600.0, 1.0, smooth_frac)
        return jnp.sum(r.cwm) + jnp.sum(r.T)

    q = saturation_specific_humidity(T, p) * jnp.array([[0.9, 1.0, 1.02]])
    assert bool(jnp.isfinite(f(q)))
    assert bool(jnp.all(jnp.isfinite(jax.grad(f)(q))))


def test_zero_carry_is_the_explicit_fresh_start_bitwise():
    """A zero carry (fresh start / restart before the carry existed) runs the
    step with tp = T, qp = max(q, epsq), psp = ps, bitwise."""
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    from legoesm.atmosphere.physics.microphysics.sundqvist import (
        sundqvist_carry_init, sundqvist_microphysics)
    fx = _fx()
    a = lambda k: jnp.asarray(fx[f"col_{k}"])  # noqa: E731
    T, q, qc, pf, ph = a("T"), a("q_v"), a("q_c"), a("p_full"), a("p_half")
    z = jnp.zeros_like(T)
    hyd = HydrometeorState(q_c=qc, q_r=z, q_i=z, q_s=z, q_g=z, N_c=z, N_r=z, N_i=z)
    rho = pf / 287.0 / T

    def run(prev):
        return sundqvist_microphysics(T, q, hyd, pf, ph, rho, jnp.ones_like(T), 600.0,
                                      cell_area=1.0e10, prev_state=prev)

    zero = run(sundqvist_carry_init(*T.shape, T.dtype))
    explicit = run({"zc_T_prev": T, "zc_q_v_prev": jnp.maximum(q, 2.0e-12),
                    "zc_p_s_prev": ph[:, -1]})
    for k in ("dT_dt", "dq_v_dt", "dq_c_dt", "precipitation"):
        np.testing.assert_array_equal(np.asarray(getattr(zero, k)),
                                      np.asarray(getattr(explicit, k)))


def test_stored_humidity_is_floored_at_epsq():
    """The oracle stores qp = max(q, epsq) for the next step [514]."""
    from legoesm.atmosphere.physics.microphysics.sundqvist import zhao_carr_gscond
    T = jnp.full((1, 2), 280.0)
    q = jnp.zeros((1, 2))
    p = jnp.full((1, 2), 8.0e4)
    ps = jnp.full((1,), 1.0e5)
    r = zhao_carr_gscond(T, q, jnp.zeros((1, 2)), p, ps, T, q + 2e-12, ps, 600.0, 0.8, 0.0)
    np.testing.assert_array_equal(np.asarray(r.q_v_store), 2.0e-12)
