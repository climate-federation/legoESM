def _fx():
    return dict(np.load(FIXTURE))


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


def _production_morrison():
    """The production deck's MorrisonConfig, resolved as the MPAS column lane
    builds it (run_amip parser -> build_config_from_args ->
    apply_microphysics_experiment_flags -> thread_morrison_scalars)."""
    from scripts.run.run_amip import build_arg_parser, build_config_from_args

    from legoesm.atmosphere.physics.microphysics.config import (
        MicrophysicsConfig,
        apply_microphysics_experiment_flags,
    )
    from legoesm.driver.physics_pipeline import thread_morrison_scalars
    from legoesm.driver.run_config_yaml import load_yaml_config
    parser = build_arg_parser()
    argv = ["--config", str(DECK)]
    keys = load_yaml_config(DECK, parser, example_keys="'microphysics'")
    parser.set_defaults(**keys)
    parser.set_defaults(_config_keys=frozenset(keys))
    cfg = build_config_from_args(parser.parse_args(argv))
    assert cfg.microphysics == "morrison"
    m = getattr(MicrophysicsConfig(scheme="morrison"), "morrison")
    m = apply_microphysics_experiment_flags(
        m, "morrison", nc_from_aerosol=cfg.nc_from_aerosol,
        subgrid_autoconversion=cfg.subgrid_autoconversion,
        homogeneous_ice_nucleation=getattr(cfg, "homogeneous_ice_nucleation", False),
        liquid_from_closure=cfg._liquid_partition_resolved(),
        hard_sat_adjust_threshold=getattr(cfg, "hard_sat_adjust_threshold", None),
        hard_sat_max_heating_K=getattr(cfg, "hard_sat_max_heating_K", None))
    return thread_morrison_scalars(cfg, "morrison", m)


def _run_columns(fx, cfg, relvar=None):
    from legoesm import constants as C
    from legoesm.atmosphere.physics.microphysics.morrison import morrison_microphysics
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    g = {k: jnp.asarray(fx[f"col_{k}"]) for k in
         ("T", "q_v", "q_c", "cf", "q_r", "N_r", "N_c", "p_full", "p_half", "rho")}
    dz = (g["p_half"][:, 1:] - g["p_half"][:, :-1]) / (C.g * g["rho"])
    z = jnp.zeros_like(g["T"])
    hyd = HydrometeorState(q_c=g["q_c"], q_r=g["q_r"], q_i=z, q_s=z, q_g=z,
                           N_c=g["N_c"], N_r=g["N_r"], N_i=z)
    return morrison_microphysics(
        g["T"], g["q_v"], hyd, g["p_full"], g["p_half"], g["rho"], dz,
        float(fx["dt"]), cfg._replace(publish_qc_budget=True),
        cloud_fraction=g["cf"], relvar=relvar)


def test_fixture_provenance_and_inputs_reproduce():
    """The committed generator rebuilds the fixture's inputs bit-for-bit."""
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    assert meta["tag"] == "cam_cesm2_1_rel_60"
    assert meta["sha"] == "a03b84b7c4e34f965b115686f22a043b85739e56"
    spec = importlib.util.spec_from_file_location("mg2_make_fixture", GENERATOR)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    cols = gen.build_columns()
    for k in gen.COL_FIELDS:
        np.testing.assert_array_equal(np.stack([c[k] for c in cols]), fx[f"col_{k}"])
    pts = gen.build_points()
    for i, k in enumerate(gen.PT_IN):
        np.testing.assert_array_equal(pts[:, i], fx[f"pt_in_{k}"])


def test_warm_rain_kernels_match_mg2():
    """Per-process: droplet-number reset + KK2000 (CAM6), accretion with
    var_coef, in-precip rain + MG2 slope bounds, Beheng self-collection,
    clear-air rain evaporation -- each against micro_mg_utils.F90."""
    from legoesm.atmosphere.physics.microphysics import _warm_rain as W
    from legoesm.atmosphere.physics.microphysics.config import MorrisonConfig
    from legoesm.atmosphere.physics.microphysics.morrison import resolve_morrison_flavor
    from legoesm.thermo import saturation_specific_humidity_goff_gratch
    fx = _fx()
    i = {k[6:]: jnp.asarray(v) for k, v in fx.items() if k.startswith("pt_in_")}
    o = {k[7:]: v for k, v in fx.items() if k.startswith("pt_out_")}
    cfg = resolve_morrison_flavor(MorrisonConfig(morrison_flavor="mg"))
    rho = i["rho"]
    nc_vol = i["ncic"] * rho
    errs = {}
    errs["ncic_adj"] = _rel(W.mg2_size_bounded_nc(i["qcic"], nc_vol, rho) / rho,
                            o["ncic_adj"])
    prc, nr_au, x_c = W.autoconversion_kk2000_cam6(i["qcic"], nc_vol, rho, i["relvar"])
    errs["prc"] = _rel(prc, o["prc"])
    errs["nprc"] = _rel(nr_au / rho, o["nprc"])
    errs["nprc1"] = _rel(jnp.where(prc > 0, prc / x_c, 0.0), o["nprc1"])
    q_ric, N_ric, lamr, n0r = W.mg2_inprecip_rain(
        i["qr"], i["nr"] * rho, rho, i["precip_frac"], cfg.lamr_min, cfg.lamr_max)
    errs["qric"] = _rel(q_ric, o["qric"])
    errs["nric"] = _rel(N_ric / rho, o["nric"])
    errs["lamr"] = _rel(lamr, o["lamr"])
    errs["n0r"] = _rel(n0r / rho, o["n0r"])
    vc = W.mg2_var_coef(i["relvar"], 1.15, rho.dtype)
    errs["pra"] = _rel(W.accretion_kk2000(i["qcic"], q_ric, fact=vc), o["pra"])
    errs["nragg"] = _rel(W.self_collection_rain_mg2(q_ric, N_ric, rho, i["precip_frac"]),
                         o["nragg"] * i["precip_frac"] * rho)
    qvl = saturation_specific_humidity_goff_gratch(i["T"], i["p"])
    errs["qvl"] = _rel(qvl, o["qvl"])
    evap = W.rain_evaporation_mg2(
        i["qfrac"] * qvl, qvl, i["T"], i["p"], rho, q_ric, lamr, n0r, i["lcldm"],
        i["precip_frac"], i["qcic"], i["qiic"], cfg)
    errs["evap"] = _rel(evap, -o["pre"] * i["precip_frac"])
    worst = {k: float(v.max()) for k, v in errs.items()}
    print("kernel max rel err", worst)
    assert max(worst.values()) <= TOL, worst
    # non-trivial coverage: every process is active somewhere, and the
    # clear-air gate both fires and blocks
    for k in ("prc", "pra", "nragg", "pre"):
        assert np.count_nonzero(o[k]) > 50, k
    assert np.any((o["pre"] == 0) & (o["qric"] > 0) & (i["qfrac"] < 1.0))
    assert np.any(o["ncic_adj"] != fx["pt_in_ncic"])


@pytest.mark.parametrize("rv", [1.0, 2.0, 10.0])
def test_whole_call_rain_matches_mg2(rv):
    """Whole micro_mg_tend vs morrison_microphysics, production deck config
    with kk2000_cam6 at relvar ``rv``, hard limit: autoconversion, accretion,
    rain evaporation, rain mass/number tendency (processes + post-source
    sedimentation + number re-adjustment) and the surface rain flux."""
    fx = _fx()
    cfg = _production_morrison()
    cfg = cfg._replace(**HARD_LIMIT, warm_rain_scheme="kk2000_cam6",
                       kk2000_cam6_relvar=rv)
    out = _run_columns(fx, cfg)
    qb = out.qc_budget
    rho = fx["col_rho"]
    p = f"ora_rv{rv:g}_"
    evap = np.asarray(out.dq_v_dt) + np.asarray(qb["condensation"])
    errs = {
        "prc": _rel(-np.asarray(qb["autoconversion"]), fx[p + "prctot"]),
        "pra": _rel(-np.asarray(qb["accretion"]), fx[p + "pratot"]),
        "evap": _rel(evap, fx[p + "nevapr"]),
        "dq_r": _rel(out.dq_r_dt, fx[p + "qrtend"]),
        "dN_r": _rel(np.asarray(out.dN_r_dt) / rho, fx[p + "nrtend"]),
        "precip": _rel(out.precipitation, fx[p + "rain_sfc_flux"]),
    }
    worst = {k: float(v.max()) for k, v in errs.items()}
    print(f"whole-call rv={rv:g} max rel err", worst)
    assert max(worst.values()) <= TOL, worst
    # MG2's q_c limiter binds on these columns (the omsm path is exercised)
    assert np.any(fx[p + "qcrat"] < 1.0)
    assert np.all(np.asarray(qb["condensation"]) == 0.0)


def test_gradients_finite_on_fixture_columns():
    """jax.grad of column rain (and precip) w.r.t. the inputs is finite."""
    fx = _fx()
    cfg = _production_morrison()._replace(warm_rain_scheme="kk2000_cam6",
                                          kk2000_cam6_relvar=2.0)

    def loss(qr, qc, T):
        f = dict(fx)
        f["col_q_r"], f["col_q_c"], f["col_T"] = qr, qc, T
        out = _run_columns(f, cfg)
        return jnp.sum(out.dq_r_dt) + jnp.sum(out.precipitation) * 1e3

    g = jax.grad(loss, argnums=(0, 1, 2))(
        jnp.asarray(fx["col_q_r"]), jnp.asarray(fx["col_q_c"]),
        jnp.asarray(fx["col_T"]))
    for gi in g:
        assert bool(jnp.all(jnp.isfinite(gi)))
    assert float(jnp.max(jnp.abs(g[0]))) > 0.0


