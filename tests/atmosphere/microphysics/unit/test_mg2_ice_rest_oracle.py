"""CAM6 MG2 ice follow-ups on the Morrison lane (tier-1 oracle rows 26, 29,
31; row 30 recorded as a gap) vs the RUNNING MG2 oracle.

Fixture ``tests/atmosphere/microphysics/oracle_fixtures/mg2_ice_rest.npz`` was
generated by RUNNING ESCOMP/CAM ``cam_cesm2_1_rel_60``
(a03b84b7c4e34f965b115686f22a043b85739e56) ``micro_mg_utils.F90`` compiled
unmodified (gfortran 8.5.0), with ``python scripts/validate/oracle/
morrison_mg2_ice_rest/make_fixture.py --cam <CAM> --build <dir> --out
mg2_ice_rest.npz`` (metadata in the npz ``meta``).

Tolerance and metric: those of the merged MG2 oracle tests (max relative
error <= 1e-10 in fp64, every existing sharpness field at its hard limit).
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

jax.config.update("jax_enable_x64", True)

ROOT = Path(__file__).resolve().parents[4]
FIXTURE = ROOT / "tests/atmosphere/microphysics/oracle_fixtures/mg2_ice_rest.npz"
GENERATOR = ROOT / "scripts/validate/oracle/morrison_mg2_ice_rest/make_fixture.py"
sys.path.insert(0, str(Path(__file__).resolve().parent))
from test_mg2_warm_rain_oracle import (  # noqa: E402
    HARD_LIMIT, TOL, _production_morrison, _rel)

QSMALL = 1.0e-18


def _fx():
    return dict(np.load(FIXTURE))


def _pts(fx):
    i = {k[6:]: v for k, v in fx.items() if k.startswith("pt_in_")}
    o = {k[7:]: v for k, v in fx.items() if k.startswith("pt_out_")}
    return i, o


def _cfg():
    return _production_morrison()._replace(**HARD_LIMIT,
                                           warm_rain_scheme="kk2000_cam6")


def _cells(T, qi, Ni, qc=0.0, rhi=0.9, cfg=None, dtype=jnp.float64, dt=600.0):
    """Single-level cells, cloud fraction 1 (in-cloud = grid), no snow/rain."""
    from legoesm import constants as C
    from legoesm.thermo import saturation_specific_humidity_ice_goff_gratch
    from legoesm.atmosphere.physics.microphysics.morrison import morrison_microphysics
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    cfg = _cfg() if cfg is None else cfg
    a = lambda x: jnp.asarray(x, dtype).reshape(-1, 1)  # noqa: E731
    T, qi, Ni, qc = a(T), a(qi), a(Ni), a(qc) + jnp.zeros_like(a(T))
    p = jnp.full_like(T, 50000.0)
    ph = jnp.concatenate([p - 500.0, p + 500.0], axis=1)
    rho = p / (C.R_d * T)
    dz = (ph[:, 1:] - ph[:, :-1]) / (C.g * rho)
    qv = rhi * saturation_specific_humidity_ice_goff_gratch(T, p)
    z = jnp.zeros_like(T)
    hyd = HydrometeorState(q_c=qc, q_r=z, q_i=qi, q_s=z, q_g=z,
                           N_c=z + 1.0e8, N_r=z, N_i=Ni, N_s=z)
    out = morrison_microphysics(T, qv, hyd, p, ph, rho, dz, dt,
                                cfg._replace(publish_qc_budget=True),
                                cloud_fraction=z + 1.0)
    return out, qi


def test_fixture_provenance_and_inputs_reproduce():
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    assert meta["tag"] == "cam_cesm2_1_rel_60"
    assert meta["sha"] == "a03b84b7c4e34f965b115686f22a043b85739e56"
    spec = importlib.util.spec_from_file_location("mg2ir_make_fixture", GENERATOR)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    pts = gen.build_points()
    for j, k in enumerate(gen.PT_IN):
        np.testing.assert_array_equal(pts[:, j], fx[f"pt_in_{k}"])


def test_ice_slope_and_ferrier_match_mg2_outside_the_gate_band():
    """MG2 size_dist_param_basic on mg_ice_props (the bounds of row 26) then
    ice_autoconversion at every fixture ice point, except two classes the
    port does not reproduce, both recorded: (i) qsmall <= qiic <= 1e-14,
    where MG2 converts and the port's 1e-14 gate does not (oracle row 30,
    open: the RULE 5 form of the new gate is an ask), and (ii) qiic ==
    qsmall exactly, where the oracle's nprci is 0/0."""
    from legoesm import constants as C
    from legoesm.atmosphere.physics.microphysics import _warm_rain as W
    fx = _fx()
    i, o = _pts(fx)
    ice = i["qiic"] > 0.0
    dcs = float(fx["dcs"])
    T, qi, ni = (jnp.asarray(i[k][ice]) for k in ("T", "qiic", "niic"))
    niic, lami = W.mg2_ice_slope(qi, ni, 500.0, dcs)
    prci, nprci = W.ice_autoconversion_mg2(qi, niic, lami, dcs, T)
    edge = (i["qiic"][ice] == QSMALL) & (i["T"][ice] <= C.T_freeze)
    assert np.array_equal(~np.isfinite(o["nprci"][ice]), edge)
    band = (i["qiic"][ice] >= QSMALL) & (i["qiic"][ice] <= 1.0e-14)
    keep = ~band
    errs = {"niic": _rel(niic, o["niic"][ice]), "lami": _rel(lami, o["lami"][ice]),
            "prci": _rel(np.asarray(prci)[keep], o["prci"][ice][keep]),
            "nprci": _rel(np.asarray(nprci)[keep], o["nprci"][ice][keep])}
    worst = {k: float(np.max(v)) for k, v in errs.items()}
    print("ice slope / Ferrier max rel err", worst)
    assert max(worst.values()) <= TOL, worst
    assert np.count_nonzero(o["prci"][ice][keep] > 0.0) >= 10
    # the recorded row-30 gap: MG2 converts in the band, the port does not
    gap = band & ~edge & (o["prci"][ice] > 0.0)
    assert np.count_nonzero(gap) >= 10
    assert np.all(np.asarray(prci)[gap] == 0.0)
    print("row-30 gap: max oracle prci in band", float(np.max(o["prci"][ice][gap])))


@pytest.mark.parametrize("lam", [300.0, 3.0e6])
def test_final_ice_number_held_inside_mg2_bounds(lam):
    """Row 26: in the CAM6 MG2 mode the final cloud-ice number re-adjustment
    holds the slope inside MG2's 1/[2 dcs, 1 um] (micro_mg2_0.F90:2778), so
    a cell beyond a bound ends at the oracle's bounded number per unit mass
    (the old 1/600 um and 1/10 um bounds gave another number).  dt = 10 s
    and ice saturation keep the cell beyond the bound after this step's
    Ferrier conversion and deposition."""
    fx = _fx()
    i, o = _pts(fx)
    k = np.flatnonzero((i["T"] == 250.0) & (i["qiic"] == 1.0e-6)
                       & np.isclose(i["niic"], lam ** 3 * 1.0e-6 / (np.pi * 500.0),
                                    rtol=1e-12))
    assert k.size == 1
    ratio_mg2 = o["niic"][k[0]] / i["qiic"][k[0]]
    out, qi = _cells([250.0], [1.0e-6], [lam ** 3 * 1.0e-6 / (np.pi * 500.0)],
                     rhi=1.0, dt=10.0)
    q_new = float(qi[0, 0] + 10.0 * out.dq_i_dt[0, 0])
    n_new = float(lam ** 3 * 1.0e-6 / (np.pi * 500.0) + 10.0 * out.dN_i_dt[0, 0])
    assert q_new > 1.0e-14
    assert float(_rel(n_new / q_new, ratio_mg2)) <= TOL, (n_new / q_new, ratio_mg2)


def test_mg2_mode_has_no_cloud_ice_riming():
    """Row 29: CAM6 MG2 has no cloud-ice riming; the legacy heuristic is off
    in the MG2 mode (it is active on the same cells outside it)."""
    T, qi, Ni = [255.0, 255.0], [1.0e-5, 1.0e-4], [1.0e5, 1.0e5]
    out, _ = _cells(T, qi, Ni, qc=2.0e-4, rhi=1.0)
    assert np.all(np.asarray(out.qc_budget["riming_ice"]) == 0.0)
    off, _ = _cells(T, qi, Ni, qc=2.0e-4, rhi=1.0,
                    cfg=_cfg()._replace(warm_rain_incloud=False))
    assert np.all(np.asarray(off.qc_budget["riming_ice"]) < 0.0)


def _riming(qc, qs, ns, T, rho, p):
    from legoesm.atmosphere.physics.microphysics import _warm_rain as W
    from legoesm.atmosphere.physics.microphysics.config import MorrisonConfig
    from legoesm.atmosphere.physics.microphysics.morrison import resolve_morrison_flavor
    cfg = resolve_morrison_flavor(MorrisonConfig(morrison_flavor="mg"))
    nc, pgam, lamc = W.mg2_size_dist_liq(qc, jnp.full_like(qc, 100.0e6), rho)
    qsic, nsic, lams, n0s = W.mg2_inprecip_snow(qs, ns, jnp.ones_like(qs), cfg)
    _, uns = W.mg2_snow_fall_speeds(lams, rho, cfg)
    _, mu = W.mg2_snow_vent_eps(n0s, lams, T, p, rho, cfg)
    return W.mg2_accrete_cloud_water_snow(T, rho, mu, uns, qc, nc / rho, qsic, pgam,
                                          lamc, lams, n0s, cfg)


def test_snow_riming_matches_mg2_including_qsmall():
    """Row 31: at qcic == qsmall exactly MG2 sets lamc = 0 while riming gates
    on qcic >= qsmall; the compiled oracle returns psacws = 0 there (eci =
    max(NaN, 0) = 0 in gfortran), where the port returned NaN.  Now every
    fixture riming point matches MG2, that one included."""
    fx = _fx()
    i, o = _pts(fx)
    rim = i["qsic"] > 0.0
    args = [jnp.asarray(i[k][rim]) for k in ("qcic", "qsic", "nsic", "T", "rho", "p")]
    ps, nps = _riming(*args)
    at = i["qcic"][rim] == QSMALL
    assert at.sum() == 1 and o["psacws"][rim][at][0] == 0.0
    errs = {"psacws": _rel(ps, o["psacws"][rim]),
            "npsacws": _rel(nps, o["npsacws"][rim])}
    assert max(float(np.max(v)) for v in errs.values()) <= TOL, errs
    assert np.all(o["psacws"][rim][~at] > 0.0)


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
@pytest.mark.parametrize("qc", [QSMALL, QSMALL * (1.0 + 1.0e-6)])
def test_snow_riming_gradient_finite_at_the_cloud_floor(dtype, qc):
    from legoesm import constants as C
    T, p = 260.0, 50000.0
    rho = p / (C.R_d * T)
    ns = 2000.0 ** 3 * 1.0e-4 / (np.pi * 250.0)
    a = [jnp.asarray(x, dtype) for x in (qc, 1.0e-4, ns, T, rho, p)]
    for j in (0, 1):
        g = jax.grad(lambda x, y: _riming(x, y, *a[2:])[j], argnums=(0, 1))(a[0], a[1])
        assert all(bool(jnp.isfinite(gi)) for gi in g), (j, g)


@pytest.mark.parametrize("dtype", [jnp.float64])
def test_whole_call_gradients_finite_on_ice_cells(dtype):
    """jax.grad through the MG2-mode call on the cells above (trace ice,
    both slope bounds, mixed-phase riming cells) is finite in fp64.
    fp32 is NaN on these cells on the base branch too (pre-existing, not
    from this change; reported in the PR)."""
    T = [250.0, 250.0, 250.0, 255.0]
    qi = [5.0e-15, 1.0e-6, 1.0e-6, 1.0e-5]
    Ni = [2.0e4 ** 3 * 5.0e-15 / (np.pi * 500.0), 300.0 ** 3 * 1.0e-6 / (np.pi * 500.0),
          3.0e6 ** 3 * 1.0e-6 / (np.pi * 500.0), 1.0e5]
    qc = [0.0, 0.0, 0.0, 2.0e-4]

    def loss(qi_, ni_, qc_):
        out, _ = _cells(T, qi_, ni_, qc=qc_, dtype=dtype,
                        cfg=_production_morrison()._replace(
                            warm_rain_scheme="kk2000_cam6"))
        return (jnp.sum(out.dq_i_dt) * 1e6 + jnp.sum(out.dq_s_dt) * 1e6
                + jnp.sum(out.dN_i_dt / jnp.asarray(Ni, dtype).reshape(-1, 1))
                + jnp.sum(out.dq_c_dt) * 1e6)
    g = jax.grad(loss, argnums=(0, 1, 2))(*(jnp.asarray(x, dtype) for x in (qi, Ni, qc)))
    for gi in g:
        assert bool(jnp.all(jnp.isfinite(gi))), g
    assert float(jnp.max(jnp.abs(g[0]))) > 0.0
