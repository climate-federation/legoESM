def _fx():
    return dict(np.load(FIXTURE))


def _pts(fx):
    i = {k[6:]: v for k, v in fx.items() if k.startswith("pt_in_")}
    o = {k[7:]: v for k, v in fx.items() if k.startswith("pt_out_")}
    return i, o


def _cfg():
    return _production_morrison()._replace(**HARD_LIMIT,
                                           warm_rain_scheme="kk2000_cam6")


def _cells(T, qi, Ni, qc=0.0, rhi=0.9, cfg=None, dtype=jnp.float64, dt=600.0):
    """Single-level cells, cloud fraction 1 (in-cloud = grid), no snow/rain."""
    from legoesm import constants as C
    from legoesm.thermo import saturation_specific_humidity_ice_goff_gratch
    from legoesm.atmosphere.physics.microphysics.morrison import morrison_microphysics
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    cfg = _cfg() if cfg is None else cfg
    a = lambda x: jnp.asarray(x, dtype).reshape(-1, 1)  # noqa: E731
    T, qi, Ni, qc = a(T), a(qi), a(Ni), a(qc) + jnp.zeros_like(a(T))
    p = jnp.full_like(T, 50000.0)
    ph = jnp.concatenate([p - 500.0, p + 500.0], axis=1)
    rho = p / (C.R_d * T)
    dz = (ph[:, 1:] - ph[:, :-1]) / (C.g * rho)
    qv = rhi * saturation_specific_humidity_ice_goff_gratch(T, p)
    z = jnp.zeros_like(T)
    hyd = HydrometeorState(q_c=qc, q_r=z, q_i=qi, q_s=z, q_g=z,
                           N_c=z + 1.0e8, N_r=z, N_i=Ni, N_s=z)
    out = morrison_microphysics(T, qv, hyd, p, ph, rho, dz, dt,
                                cfg._replace(publish_qc_budget=True),
                                cloud_fraction=z + 1.0)
    return out, qi


