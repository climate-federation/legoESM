"""Seifert & Beheng (2001) warm rain vs the RUNNING gSAM M2005 oracle.

Fixture ``tests/atmosphere/microphysics/oracle_fixtures/sb2001_warm_rain.npz``
was generated by RUNNING gSAM 1.8.8 ``SRC/MICRO_M2005/module_mp_graupel.f90``
(tarball sha256 0e9ea4a37f4daca5051cc4018cc95bbc5583159c7c27d7d05d1104fae4ed270c;
gSAM has no git tag/SHA) with IRAIN=1, the gSAM default ``dofix_pgam=.false.``
and ``dopredictNc=.false.``, compiled with gfortran 8.5.0 in fp64, via
``python scripts/validate/oracle/sb2001_warm_rain/make_fixture.py --gsam <gSAM1.8.8>
--build <dir> --out sb2001_warm_rain.npz`` (metadata in the npz ``meta``).

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64.
The SB2001 kernels have no smoothing fields, so the hard limit is the default.
Relative error is ``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0); no
floor (the tier-1 oracle tests' metric).
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from legoesm.atmosphere.physics.microphysics._warm_rain import (
    accretion_sb2001,
    autoconversion_sb2001,
    m2005_cloud_droplet_psd,
)

jax.config.update("jax_enable_x64", True)

ROOT = Path(__file__).resolve().parents[4]
FIXTURE = ROOT / "tests/atmosphere/microphysics/oracle_fixtures/sb2001_warm_rain.npz"
GENERATOR = ROOT / "scripts/validate/oracle/sb2001_warm_rain/make_fixture.py"
TOL = 1.0e-10
QSMALL = 1.0e-14     # gSAM M2005 QSMALL: the PSD is only diagnosed above it


def _fx():
    return dict(np.load(FIXTURE))


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


def _inputs(fx, dtype=jnp.float64):
    return tuple(jnp.asarray(fx[k], dtype=dtype) for k in ("q_c", "q_r", "N_c", "rho"))


def test_fixture_provenance_and_inputs_reproduce():
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    assert "dofix_pgam=.false." in meta["settings"]
    spec = importlib.util.spec_from_file_location("sb2001_fixture", GENERATOR)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    # The generator refuses sources whose sha256 differs from the pinned gSAM.
    assert meta["source_sha256"] == gen.SOURCE_SHA256
    pts = gen.build_points()
    n = len(pts)
    for i, nc0 in enumerate(gen.NC0_CM3):
        sl = slice(i * n, (i + 1) * n)
        np.testing.assert_array_equal(fx["q_c"][sl], pts[:, 6])
        np.testing.assert_array_equal(fx["q_r"][sl], pts[:, 7])
        np.testing.assert_array_equal(fx["rho"][sl], pts[:, 1])
        np.testing.assert_array_equal(fx["N_c"][sl], nc0 * 1.0e6)


def test_rates_match_gsam():
    fx = _fx()
    q_c, q_r, N_c, rho = _inputs(fx)
    prc, dnr, _ = autoconversion_sb2001(q_c, q_r, N_c, rho)
    pra = accretion_sb2001(q_c, q_r, rho)
    errs = {
        "PRC": _rel(prc, fx["ora_prc"]).max(),
        "NPRC1": _rel(dnr / rho, fx["ora_nprc1"]).max(),
        "PRA": _rel(pra, fx["ora_pra"]).max(),
    }
    assert max(errs.values()) <= TOL, errs
    # Non-vacuous: the gates and the diagnosed shape are exercised.
    assert np.sum(fx["ora_prc"] > 0) > 500 and np.sum(fx["ora_prc"] == 0) > 300
    assert np.sum(fx["ora_pra"] > 0) > 500 and np.sum(fx["ora_pra"] == 0) > 300


def test_droplet_psd_matches_gsam():
    """pgam, nu and the slope-clamped droplet number where gSAM diagnoses them."""
    fx = _fx()
    q_c, _, N_c, rho = _inputs(fx)
    pgam, nu, nc_adj = m2005_cloud_droplet_psd(q_c, N_c, rho)
    m = fx["q_c"] >= QSMALL
    errs = {
        "PGAM": _rel(np.asarray(pgam)[m], fx["ora_pgam"][m]).max(),
        "NU": _rel(np.asarray(nu)[m], fx["ora_nu"][m]).max(),
        "NC3D": _rel(np.asarray(nc_adj / rho)[m], fx["ora_nc3d"][m]).max(),
    }
    assert max(errs.values()) <= TOL, errs
    # Both pgam bounds and both droplet-slope bounds are in the fixture.
    assert {2.0, 10.0} <= set(np.round(fx["ora_pgam"][m], 12))
    ratio = fx["ora_nc3d"][m] * fx["rho"][m] / fx["N_c"][m]
    assert ratio.min() < 0.5 and ratio.max() > 2.0


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_gradients_finite_on_fixture_points(dtype):
    fx = _fx()
    q_c, q_r, N_c, rho = _inputs(fx, dtype)

    def loss(q_c, q_r, N_c):
        prc, dnr, _ = autoconversion_sb2001(q_c, q_r, N_c, rho)
        return jnp.sum(prc * 1e6 + dnr * 1e-6 + accretion_sb2001(q_c, q_r, rho) * 1e6)

    g = jax.grad(loss, argnums=(0, 1, 2))(q_c, q_r, N_c)
    for gi in g:
        assert bool(jnp.all(jnp.isfinite(gi)))


def test_jit_matches_eager():
    fx = _fx()
    args = _inputs(fx)

    def f(q_c, q_r, N_c, rho):
        prc, dnr, _ = autoconversion_sb2001(q_c, q_r, N_c, rho)
        return prc, dnr, accretion_sb2001(q_c, q_r, rho)

    for a, b in zip(f(*args), jax.jit(f)(*args)):
        assert _rel(a, b).max() <= TOL
