ROOT = Path(__file__).resolve().parents[4]
FIXTURE = ROOT / "tests/atmosphere/microphysics/oracle_fixtures/sdm_erf.npz"
TOL = 1.0e-10


def _fx():
    return dict(np.load(FIXTURE))


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


def test_fixture_provenance():
    meta = json.loads(str(_fx()["meta"]))
    assert meta["repo"] == "erf-model/ERF" and meta["tag"] == "26.09"
    assert meta["sha"] == "6d09aeb120eb4eac388106004bfaaa7f795a2e26"
    assert FIXTURE.stat().st_size < 1_000_000


def test_terminal_velocities_match_erf():
    f = _fx()
    r = jnp.asarray(f["vt_r"])
    assert _rel(sk.terminal_velocity_rogers_yau(r), f["vt_rogers_yau"]).max() <= TOL
    assert _rel(sk.terminal_velocity_atlas_ulbrich(r), f["vt_atlas_ulbrich"]).max() <= TOL
    v = sk.terminal_velocity_cloud_rain_shima(
        r, jnp.asarray(f["vt_rho"]), jnp.asarray(f["vt_p"]), jnp.asarray(f["vt_T"]))
    assert (f["vt_r"] > 4.0e-3).any()           # the 4 mm cap is exercised
    assert _rel(v, f["vt_shima"]).max() <= TOL


def test_collision_kernels_match_erf():
    f = _fx()
    r1, r2 = jnp.asarray(f["k_r1"]), jnp.asarray(f["k_r2"])
    dv = jnp.abs(jnp.asarray(f["k_v1"]) - jnp.asarray(f["k_v2"]))
    cfg = SDMConfig()
    assert _rel(sk.golovin_kernel(r1, r2, cfg.golovin_b), f["k_golovin"]).max() <= TOL
    assert _rel(sk.long_kernel(r1, r2, dv), f["k_long"]).max() <= TOL
    assert _rel(sk.hall_kernel(r1, r2, dv), f["k_hall"]).max() <= TOL
    assert _rel(sk.sedimentation_kernel(r1, r2, dv), f["k_sedimentation"]).max() <= TOL
    kb = sk.brownian_kernel(r1, r2, jnp.asarray(f["k_m1"]), jnp.asarray(f["k_m2"]),
                            jnp.asarray(f["k_p"]), jnp.asarray(f["k_T"]))
    assert _rel(kb, f["k_brownian"]).max() <= TOL


def test_saturation_pressure_matches_erf_esatw():
    f = _fx()
    es = scond.saturation_vapor_pressure_erf(jnp.asarray(f["esat_T"]))
    assert _rel(es, f["esat"]).max() <= TOL


def test_growth_rhs_and_jacobian_match_erf():
    f = _fx()
    cfg = SDMConfig()
    T = jnp.asarray(f["drsq_T"])
    es = scond.saturation_vapor_pressure_erf(T)
    Ns = jnp.asarray(f["drsq_msol"]) * cfg.solute_ionization / cfg.solute_molar_mass
    u = jnp.asarray(f["drsq_u"])
    rhs = scond.drsq_dt(u, jnp.asarray(f["drsq_S"]), T, es, Ns)
    jac = scond.drsq_dt_jac(u, T, es, Ns)
    assert _rel(rhs, f["drsq_rhs"]).max() <= TOL
    assert _rel(jac, f["drsq_jac"]).max() <= TOL


@pytest.mark.parametrize("run", ["be_cfl1000", "cn_cfl1000", "dirk2_cfl1000",
                                 "rk4_adaptive_cfl1", "rk3bs_cfl1"])
def test_mass_change_integrators_match_erf(run):
    """ERF MassChange_LV particle update, each TI integrator, ERF solver defaults.

    The explicit methods are compared at cfl 1: at ERF's default cfl 1000 they
    are unstable and amplify round-off to O(1) inside the oracle itself (ERF
    -O0 vs -O2/FMA: 0.60 / 0.96 relative), so no implementation can match them.
    """
    f = _fx()
    meth, cfl = run.rsplit("_cfl", 1)
    cfg = SDMConfig()._replace(condensation_integrator=meth, adaptive_cfl=float(cfl))
    worst = 0.0
    for g in range(int(f["mc_ngroups"])):
        st = SuperDropletState(
            multiplicity=jnp.ones(f["mc_r0"].size), radius=jnp.asarray(f["mc_r0"]),
            solute_mass=jnp.asarray(f["mc_msol"]), active=jnp.ones(f["mc_r0"].size))
        out = scond.integrate_radius(st, jnp.asarray(f[f"mc{g}_S"]),
                                     jnp.asarray(f[f"mc{g}_T"]), float(f[f"mc{g}_dt"]), cfg)
        worst = max(worst, float(_rel(out.radius, f[f"mc{g}_{run}_r"]).max()))
    assert worst <= TOL, worst


@pytest.mark.parametrize("kernel", ["golovin", "hall", "sedimentation", "long"])
@pytest.mark.parametrize("brownian", [0, 1])
def test_coalescence_update_matches_erf(kernel, brownian, monkeypatch):
    """Same pairs and the same uniform draws (ERF's shuffle/RNG injected)."""
    f = _fx()
    rho, p, T, V, dt = (float(x) for x in f["c_state"])
    n = f["c_mult"].size
    cfg = SDMConfig()._replace(collision_kernel=kernel, include_brownian=bool(brownian),
                               terminal_velocity="cloud_rain_shima")
    U = jnp.asarray(f["c_U"])
    monkeypatch.setattr(scoal, "random", types.SimpleNamespace(
        uniform=lambda key, shape, dtype=None: U.astype(dtype)))
    st = SuperDropletState(multiplicity=jnp.asarray(f["c_mult"]),
                           radius=jnp.asarray(f["c_rad"]),
                           solute_mass=jnp.asarray(f["c_sol"]), active=jnp.ones(n))
    ia, ib = jnp.asarray(f["c_ia"]), jnp.asarray(f["c_ib"])
    scaling = 0.5 * n * (n - 1) / np.floor(0.5 * n)
    out = scoal.coalescence_step_pairs(st, ia, ib, jnp.ones(ia.size), scaling, V,
                                       rho, p, T, dt, jax.random.PRNGKey(0), cfg)
    tag = f"c_{kernel}_b{brownian}"
    assert (f[tag + "_mult"] != f["c_mult"]).any()       # collisions happened
    assert _rel(out.multiplicity, f[tag + "_mult"]).max() <= TOL
    assert _rel(out.radius, f[tag + "_rad"]).max() <= TOL
    assert _rel(out.solute_mass, f[tag + "_sol"]).max() <= TOL


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_gradients_finite_on_fixture(dtype):
    """jax.grad of scalar outputs w.r.t. inputs, fixed-substep growth + kernels."""
    f = _fx()
    r0 = jnp.asarray(f["mc_r0"][3:], dtype)
    ms = jnp.asarray(f["mc_msol"][3:], dtype)
    cfg = SDMConfig()

    def growth(S, T):
        st = SuperDropletState(jnp.ones_like(r0), r0, ms, jnp.ones_like(r0))
        return jnp.sum(scond.integrate_radius(st, S, T, 10.0, cfg).radius)

    g = jax.grad(growth, argnums=(0, 1))(jnp.asarray(1.002, dtype), jnp.asarray(285.0, dtype))
    assert all(np.isfinite(np.asarray(x)) for x in g)

    def kern(r):
        v = sk.terminal_velocity_cloud_rain_shima(r, 0.8, 7.0e4, 275.0)
        dv = jnp.abs(v[:, None] - v[None, :])
        R1, R2 = r[:, None], r[None, :]
        m = 4.0 / 3.0 * jnp.pi * 1000.0 * r ** 3
        return jnp.sum(sk.hall_kernel(R1, R2, dv) + sk.sedimentation_kernel(R1, R2, dv)
                       + sk.brownian_kernel(R1, R2, m[:, None], m[None, :], 7.0e4, 275.0))

    gk = jax.grad(kern)(jnp.asarray([5e-6, 2e-5, 1e-4, 1e-3, 5e-3], dtype))
    assert np.all(np.isfinite(np.asarray(gk)))


def test_eager_jit_parity():
    f = _fx()
    cfg = SDMConfig()._replace(condensation_integrator="be")
    st = SuperDropletState(jnp.ones(f["mc_r0"].size), jnp.asarray(f["mc_r0"]),
                           jnp.asarray(f["mc_msol"]), jnp.ones(f["mc_r0"].size))
    S, T = jnp.asarray(f["mc0_S"]), jnp.asarray(f["mc0_T"])
    eager = scond.integrate_radius(st, S, T, 10.0, cfg).radius
    jitted = jax.jit(lambda s, t: scond.integrate_radius(st, s, t, 10.0, cfg).radius)(S, T)
    assert _rel(eager, jitted).max() <= TOL
