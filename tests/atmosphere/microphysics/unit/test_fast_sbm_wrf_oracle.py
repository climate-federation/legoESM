@pytest.mark.parametrize("vel", ["v0", "vtab"])
@pytest.mark.parametrize("name", NAMES)
def test_warm_condensation_matches_onecond1(name, vel):
    f = _fx()
    T, q, p, rho = (float(x) for x in f[f"cond_{name}_in"])
    v = np.zeros_like(f["vt_table"]) if vel == "v0" else f["vt_table"]
    r = fcd.warm_condensation_step(
        jnp.asarray(f[f"cond_{name}_f"]), jnp.asarray(T), jnp.asarray(q), jnp.asarray(p),
        jnp.asarray(rho), float(f["dt"]), jnp.asarray(f["masses"]),
        v_term=jnp.asarray(v), config=CFG)
    tag = f"cond_{name}_{vel}"
    assert _rel(r.T, f[tag + "_T"]) <= TOL
    assert _rel(r.q_v, f[tag + "_q"]) <= TOL
    # condensed amount itself (q - q_new) at the same tolerance
    assert _rel(q - float(r.q_v), q - float(f[tag + "_q"])) <= TOL
    assert _rel(r.f, f[tag + "_f"]).max() <= TOL


@pytest.mark.parametrize("name", ["polar_supercooled", "trop_deep_warm"])
@pytest.mark.parametrize("T", [268, 258, 243])
def test_freeze_matches_freez(name, T):
    f = _fx()
    k = f"frz_{name}_{T}"
    Tin, rho = (float(x) for x in f[k + "_in"])
    r = ffrz.freeze_step_routed(jnp.asarray(f[k + "_f"]), jnp.asarray(f["masses"]),
                                jnp.asarray(Tin), jnp.asarray(rho), float(f["dt"]), CFG)
    assert _rel(r.f_liquid, f[k + "_liq"]).max() <= TOL
    assert _rel(r.f_crystals, f[k + "_cryst"]).max() <= TOL
    assert _rel(r.f_hail, f[k + "_hail"]).max() <= TOL
    # The oracle returns only the updated T, so its increment is known to
    # spacing(T); it is compared directly wherever that resolves 1e-10 of it.
    assert _rel(Tin + r.dT, f[k + "_T"]) <= TOL
    if _resolvable(f[k + "_T"], Tin):
        assert _rel(r.dT, f[k + "_T"] - Tin) <= TOL


@pytest.mark.parametrize("dt", [60, 150])
@pytest.mark.parametrize("T", [274, 278])
@pytest.mark.parametrize("cat", list(MELT_CATEGORY))
def test_melt_matches_j_w_melt(cat, T, dt):
    f = _fx()
    base = f"melt_{dt}_{T}"
    dt_m, Tin, rho = (float(x) for x in f[base + "_in"])
    r = fmelt.melt_step(jnp.asarray(f[base + "_f"]), jnp.asarray(f["masses"]),
                        jnp.asarray(Tin), jnp.asarray(rho), dt_m, CFG,
                        category=MELT_CATEGORY[cat])
    k = f"{base}_{cat}"
    assert _rel(r.f_ice, f[k + "_ice"]).max() <= TOL
    assert _rel(r.f_liquid, f[k + "_liq"]).max() <= TOL
    assert _rel(Tin + r.dT, f[k + "_T"]) <= TOL
    if _resolvable(f[k + "_T"], Tin):
        assert _rel(r.dT, f[k + "_T"] - Tin) <= TOL
    if dt == 150:
        assert (f[k + "_ice"] < 0).any()          # oracle is unclamped at dt*rate > 1


def test_falfluxhucm_z_matches_oracle():
    f = _fx()
    chem, nsub = fsed.falfluxhucm_z(
        jnp.asarray(f["fall_chem_in"]), jnp.asarray(f["fall_v"]),
        jnp.asarray(f["fall_rho"]), jnp.asarray(f["fall_dz"]), float(f["dt"]))
    populated = (f["fall_chem_in"] * 1e-6 >= 1e-20).any(axis=0)
    assert populated.any() and (~populated).any()       # IFALL skip exercised
    assert (f["fall_nsub"][populated] > 1).any()         # adaptive NSUB exercised
    assert np.array_equal(np.asarray(nsub)[populated], f["fall_nsub"][populated])
    assert _rel(chem, f["fall_chem_out"]).max() <= TOL


def test_falfluxhucm_z_stop_paths_raise():
    f = _fx()
