@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_gradients_finite_on_fixture(dtype):
    f = _fx()
    m = jnp.asarray(f["masses"], dtype)
    tabs = fcoll.precompute_collision_tables(f["masses"])
    name = "trop_deep_warm"
    T, q, p, rho = (float(x) for x in f[f"cond_{name}_in"])

    def loss(g, TT, qq):
        g2 = fcoll.bott_coalescence(g, jnp.asarray(f["ck"], dtype), m, tabs)
        r = fcd.warm_condensation_step(fcoll.f_from_g(g2, m), TT, qq, jnp.asarray(p, dtype),
                                       jnp.asarray(rho, dtype), 60.0, m,
                                       v_term=jnp.asarray(f["vt_table"], dtype))
        fr = ffrz.freeze_step_routed(r.f, m, TT - 30.0, jnp.asarray(rho, dtype), 60.0)
        mt = fmelt.melt_step(fr.f_hail, m, TT, jnp.asarray(rho, dtype), 60.0,
                             category="graupel_hail")
        return jnp.sum(r.f * m * m) * 1e6 + r.T + fr.dT + mt.dT

    g0 = jnp.asarray(f[f"coll_{name}_g"], dtype)
    gr = jax.grad(loss, argnums=(0, 1, 2))(g0, jnp.asarray(T, dtype), jnp.asarray(q, dtype))
    assert all(np.all(np.isfinite(np.asarray(x))) for x in gr)
    gs = jax.grad(lambda c: jnp.sum(fsed.falfluxhucm_z(
        c, jnp.asarray(f["fall_v"], dtype), jnp.asarray(f["fall_rho"], dtype),
        jnp.asarray(f["fall_dz"], dtype), 60.0)[0]))(jnp.asarray(f["fall_chem_in"], dtype))
    assert np.all(np.isfinite(np.asarray(gs)))


def test_eager_jit_parity():
    f = _fx()
    m = jnp.asarray(f["masses"])
    tabs = fcoll.precompute_collision_tables(f["masses"])
    g = jnp.asarray(f["coll_trop_deep_warm_g"])
    ck = jnp.asarray(f["ck"])
    eager = fcoll.bott_coalescence(g, ck, m, tabs)
    jitted = jax.jit(lambda x: fcoll.bott_coalescence(x, ck, m, tabs))(g)
    assert _rel(eager, jitted).max() <= TOL
    args = (jnp.asarray(f["fall_chem_in"]), jnp.asarray(f["fall_v"]),
            jnp.asarray(f["fall_rho"]), jnp.asarray(f["fall_dz"]))
    e2 = fsed.falfluxhucm_z(*args, 60.0)[0]
    j2 = jax.jit(lambda *a: fsed.falfluxhucm_z(*a, 60.0)[0])(*args)
    assert _rel(e2, j2).max() <= TOL
