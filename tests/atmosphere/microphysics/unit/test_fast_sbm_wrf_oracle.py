"""Fast-SBM building blocks vs the RUNNING WRF v4.8.0 FAST_SBM oracle.

Fixture ``tests/atmosphere/microphysics/oracle_fixtures/fast_sbm_wrf.npz`` was
generated by RUNNING wrf-model/WRF ``phys/module_mp_fast_sbm.F`` at
06d4240ae989cc3e50af412bb472df3d9048783c (routines extracted verbatim, every
real promoted to double) with ``scripts/validate/oracle/fast_sbm/build.sh`` and
``make_fixture.py``: courant_bott_KS, coll_xxx_lwf, coll_xyx_lwf, POLYSVP,
ONECOND1 (one FAST_SBM condensation call), FREEZ, J_W_MELT and FALFLUXHUCM_Z.

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64,
``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0), no floor.  These
routines have no sharpness fields (hard switches only), so the default
configuration IS the hard limit.

Scope: the building blocks only.  The column adapter (stateless
reconstruction, NCOND loop, process order, WRF data tables) is NOT covered —
not yet faithful, see ``fast_sbm/column.py``.
"""
