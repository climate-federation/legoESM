"""AOD->CCN input vs the published-fit oracle on the SOURCE file, per column.

No code oracle exists (CAM6 cam_cesm2_1_rel_60, a03b84b7, uses MAM4 +
ndrop.F90).  The oracle of record is Andreae (2009) ACP 9:543, Sect. 8 /
Fig. 1, ``AOT500 = 0.0027 * CCN0.4**0.640`` with AOT500 the LOCAL TOTAL
column AOT, applied to the production total-AOD file
``aeropt_macv2sp_sw_b14_tot_1850-2014_MACv1bg.nc`` (md5 in the npz ``meta``)
at each column's own latitude AND longitude.

Fixture ``tests/atmosphere/microphysics/oracle_fixtures/ccn_aod_lon.npz`` was
generated by ``python scripts/validate/oracle/ccn_aod_lon/make_fixture.py
--src <file> --out <npz>``: an independent netCDF4/cftime read of the 0.55 um
band, time-interpolated on the file's calendar, at cell centres (the cell
value) and cell corners (bilinear = mean of four cells, incl. the file's
+-180 deg seam and the 0/360 deg wrap).  It also stores the two bracketing
records per date on a 5x5 block around each column; the test rebuilds a
small file in the production layout (NaN everywhere else, NaN in every other
band) and runs the real loader and the driver's CCN precompute on it.

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64.
The proxy has no smoothing fields (hard floor/cap), so the production gap is
the hard-limit gap.  Relative error is ``|a-b| / max(|a|, |b|)``.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path
from types import SimpleNamespace

import jax
import jax.numpy as jnp
import netCDF4
import numpy as np

jax.config.update("jax_enable_x64", True)

ROOT = Path(__file__).resolve().parents[4]
FIXTURE = ROOT / "tests/atmosphere/microphysics/oracle_fixtures/ccn_aod_lon.npz"
GENERATOR = ROOT / "scripts/validate/oracle/ccn_aod_lon/make_fixture.py"
TOL = 1.0e-10


def _fx():
    return dict(np.load(FIXTURE))


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


def _records(fx):
    """(ntime_sub, nlat, nlon) band-0.55 um records, NaN off the stored blocks."""
    lat, lon = fx["lat"], fx["lon"]
    out = np.full((fx["time_sub"].size, lat.size, lon.size), np.nan, np.float32)
    for k, pos in enumerate(fx["rec_pos"]):
        out[pos, fx["blk_i"], fx["blk_j"]] = fx["rec_vals"][k]
    return out


def _source_file(path, fx):
    """The fixture records in the production file's layout (time, lnwl, lat, lon)."""
    meta = json.loads(str(fx["meta"]))
    rec = _records(fx)
    nb = fx["wl1"].size
    with netCDF4.Dataset(path, "w") as ds:
        for d, n in (("time", rec.shape[0]), ("lnwl", nb), ("lat", fx["lat"].size),
                     ("lon", fx["lon"].size)):
            ds.createDimension(d, n)
        t = ds.createVariable("time", "f8", ("time",))
        t[:] = fx["time_sub"]
        t.units, t.calendar = str(fx["time_units"]), str(fx["calendar"])
        ds.createVariable("lat", "f8", ("lat",))[:] = fx["lat"]
        ds.createVariable("lon", "f8", ("lon",))[:] = fx["lon"]
        ds.createVariable("wl1_sun", "f8", ("lnwl",))[:] = fx["wl1"]
        ds.createVariable("wl2_sun", "f8", ("lnwl",))[:] = fx["wl2"]
        v = ds.createVariable("aod", "f4", ("time", "lnwl", "lat", "lon"), zlib=True)
        for i in range(rec.shape[0]):
            slab = np.full((nb, *rec.shape[1:]), np.nan, np.float32)
            slab[meta["band_index"]] = rec[i]
            v[i] = slab
    return str(path)


def _cols(fx):
    return jnp.radians(jnp.asarray(fx["col_lat"])), jnp.radians(jnp.asarray(fx["col_lon"]))


def test_loader_and_proxy_match_oracle(tmp_path):
    from legoesm.atmosphere.physics.microphysics.aerosol_activation import ccn_from_aod
    from legoesm.forcing.external import AerosolConfig, get_aerosol_at_time
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    cfg = AerosolConfig(enabled=True, path=_source_file(tmp_path / "tot.nc", fx),
                        start_year=meta["start_year"])
    lat, lon = _cols(fx)
    for q, day in enumerate(fx["sim_day"]):
        aod = np.asarray(get_aerosol_at_time(cfg, float(day), lat_grid=lat,
                                             band="vis", lon_grid=lon))
        assert _rel(aod, fx["aod_oracle"][q]).max() <= TOL, (q, aod, fx["aod_oracle"][q])
        n = np.asarray(ccn_from_aod(jnp.asarray(aod)))
        assert _rel(n, fx["n_oracle_m3"][q]).max() <= TOL, (q, n, fx["n_oracle_m3"][q])
        # Differentiable proxy: finite gradient on every fixture column.
        g = jax.grad(lambda a: jnp.sum(ccn_from_aod(a)) / 1.0e6)(jnp.asarray(aod))
        assert np.all(np.isfinite(np.asarray(g)))


def test_column_lane_precompute_reads_local_aod(tmp_path):
    """The driver's daily precompute (MPAS ``_run_column`` and every lane that
    calls it) hands the CCN proxy the oracle's per-column AOD."""
    from legoesm.driver.config import ExperimentConfig
    from legoesm.driver.model_driver import ModelDriver
    from legoesm.grids.vertical import make_cam6_l32_levels
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    ccn = _source_file(tmp_path / "tot.nc", fx)
    rad = str(tmp_path / "rad.nc")  # radiation path: any lon-free file
    with netCDF4.Dataset(rad, "w") as ds:
        ds.createDimension("time", 12)
        ds.createDimension("lat", 3)
        ds.createVariable("time", "f8", ("time",))[:] = 15.5 + 30.4375 * np.arange(12)
        ds.createVariable("lat", "f8", ("lat",))[:] = [-90.0, 0.0, 90.0]
        ds.createVariable("aod", "f8", ("time", "lat"))[:] = 0.1
    cfg = ExperimentConfig(radiation="rrtmgp", aerosol_forcing="external",
                           aerosol_file=rad, aerosol_ccn_file=ccn,
                           start_year=meta["start_year"])
    lat, lon = _cols(fx)
    fake = SimpleNamespace(config=cfg)
    ModelDriver._setup_external_forcing(fake)
    fake.sigma = make_cam6_l32_levels()
    fake.state = SimpleNamespace()
    fake._owned_face_ids = None
    fake._grid_lat, fake._grid_lon = lat, lon
    fake._owned_lon = lambda: ModelDriver._owned_lon(fake)
    fake._owned_temp = lambda: None
    fake.radiation_ghg_vmr = lambda day: None
    p_s = jnp.full(lat.shape, 1.0e5)
    for q, day in enumerate(fx["sim_day"]):
        ModelDriver._precompute_external_forcing(fake, float(day), p_s, lat)
        got = np.asarray(fake._aerosol_ccn_aod)
        assert _rel(got, fx["aod_oracle"][q]).max() <= TOL, (q, got)


def test_owned_lon_follows_owned_lat_layout():
    from legoesm.driver.model_driver import ModelDriver
    serial = SimpleNamespace(_owned_face_ids=None, _grid_lon="g", _physics_lon="p")
    assert ModelDriver._owned_lon(serial) == "g"
    sharded = SimpleNamespace(_owned_face_ids=jnp.array([1]), _grid_lon="g",
                              _physics_lon="p")
    assert ModelDriver._owned_lon(sharded) == "p"


def test_generator_reproduces_fixture():
    """The committed generator's oracle reproduces the fixture from its own
    stored records (direct test of the generator)."""
    spec = importlib.util.spec_from_file_location("ccn_aod_lon_fixture", GENERATOR)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    assert meta["src"].endswith("aeropt_macv2sp_sw_b14_tot_1850-2014_MACv1bg.nc")
    assert meta["band_um"][0] <= gen.VIS_UM < meta["band_um"][1]
    rec = _records(fx).astype(np.float64)
    pos = fx["rec_pos"]
    for q, w in enumerate(meta["time_weights"]):
        for k, (la, lo) in enumerate(zip(fx["col_lat"], fx["col_lon"])):
            v0 = gen.column_value(rec[pos[2 * q]], fx["lat"], fx["lon"], la, lo)[0]
            v1 = gen.column_value(rec[pos[2 * q + 1]], fx["lat"], fx["lon"], la, lo)[0]
            assert (1.0 - w) * v0 + w * v1 == fx["aod_oracle"][q, k]
    np.testing.assert_array_equal(gen.andreae_ccn_m3(fx["aod_oracle"]), fx["n_oracle_m3"])
    # Paper sanity (Andreae 2009 Sect. 8): AOT 0.075 ~ clean continental ~200 cm-3.
    assert 150.0e6 < gen.andreae_ccn_m3(0.075) < 250.0e6
