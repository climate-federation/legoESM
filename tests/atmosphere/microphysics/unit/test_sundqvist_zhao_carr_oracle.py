"""Sundqvist microphysics precipitation vs the RUNNING Zhao-Carr oracle.

Fixture ``tests/atmosphere/oracle_fixtures/sundqvist_zhao_carr.npz`` was
generated by RUNNING NCAR/ccpp-physics v7.0.1
(da75531bf90a799e4c0dcb988cc591d82bd024de) ``zhaocarr_precpd_run``, compiled
unmodified (gfortran 8.5.0, -fdefault-real-8) with legoESM's Tetens curve as
``fpvs``, by ``python scripts/validate/oracle/sundqvist_zhao_carr/make_fixture.py
--ccpp <ccpp-physics> --build <dir> --out sundqvist_zhao_carr.npz`` (metadata in
the npz ``meta``).

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64 with
``sigmoid_sharpness`` at its hard-switch limit.  Relative error is
``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0); no floor -- the metric
of the merged tier-1 oracle tests.

The oracle hard-codes m_r = 3e-4 (zhaocarr_precpd.f:244), c1 = 300 (:247) and
c2 = 0.5 (:248); the tests pass them through the matching config fields.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

jax.config.update("jax_enable_x64", True)

ROOT = Path(__file__).resolve().parents[4]
FIXTURE = ROOT / "tests/atmosphere/oracle_fixtures/sundqvist_zhao_carr.npz"
GENERATOR = ROOT / "scripts/validate/oracle/sundqvist_zhao_carr/make_fixture.py"
TOL = 1.0e-10
# Fixture-input rebuild: last-digit libm differences across machines (measured
# worst 2.6e-14 relative, q_v); a real generator change is far larger.
REBUILD_RTOL = 1e-13
HARD = 1.0e12        # sigmoid_sharpness hard-switch limit (tier-2 audit HARD)
RUNS = ("A", "B", "C")


def _fx():
    return dict(np.load(FIXTURE))


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


def _cfg(fx, run, sharpness=HARD):
    from legoesm.atmosphere.physics.microphysics.config import SundqvistConfig
    dt, u00k, prautco, psautco, evpco, wl, wi = (float(x) for x in fx[f"run_{run}"])
    return dt, SundqvistConfig(
        rh_crit=u00k, auto_rate=prautco, psautco_fine=psautco, psautco_coarse=psautco,
        evap_coeff=evpco,
        wminco_liquid=wl, wminco_ice=wi, qc_crit=3.0e-4,
        coalescence_enh_coeff=300.0, bergeron_enh_coeff=0.5,
        sigmoid_sharpness=sharpness)


def _sel(fx, names):
    idx = [list(fx["names"]).index(n) for n in names]
    return np.asarray(idx)


def _whole_call(fx, run, sharpness=HARD, dtype=jnp.float64, idx=None):
    from legoesm import constants as C
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    from legoesm.atmosphere.physics.microphysics.sundqvist import sundqvist_microphysics
    meta = json.loads(str(fx["meta"]))
    idx = _sel(fx, meta["whole_call"]) if idx is None else idx
    g = {k: jnp.asarray(fx[f"col_{k}"][idx], dtype) for k in
         ("T", "q_v", "q_c", "p_full", "p_half", "rho")}
    dz = (g["p_half"][:, 1:] - g["p_half"][:, :-1]) / (C.g * g["rho"])
    z = jnp.zeros_like(g["T"])
    hyd = HydrometeorState(q_c=g["q_c"], q_r=z, q_i=z, q_s=z, q_g=z, N_c=z, N_r=z, N_i=z)
    dt, cfg = _cfg(fx, run, sharpness)
    out = sundqvist_microphysics(g["T"], g["q_v"], hyd, g["p_full"], g["p_half"],
                                 g["rho"], dz, dt, cfg, cell_area=1.0e10)
    return idx, dt, g, dz, out


def test_fixture_provenance_and_inputs_reproduce():
    """The committed generator rebuilds the fixture's inputs to REBUILD_RTOL."""
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    assert meta["tag"] == "v7.0.1"
    assert meta["sha"] == "da75531bf90a799e4c0dcb988cc591d82bd024de"
    assert meta["source_sha256"].startswith("a209c269")
    spec = importlib.util.spec_from_file_location("zc_make_fixture", GENERATOR)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    cols = gen.build_columns()
    assert [c["name"] for c in cols] == list(fx["names"])
    for k in gen.COL_FIELDS:
        np.testing.assert_allclose(np.stack([c[k] for c in cols]), fx[f"col_{k}"],
                                   rtol=REBUILD_RTOL, atol=0.0)
    for run, vals in gen.RUNS.items():
        np.testing.assert_array_equal(np.array(vals), fx[f"run_{run}"])


@pytest.mark.parametrize("run", RUNS)
def test_precpd_kernel_matches_zhao_carr(run):
    """zhao_carr_precpd on every column (incl. super-saturated and negative
    condensate cells) vs the oracle's updated t, q, cwm and rn, sr."""
    from legoesm import constants as C
    from legoesm.atmosphere.physics.microphysics.sundqvist import zhao_carr_precpd
    fx = _fx()
    dt, cfg = _cfg(fx, run)
    T, qv, qc = fx["col_T"], fx["col_q_v"], fx["col_q_c"]
    mass = np.diff(fx["col_p_half"], axis=1) / C.g
    r = zhao_carr_precpd(jnp.asarray(T), jnp.asarray(qv), jnp.asarray(qc),
                         jnp.asarray(fx["col_p_full"]), jnp.asarray(mass), dt, cfg, wk1=1.0)
    p = f"ora_{run}_"
    rn = fx[p + "rn"] * 1000.0 / dt
    errs = {
        "dT": _rel(np.asarray(r.T) - T, fx[p + "t"] - T),
        "dq_v": _rel(np.asarray(r.q_v) - qv, fx[p + "q"] - qv),
        "dcwm": _rel(np.asarray(r.cwm) - qc, fx[p + "cwm"] - qc),
        "T": _rel(r.T, fx[p + "t"]),
        "q_v": _rel(r.q_v, fx[p + "q"]),
        "cwm": _rel(r.cwm, fx[p + "cwm"]),
        "precip": _rel(np.asarray(r.rain_sfc + r.snow_sfc), rn),
        "snow": _rel(r.snow_sfc, fx[p + "sr"] * rn),
    }
    worst = {k: float(v.max()) for k, v in errs.items()}
    print(f"run {run} kernel max rel err", worst)
    assert max(worst.values()) <= TOL, worst


@pytest.mark.parametrize("run", RUNS)
def test_whole_call_matches_zhao_carr(run):
    """sundqvist_microphysics (hard limit) on the sub-saturated columns: the
    condensation surrogate is exactly zero there, so every tendency and the
    surface fluxes are the oracle's."""
    fx = _fx()
    idx, dt, g, dz, out = _whole_call(fx, run)
    p = f"ora_{run}_"
    T, qv, qc = (fx[f"col_{k}"][idx] for k in ("T", "q_v", "q_c"))
    rn = fx[p + "rn"][idx] * 1000.0 / dt
    errs = {
        "dT": _rel(np.asarray(out.dT_dt) * dt, fx[p + "t"][idx] - T),
        "dq_v": _rel(np.asarray(out.dq_v_dt) * dt, fx[p + "q"][idx] - qv),
        "dq_c": _rel(np.asarray(out.dq_c_dt) * dt, fx[p + "cwm"][idx] - qc),
        "precip": _rel(out.precipitation, rn),
        "precip_frozen": _rel(out.precip_frozen, fx[p + "sr"][idx] * rn),
    }
    worst = {k: float(v.max()) for k, v in errs.items()}
    print(f"run {run} whole-call max rel err", worst)
    assert max(worst.values()) <= TOL, worst
    assert np.all(np.asarray(out.dq_r_dt) == 0.0)
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    from legoesm.atmosphere.physics.microphysics.sundqvist import (
        diagnose_sundqvist_process_rates)
    z = jnp.zeros_like(g["T"])
    hyd = HydrometeorState(q_c=g["q_c"], q_r=z, q_i=z, q_s=z, q_g=z, N_c=z, N_r=z, N_i=z)
    rates = diagnose_sundqvist_process_rates(
        g["T"], g["q_v"], hyd, g["p_full"], g["p_half"], g["rho"], dz, dt,
        _cfg(fx, run)[1], cell_area=1.0e10)
    assert np.all(np.asarray(rates.condensation) == 0.0)


def test_fixture_exercises_oracle_branches():
    """Coverage read off the ORACLE's own outputs: liquid release under partial
    cover, release at saturation, the ice route, melting, snow sublimation,
    rain evaporation, both negative-condensate branches, a skipped column and
    the trace-precipitation sr = 0 switch.  (The melting and over-evaporation
    caps bind on the ``caps`` column and the 0.01 cloud-cover floor on the
    ``floor`` column in run C; shown by mutation in the PR's non-vacuity runs.)"""
    from legoesm import constants as C
    from legoesm.thermo import saturation_vapor_pressure
    fx = _fx()
    names = list(fx["names"])
    T, qv, qc, p = fx["col_T"], fx["col_q_v"], fx["col_q_c"], fx["col_p_full"]
    eps = C.R_d / C.R_v
    e = np.minimum(p, np.asarray(saturation_vapor_pressure(jnp.asarray(T))))
    rq = qv / (eps * e / (p + (eps - 1.0) * e))           # the oracle's RH
    tmt0 = T - C.T_zero_zhao_carr
    for run in RUNS:
        o = {k: fx[f"ora_{run}_{k}"] for k in ("t", "q", "cwm", "rn", "sr")}
        u00k = float(fx[f"run_{run}"][1])
        released = o["cwm"] < qc
        assert np.any(released & (rq > u00k) & (rq < 1.0) & (tmt0 > 0))  # b < 1
        assert np.any(released & (rq >= 1.0))                           # b = 1
        assert np.all(o["cwm"][(rq < u00k) & (qc > 0)] == qc[(rq < u00k) & (qc > 0)])
        i = names.index("top_only")
        np.testing.assert_array_equal(o["cwm"][i], qc[i])               # skipped column
        i = names.index("super_neg")
        fill = (qc[i] < 0) & (qv[i] + qc[i] >= 0)
        drain = (qc[i] < 0) & (qv[i] + qc[i] < 0)
        assert fill.sum() == 1 and drain.sum() == 1
        assert np.all(o["cwm"][i][fill] == 0.0) and np.all(o["q"][i][drain] == 0.0)
    for run in ("A", "B"):                                              # psautco > 0
        o = {k: fx[f"ora_{run}_{k}"] for k in ("t", "q", "cwm", "rn", "sr")}
        assert np.any((o["cwm"] < qc) & (tmt0 < -15.0))                 # ice route
        i = names.index("winter_snow")
        # no liquid release in winter_snow (all cloud is ice-id): surface rain
        # there is melted snow
        assert o["rn"][i] > 0.0 and 0.0 < o["sr"][i] < 1.0
        assert np.all(tmt0[i][qc[i] > 0] < 0.0)
        assert np.any((o["q"] > qv) & (qc == 0.0) & (tmt0 < 0.0))      # sublimation
        assert np.any((o["q"] > qv) & (qc == 0.0) & (tmt0 > 0.0))      # rain evaporation
    assert np.all(fx["ora_C_sr"] == 0.0)        # psautco = 0: no snow at all
    i = names.index("trace_snow")
    assert fx["ora_B_rn"][i] > 0.0 and fx["ora_B_sr"][i] == 0.0   # trace: sr = 0


def test_gradient_finite_at_rh_crit_one():
    """rh_crit = 1 (inside the declared bounds): the oracle never forms
    1/(1-u00k); neither may the gradient."""
    from legoesm.atmosphere.physics.microphysics.sundqvist import zhao_carr_precpd
    fx = _fx()
    _, cfg = _cfg(fx, "A")
    cfg = cfg._replace(rh_crit=1.0)
    T = jnp.full((1, 2), 280.0)
    p = jnp.full((1, 2), 8.0e4)
    from legoesm.thermo import saturation_specific_humidity

    def loss(T, qv):
        r = zhao_carr_precpd(T, qv, jnp.full((1, 2), 1e-3), p, jnp.full((1, 2), 100.0),
                             600.0, cfg, wk1=1.0)
        return jnp.sum(r.T) + jnp.sum(r.rain_sfc + r.snow_sfc)

    g = jax.grad(loss, argnums=(0, 1))(T, 0.95 * saturation_specific_humidity(T, p))
    assert all(bool(jnp.all(jnp.isfinite(x))) for x in g)


def test_default_smoothing_gap_is_reported():
    """Gap between the default ``sigmoid_sharpness`` and the hard limit on the
    whole-call columns (printed for the PR body; not a tolerance)."""
    fx = _fx()
    for run in RUNS:
        _, dt, _, _, hard = _whole_call(fx, run)
        _, _, _, _, soft = _whole_call(fx, run, sharpness=20.0)
        gap = {k: float(np.max(np.abs(np.asarray(getattr(soft, k)) - np.asarray(getattr(hard, k))))
                        / max(float(np.max(np.abs(np.asarray(getattr(hard, k))))), 1e-300))
               for k in ("dT_dt", "dq_v_dt", "dq_c_dt", "precipitation")}
        print(f"run {run} default-smoothing gap (max abs diff / max abs)", gap)
        assert all(np.isfinite(v) for v in gap.values())


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_gradients_finite_on_fixture_columns(dtype):
    """jax.grad of surface precipitation + column heating w.r.t. T, q_v, q_c."""
    from legoesm import constants as C
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    from legoesm.atmosphere.physics.microphysics.sundqvist import sundqvist_microphysics
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    idx = _sel(fx, meta["whole_call"])
    g = {k: jnp.asarray(fx[f"col_{k}"][idx], dtype) for k in
         ("T", "q_v", "q_c", "p_full", "p_half", "rho")}
    dz = (g["p_half"][:, 1:] - g["p_half"][:, :-1]) / (C.g * g["rho"])
    for sharp in (20.0, HARD):
        dt, cfg = _cfg(fx, "A", sharp)

        def loss(T, qv, qc):
            z = jnp.zeros_like(T)
            hyd = HydrometeorState(q_c=qc, q_r=z, q_i=z, q_s=z, q_g=z, N_c=z, N_r=z, N_i=z)
            out = sundqvist_microphysics(T, qv, hyd, g["p_full"], g["p_half"], g["rho"],
                                         dz, dt, cfg, cell_area=1.0e10)
            return jnp.sum(out.precipitation) * 1e3 + jnp.sum(out.dT_dt)

        grads = jax.grad(loss, argnums=(0, 1, 2))(g["T"], g["q_v"], g["q_c"])
        for gi in grads:
            assert bool(jnp.all(jnp.isfinite(gi))), (dtype, sharp)
        assert float(jnp.max(jnp.abs(grads[2]))) > 0.0


def test_jit_matches_eager():
    from legoesm.atmosphere.physics.microphysics import sundqvist as S
    fx = _fx()
    idx, dt, g, dz, eager = _whole_call(fx, "A")
    _, cfg = _cfg(fx, "A")
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    z = jnp.zeros_like(g["T"])
    hyd = HydrometeorState(q_c=g["q_c"], q_r=z, q_i=z, q_s=z, q_g=z, N_c=z, N_r=z, N_i=z)
    jitted = jax.jit(S.sundqvist_microphysics, static_argnums=(7, 8))(
        g["T"], g["q_v"], hyd, g["p_full"], g["p_half"], g["rho"], dz, dt, cfg)
    for k in ("dT_dt", "dq_v_dt", "dq_c_dt", "precipitation", "precip_frozen"):
        assert float(_rel(getattr(jitted, k), getattr(eager, k)).max()) <= TOL, k


@pytest.mark.parametrize("run", RUNS)
def test_column_water_closes_like_the_oracle(run):
    """int (dq_v + dq_c) rho dz + precipitation = 0 (round-off), as the oracle's
    own q + cwm + rn budget does."""
    from legoesm import constants as C
    fx = _fx()
    idx, dt, g, dz, out = _whole_call(fx, run)
    mass = np.asarray(g["rho"] * dz)
    ours = (np.sum((np.asarray(out.dq_v_dt) + np.asarray(out.dq_c_dt)) * mass, axis=1)
            + np.asarray(out.precipitation))
    p = f"ora_{run}_"
    dp = np.diff(fx["col_p_half"][idx], axis=1)
    ora = (np.sum((fx[p + "q"][idx] - fx["col_q_v"][idx] + fx[p + "cwm"][idx]
                   - fx["col_q_c"][idx]) * dp / C.g, axis=1) / dt
           + fx[p + "rn"][idx] * 1000.0 / dt)
    scale = max(float(np.max(np.asarray(out.precipitation))), 1e-30)
    print(f"run {run} water residual / max precip: ours {np.max(np.abs(ours)) / scale:.2e}"
          f" oracle {np.max(np.abs(ora)) / scale:.2e}")
    assert np.max(np.abs(ours)) <= TOL * scale


def test_pre_port_gaussian_f2_fields_refuse_non_default():
    """The Gaussian-F2 fields have no oracle counterpart: a non-default value raises."""
    from legoesm.atmosphere.physics.microphysics.config import SundqvistConfig
    from legoesm.atmosphere.physics.microphysics.output import make_zero_hydrometeors
    from legoesm.atmosphere.physics.microphysics.sundqvist import (
        diagnose_sundqvist_process_rates)
    args = (jnp.full((1, 2), 280.0), jnp.full((1, 2), 1e-3), make_zero_hydrometeors(1, 2),
            jnp.full((1, 2), 8e4), jnp.asarray([[7e4, 8e4, 9e4]]), jnp.ones((1, 2)),
            jnp.full((1, 2), 1e3), 600.0)
    diagnose_sundqvist_process_rates(*args, SundqvistConfig(), cell_area=1.0e10)
    diagnose_sundqvist_process_rates(*args, SundqvistConfig(
        bergeron_T_peak_K=jnp.asarray(SundqvistConfig().bergeron_T_peak_K, jnp.float32)), cell_area=1.0e10)
    for kw in (dict(bergeron_T_peak_K=260.0), dict(bergeron_T_width_K=5.0)):
        with pytest.raises(ValueError, match="no counterpart"):
            diagnose_sundqvist_process_rates(*args, SundqvistConfig(**kw), cell_area=1.0e10)
