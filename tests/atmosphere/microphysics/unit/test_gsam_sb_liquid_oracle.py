"""Stand-alone Seifert-Beheng scheme vs the RUNNING gSAM oracle.

Fixture ``tests/atmosphere/microphysics/oracle_fixtures/gsam_sb_liquid.npz``
was generated by RUNNING gSAM 1.8.8 micro_proc's order -- ``satadj_liquid`` then
``M2005MICRO_GRAUPEL`` -- with ``doicemicro=.false.`` (ILIQ=1),
``dosb_warm_rain=.true.`` (IRAIN=1), ``dopredictNc=.false.`` (INUM=1) and
``dofix_pgam=.false.``, compiled with gfortran 8.5.0 in fp64 (tarball sha256
0e9ea4a37f4daca5051cc4018cc95bbc5583159c7c27d7d05d1104fae4ed270c; gSAM has no
git tag/SHA), via ``python scripts/validate/oracle/gsam_sb_liquid/make_fixture.py
--gsam <gSAM1.8.8> --build <dir> --out gsam_sb_liquid.npz``.

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64.
Relative error is ``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0); no
floor (the tier-1 oracle tests' metric).  The oracle tests run at the hard
limit of the three ``gsam_satadj_*`` fields; their smooth-default gap is pinned in
test_gsam_satadj_liquid_oracle.py.
"""
from __future__ import annotations

import importlib.util
import json
import math
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from legoesm import constants
from legoesm.atmosphere.physics.microphysics.config import SeifertBehengConfig
from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
from legoesm.atmosphere.physics.microphysics.seifert_beheng import (
    seifert_beheng_microphysics,
    seifert_beheng_step,
)

jax.config.update("jax_enable_x64", True)

ROOT = Path(__file__).resolve().parents[4]
FIXTURE = ROOT / "tests/atmosphere/microphysics/oracle_fixtures/gsam_sb_liquid.npz"
GENERATOR = ROOT / "scripts/validate/oracle/gsam_sb_liquid/make_fixture.py"
TOL = 1.0e-10
GROUPS = ("warm15", "warm60", "cold", "warm15_nc1000", "stress", "edge_rh",
          "edge_qsmall")
STATE = ("T", "q_v", "q_c", "q_r", "n_r_kg")


def _fx():
    return dict(np.load(FIXTURE))


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


def _inputs(fx, g, dtype=jnp.float64, hard=True):
    flip = lambda k: jnp.asarray(fx[f"{g}_{k}"][:, ::-1], dtype=dtype)  # top-down
    rho = flip("rho")
    z = jnp.zeros_like(rho)
    hyd = HydrometeorState(q_c=flip("q_c"), q_r=flip("q_r"), q_i=z, q_s=z, q_g=z,
                           N_c=z, N_r=flip("n_r_kg") * rho, N_i=z, N_s=z, N_g=z)
    cfg = SeifertBehengConfig(Nc_0=float(fx[f"{g}_Nc0_cm3"]) * 1.0e6)
    if hard:  # gSAM's own hard switches (RULE 5 hard limit)
        cfg = cfg._replace(gsam_satadj_excess_sharpness=math.inf,
                           gsam_satadj_qc_floor_sharpness=math.inf,
                           gsam_satadj_p_min_width_pa=0.0)
    return (flip("T"), flip("q_v"), hyd, flip("p_full"),
            jnp.asarray(fx[f"{g}_p_half"][:, ::-1], dtype=dtype), rho,
            flip("dz"), float(fx[f"{g}_dt"]), cfg)


def _run(fx, g, dtype=jnp.float64, fn=seifert_beheng_step):
    """The scheme's post-step state (what the oracle's state is compared to)."""
    T, q_v, hyd, pf, ph, rho, dz, dt, cfg = _inputs(fx, g, dtype)
    T1, qv1, qc1, qr1, nr1, precip, nsub = fn(T, q_v, hyd, pf, rho, dz, dt, cfg)
    new = dict(T=T1, q_v=qv1, q_c=qc1, q_r=qr1, n_r_kg=nr1 / rho)
    return precip, nsub, {k: np.asarray(v)[:, ::-1] for k, v in new.items()}


def test_fixture_provenance():
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    spec = importlib.util.spec_from_file_location("sbl_fixture", GENERATOR)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    shared = gen._load(gen.BUILD_DIR / "make_fixture.py", "sb2001_shared")
    assert meta["source_sha256"] == shared.SOURCE_SHA256
    assert "doicemicro=F (ILIQ=1), dosb_warm_rain=T (IRAIN=1)" in meta["settings"]
    assert [tuple(x) for x in meta["groups"]] == [tuple(x) for x in gen.GROUPS]


@pytest.mark.parametrize("g", GROUPS)
def test_whole_call_matches_gsam(g):
    fx = _fx()
    precip, _, new = _run(fx, g)
    errs = {k: _rel(new[k], fx[f"{g}_ora_{k}"]).max() for k in STATE}
    errs["precip"] = _rel(precip, fx[f"{g}_ora_precip"]).max()
    assert max(errs.values()) <= TOL, errs


@pytest.mark.parametrize("g", GROUPS)
def test_tendencies_are_the_step_state_differences(g):
    """The backend interface returns ``(state - input)/dt`` of that state."""
    fx = _fx()
    T, q_v, hyd, pf, ph, rho, dz, dt, cfg = _inputs(fx, g)
    T1, qv1, qc1, qr1, nr1, precip, nsub = seifert_beheng_step(
        T, q_v, hyd, pf, rho, dz, dt, cfg)
    out = seifert_beheng_microphysics(T, q_v, hyd, pf, ph, rho, dz, dt, cfg)
    for got, want in ((out.dT_dt, (T1 - T) / dt), (out.dq_v_dt, (qv1 - q_v) / dt),
                      (out.dq_c_dt, (qc1 - hyd.q_c) / dt),
                      (out.dq_r_dt, (qr1 - hyd.q_r) / dt),
                      (out.dN_r_dt, (nr1 - hyd.N_r) / dt),
                      (out.precipitation, precip)):
        np.testing.assert_array_equal(np.asarray(got), np.asarray(want))
    np.testing.assert_array_equal(np.asarray(out.sed_substeps_required),
                                  np.asarray(nsub))
    for f in ("dq_i_dt", "dq_s_dt", "dq_g_dt", "dN_c_dt", "dN_i_dt",
              "precip_frozen"):
        assert not np.any(np.asarray(getattr(out, f)))


def test_fixture_exercises_the_branches():
    """Non-vacuous: supercooled liquid, both rain-slope bounds, CFL sub-steps
    > 1 (up to the GCM step), both conservation limiters binding in the oracle,
    surface precipitation incl. fog fallout, a column with no hydrometeor, and
    small-amount removal are in the fixture."""
    fx = _fx()
    _, nsub, _ = _run(fx, "stress")
    assert int(np.max(np.asarray(nsub))) >= 10
    T, qc = fx["cold_T"], fx["cold_q_c"]
    assert np.any((T < constants.T_freeze) & (qc > 0))
    qr, nr = fx["cold_q_r"], fx["cold_n_r_kg"]
    lam = np.cbrt(np.pi * constants.rho_water * nr / np.where(qr > 0, qr, 1.0))
    on = qr >= 1.0e-14
    assert np.any(on & (lam < 1.0 / 2800.0e-6)) and np.any(on & (lam > 1.0 / 20.0e-6))
    # the oracle's own process-rate dumps: limiters bound (raw != final)
    st = "stress"
    assert np.sum(fx[f"{st}_ora_prc_raw"] != fx[f"{st}_ora_prc_fin"]) > 0
    assert np.sum(fx[f"{st}_ora_pre_raw"] != fx[f"{st}_ora_pre_fin"]) > 0
    names = list(fx[f"{st}_names"])
    assert fx[f"{st}_ora_precip"][names.index("stress_fog")] > 0
    i = names.index("stress_dry")
    assert not np.any(fx[f"{st}_q_c"][i]) and not np.any(fx[f"{st}_q_r"][i])
    # droplet shape PGAM = 1/(0.0005714 Nc + 0.2714)^2 - 1 at both clamps [2, 10]
    pg = [1.0 / (0.0005714 * float(fx[f"{g}_Nc0_cm3"]) + 0.2714) ** 2 - 1.0
          for g in GROUPS]
    assert min(pg) < 2.0 and max(pg) > 10.0
    # edge_dry level 10: 1e-4 kg/kg of cloud in RH-0.9 air evaporates completely
    i = list(fx["warm15_names"]).index("edge_dry")
    assert fx["warm15_q_c"][i, 10] == 1e-4 and fx["warm15_ora_q_c"][i, 10] == 0.0


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_gradients_finite(dtype):
    fx = _fx()
    for g in GROUPS:
        T, q_v, hyd, pf, ph, rho, dz, dt, cfg = _inputs(fx, g, dtype, hard=False)

        def loss(T, q_v, q_c, q_r):
            out = seifert_beheng_microphysics(
                T, q_v, hyd._replace(q_c=q_c, q_r=q_r), pf, ph, rho, dz, dt, cfg)
            return (jnp.sum(out.dT_dt) + 1e3 * jnp.sum(out.precipitation)
                    + 1e3 * jnp.sum(out.dq_r_dt) + 1e-6 * jnp.sum(out.dN_r_dt))

        for gr in jax.grad(loss, argnums=(0, 1, 2, 3))(T, q_v, hyd.q_c, hyd.q_r):
            assert bool(jnp.all(jnp.isfinite(gr))), g


def test_jit_matches_eager():
    """All state but q_c.  The saturation adjustment's q_c = (T1 - T_l)/(L/c_p)
    cancels catastrophically for a thin cloud (condition number T/(T1 - T_l)),
    so jit-vs-eager q_c differs by up to ~5e-9 relative on the just-saturated
    1e-8 kg/kg cloud of ``stress_thincloud`` (1-2 ulp of T; reported in the PR,
    as for the saturation-adjustment port)."""
    fx = _fx()
    jitted = jax.jit(seifert_beheng_step, static_argnums=(6, 7))
    for g in GROUPS:
        p_e, _, new_e = _run(fx, g)
        p_j, _, new_j = _run(fx, g, fn=jitted)
        for k in STATE:
            if k != "q_c":
                assert _rel(new_e[k], new_j[k]).max() <= TOL, (g, k)
        assert _rel(p_e, p_j).max() <= TOL, g


def test_too_many_substeps_fails():
    """gSAM's data-dependent sub-step count above the fixed maximum is an
    error, not a silent clamp (user decision 2026-10-20)."""
    fx = _fx()
    T, q_v, hyd, pf, ph, rho, dz, dt, cfg = _inputs(fx, "cold")
    with pytest.raises(Exception, match="sub-steps"):
        out = seifert_beheng_microphysics(T, q_v, hyd, pf, ph, rho,
                                          jnp.full_like(dz, 1.0), 60.0, cfg)
        jax.block_until_ready(out.dT_dt)
    with pytest.raises(Exception, match="sub-steps"):   # the public step too
        st = seifert_beheng_step(T, q_v, hyd, pf, rho, jnp.full_like(dz, 1.0),
                                 60.0, cfg)
        jax.block_until_ready(st[0])


@pytest.mark.parametrize("field,value", [
    ("k_au", 1.0e3), ("x_star", 3.0e-10), ("k_ac", 6.0), ("k_sc", 2.0e-3),
    ("D_eq", 1.0e-3), ("breakup_sharpness", 1.0e5), ("a_v_r", 100.0),
    ("b_v_r", 0.6), ("evap_coeff", 2.0), ("saturation_sharpness", 1.0e3),
    ("autoconversion_sharpness", 100.0), ("hard_saturation_adjustment", True),
    ("hard_sat_adjust_threshold", 1.0), ("hard_sat_max_heating_K", 1.0)])
def test_fields_without_gsam_counterpart_raise(field, value):
    fx = _fx()
    *args, cfg = _inputs(fx, "warm15")
    with pytest.raises(ValueError, match="no counterpart"):
        seifert_beheng_microphysics(*args, cfg._replace(**{field: value}))
