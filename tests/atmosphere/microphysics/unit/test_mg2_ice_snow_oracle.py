def test_snow_kernels_match_mg2():
    """Per-process vs micro_mg_utils.F90: in-precip snow PSD + slope bounds,
    fall speeds, self-aggregation, riming (with the droplet PSD), Bergeron
    onto snow, clear-air sublimation, Bigg rain freezing (T < 269.15 K gate),
    Ferrier ice->snow mass AND number at dcs = 500 um."""
    from legoesm.atmosphere.physics.microphysics import _warm_rain as W
    from legoesm.atmosphere.physics.microphysics.config import MorrisonConfig
    from legoesm.atmosphere.physics.microphysics.morrison import resolve_morrison_flavor
    from legoesm.thermo import (saturation_specific_humidity_goff_gratch,
                                saturation_specific_humidity_ice_goff_gratch)
    fx = _fx()
    i = {k[6:]: jnp.asarray(v) for k, v in fx.items() if k.startswith("pt_in_")}
    o = {k[7:]: v for k, v in fx.items() if k.startswith("pt_out_")}
    cfg = resolve_morrison_flavor(MorrisonConfig(
        morrison_flavor="mg", ice_snow_d_auto=500.0e-6))   # CAM6 micro_mg_dcs
    rho, T, p, pf = i["rho"], i["T"], i["p"], i["precip_frac"]
    qvl = saturation_specific_humidity_goff_gratch(T, p)
    qvi = saturation_specific_humidity_ice_goff_gratch(T, p)
    errs = {"qvl": _rel(qvl, o["qvl"]), "qvi": _rel(qvi, o["qvi"])}
    qsic, nsic, lams, n0s = W.mg2_inprecip_snow(i["qs"], i["ns"], pf, cfg)
    for k, v in (("qsic", qsic), ("nsic", nsic), ("lams", lams), ("n0s", n0s)):
        errs[k] = _rel(v, o[k])
    ums, uns = W.mg2_snow_fall_speeds(lams, rho, cfg)
    errs["ums"] = _rel(ums, o["ums"])
    errs["uns"] = _rel(uns, o["uns"])
    errs["nsagg"] = _rel(W.mg2_snow_self_aggregation(qsic, nsic, T, rho, cfg),
                         o["nsagg"])
    nc_adj, pgam, lamc = W.mg2_size_dist_liq(i["qcic"], i["ncic"] * rho, rho)
    errs["ncic_adj"] = _rel(nc_adj / rho, o["ncic_adj"])
    errs["pgam"] = _rel(pgam, o["pgam"])
    errs["lamc"] = _rel(lamc, o["lamc"])
    eps_s, mu = W.mg2_snow_vent_eps(n0s, lams, T, p, rho, cfg)
    psacws, npsacws = W.mg2_accrete_cloud_water_snow(
        T, rho, mu, uns, i["qcic"], nc_adj / rho, qsic, pgam, lamc, lams, n0s, cfg)
    errs["psacws"] = _rel(psacws, o["psacws"])
    errs["npsacws"] = _rel(npsacws, o["npsacws"])
    errs["bergs"] = _rel(W.mg2_bergeron_snow(T, i["qcic"], qsic, qvl, qvi, eps_s),
                         o["bergs"])
    errs["prds"] = _rel(W.mg2_snow_sublimation(
        i["qfrac"] * qvl, qvl, qvi, T, eps_s, qsic, i["lcldm"], pf, i["qcic"],
        i["qiic"]), o["prds"])
    q_ric, N_ric, lamr, _ = W.mg2_inprecip_rain(
        i["qr"], i["nr"] * rho, rho, pf, cfg.lamr_min, cfg.lamr_max)
    mn, nn = W.rain_freezing_bigg_mg2(q_ric, N_ric, lamr, T, rho, pf, cfg)
    errs["mnuccr"] = _rel(mn, o["mnuccr"] * pf)
    errs["nnuccr"] = _rel(nn / rho, o["nnuccr"] * pf)
    # Ferrier on MG2's ice slope (no fixture point reaches its bounds; see
    # test_mg2_ice_slope_bounds).
    niic, lami = W.mg2_ice_slope(i["qi"], i["ni"], cfg.rho_cloud_ice, float(fx["dcs"]))
    errs["lami"] = _rel(lami, o["lami"])
    errs["niic"] = _rel(niic, o["niic"])
    prci, nprci = W.ice_autoconversion_mg2(i["qi"], niic, lami, float(fx["dcs"]), T)
    errs["prci"] = _rel(prci, o["prci"])
    errs["nprci"] = _rel(nprci, o["nprci"])
    worst = {k: float(np.max(v)) for k, v in errs.items()}
    print("snow kernel max rel err", worst)
    assert max(worst.values()) <= TOL, worst
    # non-trivial coverage
    for k in ("nsagg", "psacws", "bergs", "prds", "mnuccr", "prci"):
        assert np.count_nonzero(o[k]) > 20, k
    assert np.any(o["nsic"] != fx["pt_in_ns"] / fx["pt_in_precip_frac"])  # bounds
    # Bigg gate: rain exists between 269.15 K and the melting point, MG2 does
    # not freeze it there
    warm = (fx["pt_in_T"] >= 269.15) & (fx["pt_in_qr"] > 0)
    assert np.any(warm) and np.all(o["mnuccr"][warm] == 0.0)
    assert np.all(np.asarray(mn)[warm] == 0.0)


