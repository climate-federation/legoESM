def test_whole_call_snow_matches_mg2():
    """Whole micro_mg_tend vs morrison_microphysics on the snow columns,
    production deck config (kk2000_cam6 at the fixture relvar), hard limit:
    snow mass and number tendencies (instantaneous melts, riming, Bergeron,
    sublimation, self-aggregation, limiters, post-source sedimentation at MG2
    fall speeds, final re-adjustment), rain mass and number tendencies, the
    riming and Bergeron totals, and the surface snow and rain fluxes."""
    fx = _fx()
    out = _run_columns(fx, _cfg(fx))
    qb = out.qc_budget
    rho = fx["col_rho"]
    snow_sfc = np.asarray(out.precip_frozen)
    errs = {
        "dq_s": _rel(out.dq_s_dt, fx["ora_qstend"]),
        "dN_s": _rel(out.dN_s_dt, fx["ora_nstend"]),
        "dq_r": _rel(out.dq_r_dt, fx["ora_qrtend"]),
        "dN_r": _rel(np.asarray(out.dN_r_dt) / rho, fx["ora_nrtend"]),
        "psacws": _rel(-np.asarray(qb["riming_snow"]), fx["ora_psacwstot"]),
        "bergs": _rel(-np.asarray(qb["bergeron_snow"]), fx["ora_bergstot"]),
        "snow_sfc": _rel(snow_sfc, fx["ora_sflx_sfc"]),
        "rain_sfc": _rel(np.asarray(out.precipitation) - snow_sfc,
                         fx["ora_rflx_sfc"]),
    }
    worst = {k: float(np.max(v)) for k, v in errs.items()}
    print("whole-call snow max rel err", worst)
    assert max(worst.values()) <= TOL, worst
    # the columns exercise what they claim, and nothing outside the port
    for k in ("psacwstot", "bergstot", "evapsnow", "meltsdttot"):
        assert np.count_nonzero(fx[f"ora_{k}"]) >= 3, k
    for k in ("msacwitot", "pracstot", "mnuccrtot"):
        assert np.all(fx[f"ora_{k}"] == 0.0), k
    assert np.all(np.asarray(out.dq_i_dt) == 0.0)
    assert np.all(np.asarray(out.dN_i_dt) == 0.0)


def test_snow_mass_and_energy_close():
    """Water: the column tendency of total water equals minus the surface
    precipitation (no cloud-water sedimentation here).  Frozen MSE
    c_p T + L_v q_v - L_f (q_s) changes only through the surface flux terms."""
    from legoesm import constants as C
    fx = _fx()
    out = _run_columns(fx, _cfg(fx))
    dp = np.diff(fx["col_p_half"], axis=1) / C.g
    dw = (np.asarray(out.dq_v_dt) + np.asarray(out.dq_c_dt) + np.asarray(out.dq_r_dt)
          + np.asarray(out.dq_i_dt) + np.asarray(out.dq_s_dt) + np.asarray(out.dq_g_dt))
    res_w = np.sum(dw * dp, axis=1) + np.asarray(out.precipitation)
    assert np.max(np.abs(res_w)) <= 1e-12 * np.max(np.asarray(out.precipitation)), res_w
    dh = (C.c_pd * np.asarray(out.dT_dt) + C.L_v * np.asarray(out.dq_v_dt)
          - C.L_f * (np.asarray(out.dq_s_dt) + np.asarray(out.dq_i_dt)
                     + np.asarray(out.dq_g_dt)))
    res_h = (np.sum(dh * dp, axis=1)
             - C.L_f * np.asarray(out.precip_frozen))
    scale = C.L_f * np.max(np.abs(np.asarray(out.dq_s_dt) * dp).sum(axis=1))
    assert np.max(np.abs(res_h)) <= 1e-10 * scale, res_h


def test_gradients_finite_on_fixture_columns():
    """jax.grad of column snow + surface precip w.r.t. the inputs is finite."""
    fx = _fx()
    cfg = _production_morrison()._replace(warm_rain_scheme="kk2000_cam6",
                                          kk2000_cam6_relvar=float(fx["relvar"]))

    def loss(qs, ns, qc, T):
        f = dict(fx)
        f["col_q_s"], f["col_N_s"], f["col_q_c"], f["col_T"] = qs, ns, qc, T
        out = _run_columns(f, cfg)
        return (jnp.sum(out.dq_s_dt) + jnp.sum(out.precipitation) * 1e3
                + jnp.sum(out.dN_s_dt) * 1e-9)

    g = jax.grad(loss, argnums=(0, 1, 2, 3))(
        jnp.asarray(fx["col_q_s"]), jnp.asarray(fx["col_N_s"]),
        jnp.asarray(fx["col_q_c"]), jnp.asarray(fx["col_T"]))
    for gi in g:
        assert bool(jnp.all(jnp.isfinite(gi)))
    assert float(jnp.max(jnp.abs(g[0]))) > 0.0


def test_hydrostatic_bridge_carries_snow_number(monkeypatch):
    """The MPAS column bridge hands the N_s tracer to Morrison and returns its
    tendency; without the tracer the MG2 mode is refused."""
    import types

    from legoesm.atmosphere.physics.clouds.config import CloudConfig
    from legoesm.atmosphere.physics.turbulence.clubb import CLUBBConfig
    from legoesm.atmosphere.physics.microphysics import integration as mi
    from legoesm.atmosphere.physics.microphysics.config import MicrophysicsConfig
    sys.path.insert(0, str(ROOT / "tests/unit"))
    from test_physics_macmic import _moist_setup
    cfg = _production_morrison()
    assert mi.min_tracer_slots("morrison", cfg) == 10
    assert mi.min_tracer_slots("morrison", cfg._replace(warm_rain_incloud=False)) == 9

    seen = []
    real = mi.morrison_microphysics

    def spy(T, qv, hyd, *a, **k):
        seen.append(None if hyd.N_s is None else np.asarray(hyd.N_s))
        return real(T, qv, hyd, *a, **k)
    monkeypatch.setattr(mi, "morrison_microphysics", spy)
    # aerosol droplet fill needs the external forcing stream; off here (it
    # does not touch the snow-number path under test)
    fn = mi.make_microphysics_physics(
        MicrophysicsConfig(scheme="morrison",
                           morrison=cfg._replace(nc_from_aerosol=False)),
        "mpas", 600.0,
        cloud_config=CloudConfig(scheme="cam6_clubb"),
        clubb_config=CLUBBConfig(), relvar_from_clubb=True)
    mesh, sigma, state = _moist_setup()
    shape = state.T.data.shape
    tr = dict(state.tracers)
    tr["q_s"] = state.T.replace(data=jnp.full(shape, 2.0e-4), name="q_s")
    ns = jnp.full(shape, 3.0e4)
    # production kk2000_cam6 reads CLUBB's per-cell relvar; any value works,
    # the warm-rain law is not under test here
    ps = types.SimpleNamespace(cloud_fraction=jnp.full(shape, 0.5),
                               relvar=jnp.ones(shape))
    with_ns = fn(state._replace(tracers={**tr, "N_s": state.T.replace(
        data=ns, name="N_s", units="1/kg")}), mesh, sigma, phys_state=ps)
    np.testing.assert_array_equal(seen[0], np.asarray(ns))
    # MG2 mode without the snow number is refused, never single-moment
    # (user decision 2026-10-20)
    with pytest.raises(ValueError, match="needs the snow number tracer N_s"):
        fn(state._replace(tracers=tr), mesh, sigma, phys_state=ps)
    dns = np.asarray(with_ns.tracer_tendencies["N_s"].data)
    assert np.all(np.isfinite(dns)) and np.any(dns != 0.0)


def test_mg2_ice_slope_bounds():
    """MG2 size_dist_param_basic on mg_ice_props (micro_mg_utils.F90:294,
    481-516): N <= q/1e-20 kg, then lami held inside 1/[2 dcs, 1 um] with the
    number re-adjusted; Ferrier prci/nprci on that slope equal MG2's own
    m_ip * nprci * poly form with n0i = niic*lami (micro_mg_utils.F90:880-894)."""
    from legoesm.atmosphere.physics.microphysics import _warm_rain as W
    rhoi, dcs = 500.0, 500.0e-6
    q = jnp.asarray([1.0e-5, 1.0e-5, 1.0e-5, 1.0e-12])
    n = jnp.asarray([1.0, 1.0e5, 1.0e20, 1.0e12])   # big, inside, tiny, mean mass < 1e-20
    ni, lam = W.mg2_ice_slope(q, n, rhoi, dcs)
    lo, hi = 1.0 / (2.0 * dcs), 1.0e6
    raw = (rhoi * np.pi * np.asarray(n) / np.asarray(q)) ** (1.0 / 3.0)
    assert raw[0] < lo and lo < raw[1] < hi and raw[2] > hi
    np.testing.assert_allclose(lam, [lo, raw[1], hi, hi], rtol=1e-13)
    np.testing.assert_allclose(
        ni, [lo ** 3 * 1e-5 / (rhoi * np.pi), 1.0e5, hi ** 3 * 1e-5 / (rhoi * np.pi),
             hi ** 3 * 1e-12 / (rhoi * np.pi)], rtol=1e-13)
    assert float(ni[3]) <= 1.0e-12 / 1.0e-20
    T = jnp.full(4, 250.0)
    prci, nprci = W.ice_autoconversion_mg2(q, ni, lam, dcs, T)
    d = np.asarray(lam) * dcs
    nprci_mg2 = np.asarray(ni) * np.asarray(lam) / (np.asarray(lam) * 180.0) * np.exp(-d)
    prci_mg2 = (rhoi * np.pi / 6.0) / np.asarray(lam) ** 3 * nprci_mg2 * (((d + 3) * d + 6) * d + 6)
    np.testing.assert_allclose(nprci[:3], nprci_mg2[:3], rtol=1e-12)  # [3]: below the 1e-14 gate
    np.testing.assert_allclose(prci[:3], prci_mg2[:3], rtol=1e-12)


@pytest.mark.parametrize("ice_to_snow", ["m2005_autoconv", "mg_ferrier"])
def test_mg2_ice_conservation_credits_same_step_sources(ice_to_snow):
    """MG2 conservation of qi (micro_mg2_0.F90:1717-1735): ice->snow
    autoconversion + sublimation may take q_i PLUS this step's ice sources
    (deposition here), x omsm.  Single-level cold cells at RH_ice 0.8-1.4 with
    big ice whose unlimited conversion overdraws q_i: the cell keeps only the
    omsm margin of (q_i + sources), never goes negative, and supersaturated
    cells do not keep the deposited ice the old q_i-only donor clamp left."""
    from legoesm import constants as C
    from legoesm.thermo import saturation_mixing_ratio_ice
    from legoesm.atmosphere.physics.microphysics import _warm_rain as W
    from legoesm.atmosphere.physics.microphysics.morrison import morrison_microphysics
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    cfg = _production_morrison()._replace(warm_rain_scheme="kk2000_cam6",
                                          ice_to_snow_scheme=ice_to_snow)
    assert cfg.warm_rain_incloud
    n, dt = 4, 600.0
    T = jnp.full((n, 1), 235.0)
    p = jnp.full((n, 1), 30000.0)
    ph = jnp.concatenate([p - 500.0, p + 500.0], axis=1)
    rho = p / (C.R_d * T)
    dz = (ph[:, 1:] - ph[:, :-1]) / (C.g * rho)
    rhi = jnp.asarray([0.8, 1.0, 1.2, 1.4])[:, None]
    qv = rhi * saturation_mixing_ratio_ice(T, p)
    qi = jnp.full((n, 1), 2.0e-5)
    Ni = jnp.full((n, 1), 2.0e3)
    z = jnp.zeros_like(T)
    ni, lam = W.mg2_ice_slope(qi, Ni, cfg.rho_cloud_ice, cfg.ice_snow_d_auto)
    prci, _ = W.ice_autoconversion_mg2(qi, ni, lam, cfg.ice_snow_d_auto, T)
    assert np.all(np.asarray(prci) * dt > 2.0 * np.asarray(qi))  # limit binds
    hyd = HydrometeorState(q_c=z, q_r=z, q_i=qi, q_s=z, q_g=z, N_c=z + 5.0e7,
                           N_r=z, N_i=Ni, N_s=z)
    out = morrison_microphysics(T, qv, hyd, p, ph, rho, dz, dt, cfg,
                                cloud_fraction=z + 1.0)
    qi_new = np.asarray(qi + dt * out.dq_i_dt)[:, 0]
    print("qi_new / qi", qi_new / 2.0e-5)
    assert np.all(qi_new >= -1.0e-14 * 2.0e-5), qi_new
    assert np.all(qi_new <= 1.0e-4 * 2.0e-5), qi_new


