def _run_columns(fx, cfg, n_s=True):
    from legoesm import constants as C
    from legoesm.atmosphere.physics.microphysics.morrison import morrison_microphysics
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    g = {k: jnp.asarray(fx[f"col_{k}"]) for k in
         ("T", "q_v", "q_c", "cf", "q_r", "N_r", "q_s", "N_s", "N_c", "p_full",
          "p_half", "rho")}
    dz = (g["p_half"][:, 1:] - g["p_half"][:, :-1]) / (C.g * g["rho"])
    z = jnp.zeros_like(g["T"])
    hyd = HydrometeorState(q_c=g["q_c"], q_r=g["q_r"], q_i=z, q_s=g["q_s"], q_g=z,
                           N_c=g["N_c"], N_r=g["N_r"], N_i=z,
                           N_s=g["N_s"] if n_s else None)
    return morrison_microphysics(
        g["T"], g["q_v"], hyd, g["p_full"], g["p_half"], g["rho"], dz,
        float(fx["dt"]), cfg._replace(publish_qc_budget=True),
        cloud_fraction=g["cf"])


