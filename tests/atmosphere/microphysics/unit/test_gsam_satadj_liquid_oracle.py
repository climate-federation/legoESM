"""gSAM liquid saturation adjustment (and Morrison's sam flavour) vs the RUNNING
gSAM oracle.

Fixture ``tests/atmosphere/microphysics/oracle_fixtures/gsam_satadj_liquid.npz``
was generated by RUNNING gSAM 1.8.8 ``satadj_liquid``
(SRC/MICRO_M2005/microphysics.f90:1638-1720, stock tolerance) and gSAM's
micro_proc order (satadj_liquid, then M2005MICRO_GRAUPEL, KK2000) on five warm
columns, compiled with gfortran 8.5.0 in fp64 (tarball sha256
0e9ea4a37f4daca5051cc4018cc95bbc5583159c7c27d7d05d1104fae4ed270c; gSAM has no
git tag/SHA), via ``python scripts/validate/oracle/gsam_satadj_liquid/make_fixture.py
--gsam <gSAM1.8.8> --build <dir> --out gsam_satadj_liquid.npz``.

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64 with
every existing sharpness field at its hard-switch limit.  Relative error is
``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0); no floor (the tier-1
oracle tests' metric).  The whole-call check compares post-step T and q_v:
Morrison's remaining documented departures from M2005 (no cloud-droplet
settling, rain sedimented from the pre-source state) move only q_c, q_r and
N_r within one call.
"""
from __future__ import annotations

import functools
import importlib.util
import json
import math
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from legoesm import constants
from legoesm.atmosphere.physics.microphysics._warm_rain import (
    saturation_adjustment_gsam,
)
from legoesm.atmosphere.physics.microphysics.config import MorrisonConfig
from legoesm.atmosphere.physics.microphysics.morrison import morrison_microphysics
from legoesm.atmosphere.physics.microphysics.output import HydrometeorState

jax.config.update("jax_enable_x64", True)

ROOT = Path(__file__).resolve().parents[4]
FIXTURE = ROOT / "tests/atmosphere/microphysics/oracle_fixtures/gsam_satadj_liquid.npz"
GENERATOR = ROOT / "scripts/validate/oracle/gsam_satadj_liquid/make_fixture.py"
TOL = 1.0e-10
# Every existing MorrisonConfig sharpness field other than the saturation one
# (which the sam flavour no longer reads) -> its hard-switch limit (the tier-2
# audit's HARD_LIMIT).
HARD_LIMIT = dict(
    autoconversion_sharpness=1.0e9, breakup_sharpness=1.0e12,
    ice_sigmoid_sharpness=1.0e6, nuc_rh_sharpness=1.0e9, nuc_T_sharpness=1.0e6,
    homogeneous_freeze_sharpness=1.0e6, hom_freeze_T_sharpness=1.0e6,
    hom_ice_nuc_sharpness=1.0e9, melt_sharpness=1.0e6,
    gsam_satadj_excess_sharpness=math.inf, gsam_satadj_qc_floor_sharpness=math.inf,
    gsam_satadj_p_min_width_pa=0.0)
# saturation_adjustment_gsam at gSAM's hard switches, and at the defaults.
GSAM_HARD = dict(excess_sharpness=math.inf, qc_floor_sharpness=math.inf, p_min_width_pa=0.0)
GSAM_DEFAULT = dict(
    excess_sharpness=MorrisonConfig._field_defaults["gsam_satadj_excess_sharpness"],
    qc_floor_sharpness=MorrisonConfig._field_defaults["gsam_satadj_qc_floor_sharpness"],
    p_min_width_pa=MorrisonConfig._field_defaults["gsam_satadj_p_min_width_pa"])


def _fx():
    return dict(np.load(FIXTURE))


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


def _gen():
    spec = importlib.util.spec_from_file_location("satadj_fixture", GENERATOR)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    return gen


def test_fixture_provenance_and_inputs_reproduce():
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    gen = _gen()
    assert meta["source_sha256"] == gen._shared().SOURCE_SHA256
    assert "thresh_mult=1, maxiter=20" in meta["settings"]
    pts = gen.build_points()
    for i, k in enumerate(("T", "q_v", "q_c", "p")):
        np.testing.assert_array_equal(fx[k], pts[:, i])


def test_adjustment_matches_gsam():
    fx = _fx()
    T, q_v, q_c, p = (jnp.asarray(fx[k]) for k in ("T", "q_v", "q_c", "p"))
    Tn, qvn, qcn = saturation_adjustment_gsam(T, q_v, q_c, p, **GSAM_HARD)
    errs = {"T": _rel(Tn, fx["ora_T"]).max(), "q_v": _rel(qvn, fx["ora_q_v"]).max(),
            "q_c": _rel(qcn, fx["ora_q_c"]).max()}
    assert max(errs.values()) <= TOL, errs
    # Non-vacuous: condensation, full evaporation of sub-saturated cloud and
    # the p < 50 hPa skip are all in the fixture.
    assert np.sum(fx["ora_q_c"] > 0) > 150
    evap = (fx["q_c"] > 0) & (fx["ora_q_c"] == 0) & (fx["p"] >= 5000.0)
    assert evap.sum() >= 30
    assert np.all(fx["ora_q_c"][fx["p"] < 5000.0] == 0)


def _columns(fx, dtype=jnp.float64):
    flip = lambda k: jnp.asarray(fx[f"col_{k}"][:, ::-1], dtype=dtype)  # top-down
    rho = flip("rho")
    z = jnp.zeros_like(rho)
    hyd = HydrometeorState(q_c=flip("q_c"), q_r=flip("q_r"), q_i=z, q_s=z, q_g=z,
                           N_c=jnp.full_like(rho, float(fx["col_Nc0_cm3"]) * 1e6),
                           N_r=flip("n_r_kg") * rho, N_i=z, N_s=z, N_g=z)
    return (flip("T"), flip("q_v"), hyd, flip("p_full"), flip("p_half"), rho,
            flip("dz"), float(fx["col_dt"]))


def _sam(**kw):
    return MorrisonConfig(morrison_flavor="sam", warm_rain_scheme="kk2000", **kw)


def test_morrison_sam_whole_call_T_qv_match_gsam():
    fx = _fx()
    T, q_v, hyd, pf, ph, rho, dz, dt = _columns(fx)
    out = morrison_microphysics(T, q_v, hyd, pf, ph, rho, dz, dt,
                                _sam()._replace(**HARD_LIMIT))
    T_new = np.asarray(T + dt * out.dT_dt)[:, ::-1]
    qv_new = np.asarray(q_v + dt * out.dq_v_dt)[:, ::-1]
    errs = {"T": _rel(T_new, fx["ora_col_T"]).max(),
            "q_v": _rel(qv_new, fx["ora_col_q_v"]).max()}
    assert max(errs.values()) <= TOL, errs


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_adjustment_gradients_finite(dtype):
    fx = _fx()
    T, q_v, q_c, p = (jnp.asarray(fx[k], dtype=dtype) for k in ("T", "q_v", "q_c", "p"))

    def loss(T, q_v, q_c):
        Tn, qvn, qcn = saturation_adjustment_gsam(T, q_v, q_c, p, **GSAM_DEFAULT)
        return jnp.sum(Tn) + jnp.sum(qvn + qcn) * 1e3

    for g in jax.grad(loss, argnums=(0, 1, 2))(T, q_v, q_c):
        assert bool(jnp.all(jnp.isfinite(g)))


def test_morrison_sam_column_gradients_finite_fp64():
    """fp64 only: the Morrison sam column gradient w.r.t. T is already NaN in
    fp32 on cf/main (before this port) -- reported in the PR, not masked."""
    fx = _fx()
    Tc, qvc, hyd, pf, ph, rho, dz, dt = _columns(fx)

    def col_loss(Tc, qvc):
        out = morrison_microphysics(Tc, qvc, hyd, pf, ph, rho, dz, dt, _sam())
        return jnp.sum(out.dT_dt) + jnp.sum(out.precipitation) * 1e3

    for g in jax.grad(col_loss, argnums=(0, 1))(Tc, qvc):
        assert bool(jnp.all(jnp.isfinite(g)))


def test_jit_matches_eager():
    """T and q_v.  q_c = (T1 - T_l)/(L/c_p) cancels catastrophically for tiny
    condensate, so jit-vs-eager q_c differs by up to ~2e-9 relative at the
    fixture's S = 1.0005 cold points (reported in the PR)."""
    fx = _fx()
    args = tuple(jnp.asarray(fx[k]) for k in ("T", "q_v", "q_c", "p"))
    fn = functools.partial(saturation_adjustment_gsam, **GSAM_DEFAULT)
    eager = fn(*args)
    jitted = jax.jit(fn)(*args)
    for a, b in zip(eager[:2], jitted[:2]):
        assert _rel(a, b).max() <= TOL


@pytest.mark.parametrize("field,value", [
    ("saturation_sharpness", 1.0e14), ("hard_saturation_adjustment", True),
    ("hard_sat_adjust_threshold", 1.0), ("hard_sat_max_heating_K", 1.0e9),
    ("liquid_from_closure", True)])
def test_sam_rejects_fields_without_gsam_counterpart(field, value):
    fx = _fx()
    T, q_v, hyd, pf, ph, rho, dz, dt = _columns(fx)
    with pytest.raises(ValueError, match="no counterpart"):
        morrison_microphysics(T, q_v, hyd, pf, ph, rho, dz, dt,
                              _sam(**{field: value}))


# --- RULE 5: gSAM satadj smooth switches, one class at a time (others hard) ---
# Default departure from the gSAM oracle over the fixture: (max|dT| [K], max|dq_c| [kg/kg]).
_GSAM_DEFAULT_GAP = {
    "excess_sharpness": (0.0010472030201071902, 4.20656554226504e-07),
    "qc_floor_sharpness": (3.0516852007167472e-05, 1.2258476687345997e-08),
    "p_min_width_pa": (0.00023259943355924406, 9.343410433085435e-08),
}


@pytest.mark.parametrize("field", list(_GSAM_DEFAULT_GAP))
def test_gsam_satadj_default_gap_is_pinned(field):
    fx = _fx()
    T, q_v, q_c, p = (jnp.asarray(fx[k]) for k in ("T", "q_v", "q_c", "p"))
    kw = dict(GSAM_HARD, **{field: GSAM_DEFAULT[field]})
    Tn, _, qcn = saturation_adjustment_gsam(T, q_v, q_c, p, **kw)
    gap = (float(np.abs(np.asarray(Tn) - fx["ora_T"]).max()),
           float(np.abs(np.asarray(qcn) - fx["ora_q_c"]).max()))
    assert gap == pytest.approx(_GSAM_DEFAULT_GAP[field], rel=1e-6, abs=1e-12)


def _kink_cell(field):
    """A cell on the field's hard switch: exactly saturated (excess) or a
    1% supersaturated cell at p = 5000 Pa (pressure gate).  The cloud-water
    floor binds only where the excess switch does, so its cell is the saturated
    one; the floor alone is tested just above saturation (next test)."""
    from legoesm.thermo import saturation_specific_humidity
    gate = field == "p_min_width_pa"
    p = 5000.0 if gate else 8.0e4
    T = jnp.float64(230.0 if gate else 280.0)
    s = 1.01 if gate else 1.0
    q_v = s * saturation_specific_humidity(T, jnp.float64(p))
    return T, q_v * 1e3, jnp.float64(0.0), jnp.float64(p)


@pytest.mark.parametrize("field", list(_GSAM_DEFAULT_GAP))
def test_gsam_satadj_default_gradients(field):
    from jax.test_util import check_grads
    T, qv_gkg, qc_gkg, p = _kink_cell(field)
    kw = dict(GSAM_HARD, **{field: GSAM_DEFAULT[field]})
    if field == "qc_floor_sharpness":  # the floor's only kink is the excess one
        kw = dict(GSAM_DEFAULT)

    def fn(T, qv_gkg, p):
        Tn, qvn, qcn = saturation_adjustment_gsam(T, qv_gkg * 1e-3, qc_gkg * 1e-3, p, **kw)
        return jnp.stack([Tn - T, qcn * 1e3])

    check_grads(fn, (T, qv_gkg, p), order=2, modes=("rev",), eps=1e-4, atol=1e-6, rtol=1e-3)


def test_gsam_satadj_floor_alone_scales_the_gradient_just_above_saturation():
    """Hard excess, smooth floor: just above saturation the condensation
    increment x = T1 - T_l is ~1/s, where the smooth floor's slope is
    sigmoid(s x) < 1 and the hard floor's is 1.  Fails if the floor is hard."""
    from legoesm.thermo import saturation_specific_humidity
    s = GSAM_DEFAULT["qc_floor_sharpness"]
    T, p, q_c = jnp.float64(290.0), jnp.float64(9.0e4), jnp.float64(0.0)
    q_v = saturation_specific_humidity(T, p) + 3.0e-8

    def q_c_new(q, floor):
        kw = dict(GSAM_HARD, qc_floor_sharpness=floor)
        return saturation_adjustment_gsam(T, q, q_c, p, **kw)[2]

    fac = constants.L_v / constants.c_pd
    x = q_c_new(q_v, math.inf) * fac
    g_hard = jax.grad(q_c_new)(q_v, math.inf)
    g_smooth = jax.grad(q_c_new)(q_v, s)
    assert float(g_smooth) == pytest.approx(float(jax.nn.sigmoid(s * x) * g_hard), rel=1e-6)
    assert float(g_smooth) < 0.6 * float(g_hard)


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_gsam_satadj_default_finite_and_nonnegative_over_the_cold_corner(dtype):
    """Smooth default over 150-310 K, 100 Pa-1e5 Pa, saturation ratio 0-1.2:
    finite value and gradient (fp32 q_sat underflows to 0 at the cold end) and
    no negative cloud water although the floor is not applied."""
    from legoesm.thermo import saturation_specific_humidity
    T = jnp.linspace(150.0, 310.0, 17, dtype=dtype)[:, None, None]
    p = jnp.asarray([1.0e2, 5.0e3, 3.0e4, 1.0e5], dtype=dtype)[None, :, None]
    S = jnp.linspace(0.0, 1.2, 13, dtype=dtype)[None, None, :]
    q_v = (S * saturation_specific_humidity(T, p)).ravel()
    T, p = (jnp.broadcast_to(a, (17, 4, 13)).ravel() for a in (T, p))
    q_c = jnp.zeros_like(T)
    fn = functools.partial(saturation_adjustment_gsam, **GSAM_DEFAULT)
    Tn, qvn, qcn = fn(T, q_v, q_c, p)
    assert all(bool(jnp.all(jnp.isfinite(x))) for x in (Tn, qvn, qcn))
    assert bool(jnp.all(qcn >= 0.0))
    g = jax.grad(lambda T, q: sum(jnp.sum(x) for x in fn(T, q, q_c, p)), argnums=(0, 1))(T, q_v)
    assert all(bool(jnp.all(jnp.isfinite(x))) for x in g)
