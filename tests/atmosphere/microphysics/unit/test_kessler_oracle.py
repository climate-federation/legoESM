def test_public_entry_point_returns_the_step_as_tendencies():
    from legoesm.atmosphere.physics.microphysics.config import KesslerConfig
    from legoesm.atmosphere.physics.microphysics.kessler import (
        kessler_microphysics, kessler_step_states)
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    fx = _fx()
    T, qv, qc, qr, pf, rho, dz = _inputs(fx)
    z = jnp.zeros_like(T)
    hyd = HydrometeorState(q_c=qc, q_r=qr, q_i=z, q_s=z, q_g=z, N_c=z, N_r=z, N_i=z)
    ph = jnp.asarray(fx["col_p_half"])
    cfg = KesslerConfig()
    out = kessler_microphysics(T, qv, hyd, pf, ph, rho, dz, 300.0, cfg)
    st = kessler_step_states(T, qv, qc, qr, pf, rho, dz, 300.0, cfg)
    for tend, after, before in zip(
            (out.dT_dt, out.dq_v_dt, out.dq_c_dt, out.dq_r_dt), st[:4],
            (T, qv, qc, qr)):
        np.testing.assert_array_equal(tend, (after - before) / 300.0)
    np.testing.assert_array_equal(out.precipitation, st[4])


def test_jit_matches_oracle():
    """Under jax.jit the step still matches the oracle at the hard limit."""
    from legoesm.atmosphere.physics.microphysics.config import KesslerConfig
    from legoesm.atmosphere.physics.microphysics.kessler import kessler_step_states
    fx = _fx()
    cfg = KesslerConfig(**HARD_LIMIT)
    out = jax.jit(lambda *a: kessler_step_states(*a, 1200.0, cfg))(*_inputs(fx))
    ours = dict(zip(STATES + ("precip",), out[:5]))
    ora = _oracle(fx, 1200.0)
    worst = {k: float(_rel(ours[k], ora[k]).max()) for k in ora}
    assert max(worst.values()) <= TOL, worst


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
@pytest.mark.parametrize("sharp", [None, 1.0e30])
def test_gradient_finite_on_fixture_columns(dtype, sharp):
    from legoesm.atmosphere.physics.microphysics.config import KesslerConfig
    from legoesm.atmosphere.physics.microphysics.kessler import kessler_step_states
    fx = _fx()
    T, qv, qc, qr, pf, rho, dz = _inputs(fx, dtype)
    cfg = KesslerConfig() if sharp is None else KesslerConfig(saturation_sharpness=sharp)

    def loss(T, qv, qc, qr):
        Tn, qvn, qcn, qrn, pr, _ = kessler_step_states(T, qv, qc, qr, pf, rho, dz,
                                                        300.0, cfg)
        return jnp.sum(Tn) + 1e3 * (jnp.sum(qcn) + jnp.sum(qrn) + jnp.sum(qvn)) \
            + 1e3 * jnp.sum(pr)

    g = jax.grad(loss, argnums=(0, 1, 2, 3))(T, qv, qc, qr)
    for x in g:
        assert np.all(np.isfinite(np.asarray(x)))
    assert float(jnp.max(jnp.abs(g[3]))) > 0.0


