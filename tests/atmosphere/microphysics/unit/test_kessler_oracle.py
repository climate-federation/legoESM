def test_step_needing_more_subcycles_than_the_cap_errors():
    """Morrison's strict sub-step error path, reused: eager and jit raise; a
    jit(grad) composition, where error_if sits outside AD, gets NaN."""
    from legoesm.atmosphere.physics.microphysics.config import KesslerConfig
    from legoesm.atmosphere.physics.microphysics.kessler import kessler_step_states
    fx = _fx()
    args = _inputs(fx)
    cfg = KesslerConfig()
    with pytest.raises(Exception, match="CFL subcycles"):
        jax.block_until_ready(kessler_step_states(*args, 1.0e7, cfg))
    with pytest.raises(Exception, match="CFL subcycles"):
        jax.block_until_ready(jax.jit(
            lambda *a: kessler_step_states(*a, 1.0e7, cfg))(*args))
    g = jax.jit(jax.grad(lambda T: jnp.sum(
        kessler_step_states(T, *args[1:], 1.0e7, cfg)[1])))
    try:
        out = jax.block_until_ready(g(args[0]))
    except Exception as exc:                      # the abort is fine too
        assert "CFL subcycles" in str(exc)
    else:
        assert not bool(jnp.isfinite(out).all())
    # every public output carries the poison, including the zero fields
    from legoesm.atmosphere.physics.microphysics.kessler import kessler_microphysics
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    T, qv, qc, qr, pf, rho, dz = args
    z = jnp.zeros_like(T)
    hyd = HydrometeorState(q_c=qc, q_r=qr, q_i=z, q_s=z, q_g=z, N_c=z, N_r=z, N_i=z)
    ph = jnp.asarray(fx["col_p_half"])
    for name in ("dq_i_dt", "dN_c_dt", "precip_frozen", "dq_v_to_qc_dt"):
        f = jax.jit(lambda T, name=name: getattr(kessler_microphysics(
            T, qv, hyd, pf, ph, rho, dz, 1.0e7, cfg), name))
        try:
            out = jax.block_until_ready(f(T))
        except Exception as exc:                  # the abort is fine too
            assert "CFL subcycles" in str(exc)
        else:
            assert not bool(jnp.isfinite(out).all()), name


def test_public_entry_precipitation_matches_oracle():
    """Surface rain through the public ``kessler_microphysics`` entry point
    (the pre-port scheme returned exactly 0 here)."""
    from legoesm.atmosphere.physics.microphysics.config import KesslerConfig
    from legoesm.atmosphere.physics.microphysics.kessler import kessler_microphysics
    from legoesm.atmosphere.physics.microphysics.output import HydrometeorState
    fx = _fx()
    T, qv, qc, qr, pf, rho, dz = _inputs(fx)
    z = jnp.zeros_like(T)
    hyd = HydrometeorState(q_c=qc, q_r=qr, q_i=z, q_s=z, q_g=z, N_c=z, N_r=z, N_i=z)
    ph = jnp.asarray(fx["col_p_half"])
    for dt in (1200.0, 300.0):
        out = kessler_microphysics(T, qv, hyd, pf, ph, rho, dz, dt,
                                   KesslerConfig(**HARD_LIMIT))
        err = float(_rel(out.precipitation, _oracle(fx, dt)["precip"]).max())
        assert err <= TOL, (dt, err)
