"""Kessler warm rain vs the RUNNING ESCOMP kessler_run oracle.

Fixture ``tests/atmosphere/oracle_fixtures/kessler.npz`` was generated by
RUNNING ESCOMP/atmospheric_physics ``atmos_phys0_31_000``
(856127273a3f8b6a64315967e0d7d42ce4d02994) ``schemes/kessler/kessler.F90``,
compiled unmodified (gfortran 8.5.0, fp64), with ``python
scripts/validate/oracle/kessler/make_fixture.py --ap <atmospheric_physics>
--build <dir> --out kessler.npz`` (metadata in the npz ``meta``).

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64 with
the existing sharpness field at its hard-switch limit.  Relative error is
``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0); no floor.  Compared
quantities are the oracle's own outputs: the states after the step and the
step-mean surface precipitation.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

jax.config.update("jax_enable_x64", True)

ROOT = Path(__file__).resolve().parents[4]
FIXTURE = ROOT / "tests/atmosphere/oracle_fixtures/kessler.npz"
GENERATOR = ROOT / "scripts/validate/oracle/kessler/make_fixture.py"
TOL = 1.0e-10
HARD_LIMIT = dict(saturation_sharpness=1.0e30)
STATES = ("T", "q_v", "q_c", "q_r")


def _fx():
    return dict(np.load(FIXTURE))


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


def _inputs(fx, dtype=jnp.float64):
    return [jnp.asarray(fx[k], dtype=dtype) for k in
            ("col_T", "col_q_v", "col_q_c", "col_q_r", "col_p_full",
             "col_rho", "col_dz")]


def _oracle(fx, dt):
    t = f"ora_dt{dt:g}_"
    rho_w = json.loads(str(fx["meta"]))["rho_water"]
    return dict(T=fx[t + "theta"] * fx["ora_in_pk"], q_v=fx[t + "q_v"],
                q_c=fx[t + "q_c"], q_r=fx[t + "q_r"],
                precip=fx[t + "precl_m_s"] * rho_w)


def _ours(fx, dt, cfg, dtype=jnp.float64):
    from legoesm.atmosphere.physics.microphysics.kessler import kessler_step_states
    T, qv, qc, qr, pf, rho, dz = _inputs(fx, dtype)
    out = kessler_step_states(T, qv, qc, qr, pf, rho, dz, dt, cfg)
    return dict(zip(STATES + ("precip",), out[:5]))


def test_fixture_provenance_and_inputs_reproduce():
    """The committed generator rebuilds the fixture's inputs bit-for-bit."""
    fx = _fx()
    meta = json.loads(str(fx["meta"]))
    assert meta["tag"] == "atmos_phys0_31_000"
    assert meta["sha"] == "856127273a3f8b6a64315967e0d7d42ce4d02994"
    spec = importlib.util.spec_from_file_location("kessler_make_fixture", GENERATOR)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    cols = gen.build_columns()
    for k in gen.COL_FIELDS:
        np.testing.assert_array_equal(np.stack([c[k] for c in cols]), fx[f"col_{k}"])
    for a, k in zip(gen.geometry(cols),
                    ("col_rho", "col_dz", "ora_in_z", "ora_in_pk", "ora_in_theta")):
        np.testing.assert_array_equal(a, fx[k])


@pytest.mark.parametrize("dt", [1200.0, 300.0])
def test_step_matches_oracle_at_hard_limit(dt):
    from legoesm.atmosphere.physics.microphysics.config import KesslerConfig
    fx = _fx()
    ours = _ours(fx, dt, KesslerConfig(**HARD_LIMIT))
    ora = _oracle(fx, dt)
    worst = {k: float(_rel(ours[k], ora[k]).max()) for k in ora}
    print(f"dt={dt:g} hard-limit max rel err", worst)
    assert max(worst.values()) <= TOL, worst
    # non-trivial: rain reaches the ground in every rainy column, the cloud
    # evaporates somewhere and condenses somewhere
    assert np.count_nonzero(ora["precip"] > 0) >= 6
    assert np.any(ora["q_c"] < fx["col_q_c"]) and np.any(ora["q_c"] > fx["col_q_c"])


