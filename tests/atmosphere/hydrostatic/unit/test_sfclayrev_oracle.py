jax.config.update("jax_enable_x64", True)

TOL = 1.0e-10
JIT_TOL = 1.0e-12   # jit vs eager: max|diff| / max|field| (vote J1)
FIXTURE = Path(__file__).resolve().parents[2] / "oracle_fixtures" / "sfclayrev.npz"
DRIVE = ("u1", "v1", "t1", "qv1", "p1", "dz1", "psfc", "tsk", "xland", "mavail", "pblh", "dx")
STATE = ("ust", "mol", "znt", "hfx", "qfx", "qsfc")
NOT_PORTED = ("ustm", "ck", "cka", "cd", "cda")   # vote X2: not produced


@pytest.fixture(scope="module")
def fx():
    return dict(np.load(FIXTURE))


def _meta(fx):
    return json.loads(str(fx["meta"]))


def _rel(a, b):
    a, b = np.asarray(a, np.float64), np.asarray(b, np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    den = np.maximum(np.abs(a), np.abs(b))
    return np.where(den > 0, np.abs(a - b) / np.where(den > 0, den, 1.0), 0.0)


def _run(fx, sff, fn=sfclayrev_run, nstep=None):
    drive = {k: jnp.asarray(fx[f"in_{k}"]) for k in DRIVE}
    st = SfclayState(**{k: jnp.asarray(fx[f"in_{k}"]) for k in STATE})
    outs = []
    for _ in range(nstep or _meta(fx)["nstep"]):
        o = fn(*(drive[k] for k in DRIVE), st, scm_force_flux=bool(sff))
        outs.append(o)
        st = SfclayState(**{k: getattr(o, k) for k in STATE})
    return outs


def test_fixture_provenance(fx):
    m = _meta(fx)
    assert m["oracle"]["sha"] == "06d4240ae989cc3e50af412bb472df3d9048783c"
    assert m["oracle"]["physics_mmm_sha"] == "550b5b494758ad2756394e93cb08b5709b8feb83"
    c = m["constants"]
    assert (c["cp"], c["g"], c["r"], c["xlv"], c["karman"], c["p1000mb"], c["svpt0"]) == (
        constants.c_pd, constants.g, constants.R_d, constants.L_v,
        constants.kappa_von_karman, constants.p_ref, constants.T_freeze)
    assert FIXTURE.stat().st_size < 1_000_000


def test_fixture_covers_branches(fx):
    o = fx["ora_sff0"][0]
    i = {k: n for n, k in enumerate(_meta(fx)["outputs"])}
    xl, br = fx["in_xland"], o[:, i["br"]]
    for land in (xl < 1.5, xl >= 1.5):
        assert np.any(land & (br > 0)) and np.any(land & (br < 0))
    assert np.any(br == 0.0)                                   # neutral class
    assert np.any(br >= 250.0) and np.any(br <= -250.0)        # zolri clips
    assert np.any(o[:, i["wspd"]] == 0.1)                      # calm floor
    assert np.any((fx["in_ust"] < 0.001) & (br < 0))           # zol = br*gz1oz0
    assert np.any(o[:, i["flhc"]] == 0.0)                      # |dtheta| <= 1e-5
    assert np.any(np.abs(o[:, i["zol"]]) * 10.0 / (0.5 * fx["in_dz1"]) > 10.0)  # past table
    zw = o[:, i["znt"]][xl >= 1.5]
    assert np.any(zw == 2.85e-3) and np.any(zw < 2.85e-3)      # Charnock cap / free


@pytest.mark.parametrize("sff", [0, 1])
def test_sfclayrev_matches_oracle(fx, sff):
    names = _meta(fx)["outputs"]
    ora = fx[f"ora_sff{sff}"]
    worst = {}
    for s, o in enumerate(_run(fx, sff)):
        for j, k in enumerate(names):
            if k in NOT_PORTED or (k == "lh" and sff == 1):
                continue
            worst[k] = max(worst.get(k, 0.0), float(np.max(_rel(getattr(o, k), ora[s, :, j]))))
    bad = {k: v for k, v in worst.items() if not v <= TOL}
    assert not bad, bad


def test_forced_flux_lh_is_nan(fx):
    o = _run(fx, 1, nstep=1)[0]
    assert np.all(np.isnan(np.asarray(o.lh)))
    np.testing.assert_array_equal(np.asarray(o.hfx), fx["in_hfx"])
    np.testing.assert_array_equal(np.asarray(o.qfx), fx["in_qfx"])


def test_jit_matches_eager(fx):
    eager = _run(fx, 0)
    jitted = _run(fx, 0, fn=jax.jit(sfclayrev_run, static_argnames="scm_force_flux"))
    for a, b in zip(eager, jitted):
        for k in a._fields:
            x, y = np.asarray(getattr(a, k)), np.asarray(getattr(b, k))
            scale = max(float(np.max(np.abs(x))), 1e-300)
            assert float(np.max(np.abs(x - y))) / scale <= JIT_TOL, k


def test_finite_gradients(fx):
    drive = {k: jnp.asarray(fx[f"in_{k}"]) for k in DRIVE}
    st = SfclayState(**{k: jnp.asarray(fx[f"in_{k}"]) for k in STATE})

    def loss(t1, tsk, u1, ust, znt):
        d = dict(drive, t1=t1, tsk=tsk, u1=u1)
        o = sfclayrev_run(*(d[k] for k in DRIVE), st._replace(ust=ust, znt=znt),
                          scm_force_flux=False)
        return jnp.sum(o.hfx + o.lh + o.ust + o.br + o.u10 + o.znt + o.fm + o.fh)

    g = jax.grad(loss, argnums=(0, 1, 2, 3, 4))(drive["t1"], drive["tsk"], drive["u1"],
                                               st.ust, st.znt)
    for gi in g:
        assert np.all(np.isfinite(np.asarray(gi)))
    assert float(np.max(np.abs(np.asarray(g[1])))) > 0.0      # flux responds to T_sfc

