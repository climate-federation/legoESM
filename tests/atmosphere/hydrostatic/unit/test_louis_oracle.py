def test_default_smoothing_gap_is_reported(fx, monkeypatch):
    """Production blend_ri_sharpness (100) vs its hard limit: printed for the
    PR record, not bounded (the default-smoothing gap is a reported number)."""
    for arm in ("ifs", "icon"):
        kw = dict(_arm(fx, arm))
        _, _, Km_h, Kh_h = _captured(fx, monkeypatch, kw)
        kw["blend_ri_sharpness"] = LouisConfig().blend_ri_sharpness
        _, _, Km_d, Kh_d = _captured(fx, monkeypatch, kw)
        print(arm, "default-smoothing gap (per-column max rel): Km %.2e Kh %.2e"
              % (_err(Km_d, Km_h, True), _err(Kh_d, Kh_h, True)))


def test_column_water_budget_closes(fx):
    """Column water (the solver's own layer mass rho*dz) changes by exactly the
    surface moisture flux (interior flux-form diffusion, zero-flux top); the
    column c_p*T + KE residual (theta-space heat diffusion with a surface-Exner
    heat flux, a documented solver departure) is printed."""
    out = _run(fx, {})
    T, q, p = fx["in_T"], fx["in_q"], fx["in_p_full"]
    rho = np.asarray(compute_rho(jnp.asarray(T), jnp.asarray(p), q_v=jnp.asarray(q)))
    dm = rho * np.clip(np.abs(np.diff(fx["in_zi"], axis=1)), 1.0, None)
    evap = np.asarray(out.evap_sfc)
    res_q = (np.sum(np.asarray(out.dq_v_dt) * dm, axis=1) - evap) / np.max(np.abs(evap))
    dt = float(fx["dt"])
    u, v = fx["in_u"], fx["in_v"]
    un, vn = u + dt * np.asarray(out.du_dt), v + dt * np.asarray(out.dv_dt)
    dke = 0.5 * (un ** 2 + vn ** 2 - u ** 2 - v ** 2) / dt
    res_e = (np.sum((constants.c_pd * np.asarray(out.dT_dt) + dke) * dm, axis=1)
             - fx["in_shflx"]) / np.max(np.abs(fx["in_shflx"]))
    print("budget residual / max sfc flux: water %.2e, c_p T + KE %.2e"
          % (np.abs(res_q).max(), np.abs(res_e).max()))
    assert np.abs(res_q).max() <= TOL


def _tendency_grads(fx, dtype, cfg_kw):
    f = {k: jnp.asarray(fx[f"in_{k}"], dtype) for k in ("T", "q", "u", "zm")}

    def loss(T, q, u, zm):  # zm: the full-level heights the unstable geometry reads
        fx2 = dict(fx)
        fx2.update(in_T=T, in_q=q, in_u=u, in_zm=zm)
        o = _run(fx2, cfg_kw, dtype=dtype)
        return (jnp.sum(o.dT_dt ** 2) * 1e8 + jnp.sum(o.dq_v_dt ** 2) * 1e14
                + jnp.sum(o.du_dt ** 2) * 1e6 + jnp.sum(o.Km) + jnp.sum(o.Kh))
    return jax.grad(loss, argnums=(0, 1, 2, 3))(f["T"], f["q"], f["u"], f["zm"])


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
@pytest.mark.parametrize("arm", ["default", "ifs", "icon"])
def test_grad_finite_on_fixture_columns(fx, dtype, arm):
    cfg_kw = {} if arm == "default" else _arm(fx, arm)
    for gr in _tendency_grads(fx, dtype, cfg_kw):
        assert gr.dtype == dtype
        assert bool(jnp.all(jnp.isfinite(gr)))
        assert float(jnp.max(jnp.abs(gr))) > 0.0


def test_eager_jit_parity(fx):
    """Eager vs jit on the fields this port changes (tendencies, K)."""
    eager = _run(fx, {})
    jitted = jax.jit(lambda: _run(fx, {}))()
    for k in ("du_dt", "dv_dt", "dT_dt", "dq_v_dt", "Km", "Kh"):
        assert _err(np.asarray(getattr(jitted, k)), np.asarray(getattr(eager, k))) <= TOL, k
