from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

import jax
import jax.numpy as jnp

from legoesm import constants
from legoesm.atmosphere.physics._shared import compute_rho
from legoesm.atmosphere.physics.turbulence import louis as L
from legoesm.atmosphere.physics.turbulence.config import LouisConfig

jax.config.update("jax_enable_x64", True)

TOL = 1.0e-10
FIXTURE = Path(__file__).resolve().parents[2] / "oracle_fixtures" / "louis.npz"
FIELDS = ("T", "q", "u", "v", "p_full", "p_half", "zm", "zi",
          "taux", "tauy", "shflx", "lhflx")


@pytest.fixture(scope="module")
def fx():
    return dict(np.load(FIXTURE))


def _arm(fx, name):
    return json.loads(str(fx["meta"]))["arms"][name]


def _err(ours, ref, per_column=False):
    """max|ours-ref| / max|ref| (0 when both are identically 0): over the whole
    fixture, or per column (``per_column``, worst column returned)."""
    ref = np.asarray(ref, np.float64)
    ref = ref.reshape(ref.shape[0], -1)
    ours = np.asarray(ours, np.float64).reshape(ref.shape)
    assert np.all(np.isfinite(ours)) and np.all(np.isfinite(ref))
    ax = 1 if per_column else None
    num, den = np.max(np.abs(ours - ref), axis=ax), np.max(np.abs(ref), axis=ax)
    e = np.where(den > 0, num / np.where(den > 0, den, 1.0), np.where(num > 0, np.inf, 0.0))
    return float(np.max(e))


def _run(fx, cfg_kw, *, dtype=jnp.float64, capture=None):
    f = {k: jnp.asarray(fx[f"in_{k}"], dtype) for k in FIELDS}
    rho = compute_rho(f["T"], f["p_full"], q_v=f["q"])
    ustar = jnp.sqrt(jnp.hypot(f["taux"], f["tauy"]) / rho[:, -1])
    return L.louis_turbulence(
        f["u"], f["v"], f["T"], f["q"], f["p_full"], f["p_half"], f["zm"], f["zi"],
        f["T"][:, -1], f["q"][:, -1], rho, float(fx["dt"]),
        LouisConfig()._replace(**cfg_kw),
        surface_flux=(f["taux"], f["tauy"], f["shflx"], f["lhflx"], ustar))


def _captured(fx, monkeypatch, cfg_kw):
    """Run the production entry; capture Ri (stability-function call) and the
    K_m (u solve) / K_h (q solve) interface diffusivities."""
    cap = {"stab": [], "K": []}
    orig_stab, orig_ivd = L.louis_stability_functions, L.implicit_vertical_diffusion

    def stab(*a, **k):
        cap["stab"].append(a)
        return orig_stab(*a, **k)

    def ivd(phi, K, *a):
        cap["K"].append(K)
        return orig_ivd(phi, K, *a)
    monkeypatch.setattr(L, "louis_stability_functions", stab)
    monkeypatch.setattr(L, "implicit_vertical_diffusion", ivd)
    out = _run(fx, cfg_kw)
    assert len(cap["stab"]) == 1 and len(cap["K"]) == 3
    return out, np.asarray(cap["stab"][0][0]), np.asarray(cap["K"][0]), np.asarray(cap["K"][2])


def test_fixture_provenance(fx):
    meta = json.loads(str(fx["meta"]))
    assert meta["oracle"]["ifs"]["sha"] == "8f6f722f732b92fed2c39af763d8fcd1ab15f573"
    assert meta["oracle"]["icon"]["sha"] == "8597da45ef4b86323f3fb844caedc4ae5e1ffc01"
    assert meta["constants"]["kappa_vk"] == constants.kappa_vk  # IFS RKAP = 0.4
    assert meta["icon_cb_cc"] == [5.0, 5.0]
    assert FIXTURE.stat().st_size < 1_000_000


def _masked(a, m):
    return np.where(m, a, 0.0)


def test_stable_diffusivities_match_openifs_vdfexcu(fx, monkeypatch):
    _, Ri, Km, Kh = _captured(fx, monkeypatch, _arm(fx, "ifs"))
    m = fx["ifs_Ri"] > 0.0
    assert m.sum() >= 700
    e = {"km": _err(_masked(Km, m), _masked(fx["ora_ifs_km"], m), True),
         "kh": _err(_masked(Kh, m), _masked(fx["ora_ifs_kh"], m), True),
         # Ri is legoESM's (it was the oracle's input PRI): regression pin only
         "ri_pin": _err(Ri, fx["ifs_Ri"], True)}
    print("Louis stable vs OpenIFS vdfexcu, hard limit, max rel err", e)
    assert max(e.values()) <= TOL, e


def test_unstable_diffusivities_match_icon_louis79(fx, monkeypatch):
    _, Ri, Km, Kh = _captured(fx, monkeypatch, _arm(fx, "icon"))
    m = fx["icon_Ri"] < 0.0
    assert m.sum() >= 30
    e = {"km": _err(_masked(Km, m), _masked(fx["ora_icon_km"], m), True),
         "kh": _err(_masked(Kh, m), _masked(fx["ora_icon_kh"], m), True),
         "ri_pin": _err(Ri, fx["icon_Ri"], True)}
    print("Louis unstable vs ICON mo_turb_vdiff_diag:518-530, hard limit, max rel err", e)
