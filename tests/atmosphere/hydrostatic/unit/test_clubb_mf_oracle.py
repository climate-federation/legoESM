def _gaps(fx):
    out = {}
    for sw in MFSmoothing._fields:
        sm = HARD._replace(**{sw: getattr(MFSmoothing(), sw)})
        for step in (1, 2):
            got = _run(fx, sm, step)
            out[f"{sw}_step{step}"] = {
                k: [_rel(got[k][i], fx[f"ora{step}_{k}"][i]) for i in range(got[k].shape[0])]
                for k in FIELDS
            }
    return out


def test_default_smoothing_gap_per_case(fx):
    """RULE 5: each switch at its default (the others hard) vs the oracle, per
    column and step, to the stored measurement.  Re-measure (``python
    test_clubb_mf_oracle.py``) when a smooth form or default changes."""
