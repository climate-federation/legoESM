def _run(fx, sm, step):
    """Reference on every fixture column for oracle step 1 or 2 (vmapped, jitted per sm)."""
    if sm not in _RUN:
        _RUN[sm] = jax.jit(jax.vmap(lambda c, e, z: integrate_mf(c, e, z, sm)))
    out = _RUN[sm](
        _cols(fx), jnp.asarray(fx[f"ora{step}_enti"]), jnp.asarray(fx[f"ora{step}_ztopm1_in"])
    )
    return {k: np.asarray(v) for k, v in out.items()}


def _rel(a, b):
    d = float(np.max(np.abs(b)))
    return float(np.max(np.abs(a - b))) / (d if d > 0.0 else 1.0)


