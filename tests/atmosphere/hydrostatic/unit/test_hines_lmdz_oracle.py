"""Oracle match: Hines Doppler-spread GWD vs LMDZ r5891 hines_gwd, RUN as Fortran.

Oracle: LMDZ6 trunk r5891 ``libf/phylmd/hines_gwd.f90`` compiled unmodified,
fixture ``oracle_fixtures/hines_lmdz.npz`` generated by
scripts/validate/oracle/hines_lmdz/{build.sh,make_fixture.py}.  Ours = ``hines_gwd``
with the oracle's hard switch forms (``smooth_sharpness = inf``) and LMDZ's
launch level (``k_launch = nlev - 3``); compared outputs du_dt, dv_dt.

Metric: per column, max|ours - ref| / max|ref|, worst column returned.

Run with ``JAX_ENABLE_X64=1``.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import jax

jax.config.update("jax_enable_x64", True)

import jax.numpy as jnp
import numpy as np
import pytest

from legoesm import constants
from legoesm.atmosphere.physics.gravity_wave_drag.config import HinesConfig
from legoesm.atmosphere.physics.gravity_wave_drag.hines import hines_gwd

FIXTURE = (Path(__file__).parents[2] / "oracle_fixtures" / "hines_lmdz.npz")
_TOL = 1e-10  # user-approved oracle-match tolerance (max relative error, fp64)


def _rel(ours, ref):
    ours, ref = np.asarray(ours, np.float64), np.asarray(ref, np.float64)
    assert np.all(np.isfinite(ours)) and np.all(np.isfinite(ref))
    den = np.max(np.abs(ref))
    return float(np.max(np.abs(ours - ref)) / den) if den > 0 else float(np.max(np.abs(ours)))


@pytest.fixture(scope="module")
def fix():
    """Per-column dict of arrays (the fixture stores ragged columns flat)."""
    z = np.load(FIXTURE)
    n = z["nlev"]
    cuts = {"p_half": np.cumsum(n + 1)[:-1], "flux_top": np.cumsum(np.full_like(n, 2))[:-1]}
    out = {k: z[k] for k in ("names", "lat", "meta")}
    for k in ("p_half", "p_full", "T", "u", "v", "du_dt", "dv_dt", "flux_top"):
        out[k] = np.split(z[k], cuts.get(k, np.cumsum(n)[:-1]))
    return out


def _column(z, i, cfg, t_scale=1.0):
    g = lambda k: jnp.asarray(np.asarray(z[k][i], np.float64))[None, :]
    p_full, p_half, T = g("p_full"), g("p_half"), g("T") * t_scale
    nlev = p_full.shape[1]
    zero = jnp.zeros((1, nlev + 1))
    lat = jnp.asarray([float(z["lat"][i]) / 180.0 * np.pi])
    return hines_gwd(g("u"), g("v"), T, p_full, p_half, zero[:, :-1], zero,
                     jnp.ones((1, nlev)), lat, json.loads(str(z["meta"]))["dt"], cfg,
                     k_launch=jnp.asarray([nlev - 3]))


def _errors(z, cfg, t_scale=1.0):
    errs = {}
    for i, name in enumerate(z["names"]):
        o = _column(z, i, cfg, t_scale)
        errs[str(name)] = max(_rel(o.du_dt[0], z["du_dt"][i]), _rel(o.dv_dt[0], z["dv_dt"][i]))
    return errs


def test_hines_matches_lmdz(fix):
    errs = _errors(fix, HinesConfig(smooth_sharpness=math.inf))
    assert max(errs.values()) <= _TOL, errs


def test_hines_oracle_comparison_can_fail(fix):
    """Controls (V56): a 1% change of the launch rms wind, and a 0.1% change of T
    (through N and the density), must each break the match on every column."""
    hard = HinesConfig(smooth_sharpness=math.inf)
    errs = _errors(fix, hard._replace(total_rms_wind=1.01))
    assert min(errs.values()) > 1e3 * _TOL, errs
    errs = _errors(fix, hard, t_scale=1.001)
    assert min(errs.values()) > 1e3 * _TOL, errs


def test_hines_column_momentum_telescopes(fix):
    """LMDZ's flux divergence: the column integral of the drag over the scheme's own
    layers is zero (deep column excluded: the 105 km decay breaks the telescoping)."""
    from legoesm import constants
    cfg = HinesConfig(smooth_sharpness=math.inf)
    for i in range(len(fix["names"]) - 1):
        o = _column(fix, i, cfg)
        p_half, p_full, T = (np.asarray(fix[k][i], np.float64) for k in ("p_half", "p_full", "T"))
        ps = p_half[-1]
        sg, dsg = p_full / ps, np.diff(p_half) / ps
        hscal = constants.R_d * T / constants.g
        rho = sg * ps / (constants.g * hscal)
        alt = np.append(np.cumsum((hscal * dsg / sg)[-2::-1])[::-1], 0.0)
        dz = np.append(alt[0] - alt[1], alt[:-1] - alt[1:])
        t = rho * dz * np.asarray(o.du_dt[0])
        assert abs(t.sum()) <= 1e-12 * np.abs(t).max()


def test_hines_smooth_default_close_and_differentiable(fix):
    """Default (smooth) switch forms: within 5% (V52; measured max 1.85e-2, rest
    column) of the hard oracle form on every column, and a gradient wrt the wind that
    is finite, nonzero and matches central finite differences (V53)."""
    z = fix
    gaps = []
    for i in range(len(z["names"])):
        hard = _column(z, i, HinesConfig(smooth_sharpness=math.inf)).du_dt
        soft = _column(z, i, HinesConfig()).du_dt
        gaps.append(_rel(soft, hard))
    assert max(gaps) < 0.05, dict(zip(z["names"], gaps))
    assert max(gaps) > 1e-3, "the default must actually be the smooth form"

    i = 0
    g = lambda k: jnp.asarray(np.asarray(z[k][i], np.float64))[None, :]
    nlev = g("p_full").shape[1]

    def loss(u):
        o = hines_gwd(u, g("v"), g("T"), g("p_full"), g("p_half"),
                      jnp.zeros((1, nlev)), jnp.zeros((1, nlev + 1)), jnp.ones((1, nlev)),
                      jnp.asarray([0.5]), 1800.0, HinesConfig(), k_launch=jnp.asarray([nlev - 3]))
        return jnp.sum(o.du_dt ** 2)

    u0 = g("u")
    grad = jax.grad(loss)(u0)
    assert np.all(np.isfinite(np.asarray(grad))) and float(jnp.max(jnp.abs(grad))) > 0.0
    for k in (5, 20, 28):
        e = jnp.zeros_like(u0).at[0, k].set(1e-4)
        fd = (loss(u0 + e) - loss(u0 - e)) / 2e-4
        assert abs(float(fd) / float(grad[0, k]) - 1.0) < 1e-4, k


def test_hines_fp32_columns_take_fp64_host_pressures():
    """fp32 column fields with fp64 pressures/latitude stay fp32 end to end."""
    nlev = 20
    p_half = np.linspace(100.0, 1.0e5, nlev + 1)[None, :]
    p_full = 0.5 * (p_half[:, 1:] + p_half[:, :-1])
    z_half = 7000.0 * np.log(1.0e5 / p_half)
    z_full = 0.5 * (z_half[:, 1:] + z_half[:, :-1])
    f32 = lambda a: jnp.asarray(a, jnp.float32)
    T = f32(np.full((1, nlev), 250.0))
    u = f32(np.linspace(30.0, 2.0, nlev)[None, :])
    out = hines_gwd(u, 0.3 * u, T, jnp.asarray(p_full), jnp.asarray(p_half),
                    jnp.asarray(z_full), jnp.asarray(z_half),
                    jnp.asarray(p_full / (constants.R_d * 250.0)),
                    jnp.asarray([0.5]), 1800.0, HinesConfig())
    assert out.du_dt.dtype == jnp.float32 and out.eps_gwd.dtype == jnp.float32
    assert np.all(np.isfinite(np.asarray(out.du_dt)))
