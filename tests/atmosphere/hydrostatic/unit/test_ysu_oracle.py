def _budgets(fx, dT, dq, du):
    """Column theta-enthalpy and water change minus the surface sensible-heat
    and water flux (the oracle's flux-form solve conserves both), and the
    column momentum change (equal to the implicit surface drag)."""
    dpg = np.diff(fx["in_p_half"], axis=1) / constants.g
    res_q = np.sum(dq * dpg, axis=1) - fx["in_qfx"]
    res_h = np.sum(constants.c_pd * dT / fx["in_exner"] * dpg, axis=1) - fx["in_hfx"]
    mom = np.sum(du * dpg, axis=1)
    return res_q / np.max(np.abs(fx["in_qfx"])), res_h / np.max(np.abs(fx["in_hfx"])), mom


def test_column_budgets_close_as_the_oracle(fx):
    o = _kernel(fx)
    ours = _budgets(fx, *(np.asarray(x) for x in (o.dT_dt, o.dq_v_dt, o.du_dt)))
    ora = _budgets(fx, fx["ora_dT"], fx["ora_dq"], fx["ora_du"])
    print("budget residual / max sfc flux: water ours %.2e oracle %.2e; heat ours %.2e "
          "oracle %.2e" % (np.abs(ours[0]).max(), np.abs(ora[0]).max(),
                           np.abs(ours[1]).max(), np.abs(ora[1]).max()))
    assert np.abs(ours[0]).max() <= TOL and np.abs(ours[1]).max() <= TOL
    assert np.abs(ours[0] - ora[0]).max() <= TOL and np.abs(ours[1] - ora[1]).max() <= TOL
    assert _err(ours[2][:, None], ora[2][:, None]) <= TOL
    # the drag opposes the lowest-level wind
    assert np.all(ours[2] * fx["in_u"][:, -1] <= 0.0)


def _grads(fx, dtype, sharp):
    def loss(T, q, u):
        o = _kernel(fx, sharp=sharp, dtype=dtype, T=T, q=q, u=u)
        return (jnp.sum(o.dT_dt ** 2) * 1e8 + jnp.sum(o.dq_v_dt ** 2) * 1e14
                + jnp.sum(o.du_dt ** 2) * 1e6 + jnp.sum(o.hpbl) + jnp.sum(o.exch_h))
    args = [jnp.asarray(fx[f"in_{k}"], dtype) for k in ("T", "q", "u")]
    return jax.grad(loss, argnums=(0, 1, 2))(*args)


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
@pytest.mark.parametrize("smooth", ["default", "hard"])
def test_grad_finite_on_fixture_columns(fx, dtype, smooth):
    cfg = YSUConfig()
    # near-hard 1e12 (1e300 is not representable in fp32)
    sharp = dict.fromkeys(HARD, 1e12) if smooth == "hard" else dict(
        pbl_sharpness=cfg.pbl_smooth_sharpness, region_sharpness=cfg.blend_pbl_sharpness,
        ri_sharpness=cfg.blend_ri_sharpness)
    for gr in _grads(fx, dtype, sharp):
        assert gr.dtype == dtype
        assert bool(jnp.all(jnp.isfinite(gr)))
        assert float(jnp.max(jnp.abs(gr))) > 0.0


def test_eager_jit_parity(fx):
    eager = _kernel(fx)
    jitted = jax.jit(lambda: _kernel(fx))()
    for a, b in zip(eager, jitted):
        assert _err(np.asarray(b, float), np.asarray(a, float)) <= TOL
