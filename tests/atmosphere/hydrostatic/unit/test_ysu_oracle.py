SFC_KEYS = ("br", "psim", "psih", "wspd", "znt", "u10", "v10", "xland")


@pytest.fixture(scope="module")
def fx():
    return dict(np.load(FIXTURE))


def _names(fx):
    return json.loads(str(fx["meta"]))["names"]


def _err(ours, ref, per_column=False):
    """max|ours-ref| / max|ref| (0 when both are identically 0): over the whole
    fixture, or per column (``per_column``, worst column returned)."""
    ref = np.asarray(ref, np.float64)
    ref = ref.reshape(ref.shape[0], -1)
    ours = np.asarray(ours, np.float64).reshape(ref.shape)
    assert np.all(np.isfinite(ours)) and np.all(np.isfinite(ref))
    ax = 1 if per_column else None
    num, den = np.max(np.abs(ours - ref), axis=ax), np.max(np.abs(ref), axis=ax)
    e = np.where(den > 0, num / np.where(den > 0, den, 1.0), np.where(num > 0, np.inf, 0.0))
    return float(np.max(e))


def _sfc(fx, dtype=jnp.float64):
    return YSUSurfaceLayer(**{k: jnp.asarray(fx[f"in_{k}"], dtype) for k in SFC_KEYS})


def _kernel(fx, sharp=HARD, dtype=jnp.float64, **over):
    """bl_ysu_run on fixture-style inputs (``in_*`` keys)."""
    f = {k: jnp.asarray(over.get(k, fx[f"in_{k}"]), dtype) for k in
         ("u", "v", "T", "q", "p_full", "p_half", "exner", "dz", "ust", "hfx", "qfx")}
    return bl_ysu_run(f["u"], f["v"], f["T"], f["q"], f["p_full"], f["p_half"],
                      f["exner"], f["dz"], f["ust"], f["hfx"], f["qfx"], _sfc(fx, dtype),
                      float(fx["dt"]), **sharp)


def _wrapper(fx, cfg_kw, dtype=jnp.float64):
    """ysu_turbulence on the WRF path with the oracle's surface fluxes
    prescribed (ustar = sqrt(|tau|/rho_low) reproduces the oracle's ust)."""
    f = {k: jnp.asarray(fx[f"in_{k}"], dtype) for k in
         ("u", "v", "T", "q", "p_full", "p_half", "zi")}
    sfc = SurfaceLayerConfig()._replace(
        prescribed_shflx_w_m2=jnp.asarray(fx["in_hfx"], dtype),
        prescribed_lhflx_w_m2=jnp.asarray(fx["in_lhflx"], dtype),
        prescribed_evap_kg_m2_s=jnp.asarray(fx["in_qfx"], dtype),
        prescribed_tau_x_pa=jnp.asarray(fx["in_taux"], dtype),
        prescribed_tau_y_pa=jnp.asarray(fx["in_tauy"], dtype))
    cfg = YSUConfig()._replace(surface=sfc, **cfg_kw)
    rho = compute_rho(f["T"], f["p_full"], q_v=f["q"])
    zm = 0.5 * (f["zi"][:, :-1] + f["zi"][:, 1:])
    return ysu_turbulence(f["u"], f["v"], f["T"], f["q"], f["p_full"], f["p_half"], zm,
                          f["zi"], f["T"][:, -1], f["q"][:, -1], rho, float(fx["dt"]), cfg,
                          surface_layer=_sfc(fx, dtype))


def test_fixture_provenance(fx):
    meta = json.loads(str(fx["meta"]))
    assert meta["oracle"]["sha"] == "06d4240ae989cc3e50af412bb472df3d9048783c"
    assert meta["oracle"]["physics_mmm_sha"] == "550b5b494758ad2756394e93cb08b5709b8feb83"
    c = meta["constants"]
    assert (c["cp"], c["g"], c["rd"], c["karman"]) == (
        constants.c_pd, constants.g, constants.R_d, constants.kappa_vk)
    assert c["ep1"] == constants.R_v / constants.R_d - 1.0
    assert FIXTURE.stat().st_size < 1_000_000
    assert np.all(fx["ora_exch_h"][:, -1] == 0.0) and np.all(fx["ora_exch_m"][:, -1] == 0.0)


def _kernel_errors(fx, o):
    return {
        "hpbl": _err(o.hpbl, fx["ora_hpbl"][:, None], True),
        "wstar": _err(o.wstar, fx["ora_wstar"][:, None], True),
        "delta": _err(o.delta, fx["ora_delta"][:, None], True),
        "exch_h": _err(o.exch_h, fx["ora_exch_h"], True),
        "exch_m": _err(o.exch_m, fx["ora_exch_m"], True),
        "du": _err(o.du_dt, fx["ora_du"]),
        "dv": _err(o.dv_dt, fx["ora_dv"]),
        "dT": _err(o.dT_dt, fx["ora_dT"]),
        "dq": _err(o.dq_v_dt, fx["ora_dq"]),
    }


def test_bl_ysu_run_matches_oracle(fx):
    o = _kernel(fx)
    assert np.array_equal(np.asarray(o.kpbl), fx["ora_kpbl"])
    worst = _kernel_errors(fx, o)
    print("YSU kernel vs oracle, hard limit, max rel err", worst)
    assert max(worst.values()) <= TOL, worst


def test_fixture_exercises_every_branch(fx):
    """Unstable PBL with thermal, kpbl = 1, stable PBL over land and over water
    (the Rossby critical Ri changes the height), and an entrainment layer."""
    names, o = _names(fx), _kernel(fx)
    pbl = np.asarray(o.pblflg)
    assert pbl.sum() >= 5 and (~pbl).sum() >= 5
    assert np.any(fx["ora_kpbl"] == 1)
    assert np.any((fx["in_br"] > 0) & (fx["ora_kpbl"] > 1))
    for n in ("polar_dry", "nocturnal_elevated"):
        assert fx["ora_hpbl"][names.index(n)] != fx["ora_hpbl"][names.index(n + "_water")]
    assert np.all(fx["ora_delta"][pbl] > 0) and np.all(fx["ora_delta"][~pbl] == 0)
    # a PBL top exactly on level kpbl-1 (brint = 0 after an exact bulk-Ri tie)
    t = names.index("tibet_deep_mixed_noflux")
    zq = np.concatenate([[0.0], np.cumsum(fx["in_dz"][t, ::-1])])
    za = 0.5 * (zq[:-1] + zq[1:])
    assert fx["ora_kpbl"][t] > 2 and fx["ora_hpbl"][t] == za[fx["ora_kpbl"][t] - 2]


def test_pbl_top_rounded_onto_level_kpbl_matches_oracle(fx):
    """8-level column whose PBL top rounds exactly onto za(kpbl): the interface
    there is above the PBL (free-atmosphere K), as in the oracle."""
    up = {k[3:]: v for k, v in fx.items() if k.startswith("up_")}
    up["dt"] = fx["dt"]
    o = _kernel(up)
    assert int(o.kpbl[0]) == int(up["ora_kpbl"][0]) == 3
    zq = np.concatenate([[0.0], np.cumsum(up["in_dz"][0, ::-1])])
    assert up["ora_hpbl"][0] == 0.5 * (zq[2] + zq[3])
    worst = _kernel_errors(up, o)
    print("upper-endpoint column vs oracle", worst)
    assert max(worst.values()) <= TOL, worst


