def _rel(ours, ref, ax):
    """max|ours-ref| / max|ref| along ``ax`` (0 when both are identically 0)."""
    ref = np.asarray(ref, np.float64)
    ref = ref.reshape(ref.shape[0], -1)
    ours = np.asarray(ours, np.float64).reshape(ref.shape)
    assert np.all(np.isfinite(ours)) and np.all(np.isfinite(ref))
    num, den = np.max(np.abs(ours - ref), axis=ax), np.max(np.abs(ref), axis=ax)
    return np.where(den > 0, num / np.where(den > 0, den, 1.0), np.where(num > 0, np.inf, 0.0))


def _err(ours, ref, per_column=False):
    """``_rel`` over the whole fixture, or per column (``per_column``, worst
    column returned)."""
    return float(np.max(_rel(ours, ref, 1 if per_column else None)))


def _sfc(fx, dtype=jnp.float64):
    return YSUSurfaceLayer(**{k: jnp.asarray(fx[f"in_{k}"], dtype) for k in SFC_KEYS})


def _kernel(fx, sharp=HARD, dtype=jnp.float64, **over):
    """bl_ysu_run on fixture-style inputs (``in_*`` keys)."""
    f = {k: jnp.asarray(over.get(k, fx[f"in_{k}"]), dtype) for k in
         ("u", "v", "T", "q", "p_full", "p_half", "exner", "dz", "ust", "hfx", "qfx")}
    return bl_ysu_run(f["u"], f["v"], f["T"], f["q"], f["p_full"], f["p_half"],
                      f["exner"], f["dz"], f["ust"], f["hfx"], f["qfx"], _sfc(fx, dtype),
                      float(fx["dt"]), **sharp)


def _wrapper(fx, cfg_kw, dtype=jnp.float64):
    """ysu_turbulence on the WRF path with the oracle's surface fluxes
    prescribed (ustar = sqrt(|tau|/rho_low) reproduces the oracle's ust)."""
    f = {k: jnp.asarray(fx[f"in_{k}"], dtype) for k in
         ("u", "v", "T", "q", "p_full", "p_half", "zi")}
    sfc = SurfaceLayerConfig()._replace(
        prescribed_shflx_w_m2=jnp.asarray(fx["in_hfx"], dtype),
        prescribed_lhflx_w_m2=jnp.asarray(fx["in_lhflx"], dtype),
        prescribed_evap_kg_m2_s=jnp.asarray(fx["in_qfx"], dtype),
        prescribed_tau_x_pa=jnp.asarray(fx["in_taux"], dtype),
        prescribed_tau_y_pa=jnp.asarray(fx["in_tauy"], dtype))
    cfg = YSUConfig()._replace(surface=sfc, **cfg_kw)
    rho = compute_rho(f["T"], f["p_full"], q_v=f["q"])
    zm = 0.5 * (f["zi"][:, :-1] + f["zi"][:, 1:])
    return ysu_turbulence(f["u"], f["v"], f["T"], f["q"], f["p_full"], f["p_half"], zm,
                          f["zi"], f["T"][:, -1], f["q"][:, -1], rho, float(fx["dt"]), cfg,
                          surface_layer=_sfc(fx, dtype))


