"""WRF v4.8.0 km_opt=3 Smagorinsky coefficients: port vs the RUNNING oracle.

Fixture: tests/atmosphere/oracle_fixtures/smag_wrf_km3.npz, generated by
scripts/validate/oracle/smag_wrf_km3/ (unmodified dyn_em/module_diffusion_em.F).
Metric (VOTE D14): per column max|ours - wrf| / max|wrf|, tolerance 1e-10, on the
HARD form (``hard=True``); the smooth production form is scored separately.
"""
import json
from pathlib import Path

import jax
import numpy as np
import pytest

from legoesm.atmosphere.physics.turbulence.config import SmagorinskyConfig
from legoesm.atmosphere.physics.turbulence.smagorinsky import wrf_km3_coefficients

jax.config.update("jax_enable_x64", True)

FIXTURE = Path(__file__).resolve().parents[2] / "oracle_fixtures" / "smag_wrf_km3.npz"
TOL = 1e-10
ROWS = ("defor13", "defor23", "bn2", "xkmv", "xkhv")


def _load():
    return np.load(FIXTURE, allow_pickle=False)


def _ours(d, hard, dt=None):
    m = json.loads(str(d["meta"]))
    cfg = SmagorinskyConfig()._replace(wrf_c_s=m["wrf_c_s"], wrf_prandtl=m["wrf_prandtl"],
                                       mix_upper_bound=m["mix_upper_bound"])
    return wrf_km3_coefficients(d["u"], d["v"], d["T"], d["q"], d["qc"], d["qi"],
                                d["p_full"], d["p_half"], d["zi"],
                                float(d["dt"]) if dt is None else dt, cfg, hard=hard)


def _rel(a, b):
    a, b = np.asarray(a), np.asarray(b)
    return np.max(np.abs(a - b), axis=1) / np.maximum(np.max(np.abs(b), axis=1), 1e-300)


def test_fixture_config_is_the_default():
    m = json.loads(str(_load()["meta"]))
    c = SmagorinskyConfig()
    assert (m["wrf_c_s"], m["wrf_prandtl"], m["mix_upper_bound"]) == (
        c.wrf_c_s, c.wrf_prandtl, c.mix_upper_bound)
    assert c.stability_form == "wrf_km3"


@pytest.mark.parametrize("row", ROWS)
def test_matches_wrf(row):
    d = _load()
    got = _ours(d, hard=True)[row]
    rel = _rel(got, d[row])
    assert np.all(rel <= TOL), (row, float(rel.max()), str(d["names"][int(rel.argmax())]))


@pytest.mark.parametrize("row", ("xkmv", "xkhv"))
def test_matches_wrf_short_step(row):
    """At the short step K leaves the floor/cap, so the deformation average counts."""
    d = _load()
    dt = json.loads(str(d["meta"]))["dt_short"]
    ref = d[row + "_short"]
    dz = d["zi"][:, :-1] - d["zi"][:, 1:]
    floor = 1e-6 * dz ** 2 / (SmagorinskyConfig().wrf_prandtl if row == "xkhv" else 1.0)
    free = (ref > floor * (1 + 1e-9)) & (ref < 0.1 * dz ** 2 / dt * (1 - 1e-9))
    assert free.sum() >= 20
    rel = _rel(_ours(d, hard=True, dt=dt)[row], ref)
    assert np.all(rel <= TOL), (row, float(rel.max()))


def test_moist_branch_is_exercised():
    d = _load()
    names = [str(n) for n in d["names"]]
    cloudy = [i for i, n in enumerate(names) if n.endswith("_cloudy")]
    assert cloudy
    for i in cloudy:
        base = names.index(names[i][: -len("_cloudy")])
        assert not np.array_equal(d["bn2"][i], d["bn2"][base])


def test_smooth_form_equals_hard_outside_the_bands():
    """VOTE S8: the smooth form is WRF's own wherever no switch is in its band."""
    from legoesm import constants as C
    from legoesm.thermo import saturation_vapor_pressure
    d = _load()
    hard, soft = _ours(d, hard=True), _ours(d, hard=False)
    dry = 1.0 - d["q"] - d["qc"] - d["qi"]
    es = np.asarray(saturation_vapor_pressure(d["T"]))
    xv = (d["q"] / dry) / (C.epsilon * es / (d["p_full"] - es)) - 1.0
    xc = (d["qc"] / dry) / 1.0e-5 - 1.0
    out_moist = ((xv >= 0) | (xv <= -0.01)) & ((xc >= 0) | (xc <= -0.01))
    out_moist[:, 0] = out_moist[:, 1]   # WRF's top BN2 copies the level below
    dz = d["zi"][:, :-1] - d["zi"][:, 1:]
    floor, cap = 1e-6 * dz ** 2, 0.1 * dz ** 2 / float(d["dt"])
    rel = np.abs(np.asarray(soft["bn2"]) - np.asarray(hard["bn2"])) / np.max(
        np.abs(np.asarray(hard["bn2"])), axis=1, keepdims=True)
    assert out_moist.mean() > 0.9 and np.all(rel[out_moist] <= 1e-12)
    # unclamped WRF K from the hard form's own deformation and BN2
    c = SmagorinskyConfig()
    d13, d23 = np.asarray(hard["defor13"]), np.asarray(hard["defor23"])
    t13, t23 = 0.5 * (d13[:, 1:] + d13[:, :-1]), 0.5 * (d23[:, 1:] + d23[:, :-1])
    arg = t13 ** 2 + t23 ** 2 - np.asarray(hard["bn2"]) / c.wrf_prandtl
    raw = c.wrf_c_s ** 2 * dz ** 2 * np.sqrt(np.maximum(arg, 0.0))

    def away(x, edge):           # outside [edge/1.5, 1.5 edge]
        return (x < edge / 1.5) | (x > 1.5 * edge)

    km_raw = np.maximum(raw, floor)
    ok_m = out_moist & away(raw, floor) & away(km_raw, cap)
    ok_h = ok_m & away(np.minimum(km_raw, cap) / c.wrf_prandtl, cap)
    assert ok_m.mean() > 0.8 and ok_h.mean() > 0.5
    for row, ok in (("xkmv", ok_m), ("xkhv", ok_h)):
        r = np.abs(np.asarray(soft[row]) - np.asarray(hard[row])) / np.asarray(hard[row])
        assert np.all(r[ok] <= 1e-12), (row, float(r[ok].max()))


def test_smooth_form_gradient():
    """Gradient check where K is NOT floor/cap-bound (short step, the two columns
    with the most unclamped points), so a detached gradient cannot pass."""
    d = _load()
    m = json.loads(str(d["meta"]))
    dt = m["dt_short"]
    dz = d["zi"][:, :-1] - d["zi"][:, 1:]
    ref = d["xkmv_short"]
    free = (ref > 1e-6 * dz ** 2 * (1 + 1e-9)) & (ref < 0.1 * dz ** 2 / dt * (1 - 1e-9))
    cols = np.argsort(free.sum(axis=1))[-2:]
    assert free[cols].sum() >= 4
    cfg = SmagorinskyConfig()
    sel = {k: d[k][cols] for k in ("v", "q", "qc", "qi", "p_full", "p_half", "zi")}

    def f(u, T):
        out = wrf_km3_coefficients(u, sel["v"], T, sel["q"], sel["qc"], sel["qi"],
                                   sel["p_full"], sel["p_half"], sel["zi"], dt, cfg)
        return (out["xkmv"].sum() + out["xkhv"].sum())

    from jax.test_util import check_grads
    args = (jax.numpy.asarray(d["u"][cols]), jax.numpy.asarray(d["T"][cols]))
    gu, gT = jax.grad(f, argnums=(0, 1))(*args)
    assert np.max(np.abs(np.asarray(gu))) > 0.0 and np.max(np.abs(np.asarray(gT))) > 0.0
    check_grads(f, args, order=1, modes=("rev",), atol=1e-6, rtol=1e-4)
