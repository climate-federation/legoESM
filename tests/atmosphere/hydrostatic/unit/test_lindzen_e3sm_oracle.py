from __future__ import annotations

from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest
from jax.test_util import check_grads

from legoesm.atmosphere.physics.gravity_wave_drag.config import LindzenConfig
from legoesm.atmosphere.physics.gravity_wave_drag.lindzen import lindzen_gwd

FIXTURE = Path(__file__).resolve().parents[2] / "oracle_fixtures" / "lindzen_e3sm.npz"
_HARD = 1.0e12   # sharpness at the hard-switch limit
_KEYS = ("u", "v", "T", "p_full", "p_half", "z_full", "z_half", "rho", "lat", "sgh")


def _hard_config():
    return LindzenConfig()._replace(
        Fr_sharpness=_HARD, crit_level_sharpness=_HARD, crit_level_floor=0.0)


def _run(f, cfg, dtype=jnp.float64):
    j = {k: jnp.asarray(f[k], dtype=dtype) for k in _KEYS}
    return lindzen_gwd(
        j["u"], j["v"], j["T"], j["p_full"], j["p_half"], j["z_full"], j["z_half"],
        j["rho"], j["lat"], float(f["dt"]), cfg, h_topo_col=j["sgh"])


def _rel_err(ours, oracle):
    diff = np.abs(np.asarray(ours) - oracle).max(axis=-1)
    scale = np.abs(oracle).max(axis=-1)
    return float(np.where(scale > 0, diff / np.where(scale > 0, scale, 1.0), diff).max())


@pytest.fixture(scope="module")
def fx():
    if not jax.config.jax_enable_x64:
        pytest.skip("oracle match is certified in fp64 (JAX_ENABLE_X64=1)")
    return dict(np.load(FIXTURE))


def test_matches_e3sm_oracle_at_hard_limit(fx):
    out = _run(fx, _hard_config())
    errs = {
        "du_dt": _rel_err(out.du_dt, fx["oracle_utgw"]),
        "dv_dt": _rel_err(out.dv_dt, fx["oracle_vtgw"]),
        "dT_dt": _rel_err(out.dT_dt, fx["oracle_ttgw"]),
    }
    print("max rel err vs E3SM oracle (hard limit):", errs)
    # The oracle must exercise drag, heating, both launch gates and the
    # source hold (src_level = pver means no wave in that column).
    assert np.abs(fx["oracle_utgw"]).max() > 1e-4
    assert np.abs(fx["oracle_ttgw"]).max() > 1e-6
    nlev = fx["u"].shape[1]
    assert (fx["oracle_src_level"] == nlev).sum() >= 3
    assert (fx["oracle_src_level"] < nlev - 1).sum() >= 3
    assert max(errs.values()) <= 1e-10, errs
    # The umcfac limiter binds on the fixture (removing it moves the answer).
    nolim = _run(fx, _hard_config()._replace(umcfac=1.0e9))
    assert _rel_err(nolim.du_dt, fx["oracle_utgw"]) > 1e-2


