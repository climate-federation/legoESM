def _per_column_err(ours, oracle):
    diff = np.abs(np.asarray(ours) - oracle).max(axis=-1)
    scale = np.abs(oracle).max(axis=-1)
    return np.where(scale > 0, diff / np.where(scale > 0, scale, 1.0), diff)


def test_default_smoothing_gap_per_column(fx):
    """Production smoothing departs from the E3SM oracle by the recorded per-column gap."""
    out = _run(fx, LindzenConfig())
    for k, o in (("du_dt", "oracle_utgw"), ("dv_dt", "oracle_vtgw"), ("dT_dt", "oracle_ttgw")):
        got = _per_column_err(getattr(out, k), fx[o])
        want = np.asarray(_DEFAULT_GAP[k])
        np.testing.assert_allclose(got, want, rtol=1e-6, atol=1e-12, err_msg=k)


def test_jit_matches_eager(fx):
    cfg = LindzenConfig()
    eager = _run(fx, cfg)
    jitted = jax.jit(lambda f: _run(dict(f, dt=fx["dt"]), cfg))({k: fx[k] for k in _KEYS})
    for k in ("du_dt", "dv_dt", "dT_dt", "eps_gwd"):
        np.testing.assert_allclose(np.asarray(getattr(jitted, k)),
                                   np.asarray(getattr(eager, k)), rtol=1e-12, atol=1e-20)


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
@pytest.mark.parametrize("hard", [False, True])
def test_gradient_finite_on_oracle_columns(fx, dtype, hard):
    cfg = _hard_config() if hard else LindzenConfig()
    f = {k: jnp.asarray(fx[k], dtype=dtype) for k in _KEYS}

    def loss(u, T, v):
        out = lindzen_gwd(u, v, T, f["p_full"], f["p_half"], f["z_full"], f["z_half"],
                          f["rho"], f["lat"], float(fx["dt"]), cfg, h_topo_col=f["sgh"])
        return jnp.sum(out.du_dt ** 2) + jnp.sum(out.dv_dt ** 2) + jnp.sum(out.dT_dt ** 2)

    gu, gT, gv = jax.grad(loss, argnums=(0, 1, 2))(f["u"], f["T"], f["v"])
    for gr in (gu, gT, gv):
        assert bool(jnp.all(jnp.isfinite(gr)))
    assert float(jnp.abs(gu).max()) > 0.0


# (column, s*) points where the HARD-limit tendency has a derivative jump in
# the wind scale s (u, v of that column times s) that the default smoothing
# removes.  Found 2026-10-28 by scanning s in [0.8, 1.2] (step 5e-4) for
# derivative jumps, then bisecting each jump; at every point check_grads FAILS
# at the hard limit.  Columns 0 and 15: the first taudmp = tausat crossing,
# where the former sigmoid-blend smooth min also failed (non-vacuity of the
# p-norm form); columns 4 and 8: hard-only kinks.
_KINKS = ((0, 0.9206140787969848), (4, 1.0525168220622896),
          (8, 0.984170443965446), (15, 1.1074788765920371))


@pytest.mark.parametrize("col,s_star", _KINKS)
def test_check_grads_through_the_smoothing_at_default(fx, col, s_star):
    """RULE 5 gradient test: finite, non-zero derivative through a switch the
    default smoothing removes (a kink of the hard limit at s*).  eps = 1e-5,
    as in the Vreman/AMD tests; tolerances stay JAX's."""
    cfg = LindzenConfig()
    f1 = {k: jnp.asarray(fx[k][col:col + 1]) for k in _KEYS}

    def f(s):
        out = lindzen_gwd(f1["u"] * s, f1["v"] * s, f1["T"], f1["p_full"], f1["p_half"],
                          f1["z_full"], f1["z_half"], f1["rho"], f1["lat"], float(fx["dt"]),
                          cfg, h_topo_col=f1["sgh"])
        return jnp.sum(out.du_dt) + jnp.sum(out.dv_dt) + jnp.sum(out.dT_dt)

    f = jax.jit(f)
    s0 = jnp.asarray(s_star)
    check_grads(f, (s0,), order=2, modes=("fwd", "rev"), eps=1e-5)
    assert float(jax.grad(f)(s0)) != 0.0
