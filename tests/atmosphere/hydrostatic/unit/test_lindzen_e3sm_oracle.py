"""``lindzen_gwd`` vs the E3SM v3.0.1 orographic-only gravity-wave-drag oracle.

Fixture ``tests/atmosphere/oracle_fixtures/lindzen_e3sm.npz``: 17 CAM6 L32
columns (the ``gw_oro_cam6`` set: 11 constructed soundings incl. launch-gate,
critical-level and limiter columns + 3 real MPAS AMIP T/q/p columns, plus a
calm column, a column where the umcfac limit binds and one with an exactly
zero interface wind) and the outputs of the REAL E3SM Fortran (E3SM-Project/E3SM tag
v3.0.1, SHA d4ca7d0606930f53f30eb7ff7dbb92ec83b83b84: gw_prof + gw_oro_src +
gw_drag_prof with ``orographic_only``, alpha = 1e-6, discrete-KE heating;
effgw_oro = 1, no land-fraction scaling, as the tier-2 audit ran it),
generated by ``bash scripts/validate/oracle/lindzen_e3sm/build.sh <E3SM> <bld>``
then ``python scripts/validate/oracle/lindzen_e3sm/make_fixture.py --drv
<bld>/gw_oro_e3sm --out tests/atmosphere/oracle_fixtures/lindzen_e3sm.npz``
(provenance also in the npz ``meta``).

Acceptance (user decision 2026-10-19): max relative error <= 1e-10 in fp64
with the existing smoothing fields at their hard-switch limit, metric of the
merged tier-1 oracle tests: per column max|ours - oracle| / max|oracle|
(absolute where the oracle column is identically zero).
"""
from __future__ import annotations

from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from legoesm.atmosphere.physics.gravity_wave_drag.config import LindzenConfig
from legoesm.atmosphere.physics.gravity_wave_drag.lindzen import lindzen_gwd

FIXTURE = Path(__file__).resolve().parents[2] / "oracle_fixtures" / "lindzen_e3sm.npz"
_HARD = 1.0e12   # sharpness at the hard-switch limit
_KEYS = ("u", "v", "T", "p_full", "p_half", "z_full", "z_half", "rho", "lat", "sgh")


def _hard_config():
    return LindzenConfig()._replace(
        Fr_sharpness=_HARD, crit_level_sharpness=_HARD, crit_level_floor=0.0)


def _run(f, cfg, dtype=jnp.float64):
    j = {k: jnp.asarray(f[k], dtype=dtype) for k in _KEYS}
    return lindzen_gwd(
        j["u"], j["v"], j["T"], j["p_full"], j["p_half"], j["z_full"], j["z_half"],
        j["rho"], j["lat"], float(f["dt"]), cfg, h_topo_col=j["sgh"])


def _rel_err(ours, oracle):
    diff = np.abs(np.asarray(ours) - oracle).max(axis=-1)
    scale = np.abs(oracle).max(axis=-1)
    return float(np.where(scale > 0, diff / np.where(scale > 0, scale, 1.0), diff).max())


@pytest.fixture(scope="module")
def fx():
    if not jax.config.jax_enable_x64:
        pytest.skip("oracle match is certified in fp64 (JAX_ENABLE_X64=1)")
    return dict(np.load(FIXTURE))


def test_matches_e3sm_oracle_at_hard_limit(fx):
    out = _run(fx, _hard_config())
    errs = {
        "du_dt": _rel_err(out.du_dt, fx["oracle_utgw"]),
        "dv_dt": _rel_err(out.dv_dt, fx["oracle_vtgw"]),
        "dT_dt": _rel_err(out.dT_dt, fx["oracle_ttgw"]),
    }
    print("max rel err vs E3SM oracle (hard limit):", errs)
    # The oracle must exercise drag, heating, both launch gates and the
    # source hold (src_level = pver means no wave in that column).
    assert np.abs(fx["oracle_utgw"]).max() > 1e-4
    assert np.abs(fx["oracle_ttgw"]).max() > 1e-6
    nlev = fx["u"].shape[1]
    assert (fx["oracle_src_level"] == nlev).sum() >= 3
    assert (fx["oracle_src_level"] < nlev - 1).sum() >= 3
    assert max(errs.values()) <= 1e-10, errs
    # The umcfac limiter binds on the fixture (removing it moves the answer).
    nolim = _run(fx, _hard_config()._replace(umcfac=1.0e9))
    assert _rel_err(nolim.du_dt, fx["oracle_utgw"]) > 1e-2


def test_default_smoothing_gap_reported(fx):
    """Production smoothing departs from the hard limit (reported, not asserted)."""
    out = _run(fx, LindzenConfig())
    gap = {k: _rel_err(getattr(out, k), fx[o]) for k, o in
           (("du_dt", "oracle_utgw"), ("dv_dt", "oracle_vtgw"), ("dT_dt", "oracle_ttgw"))}
    glob = {k: float(np.abs(np.asarray(getattr(out, k)) - fx[o]).max() / np.abs(fx[o]).max())
            for k, o in (("du_dt", "oracle_utgw"), ("dT_dt", "oracle_ttgw"))}
    print("default smoothing vs oracle: per-column", gap, "global", glob)
    assert all(np.isfinite(v) for v in gap.values())


def test_jit_matches_eager(fx):
    cfg = LindzenConfig()
    eager = _run(fx, cfg)
    jitted = jax.jit(lambda f: _run(dict(f, dt=fx["dt"]), cfg))({k: fx[k] for k in _KEYS})
    for k in ("du_dt", "dv_dt", "dT_dt", "eps_gwd"):
        np.testing.assert_allclose(np.asarray(getattr(jitted, k)),
                                   np.asarray(getattr(eager, k)), rtol=1e-12, atol=1e-20)


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
@pytest.mark.parametrize("hard", [False, True])
def test_gradient_finite_on_oracle_columns(fx, dtype, hard):
    cfg = _hard_config() if hard else LindzenConfig()
    f = {k: jnp.asarray(fx[k], dtype=dtype) for k in _KEYS}

    def loss(u, T, v):
        out = lindzen_gwd(u, v, T, f["p_full"], f["p_half"], f["z_full"], f["z_half"],
                          f["rho"], f["lat"], float(fx["dt"]), cfg, h_topo_col=f["sgh"])
        return jnp.sum(out.du_dt ** 2) + jnp.sum(out.dv_dt ** 2) + jnp.sum(out.dT_dt ** 2)

    gu, gT, gv = jax.grad(loss, argnums=(0, 1, 2))(f["u"], f["T"], f["v"])
    for gr in (gu, gT, gv):
        assert bool(jnp.all(jnp.isfinite(gr)))
    assert float(jnp.abs(gu).max()) > 0.0
