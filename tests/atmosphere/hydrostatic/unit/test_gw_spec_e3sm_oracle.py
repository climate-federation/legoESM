"""``e3sm_cam_gwd`` spectral sources vs the E3SM v3.0.1 gravity-wave oracle.

Fixture ``tests/atmosphere/oracle_fixtures/gw_spec_e3sm.npz``: 8 constructed
soundings on the L36 deck grid + 3 real MPAS AMIP T/q/p columns on CAM6 L32,
and the outputs of the REAL E3SM Fortran (E3SM-Project/E3SM tag v3.0.1, SHA
d4ca7d0606930f53f30eb7ff7dbb92ec83b83b84: gw_prof, gw_cm_src, gw_beres_src,
gw_oro_src, gw_drag_prof + gw_ediff, the C.-C. Chen fixer, and the
gw_drag.F90 orographic closure), run at E3SM's own gw_init settings (alpha
profile and level indices from pref_edge, kwv 6.28e-5), generated by
``bash scripts/validate/oracle/gw_spec_e3sm/build.sh <E3SM> <bld>`` then
``python scripts/validate/oracle/gw_spec_e3sm/make_fixture.py --drv
<bld>/gw_spec_oracle --out tests/atmosphere/oracle_fixtures/gw_spec_e3sm.npz``
(provenance in the npz ``meta``).  Arms: the L36 deck background source (at
dt 112.5 s and 1800 s), frontal with cos(lat) taper, Beres+frontal, and
Beres+frontal+orographic (E3SM's orographic member of a spectral suite).
The Beres table is a seeded harness table, regenerated here.

Acceptance (user decision 2026-10-19): max relative error <= 1e-10 in fp64.
The scheme has no smoothing fields, so the hard limit is the default config.
Metric reused unchanged from test_gw_oro_cam6_oracle.py: wind tendencies per
column max|ours - oracle| / max|oracle| (absolute where the oracle column is
zero); heating as the field max-norm, because the implicit dse diffusion
``(s_new - s)/dt`` (s ~ 3e5 J/kg) has a round-off floor ~eps*s/dt in the
oracle itself.

KNOWN GAP (asked, not fixed): E3SM diffuses dse = c_p*T + g*z + phis; the
kernel has no phis input and diffuses c_p*T + g*z.  The constant cancels
exactly in exact arithmetic, but in the one column with surface height
(midlat_front, phis = g*1500 m) the last ulp of s_new differs: 1.03e-12 W/kg
= 2 ulp(dse)/dt at dt = 112.5 s, i.e. 4.5e-9 field-relative.  That column's
heating is asserted against the same oracle fed dse without phis
(``ptend_s_nophis``), and against the true oracle as a strict xfail;
momentum is asserted on every column.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from legoesm import constants
from legoesm.atmosphere.physics.gravity_wave_drag.config import (
    E3SMBeresConfig,
    E3SMCAMConfig,
    E3SMFrontalConfig,
)
from legoesm.atmosphere.physics.gravity_wave_drag.e3sm_cam import e3sm_cam_gwd

FIXTURE = Path(__file__).resolve().parents[2] / "oracle_fixtures" / "gw_spec_e3sm.npz"
_TOL = 1.0e-10


def _rel_err(ours, oracle):
    diff = np.abs(np.asarray(ours) - oracle).max(axis=-1)
    scale = np.abs(oracle).max(axis=-1)
    return float(np.where(scale > 0, diff / np.where(scale > 0, scale, 1.0), diff).max())


def _rel_err_field(ours, oracle):
    return float(np.abs(np.asarray(ours) - oracle).max() / np.abs(oracle).max())


@pytest.fixture(scope="module")
def fx():
    if not jax.config.jax_enable_x64:
        pytest.skip("oracle match is certified in fp64 (JAX_ENABLE_X64=1)")
    z = dict(np.load(FIXTURE))
    meta = json.loads(str(z.pop("meta")))
    m = meta["mfcc"]
    t = np.random.default_rng(m["seed"]).uniform(
        0.0, m["hi"], size=(m["maxh"], 2 * m["maxuh"] + 1, 2 * m["pgwv"] + 1))
    t[:, :, m["pgwv"]] = 0.0
    assert hashlib.sha256(t.tobytes()).hexdigest() == m["sha256"]
    return z, meta, t


def _config(ours):
    o = dict(ours)
    fr = E3SMFrontalConfig()._replace(**o.pop("frontal", {}))
    br = E3SMBeresConfig()._replace(**o.pop("beres", {}))
    return E3SMCAMConfig()._replace(frontal=fr, beres=br, **o)


def _inputs(z, ds, dtype=jnp.float64):
    return {k: jnp.asarray(z[f"{ds}/{k}"], dtype) for k in (
        "u", "v", "T", "p_full", "p_half", "z_full", "z_half", "rho", "lat",
        "sgh", "frontgf", "netdt", "lf", "pref_edge")}


def _run(j, cfg, dt, mfcc):
    return e3sm_cam_gwd(
        j["u"], j["v"], j["T"], j["p_full"], j["p_half"], j["z_full"], j["z_half"],
        j["rho"], jnp.deg2rad(j["lat"]), dt, cfg, h_topo_col=j["sgh"],
        frontgf_col=j["frontgf"], netdt_col=j["netdt"],
        mfcc_table=None if mfcc is None else jnp.asarray(mfcc, j["u"].dtype),
        land_frac_col=j["lf"], p_ref_half=j["pref_edge"])


def _cases():
    meta = json.loads(str(np.load(FIXTURE)["meta"]))
    return [(a, ds) for a, m in meta["arms"].items() for ds in m["datasets"]]


def test_fixture_matches_the_shipped_defaults(fx):
    """The oracle ran with the kwv and constants the code ships."""
    _, meta, _ = fx
    assert E3SMCAMConfig().kwv == meta["kwv"]
    assert meta["constants"] == dict(g=constants.g, R_d=constants.R_d, c_pd=constants.c_pd)


def _arm(fx, arm, ds):
    z, meta, table = fx
    m = meta["arms"][arm]
    out = _run(_inputs(z, ds), _config(m["ours"]), m["dt"], table if m["mfcc"] else None)
    ref = {k: z[f"{arm}/{ds}/ptend_{k}"] for k in "uvs"}
    ref["s0"] = z.get(f"{arm}/{ds}/ptend_s_nophis", ref["s"])
    return out, ref, z[f"{ds}/phis"] == 0.0


@pytest.mark.parametrize("arm,ds", _cases())
def test_matches_e3sm_oracle(fx, arm, ds):
    out, ref, flat = _arm(fx, arm, ds)
    ds_ours = np.asarray(out.dT_dt) * constants.c_pd
    errs = {"du_dt": _rel_err(out.du_dt, ref["u"]), "dv_dt": _rel_err(out.dv_dt, ref["v"]),
            "dT_dt": _rel_err_field(ds_ours[flat], ref["s"][flat]),
            "dT_dt_elevated_vs_nophis": _rel_err_field(ds_ours[~flat], ref["s0"][~flat])
            if np.any(~flat) else 0.0}
    print(arm, ds, "max rel err vs E3SM v3.0.1:", errs)
    assert np.abs(ref["u"]).max() > 1e-6 and np.abs(ref["s"][flat]).max() > 1e-4
    assert max(errs.values()) <= _TOL, errs


@pytest.mark.xfail(strict=True, reason="kernel dse omits phis (asked): 2 ulp(dse)/dt")
@pytest.mark.parametrize("arm", [a for a, ds in _cases() if ds == "l36"])
def test_heating_matches_e3sm_oracle_with_surface_height(fx, arm):
    out, ref, flat = _arm(fx, arm, "l36")
    ds_ours = np.asarray(out.dT_dt) * constants.c_pd
    err = _rel_err_field(ds_ours[~flat], ref["s"][~flat])
    print(arm, "phis column dT field-relative error:", err)
    assert err <= _TOL


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_gradient_finite_on_oracle_columns(fx, dtype):
    z, meta, table = fx
    m = meta["arms"]["oro_frontal_convective"]
    cfg = _config(m["ours"])
    for ds in m["datasets"]:
        j = _inputs(z, ds, dtype)

        def loss(u, T, j=j):
            out = _run(dict(j, u=u, T=T), cfg, m["dt"], table)
            return jnp.sum(out.du_dt ** 2) + jnp.sum(out.dT_dt ** 2)

        gu, gT = jax.grad(loss, argnums=(0, 1))(j["u"], j["T"])
        assert bool(jnp.all(jnp.isfinite(gu))) and bool(jnp.all(jnp.isfinite(gT)))
        assert float(jnp.abs(gu).max()) > 0.0


def test_jit_matches_eager(fx):
    z, meta, table = fx
    m = meta["arms"]["oro_frontal_convective"]
    cfg = _config(m["ours"])
    j = _inputs(z, "l36")
    eager = _run(j, cfg, m["dt"], table)
    jitted = jax.jit(lambda jj: _run(jj, cfg, m["dt"], table))(j)
    # same metric and bound as the oracle match
    for a, b in zip(eager[:3], jitted[:3]):
        assert _rel_err(np.asarray(b), np.asarray(a)) <= _TOL


def test_spectral_source_without_reference_interfaces_raises(fx):
    z, meta, _ = fx
    j = _inputs(z, "l36")
    with pytest.raises(ValueError, match="p_ref_half"):
        e3sm_cam_gwd(j["u"], j["v"], j["T"], j["p_full"], j["p_half"], j["z_full"],
                     j["z_half"], j["rho"], jnp.deg2rad(j["lat"]), 112.5,
                     _config(meta["arms"]["background"]["ours"]))
