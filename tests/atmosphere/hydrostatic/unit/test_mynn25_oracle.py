"""WRF MYNN-EDMF level 2.5 vs the RUNNING oracle (WRF v4.8.0 mynnedmf).

Fixture ``tests/atmosphere/oracle_fixtures/mynn25.npz`` was generated by RUNNING
WRF v4.8.0 (06d4240ae989cc3e50af412bb472df3d9048783c; MYNN-EDMF submodule
8f8e8b59021249949c04d1686edc5a02ca325627) ``phys/MYNN-EDMF/module_bl_mynnedmf.F90``
compiled unmodified (gfortran 8.5.0, fp64 -fdefault-real-8, -finit-integer=-999
as the MYNN-EDMF CI Makefile) with
``scripts/validate/oracle/mynn25/{build.sh,mynn_driver.F90,make_fixture.py}``:
level-2.5 closure, WRF namelist defaults for every other option.  Two column
groups (``l32``: tier-2 audit set + 4 variants, dt 1200 s; ``l65``: the
MYNN-EDMF CI cases, dt 18 s), three steps each (step 1 cold start); steps 1
and 3 are stored, plus the oracle's per-subroutine intermediates at step 3
(a second build with dump calls, asserted bitwise equal to the unmodified one).

Metric (the tier-1 audit metric): per field, ``max|ours - oracle| /
max(max|oracle|, 1e-300)`` over the group.  Bound 1e-10 in fp64 (user decision
2026-10-19).  The oracle has no smoothing on this path, so there is no
sharpness field to set.
"""

from __future__ import annotations

import ast
from pathlib import Path

import numpy as np
import pytest

import jax
import jax.numpy as jnp

from legoesm import constants
from legoesm.atmosphere.physics.turbulence.mynnedmf_wrf import mynnedmf_column

jax.config.update("jax_enable_x64", True)

TOL = 1.0e-10
FIXTURE = Path(__file__).resolve().parents[2] / "oracle_fixtures" / "mynn25.npz"
LEVEL = "dz u v w th tk p exner rho sqv sqc sqi qke qsq el".split()
SURF = "xland ps ts ust hfx qfx wspd dt dx".split()
GROUPS = ("l32", "l65")


@pytest.fixture(scope="module")
def fx():
    return dict(np.load(FIXTURE))


def _err(ours, ref):
    ref = np.asarray(ref, np.float64)
    ours = np.asarray(ours, np.float64).reshape(ref.shape)
    assert np.all(np.isfinite(ours)) and np.all(np.isfinite(ref))
    return float(np.max(np.abs(ours - ref)) / max(np.max(np.abs(ref)), 1e-300))


def _args(fx, g, s, dtype=jnp.float64):
    p = f"{g}_s{s}_in_"
    return ([jnp.asarray(fx[p + k], dtype) for k in LEVEL]
            + [jnp.asarray(fx[p + k][:, 0], dtype) for k in SURF])


_JIT = jax.jit(mynnedmf_column, static_argnames=("initflag", "return_intermediates"))


def _run(fx, g, s, dtype=jnp.float64, inter=False, jit=True):
    f = _JIT if jit else mynnedmf_column
    return f(*_args(fx, g, s, dtype), initflag=(s == 1), return_intermediates=inter)


@pytest.fixture(scope="module")
def runs(fx):
    return {(g, s): _run(fx, g, s, inter=True) for g in GROUPS for s in (1, 3)}


def test_fixture_provenance(fx):
    meta = ast.literal_eval(str(fx["meta"]))
    assert meta["sha"] == "06d4240ae989cc3e50af412bb472df3d9048783c"
    assert meta["mynn_edmf_sha"] == "8f8e8b59021249949c04d1686edc5a02ca325627"
    assert FIXTURE.stat().st_size < 1_000_000


@pytest.mark.parametrize("g", GROUPS)
@pytest.mark.parametrize("s", (1, 3))
def test_outputs_match_oracle(fx, runs, g, s):
    out, _ = runs[(g, s)]
    worst = {k: _err(getattr(out, k), fx[f"{g}_s{s}_out_{k}"]) for k in out._fields}
    print(g, s, "worst", max(worst.items(), key=lambda t: t[1]))
    assert max(worst.values()) <= TOL, {k: v for k, v in worst.items() if v > TOL}


@pytest.mark.parametrize("g", GROUPS)
def test_intermediates_match_oracle(fx, runs, g):
    """Per subroutine (PBL height, scale awareness, condensation, mass flux,
    length scale, stability functions, qke prediction, tendencies) at step 3."""
    _, inter = runs[(g, 3)]
    keys = [k for k in fx if k.startswith(f"{g}_s3_dump_")]
    assert len(keys) > 40
    worst = {}
    for key in keys:
        ref = fx[key]
        ours = np.asarray(inter[key[len(f"{g}_s3_dump_"):]])
        if ours.size != ref.size:      # interface arrays carry one extra level
            ours = ours[:, :ref.shape[1]]
        if key.endswith("_dump_sgm"):  # the oracle never assigns sgm(kte)
            ours, ref = ours[:, :-1], ref[:, :-1]
        worst[key] = _err(ours, ref)
    assert max(worst.values()) <= TOL, {k: v for k, v in worst.items() if v > TOL}


def test_fixture_exercises_branches(fx):
    """Mass flux on (with a moist plume) and off, clouds, ice, land and water."""
    for g in GROUPS:
        o = f"{g}_s3_out_"
        assert np.any(fx[o + "maxmf"] != 0) and np.any(fx[o + "maxmf"] == 0)
        assert np.any(fx[o + "cldfra_bl"] > 0)
        assert set(np.unique(fx[f"{g}_s3_in_xland"])) == {1.0, 2.0}
    assert np.any(fx["l32_s3_out_edmf_qc"] > 0)
    assert np.any(fx["l32_s3_out_qi_bl"] > 0)


@pytest.mark.parametrize("g", GROUPS)
def test_column_budgets_close_as_the_oracle(fx, runs, g):
    """Column-integrated water and heat tendencies equal the oracle's, so the
    budgets against the (identical) surface fluxes close exactly as the
    oracle's do.  Water: sum rho*dz*(dqv+dqc+dqi) vs qfx."""
    out, _ = runs[(g, 3)]
    p = f"{g}_s3_"
    w = fx[p + "in_rho"] * fx[p + "in_dz"]
    water = lambda dqv, dqc, dqi: np.sum(w * (dqv + dqc + dqi), axis=1)
    ref_w = water(fx[p + "out_dqv"], fx[p + "out_dqc"], fx[p + "out_dqi"])
    assert _err(water(out.dqv, out.dqc, out.dqi), ref_w) <= TOL
    heat_ref = np.sum(w * fx[p + "out_dth"] * fx[p + "in_exner"], axis=1) * constants.c_pd
    heat = np.sum(w * np.asarray(out.dth) * fx[p + "in_exner"], axis=1) * constants.c_pd
    assert _err(heat, heat_ref) <= TOL
    print(g, "oracle water residual vs qfx [kg/m2/s]:",
          float(np.max(np.abs(ref_w - fx[p + "in_qfx"][:, 0]))))


def test_eager_jit_parity(fx):
    eager = _run(fx, "l32", 3, jit=False)
    jitted = _run(fx, "l32", 3)
    for k in eager._fields:
        assert _err(getattr(jitted, k), getattr(eager, k)) <= TOL, k


def test_fp32_runs_finite(fx):
    for g in GROUPS:
        out = _run(fx, g, 3, dtype=jnp.float32)
        for k in out._fields:
            assert np.all(np.isfinite(np.asarray(getattr(out, k)))), (g, k)


def _loss(xs, init):
    o = mynnedmf_column(*xs, initflag=init)
    return (jnp.sum(o.dth) + 1e3 * jnp.sum(o.dqv) + jnp.sum(o.du)
            + jnp.sum(o.qke) + jnp.sum(o.cldfra_bl))


@pytest.mark.parametrize("dtype", (jnp.float64, jnp.float32))
@pytest.mark.parametrize("g", GROUPS)
@pytest.mark.parametrize("s", (1, 3))
def test_grad_finite(fx, dtype, g, s):
    grads = jax.jit(jax.grad(_loss), static_argnums=1)(_args(fx, g, s, dtype), s == 1)
    bad = [k for k, v in zip(LEVEL + SURF, grads) if not np.all(np.isfinite(np.asarray(v)))]
    assert not bad, bad



def test_grad_finite_calm_wind_and_zero_qke(fx):
    """Reviewer inputs: lowest-level wind exactly 0 (column 0) and carried
    qke = 0 (column 1); the forward value is the oracle's either way."""
    xs = _args(fx, "l32", 3)
    names = LEVEL + SURF
    for k in ("u", "v"):
        xs[names.index(k)] = xs[names.index(k)].at[0, 0].set(0.0)
    xs[names.index("qke")] = xs[names.index("qke")].at[1].set(0.0)
    grads = jax.jit(jax.grad(_loss), static_argnums=1)(xs, False)
    bad = [k for k, v in zip(names, grads) if not np.all(np.isfinite(np.asarray(v)))]
    assert not bad, bad
