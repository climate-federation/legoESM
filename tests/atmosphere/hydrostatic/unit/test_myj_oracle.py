def _args(fx, s, dtype=jnp.float64):
    p = f"s{s}_in_"
    lev = {k: jnp.asarray(fx[p + k], dtype) for k in LEVEL}
    sfc = {k: jnp.asarray(fx[p + k][:, 0], dtype) for k in SURF}
    sfc["ustar"] = sfc.pop("ust")
    return dict(dt=jnp.asarray(fx[p + "dt"][:, 0], dtype),
                ht=jnp.asarray(fx[p + "ht"][:, 0], dtype), **lev, **sfc)


def _run(fx, s, cfg=ORACLE_HARD, dtype=jnp.float64, jit=True):
    f = jax.vmap(lambda kw: myjpbl_column(**kw, cfg=cfg))
    return (jax.jit(f) if jit else f)(_args(fx, s, dtype))


def _err(ours, ref):
    ref = np.asarray(ref, np.float64)
    ours = np.asarray(ours, np.float64).reshape(ref.shape)
    assert np.all(np.isfinite(ours)) and np.all(np.isfinite(ref))
    return float(np.max(np.abs(ours - ref)) / max(np.max(np.abs(ref)), 1e-300))


def test_fixture_provenance(fx):
    meta = ast.literal_eval(str(fx["meta"]))
    assert meta["sha"] == "06d4240ae989cc3e50af412bb472df3d9048783c"
    assert meta["source_sha256"] == (
        "ee6acc5e65b57a74a5f620d872000f46c321ddc9331d6773d88053f9144bc1cb")
    assert len(fx["names"]) == 25
    assert FIXTURE.stat().st_size < 1_000_000


@pytest.mark.parametrize("s", (1, 3))
def test_matches_oracle(fx, s):
    out = _run(fx, s)._asdict()
    errs = {k: _err(out[k], fx[f"s{s}_out_{v}"]) for k, v in FIELDS.items()}
    L = fx[f"s{s}_in_dz"].shape[1]
    errs["exch_h"] = _err(out["exch_h"], fx[f"s{s}_out_exch_h"][:, :L - 1])
    bad = {k: e for k, e in errs.items() if e > TOL_FIELD.get(k, TOL)}
    assert not bad, bad


def test_branches_reached(fx):
    """The variants reach what the audit columns do not (non-vacuity)."""
    names = list(fx["names"])
    i = names.index("desert_high_lcl_ct")
    assert fx["s1_in_ct"][i, 0] == 0.5 and fx["s1_out_ct"][i, 0] == 0.0
    no_ct = dict(fx)
    no_ct["s1_in_ct"] = np.where(np.arange(len(names))[:, None] == i, 0.0, fx["s1_in_ct"])
    assert _err(_run(no_ct, 1).rthblten, fx["s1_out_rthblten"]) > 1.0e3 * TOL
    j = names.index("trop_ocean_deep_uz0")
    assert fx["s1_in_uz0"][j, 0] == 1.0 and fx["s1_in_vz0"][j, 0] == -0.5
    no_uz0 = dict(fx)
    for k in ("s1_in_uz0", "s1_in_vz0"):
        no_uz0[k] = np.where(np.arange(len(names))[:, None] == j, 0.0, fx[k])
    out = _run(no_uz0, 1)
    assert _err(out.rublten, fx["s1_out_rublten"]) > 1.0e3 * TOL
    assert _err(out.rvblten, fx["s1_out_rvblten"]) > 1.0e3 * TOL
    assert np.any(fx["s1_in_qci"] > 0) and np.any(fx["s1_in_qcw"] > 0)
    assert np.any(np.abs(fx["s3_out_rqiblten"]) > 0)
    assert np.any(fx["s1_in_snow"] > 0)


def test_jit_matches_eager(fx):
    a = _run(fx, 3)
    b = _run(fx, 3, jit=False)
    errs = {k: _err(x, y) for k, x, y in zip(a._fields, a, b)}
    assert max(errs.values()) <= TOL, errs


def test_bitwise_without_fma():
    """Same comparison with XLA's FMA contraction off: <= 1e-15 everywhere."""
    code = (
        "import sys; sys.path.insert(0, %r)\n"
        "import numpy as np, test_myj_oracle as t\n"
        "fx = dict(np.load(t.FIXTURE)); worst = 0.0\n"
        "for s in (1, 3):\n"
        "    o = t._run(fx, s)._asdict(); L = fx[f's{s}_in_dz'].shape[1]\n"
        "    for k, v in t.FIELDS.items(): worst = max(worst, t._err(o[k], fx[f's{s}_out_{v}']))\n"
        "    worst = max(worst, t._err(o['exch_h'], fx[f's{s}_out_exch_h'][:, :L - 1]))\n"
        "print('WORST', worst)\n" % str(Path(__file__).parent))
    env = dict(os.environ, XLA_FLAGS="--xla_cpu_max_isa=AVX", JAX_PLATFORMS="cpu",
               JAX_ENABLE_X64="1")
