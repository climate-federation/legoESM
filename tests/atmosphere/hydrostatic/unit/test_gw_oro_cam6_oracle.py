"""``mcfarlane_gwd`` vs the CAM6 orographic gravity-wave-drag oracle.

Fixture ``tests/atmosphere/oracle_fixtures/gw_oro_cam6.npz``: 14 CAM6 L32
columns (11 constructed soundings incl. umcfac- and tndmax-binding limiter
columns + 3 real MPAS AMIP T/q/p columns) and the
outputs of the REAL CAM Fortran (ESCOMP/CAM tag cam_cesm2_1_rel_60, SHA
a03b84b7c4e34f965b115686f22a043b85739e56: gw_prof + gw_oro_src + gw_drag_prof
with gw eddy diffusion, alpha from CAM lininterp), generated by
``bash scripts/validate/oracle/gw_oro_cam6/build.sh <CAM> <bld>`` then
``python scripts/validate/oracle/gw_oro_cam6/make_fixture.py --drv
<bld>/gw_oro_oracle --out tests/atmosphere/oracle_fixtures/gw_oro_cam6.npz``
(provenance also in the npz ``meta``).

Acceptance (user decision 2026-10-19): max relative error <= 1e-10 in fp64
with the existing smoothing fields at their hard-switch limit.  Momentum
tendencies use the tier-1 audit metric, per column max|ours - oracle| /
max|oracle| (absolute where the oracle column is identically zero).  The
heating and tracer tendencies contain the implicit eddy diffusion
``(q_new - q)/dt`` of dse (~3e5 J/kg) and q, whose round-off floor is
~eps*|q|/dt in the ORACLE itself; in columns where that diffusion is weak the
per-column ratio measures that floor (2.2e-9 dT in the Antarctic column,
3.4e-10 dq: absolute 6e-17 K/s and 5e-22 1/s, a few ulp of dse and q), so
those two use the field max-norm, max|ours - oracle| / max|oracle| over the
fixture (metric choice pending user confirmation; both printed).
"""
from __future__ import annotations

from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest
