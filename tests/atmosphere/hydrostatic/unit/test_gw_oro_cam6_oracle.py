"""``mcfarlane_gwd`` vs the CAM6 orographic gravity-wave-drag oracle.

Fixture ``tests/atmosphere/oracle_fixtures/gw_oro_cam6.npz``: 14 CAM6 L32
columns (11 constructed soundings incl. umcfac- and tndmax-binding limiter
columns + 3 real MPAS AMIP T/q/p columns) and the
outputs of the REAL CAM Fortran (ESCOMP/CAM tag cam_cesm2_1_rel_60, SHA
a03b84b7c4e34f965b115686f22a043b85739e56: gw_prof + gw_oro_src + gw_drag_prof
with gw eddy diffusion, alpha from CAM lininterp), generated by
``bash scripts/validate/oracle/gw_oro_cam6/build.sh <CAM> <bld>`` then
``python scripts/validate/oracle/gw_oro_cam6/make_fixture.py --drv
<bld>/gw_oro_oracle --out tests/atmosphere/oracle_fixtures/gw_oro_cam6.npz``
(provenance also in the npz ``meta``).

Acceptance (user decision 2026-10-19): max relative error <= 1e-10 in fp64
with the existing smoothing fields at their hard-switch limit.  Momentum
tendencies use the tier-1 audit metric, per column max|ours - oracle| /
max|oracle| (absolute where the oracle column is identically zero).  The
heating and tracer tendencies contain the implicit eddy diffusion
``(q_new - q)/dt`` of dse (~3e5 J/kg) and q, whose round-off floor is
~eps*|q|/dt in the ORACLE itself; in columns where that diffusion is weak the
per-column ratio measures that floor (2.2e-9 dT in the Antarctic column,
3.4e-10 dq: absolute 6e-17 K/s and 5e-22 1/s, a few ulp of dse and q), so
those two use the field max-norm, max|ours - oracle| / max|oracle| over the
fixture (metric choice pending user confirmation; both printed).
"""
from __future__ import annotations

from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from legoesm.atmosphere.physics.gravity_wave_drag.config import McFarlaneConfig
from legoesm.atmosphere.physics.gravity_wave_drag.mcfarlane import mcfarlane_gwd

FIXTURE = Path(__file__).resolve().parents[2] / "oracle_fixtures" / "gw_oro_cam6.npz"
_HARD = 1.0e12   # sharpness at the hard-switch limit


def _hard_config():
    return McFarlaneConfig()._replace(
        min_wind_sharpness=_HARD, softmin_sharpness=_HARD,
        crit_level_sharpness=_HARD, crit_level_floor=0.0)


def _run(f, cfg):
    j = {k: jnp.asarray(f[k]) for k in ("u", "v", "T", "p_full", "p_half", "z_full",
                                        "z_half", "rho", "lat", "sgh", "lf", "q",
                                        "p_ref_half")}
    return mcfarlane_gwd(
        j["u"], j["v"], j["T"], j["p_full"], j["p_half"], j["z_full"], j["z_half"],
        j["rho"], j["lat"], float(f["dt"]), cfg, h_topo_col=j["sgh"],
        p_ref_half=j["p_ref_half"], land_frac_col=j["lf"], tracers={"q_v": j["q"]})


def _rel_err(ours, oracle):
    diff = np.abs(np.asarray(ours) - oracle).max(axis=-1)
    scale = np.abs(oracle).max(axis=-1)
    return float(np.where(scale > 0, diff / np.where(scale > 0, scale, 1.0), diff).max())


def _rel_err_field(ours, oracle):
    return float(np.abs(np.asarray(ours) - oracle).max() / np.abs(oracle).max())


@pytest.fixture(scope="module")
def fx():
    if not jax.config.jax_enable_x64:
        pytest.skip("oracle match is certified in fp64 (JAX_ENABLE_X64=1)")
    return dict(np.load(FIXTURE))


def test_matches_cam6_oracle_at_hard_limit(fx):
    out = _run(fx, _hard_config())
    errs = {
        "du_dt": _rel_err(out.du_dt, fx["oracle_utgw"]),
        "dv_dt": _rel_err(out.dv_dt, fx["oracle_vtgw"]),
        "dT_dt": _rel_err_field(out.dT_dt, fx["oracle_ttgw"]),
        "dq_v_dt": _rel_err_field(out.dq_dt["q_v"], fx["oracle_qtgw1"]),
    }
    print("max rel err vs CAM6 oracle (hard limit):", errs)
    print("per-column dT_dt / dq_v_dt (round-off floor, not asserted):",
          _rel_err(out.dT_dt, fx["oracle_ttgw"]),
          _rel_err(out.dq_dt["q_v"], fx["oracle_qtgw1"]))
    # The oracle must exercise every piece: drag, diffusion heating, tracer.
    assert np.abs(fx["oracle_utgw"]).max() > 1e-4
    assert np.abs(fx["oracle_dttdf"]).max() > 1e-5
    assert np.abs(fx["oracle_qtgw1"]).max() > 1e-9
    assert max(errs.values()) <= 1e-10, errs


def test_gradient_finite_on_oracle_columns(fx):
    f = {k: jnp.asarray(v) for k, v in fx.items() if k != "meta" and k != "names"}

    def loss(u, T, v=f["v"]):
        out = mcfarlane_gwd(
            u, v, T, f["p_full"], f["p_half"], f["z_full"], f["z_half"],
            f["rho"], f["lat"], float(fx["dt"]), McFarlaneConfig(),
            h_topo_col=f["sgh"], p_ref_half=f["p_ref_half"],
            land_frac_col=f["lf"], tracers={"q_v": f["q"]})
        return (jnp.sum(out.du_dt ** 2) + jnp.sum(out.dT_dt ** 2)
                + jnp.sum(out.dq_dt["q_v"] ** 2))

    gu, gT = jax.grad(loss, argnums=(0, 1))(f["u"], f["T"])
    assert bool(jnp.all(jnp.isfinite(gu))) and bool(jnp.all(jnp.isfinite(gT)))
    assert float(jnp.abs(gu).max()) > 0.0
    # Calm columns: CAM's zero unit vector must not poison the cotangent.
    gu0, gT0 = jax.grad(loss, argnums=(0, 1))(0.0 * f["u"], f["T"], 0.0 * f["v"])
    assert bool(jnp.all(jnp.isfinite(gu0))) and bool(jnp.all(jnp.isfinite(gT0)))


def _run_stress(f, cfg):
    j = {k: jnp.asarray(f[k]) for k in ("u", "v", "T", "p_full", "p_half", "z_full",
                                        "z_half", "rho", "lat", "sgh", "lf", "q",
                                        "p_ref_half")}
    return mcfarlane_gwd(
        j["u"], j["v"], j["T"], j["p_full"], j["p_half"], j["z_full"], j["z_half"],
        j["rho"], j["lat"], float(f["dt"]), cfg, h_topo_col=j["sgh"],
        p_ref_half=j["p_ref_half"], land_frac_col=j["lf"], tracers={"q_v": j["q"]},
        return_stress=True)


def test_stress_profile_matches_cam6_oracle_at_hard_limit(fx):
    """The optional interface stress (#1712) is CAM's ``tau`` after effgw,
    same per-column metric and 1e-10 bound as the momentum tendencies."""
    _, tau = _run_stress(fx, _hard_config())
    assert tau.shape == fx["oracle_tau"].shape
    assert np.abs(fx["oracle_tau"][:, -1]).max() > 1e-3   # launch exercised
    err = _rel_err(tau, fx["oracle_tau"])
    print("tau max rel err vs CAM6 oracle (hard limit):", err)
    assert err <= 1e-10, err


@pytest.mark.parametrize("hard", [False, True])
def test_return_stress_leaves_tendencies_bit_identical(fx, hard):
    """Turning the stress output on changes no tendency, bit for bit."""
    cfg = _hard_config() if hard else McFarlaneConfig()
    base = _run(fx, cfg)
    out, _ = _run_stress(fx, cfg)
    for f in ("du_dt", "dv_dt", "dT_dt", "eps_gwd"):
        assert np.array_equal(np.asarray(getattr(base, f)),
                              np.asarray(getattr(out, f))), f
    assert np.array_equal(np.asarray(base.dq_dt["q_v"]),
                          np.asarray(out.dq_dt["q_v"]))


def test_effgw_oro_default_is_cam6_namelist_value():
    """#1712: the knob's default is CAM6's effgw_oro, the constant it replaced."""
    assert McFarlaneConfig().effgw_oro == 0.125


def test_effgw_oro_is_read(fx):
    """#1712: the field reaches the kernel.  The default equals an explicit
    0.125 bit-for-bit, and doubling it changes the drag (with the limiters
    binding in some fixture columns the response is not exactly linear, so
    only "changed" is asserted here).  Bit-identity with the pre-#1712
    constant was measured across commits (PR body); this test cannot see
    the old code."""
    base = _run(fx, McFarlaneConfig())
    same = _run(fx, McFarlaneConfig()._replace(effgw_oro=0.125))
    dbl = _run(fx, McFarlaneConfig()._replace(effgw_oro=0.25))
    for f in ("du_dt", "dv_dt", "dT_dt"):
        assert np.array_equal(np.asarray(getattr(base, f)),
                              np.asarray(getattr(same, f))), f
    assert np.abs(np.asarray(base.du_dt)).max() > 0.0
    assert not np.allclose(np.asarray(dbl.du_dt), np.asarray(base.du_dt),
                           rtol=1e-3, atol=0.0)
