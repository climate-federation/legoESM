def _load():
    z = dict(np.load(FIXTURE))
    z["meta"] = json.loads(str(z["meta"]))
    return z


@pytest.fixture(scope="module")
def fx():
    return _load()


def _cfg(v, hard=True):
    cfg = EmanuelConfig(enable_unsaturated_downdraft=(v == "dd"))
    return cfg._replace(**HARD) if hard else cfg


def _run(fx, v, cb, cfg, dtype=jnp.float64, fn=emanuel_convection):
    T, q, pf, ph = (jnp.asarray(fx[k], dtype) for k in ("T", "q", "p_full", "p_half"))
    prog = jnp.zeros_like(T).at[:, -1].set(fx["meta"]["cbmf_in"][cb])
    return fn(T, q, pf, ph, prog, float(fx["meta"]["dt"]), cfg)


def _err(a, b):
    a = np.asarray(a, np.float64)
    b = np.asarray(b, np.float64)
    if not (np.all(np.isfinite(a)) and np.all(np.isfinite(b))):
        return np.inf
    return float(np.max(np.abs(a - b)) / max(np.max(np.abs(b)), 1e-300))


def test_fixture_provenance_and_coverage(fx):
    m = fx["meta"]
    assert m["oracle_sha256"] == "3eb50b9cf65817966ab89c56fbbdaf09fa546056d7f58b2ceb8564a4c254cc23"
    assert m["constants"] == dict(
        cpd=constants.c_pd,
        cpv=constants.c_pv,
        cl=EmanuelConfig().c_l_emanuel,
        rv=constants.R_v,
        rd=constants.R_d,
        lv0=constants.L_v,
        g=constants.g,
    )
    assert m["nl"] == fx["T"].shape[1] - 1
    assert np.array_equal(
        fx["qs"],
        np.asarray(
            __import__(
                "legoesm.atmosphere.physics.convection._emanuel_mixing", fromlist=["_oracle_qsat"]
            )._oracle_qsat(jnp.asarray(fx["T"]), jnp.asarray(fx["p_full"]))
        ),
    )
    for v, cb in GROUPS:
        p = f"{v}_{cb}"
        iflag = fx[f"{p}_iflag"]
        assert np.any(np.isin(iflag, (1, 4))), p  # convecting columns
        assert np.any(iflag == 0), p  # rejected columns
        assert np.any(fx[f"{p}_nk"][np.isin(iflag, (1, 4))] > 1), p  # elevated source
        fr = fx[f"{p}_frac"][fx[f"{p}_cbmf"] > 0]
        assert np.any((fr > 0) & (fr < 1)), p  # FRAC strictly inside (0, 1)
        assert np.any(fx[f"{p}_n_local_rows"] > 0), p  # NENT=0 local detrainment
    assert np.any(fx["dd_cbw_max_mp"] > 0)  # the downdraught runs
    assert np.all(fx["nodd_cbw_max_mp"] == 0)


@pytest.mark.parametrize("v,cb", GROUPS)
def test_matches_convect43c_oracle_at_hard_limit(fx, v, cb):
    out, prog = _run(fx, v, cb, _cfg(v))
    p = f"{v}_{cb}"
    errs = {
        "FT": _err(out.dT_dt, fx[f"{p}_FT"]),
        "FQ": _err(out.dq_v_dt, fx[f"{p}_FQ"]),
        "CBMF": _err(prog[:, -1], fx[f"{p}_cbmf"]),
    }
    print(f"Emanuel {p} vs convect43c, hard limit, max rel err", errs)
    assert max(errs.values()) <= TOL, errs


def _per_case(a, b):
    """Per column: max_k|a - b| / max_k|b|, absolute where b's column is 0."""
    a = np.asarray(a, np.float64).reshape(len(b), -1)
    b = np.asarray(b, np.float64).reshape(len(b), -1)
    d = np.max(np.abs(a - b), axis=1)
    s = np.max(np.abs(b), axis=1)
    return np.where(s > 0.0, d / np.where(s > 0.0, s, 1.0), d)


def _default_gaps(fx):
    gaps = {}
    for v, cb in GROUPS:
        out, prog = _run(fx, v, cb, _cfg(v, hard=False))
        p = f"{v}_{cb}"
        for name, ours, ora in (
            ("FT", out.dT_dt, fx[f"{p}_FT"]),
            ("FQ", out.dq_v_dt, fx[f"{p}_FQ"]),
            ("CBMF", prog[:, -1], fx[f"{p}_cbmf"]),
        ):
            gaps[f"{p}/{name}"] = _per_case(ours, ora).tolist()
    return gaps


def test_default_smoothing_gap_pinned_per_case(fx):
    """RULE 5: the gap at the default smoothing, per fixture column, equals the
    recorded value to 1e-6 relative / 1e-12 absolute."""
    pinned = json.loads(GAPS.read_text())["gaps"]
    measured = _default_gaps(fx)
    assert set(measured) == set(pinned)
    for key, ref in pinned.items():
        got, ref = np.asarray(measured[key]), np.asarray(ref)
        print(f"Emanuel {key} default gap: max over columns {np.max(got):.3e}")
        assert got.shape == ref.shape, key
        assert np.all(np.abs(got - ref) <= 1.0e-12 + 1.0e-6 * np.abs(ref)), key


def test_smoothing_field_validation():
    """The smooth forms refuse settings they are not valid for."""
    T, q, pf, ph = _toy_column()
    prog = jnp.zeros_like(T)
    for bad in (dict(tlcrit=1.0), dict(denom_floor_sharpness=1.0e3),
                dict(cbmf_sharpness=0.0), dict(sort_sharpness=-1.0)):
        with pytest.raises(ValueError):
            emanuel_convection(T, q, pf, ph, prog, 1800.0, EmanuelConfig(**bad))
    emanuel_convection(T, q, pf, ph, prog, 1800.0,
                       EmanuelConfig(denom_floor_sharpness=math.inf))


def _toy_column():
    fx_ = _load()
    return tuple(jnp.asarray(fx_[k][:1]) for k in ("T", "q", "p_full", "p_half"))


@pytest.mark.parametrize("v,cb", GROUPS)
def test_column_water_and_enthalpy_close(fx, v, cb):
    """Water: vapour + cloud + rain sources integrate to zero, and in the
    downdraught-off case the condensate output equals the oracle's column
    vapour loss.  Enthalpy: sum (c_pn FT + L_v(T) FQ) dp over levels 1..INB is
    zero (the oracle's ENTS pass); residuals printed."""
    from legoesm.thermo import latent_heat_vaporization

    out, _ = _run(fx, v, cb, _cfg(v))
    p = f"{v}_{cb}"
    dpg = np.diff(fx["p_half"], axis=1) / constants.g
    dqv, dqc, dqr = (np.asarray(x) for x in (out.dq_v_dt, out.dq_c_conv_dt, out.dq_r_conv_dt))
    loss = -np.sum(fx[f"{p}_FQ"] * dpg, axis=1)
    scale = max(np.max(np.abs(loss)), 1e-300)
    water = np.sum((dqv + dqc + dqr) * dpg, axis=1)
    print(
        f"{p}: max |column water residual| / max oracle vapour loss = "
        f"{np.max(np.abs(water)) / scale:.3e}"
    )
    assert np.max(np.abs(water)) <= TOL * scale
    if v == "nodd":
        assert np.max(np.abs(np.sum((dqc + dqr) * dpg, axis=1) - loss)) <= TOL * scale
    T, q = fx["T"], fx["q"]
    cpn = constants.c_pd * (1.0 - q) + constants.c_pv * q
    lv = np.asarray(latent_heat_vaporization(jnp.asarray(T), c_liquid=EmanuelConfig().c_l_emanuel))
    nlev = T.shape[1]
    inb_sl = nlev - fx[f"{p}_inb"]  # 1-based surface-first -> surface-last
    mask = np.arange(nlev)[None, :] >= inb_sl[:, None]
    h = np.sum(mask * (cpn * np.asarray(out.dT_dt) + lv * dqv) * dpg, axis=1)
    hs = max(np.max(np.abs(np.sum(mask * cpn * np.abs(fx[f"{p}_FT"]) * dpg, axis=1))), 1e-300)
    print(
        f"{p}: max |column enthalpy residual over 1..INB| / max sum c_pn|FT| = "
        f"{np.max(np.abs(h)) / hs:.3e}"
    )
    assert np.max(np.abs(h)) <= TOL * hs


@pytest.mark.parametrize("v", ("nodd", "dd"))
def test_gradients_finite_fp64_and_fp32(fx, v):
    for dtype in (jnp.float64, jnp.float32):
        T, q, pf, ph = (jnp.asarray(fx[k], dtype) for k in ("T", "q", "p_full", "p_half"))
        prog = jnp.zeros_like(T).at[:, -1].set(0.01)
        cfg = _cfg(v, hard=False)

        def loss(T, q):
            o, pr = emanuel_convection(T, q, pf, ph, prog, 1800.0, cfg)
            return (
                jnp.sum(o.dT_dt)
                + 1.0e3 * jnp.sum(o.dq_v_dt)
                + 1.0e3 * jnp.sum(o.dq_r_conv_dt)
                + jnp.sum(pr)
            )

        gT, gq = jax.grad(loss, argnums=(0, 1))(T, q)
        assert bool(jnp.all(jnp.isfinite(gT))) and bool(jnp.all(jnp.isfinite(gq))), (v, dtype)
        assert float(jnp.max(jnp.abs(gT))) > 0.0


