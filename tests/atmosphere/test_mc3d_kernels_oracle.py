"""mc3d sampling kernels vs the RUNNING microhh ray-tracer device functions.

Fixture ``oracle_fixtures/mc3d_kernels.npz`` was generated by RUNNING microhh
rte-rrtmgp-cpp v0.3 (fc291af01820674ff6dcd05889d7eb191b3daca4) ``henyey``,
``rayleigh``, ``sample_tau``, ``mie_sample_angle`` and ``create_knull_grid``,
compiled for CPU in double precision, via
scripts/validate/oracle/mc3d_kernels/{build.sh,make_fixture.py} (provenance in
the npz ``meta``).  The kernels draw their uniform from ``jax.random.uniform``;
the test hands them the fixture's uniforms instead.

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64.
Relative error is ``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0), the
metric of the merged tier-1 oracle tests.  No smoothing knob: hard limit =
production.  Henyey-Greenstein is compared for |g| >= 1e-3 only (below that
legoESM switches to an isotropic branch the oracle does not have).
"""
from __future__ import annotations

import json
from pathlib import Path

import jax

jax.config.update("jax_enable_x64", True)

import jax.numpy as jnp  # noqa: E402
import numpy as np  # noqa: E402
import pytest  # noqa: E402

from legoesm.atmosphere.physics.radiation.mc3d import knull_grid, mie, sampling  # noqa: E402

FIXTURE = Path(__file__).parent / "oracle_fixtures" / "mc3d_kernels.npz"
TOL = 1.0e-10


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


@pytest.fixture(scope="module")
def fx():
    return dict(np.load(FIXTURE))


@pytest.fixture
def inject_uniform(monkeypatch):
    """Make ``jax.random.uniform(key, dtype=...)`` return the 'key' itself, so a
    kernel called with key=u uses exactly the fixture's uniform u."""
    monkeypatch.setattr(jax.random, "uniform",
                        lambda key, *a, dtype=jnp.float64, **k: jnp.asarray(key, dtype))


def test_fixture_provenance(fx):
    meta = json.loads(str(fx["meta"]))
    assert "fc291af01820674ff6dcd05889d7eb191b3daca4" in meta["oracle"]


def test_henyey_greenstein(fx, inject_uniform):
    g = jnp.asarray(fx["g"])
    assert float(jnp.min(jnp.abs(g))) >= 1e-3
    ours = jax.vmap(sampling.henyey_greenstein_mu)(jnp.asarray(fx["u_hg"]), g)
    assert float(_rel(ours, fx["henyey_oracle"]).max()) <= TOL


def test_rayleigh(fx, inject_uniform):
    ours = jax.vmap(lambda u: sampling.rayleigh_mu(u, jnp.float64))(jnp.asarray(fx["u_edge"]))
    assert float(_rel(ours, fx["rayleigh_oracle"]).max()) <= TOL


def test_free_path_is_the_kernel_step(fx, inject_uniform):
    ours = jax.vmap(sampling.free_path)(jnp.asarray(fx["u_edge"]), jnp.asarray(fx["k_fp"]))
    assert float(_rel(ours, fx["tau_oracle"]).max()) <= TOL


def test_mie_sample_angle(fx):
    meta = json.loads(str(fx["meta"]))
    lut = mie.load_mie_sampling_lut(dtype=jnp.float64)
    b = meta["mie_band"]
    ours = jax.vmap(lambda u, r: mie.mie_sample_cos(u, r, lut.phase_cdf[b], lut.phase_cdf_angle[b]))(
        jnp.asarray(fx["u"]), jnp.asarray(fx["re"]))
    assert np.any(fx["re"] < 2.5)
    assert float(_rel(ours, jnp.cos(jnp.asarray(fx["mie_angle_oracle"]))).max()) <= TOL


def test_knull_grid(fx):
    meta = json.loads(str(fx["meta"]))
    nx, ny, nz, kx, ky, kz = meta["knull_dims"]
    kext = jnp.asarray(np.transpose(fx["kext"], (2, 1, 0)))          # (nx, ny, nz)
    maj = knull_grid.build_majorant_grid(kext, jnp.arange(nz + 1) * 100.0, meta["knull_kmin"],
                                         coarsen_xy=nx // kx, coarsen_z=nz // kz)
    ref = fx["knull_oracle"].reshape(kz, ky, kx).transpose(2, 1, 0)
    assert float(_rel(maj.grid, ref).max()) <= TOL


def test_free_path_gradient_wrt_majorant_is_finite(fx, inject_uniform):
    for dt in (jnp.float64, jnp.float32):
        u = jnp.asarray(fx["u_edge"], dt)
        g = jax.grad(lambda m: jnp.sum(jax.vmap(lambda x: sampling.free_path(x, m))(u)))(
            jnp.asarray(2.0, dt))
        assert np.isfinite(float(g))
