def test_max_random_backend_seeds_a_per_column_shift(monkeypatch):
    """Through the REAL radiation backend: an isolated layer with cf < 1/16 is
    cloudy in some columns (CAM draws different uniforms per column).  With
    one table shared by every column it could never be cloudy.  The cloud
    scheme's output is pinned to a known cloud fraction so only the overlap
    branch is under test."""
    from legoesm.atmosphere.physics.clouds.config import CloudConfig
    from legoesm.atmosphere.physics.radiation import integration as rad_int
    from legoesm.atmosphere.physics.radiation.config import RadiationConfig

    class _Stop(Exception):
        pass

    seen = {}

    class _Solver:
        def solve_columns(self, **kw):
            seen.update(kw)
            raise _Stop()

    ncol, nlev, n_sub = 64, 4, 8
    p_half = jnp.array([10000.0, 45000.0, 70000.0, 90000.0, 100000.0])[None, :] \
        + jnp.linspace(0.0, 0.987, ncol)[:, None]
    p_full = 0.5 * (p_half[:, 1:] + p_half[:, :-1])
    cf = jnp.zeros((ncol, nlev)).at[:, 1].set(0.04)
    cc = CloudConfig(scheme="sundqvist", cloud_vertical_overlap_optics="max_random",
                     cloud_n_subcolumns=n_sub, cloud_subcolumn_mask_width=0.0)
    cfg = RadiationConfig(scheme="rrtmgp", cloud_scheme="sundqvist", cloud_config=cc)
    real = rad_int.compute_cloud_properties
    monkeypatch.setattr(rad_int, "compute_cloud_properties",
                        lambda *a, **k: real(*a, **k)._replace(cloud_fraction=cf))
    with pytest.raises(_Stop):
        rad_int._call_radiation_backend(
            cfg, T=jnp.full((ncol, nlev), 260.0), p_full=p_full, p_half=p_half,
            sfc_temperature=jnp.full(ncol, 280.0), lat=jnp.zeros(ncol),
            q_v=jnp.full((ncol, nlev), 1e-4), insolation=jnp.zeros(ncol),
            q_cloud=jnp.full((ncol, nlev), 1e-5), q_ice=jnp.zeros((ncol, nlev)),
            rrtmgp_solver=_Solver())
    lwp = np.asarray(seen["cloud_path_liq"]).reshape(n_sub, ncol, nlev)
    cloudy = (lwp[:, :, 1] > 0).sum(axis=0)          # cloudy subcolumns per column
    assert cloudy.max() == 1 and 0 < cloudy.sum() < ncol
    assert not (lwp[:, :, [0, 2, 3]] > 0).any()


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_paths_gradient_is_finite(fx, dtype):
    cf = jnp.asarray(fx["rnd/cf"], dtype)
    u = jnp.asarray(fx["rnd/u"], dtype)
    mask = sub.max_random_mask(u, cf, width=0.0)

    def f(lwp, iwp):
        a, b = sub.subcolumn_paths(mask, cf, lwp, iwp)
        return jnp.sum(a) + jnp.sum(b)

    g = jax.grad(f, argnums=(0, 1))(jnp.asarray(fx["rnd/lwp"], dtype),
                                    jnp.asarray(fx["rnd/iwp"], dtype))
    assert all(np.all(np.isfinite(np.asarray(x))) for x in g)


def test_jit_parity(fx):
    cf = jnp.asarray(fx["rnd/cf"])
    u = jnp.asarray(fx["rnd/u"])
    np.testing.assert_array_equal(np.asarray(sub.max_random_mask(u, cf, width=0.0)),
                                  np.asarray(jax.jit(lambda a, b: sub.max_random_mask(a, b, width=0.0))(u, cf)))


