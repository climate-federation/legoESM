"""Maximum-random subcolumns vs the RUNNING CAM McICA generator.

Fixture ``oracle_fixtures/max_random_subcolumns.npz`` was generated by RUNNING
CAM cam_cesm2_1_rel_60 (a03b84b7c4e34f965b115686f22a043b85739e56)
``mcica_subcol_sw`` -> ``generate_stochastic_clouds_sw`` case(2), compiled with
one inserted line that hands CAM the harness uniforms before the recursion, via
scripts/validate/oracle/max_random_subcolumns/{build.sh,make_fixture.py}
(provenance in the npz ``meta``).  Columns: ecRad 1.7.2 test/ifs/ecrad_meridian.nc
(32 x 137) plus a tie column; 8 subcolumns.

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64.
Relative error is ``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0), the
metric of the merged tier-1 oracle tests; masks are compared as 0/1 floats.
The oracle match runs the hard limit (``width = 0``); the production default
``CloudConfig.cloud_subcolumn_mask_width`` is smooth (RULE 5), and its
per-column gap against the oracle is pinned below.
"""
