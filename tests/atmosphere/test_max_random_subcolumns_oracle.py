"""Maximum-random subcolumns vs the RUNNING CAM McICA generator.

Fixture ``oracle_fixtures/max_random_subcolumns.npz`` was generated by RUNNING
CAM cam_cesm2_1_rel_60 (a03b84b7c4e34f965b115686f22a043b85739e56)
``mcica_subcol_sw`` -> ``generate_stochastic_clouds_sw`` case(2), compiled with
one inserted line that hands CAM the harness uniforms before the recursion, via
scripts/validate/oracle/max_random_subcolumns/{build.sh,make_fixture.py}
(provenance in the npz ``meta``).  Columns: ecRad 1.7.2 test/ifs/ecrad_meridian.nc
(32 x 137) plus a tie column; 8 subcolumns.

Tolerance (user decision 2026-10-19): max relative error <= 1e-10 in fp64.
Relative error is ``|a-b| / max(|a|, |b|)`` (0 where both are exactly 0), the
metric of the merged tier-1 oracle tests; masks are compared as 0/1 floats.
The generator has no smoothing knob, so hard limit = production.
"""
from __future__ import annotations

import json
from pathlib import Path

import jax

jax.config.update("jax_enable_x64", True)

import jax.numpy as jnp  # noqa: E402
import numpy as np  # noqa: E402
import pytest  # noqa: E402

from legoesm.atmosphere.physics.clouds import subcolumns as sub  # noqa: E402

FIXTURE = Path(__file__).parent / "oracle_fixtures" / "max_random_subcolumns.npz"
TOL = 1.0e-10
CASES = ("rnd", "table")


def _rel(a, b):
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    assert np.all(np.isfinite(a)) and np.all(np.isfinite(b))
    d = np.maximum(np.abs(a), np.abs(b))
    return np.where(d > 0, np.abs(a - b) / np.where(d > 0, d, 1.0), 0.0)


@pytest.fixture(scope="module")
def fx():
    return dict(np.load(FIXTURE))


def _ours(fx, case):
    cf = jnp.asarray(fx[f"{case}/cf"])
    u = jnp.asarray(fx[f"{case}/u"])
    mask = sub.max_random_mask(u, cf)
    n_sub, ncol, nlev = mask.shape
    lwp, iwp = sub.subcolumn_paths(mask, cf, jnp.asarray(fx[f"{case}/lwp"]),
                                   jnp.asarray(fx[f"{case}/iwp"]))
    return (np.asarray(mask), np.asarray(lwp).reshape(n_sub, ncol, nlev),
            np.asarray(iwp).reshape(n_sub, ncol, nlev))


def test_fixture_provenance(fx):
    meta = json.loads(str(fx["meta"]))
    assert "a03b84b7c4e34f965b115686f22a043b85739e56" in meta["oracle"]
    assert meta["n_sub"] == sub.N_SUBCOLUMNS_DEFAULT == 8


@pytest.mark.parametrize("case", CASES)
def test_masks_and_paths_match_cam(fx, case):
    mask, lwp, iwp = _ours(fx, case)
    ref = fx[f"{case}/mask_oracle"]
    assert mask.shape == ref.shape and ref.any() and not ref.all()
    worst = {
        "mask": float(_rel(mask, ref).max()),
        "clwp": float(_rel(lwp, fx[f"{case}/clwp_oracle"]).max()),
        "ciwp": float(_rel(iwp, fx[f"{case}/ciwp_oracle"]).max()),
    }
    assert max(worst.values()) <= TOL, worst


def test_table_case_is_what_the_generator_runs(fx):
    """The no-shift generator uses exactly the fixture's 'table' uniforms, so
    the oracle-tested recursion is the one generate_subcolumns runs."""
    cf = jnp.asarray(fx["table/cf"])
    np.testing.assert_array_equal(
        np.asarray(sub.generate_subcolumns(cf, 8)), fx["table/mask_oracle"])


def test_table_case_contains_exact_ties(fx):
    """Non-vacuity of the '>=' test: some cells sit exactly on 1 - cf == CDF."""
    cf = fx["table/cf"]
    u = np.broadcast_to(fx["table/u"], (8,) + cf.shape)
    assert np.any(u == 1.0 - cf[None])


def test_max_random_backend_seeds_a_per_column_shift(monkeypatch):
    """Through the REAL radiation backend: an isolated layer with cf < 1/16 is
    cloudy in some columns (CAM draws different uniforms per column).  With
    one table shared by every column it could never be cloudy.  The cloud
    scheme's output is pinned to a known cloud fraction so only the overlap
    branch is under test."""
    from legoesm.atmosphere.physics.clouds.config import CloudConfig
    from legoesm.atmosphere.physics.radiation import integration as rad_int
    from legoesm.atmosphere.physics.radiation.config import RadiationConfig

    class _Stop(Exception):
        pass

    seen = {}

    class _Solver:
        def solve_columns(self, **kw):
            seen.update(kw)
            raise _Stop()

    ncol, nlev, n_sub = 64, 4, 8
    p_half = jnp.array([10000.0, 45000.0, 70000.0, 90000.0, 100000.0])[None, :] \
        + jnp.linspace(0.0, 0.987, ncol)[:, None]
    p_full = 0.5 * (p_half[:, 1:] + p_half[:, :-1])
    cf = jnp.zeros((ncol, nlev)).at[:, 1].set(0.04)
    cc = CloudConfig(scheme="sundqvist", cloud_vertical_overlap_optics="max_random",
                     cloud_n_subcolumns=n_sub)
    cfg = RadiationConfig(scheme="rrtmgp", cloud_scheme="sundqvist", cloud_config=cc)
    real = rad_int.compute_cloud_properties
    monkeypatch.setattr(rad_int, "compute_cloud_properties",
                        lambda *a, **k: real(*a, **k)._replace(cloud_fraction=cf))
    with pytest.raises(_Stop):
        rad_int._call_radiation_backend(
            cfg, T=jnp.full((ncol, nlev), 260.0), p_full=p_full, p_half=p_half,
            sfc_temperature=jnp.full(ncol, 280.0), lat=jnp.zeros(ncol),
            q_v=jnp.full((ncol, nlev), 1e-4), insolation=jnp.zeros(ncol),
            q_cloud=jnp.full((ncol, nlev), 1e-5), q_ice=jnp.zeros((ncol, nlev)),
            rrtmgp_solver=_Solver())
    lwp = np.asarray(seen["cloud_path_liq"]).reshape(n_sub, ncol, nlev)
    cloudy = (lwp[:, :, 1] > 0).sum(axis=0)          # cloudy subcolumns per column
    assert cloudy.max() == 1 and 0 < cloudy.sum() < ncol
    assert not (lwp[:, :, [0, 2, 3]] > 0).any()


@pytest.mark.parametrize("dtype", [jnp.float64, jnp.float32])
def test_paths_gradient_is_finite(fx, dtype):
    cf = jnp.asarray(fx["rnd/cf"], dtype)
    u = jnp.asarray(fx["rnd/u"], dtype)
    mask = sub.max_random_mask(u, cf)

    def f(lwp, iwp):
        a, b = sub.subcolumn_paths(mask, cf, lwp, iwp)
        return jnp.sum(a) + jnp.sum(b)

    g = jax.grad(f, argnums=(0, 1))(jnp.asarray(fx["rnd/lwp"], dtype),
                                    jnp.asarray(fx["rnd/iwp"], dtype))
    assert all(np.all(np.isfinite(np.asarray(x))) for x in g)


def test_jit_parity(fx):
    cf = jnp.asarray(fx["rnd/cf"])
    u = jnp.asarray(fx["rnd/u"])
    np.testing.assert_array_equal(np.asarray(sub.max_random_mask(u, cf)),
                                  np.asarray(jax.jit(sub.max_random_mask)(u, cf)))
