! Oracle driver: OpenIFS 49r1 (8f6f722) VDF column kernels, compiled unchanged,
! called in VDFMAIN's order for sections 5.4-5.7 (vdfmain.F90:991-1086):
!   flux boundary condition (vdfmain.F90:994-1000, LLSFCFLX path, recomputed
!   here with the same expressions) -> VDFDPBL -> VDFHGHTN -> VDFEXCU.
! VDFMAIN's post-VDFHGHTN cloud correction (vdfmain.F90:1029-1048) and the SPP
! perturbations are NOT applied: VDFEXCU sees VDFHGHTN's outputs directly, and
! the legoESM test feeds it the same intermediates.  One column per call.
!
! Namelist &RUN: CONST_MODE = 2 IFS-native constants (SETUP_CONSTANTS +
! suphec.F90:231-255 thermodynamics); = 1 as 2 with RG RD RCPD RV RLVTT
! overwritten from the namelist (legoESM), RETV/RLSTT and the thermodynamic
! derived constants recomputed from them.  LMFGLAC = .TRUE. (sucumf.F90:205),
! so RTICECU = RTT-38 (sucumf.F90:270-274).  RVTMP2 = 0 (suphec.F90:231).
! PTSPHY, INFILE, OUTFILE.  Namelists &NAMVDF and &NAMGWD are read empty.
!
! Input text (reals '%.17e'): line 1 NCOL KLEV; per column:
!   'COL' name / LAND SHF_DOWN LHF_DOWN USTAR Z0M SIGFLT / PAPHM1(0:KLEV) / PAPM1 /
!   PGEOM1 / PGEOH(0:KLEV) / PTM1 / PQM1 / PUM1 / PVM1 / PLM1 / PIM1 / PHRLW /
!   PHRSW / PQE                                   (one record per line, top -> bottom)
! Output text per column: 'COL' name; 'SCAL' KMFL KHFL KQFL PBLH ZINV ZCLDBASE EIS KHVFL;
!   'INT' KINV KCBASE KCTOP KPBLTYPE NJKT2 NJKT6; then rows RI, MFLX(KLEV+1),
!   SLGUH(KLEV+1), QTUH(KLEV+1), UUH(KLEV+1), VUH(KLEV+1), CFM, CFH, KH, KM, TOFDC.
! VDFTOFDC (vdfmain.F90:1101) runs on the same column with PSIGFLT = SIGFLT.
PROGRAM DRIVER
USE PARKIND1, ONLY : JPIM, JPRB
USE YOMLUN, ONLY : NULNAM
USE YOMCST, ONLY : SETUP_CONSTANTS, TCST_INIT, YRCST, RG, RD, RCPD, RETV, RLVTT
USE YOETHF, ONLY : YRTHF, TTHF_INIT, R2ES, R3LES, R3IES, R4LES, R4IES, R5LES, R5IES, &
  & RVTMP2, RHOH2O, R5ALVCP, R5ALSCP, RALVDCP, RALSDCP, RALFDCP, RTWAT, RTBER, RTBERCU, &
  & RTICE, RTICECU, RTWAT_RTICE_R, RTWAT_RTICECU_R, RKOOP1, RKOOP2
USE YOEPHLI, ONLY : TEPHLI
USE YOECLDP, ONLY : TECLDP
USE YOECUMF, ONLY : TECUMF
USE YOEVDF, ONLY : TVDF
USE YOEGWD, ONLY : TEGWD
USE YOEPHY, ONLY : TEPHY
USE SPP_MOD, ONLY : TSPP_CONFIG
IMPLICIT NONE
INTEGER(KIND=JPIM) :: CONST_MODE = 2
REAL(KIND=JPRB) :: CRG = -1., CRD = -1., CRCPD = -1., CRV = -1., CRLVTT = -1.
REAL(KIND=JPRB) :: PTSPHY = 900.0_JPRB
CHARACTER(LEN=512) :: INFILE = '', OUTFILE = '', CNML
NAMELIST /RUN/ CONST_MODE, CRG, CRD, CRCPD, CRV, CRLVTT, PTSPHY, INFILE, OUTFILE
TYPE(TEPHLI) :: YDEPHLI
TYPE(TECLDP) :: YDECLDP
TYPE(TECUMF) :: YDECUMF
TYPE(TVDF) :: YDVDF
TYPE(TEGWD) :: YDEGWD
TYPE(TEPHY) :: YDEPHY
TYPE(TSPP_CONFIG) :: YDSPP
INTEGER(KIND=JPIM), PARAMETER :: KLON = 1
INTEGER(KIND=JPIM) :: NCOL, KLEV, IC, JK, JLEV
CHARACTER(LEN=128) :: CNAME, CTAG
REAL(KIND=JPRB) :: ZLAND, ZSHF, ZLHF, ZUST, ZZ0M(1), ZSIGF(1), ZRHO, ZGP2D(1,1)
REAL(KIND=JPRB) :: ZKMFL(1), ZKHFL(1), ZKQFL(1), PBLH(1), PZINV(1), ZCLDBASE(1), PEIS(1), ZKHVFL(1)
INTEGER(KIND=JPIM) :: IINV(1), ICBASE(1), ICTOP(1), KPBLTYPE(1)
LOGICAL :: LLAND(1)
REAL(KIND=JPRB), ALLOCATABLE :: PAPH(:,:), PAP(:,:), PGEO(:,:), PGEOH(:,:), PT(:,:), PQ(:,:), &
  & PU(:,:), PV(:,:), PL(:,:), PI(:,:), PHRLW(:,:), PHRSW(:,:), PQE(:,:), ZCPTGZ(:,:), ZSLGSM1(:,:), &
  & PRI(:,:), ZMFLX(:,:), ZSLGUH(:,:), ZQTUH(:,:), ZUUH(:,:), ZVUH(:,:), ZCFM(:,:), ZCFH(:,:), &
  & PKH(:,:), PKM(:,:), ZTOFDC(:,:)
#include "vdfdpbl.intfb.h"
#include "vdfhghtn.intfb.h"
#include "vdfexcu.intfb.h"
#include "suvdf.intfb.h"
#include "suvdfs.intfb.h"
#include "vdftofdc.intfb.h"

CALL GET_COMMAND_ARGUMENT(1, CNML)
OPEN(NULNAM, FILE=TRIM(CNML), STATUS='OLD', ACTION='READ')
READ(NULNAM, NML=RUN)

CALL SETUP_CONSTANTS(6, 0)
IF (CONST_MODE == 1) THEN
  IF (MIN(CRG, CRD, CRCPD, CRV, CRLVTT) <= 0) STOP 'CONST_MODE=1 needs CRG CRD CRCPD CRV CRLVTT'
  YRCST%RG = CRG; YRCST%RD = CRD; YRCST%RCPD = CRCPD; YRCST%RV = CRV; YRCST%RLVTT = CRLVTT
  YRCST%RETV = YRCST%RV / YRCST%RD - 1.0_JPRB          ! yomcst.F90 RETV=RV/RD-1
  YRCST%RLSTT = YRCST%RLVTT + YRCST%RLMLT
  CALL TCST_INIT(YRCST)
ELSEIF (CONST_MODE /= 2) THEN
  STOP 'CONST_MODE must be 1 or 2'
ENDIF
! suphec.F90:231-255, unchanged expressions, on the constants in use
RVTMP2 = 0.0_JPRB
RHOH2O = 1000.0_JPRB
R2ES = 611.21_JPRB*YRCST%RD/YRCST%RV
R3LES = 17.502_JPRB; R3IES = 22.587_JPRB; R4LES = 32.19_JPRB; R4IES = -0.7_JPRB
R5LES = R3LES*(YRCST%RTT-R4LES); R5IES = R3IES*(YRCST%RTT-R4IES)
R5ALVCP = R5LES*YRCST%RLVTT/YRCST%RCPD; R5ALSCP = R5IES*YRCST%RLSTT/YRCST%RCPD
RALVDCP = YRCST%RLVTT/YRCST%RCPD; RALSDCP = YRCST%RLSTT/YRCST%RCPD; RALFDCP = YRCST%RLMLT/YRCST%RCPD
RTWAT = YRCST%RTT; RTBER = YRCST%RTT-5._JPRB; RTBERCU = YRCST%RTT-5.0_JPRB
RTICE = YRCST%RTT-23._JPRB; RTICECU = YRCST%RTT-23._JPRB
RTWAT_RTICE_R = 1.0_JPRB/(RTWAT-RTICE); RTWAT_RTICECU_R = 1.0_JPRB/(RTWAT-RTICECU)
RKOOP1 = 2.583_JPRB; RKOOP2 = 0.48116E-2_JPRB
! sucumf.F90:205 LMFGLAC=.TRUE. -> sucumf.F90:270-274
YDECUMF%LMFGLAC = .TRUE.
RTICECU = YRCST%RTT-38._JPRB
RTWAT_RTICECU_R = 1.0_JPRB/(RTWAT-RTICECU)
ALLOCATE(YRTHF)
YRTHF = TTHF_INIT()
! sucumf.F90 defaults read by CUBASEN/VDFHGHTN (RPLRG = 1)
YDECUMF%ENTRORG = 1.75E-3_JPRB; YDECUMF%ENTSTPC1 = 0.8_JPRB; YDECUMF%ENTSTPC2 = 2.E-4_JPRB
YDECUMF%ENTSTPC3 = 3.0_JPRB; YDECUMF%ENTRDD = 3.0E-4_JPRB; YDECUMF%RMFCMIN = 1.E-8_JPRB
YDECUMF%RDEPTHS = 2.E4_JPRB
YDEPHLI%LPHYLIN = .FALSE.
CALL SUVDF(YDVDF)
CALL SUVDFS
YDEGWD%LRDIFF_STRATO = .FALSE.; YDEGWD%NDIFF_STRATO = 5   ! sugwd.F90:200-201
WRITE(6, '(A,I2,6ES25.17)') 'CONST MODE RG RD RCPD RETV RLVTT RTICECU ', CONST_MODE, RG, RD, RCPD, &
  & RETV, RLVTT, YRTHF%RTICECU
WRITE(6, '(A,3ES25.17)') 'SUVDF RLAM REISTHSC PTSPHY ', YDVDF%RLAM, YDVDF%REISTHSC, PTSPHY

OPEN(11, FILE=TRIM(INFILE), STATUS='OLD', ACTION='READ')
OPEN(12, FILE=TRIM(OUTFILE), STATUS='REPLACE', ACTION='WRITE')
READ(11, *) NCOL, KLEV
WRITE(12, '(2I6)') NCOL, KLEV
ALLOCATE(PAPH(1,0:KLEV), PAP(1,KLEV), PGEO(1,KLEV), PGEOH(1,0:KLEV), PT(1,KLEV), PQ(1,KLEV), &
  & PU(1,KLEV), PV(1,KLEV), PL(1,KLEV), PI(1,KLEV), PHRLW(1,KLEV), PHRSW(1,KLEV), PQE(1,KLEV), &
  & ZCPTGZ(1,KLEV), ZSLGSM1(1,KLEV), PRI(1,KLEV), ZMFLX(1,KLEV+1), ZSLGUH(1,KLEV+1), &
  & ZQTUH(1,KLEV+1), ZUUH(1,KLEV+1), ZVUH(1,KLEV+1), ZCFM(1,KLEV), ZCFH(1,KLEV), PKH(1,KLEV), PKM(1,KLEV), ZTOFDC(1,KLEV))
DO IC = 1, NCOL
  READ(11, *) CTAG, CNAME
  IF (CTAG /= 'COL') STOP 'bad column header'
  READ(11, *) ZLAND, ZSHF, ZLHF, ZUST, ZZ0M(1), ZSIGF(1)
  READ(11, *) PAPH(1,0:KLEV)
  READ(11, *) PAP(1,:)
  READ(11, *) PGEO(1,:)
  READ(11, *) PGEOH(1,0:KLEV)
  READ(11, *) PT(1,:)
  READ(11, *) PQ(1,:)
  READ(11, *) PU(1,:)
  READ(11, *) PV(1,:)
  READ(11, *) PL(1,:)
  READ(11, *) PI(1,:)
  READ(11, *) PHRLW(1,:)
  READ(11, *) PHRSW(1,:)
  READ(11, *) PQE(1,:)
  ! per-column NJKT* (sucumf.F90:288-298 with STPRE := this column's PAP), as bechtold_ifs
  YDECUMF%NJKT1 = 2; YDECUMF%NJKT2 = 2; YDECUMF%NJKT8 = 2; YDECUMF%NJKT3 = KLEV-2
  DO JLEV = KLEV, 2, -1
    IF (PAP(1,JLEV) > 350.E2_JPRB) YDECUMF%NJKT1 = JLEV
    IF (PAP(1,JLEV) >  60.E2_JPRB) YDECUMF%NJKT2 = JLEV
    IF (PAP(1,JLEV) > 950.E2_JPRB) YDECUMF%NJKT3 = JLEV
    IF (PAP(1,JLEV) > 850.E2_JPRB) YDECUMF%NJKT4 = JLEV
    IF (PAP(1,JLEV) > 500.E2_JPRB) YDECUMF%NJKT5 = JLEV
    IF (PAP(1,JLEV) > 700.E2_JPRB) YDECUMF%NJKT6 = JLEV
    IF (PAP(1,JLEV) > 100.E2_JPRB) YDECUMF%NJKT7 = JLEV
    IF (PAP(1,JLEV) >   1.E2_JPRB) YDECUMF%NJKT8 = JLEV
  ENDDO
  YDECUMF%NJKT3 = MIN(KLEV-2, YDECUMF%NJKT3)
  ! vdfmain.F90:783-787 and 966-975 (S, SLGS), unchanged expressions
  DO JK = 1, KLEV
    ZCPTGZ(1,JK) = PGEO(1,JK) + PT(1,JK)*RCPD*(1.0_JPRB+RVTMP2*PQ(1,JK))
    ZSLGSM1(1,JK) = (ZCPTGZ(1,JK) - RLVTT*PL(1,JK)) + RCPD*PT(1,JK)*5.87_JPRB*(PQ(1,JK)+PL(1,JK))
  ENDDO
  ! vdfmain.F90:994-1000 flux boundary condition (fluxes downward positive)
  ZRHO = PAPH(1,KLEV)/( RD*PT(1,KLEV)*(1.0_JPRB+RETV*PQ(1,KLEV)) )
  ZKHFL(1) = ZSHF / ( RCPD*(1.0_JPRB+RVTMP2*PQ(1,KLEV)) ) / ZRHO
  ZKQFL(1) = ZLHF / RLVTT / ZRHO
  ZKMFL(1) = ZUST**2
  LLAND(1) = ZLAND > 0.5_JPRB
  ZGP2D = 0.0_JPRB

  CALL VDFDPBL(YDEPHY, 1, 1, KLON, KLEV, PU, PV, PT, PQ, PGEO, ZKMFL, ZKHFL, ZKQFL, PBLH)
  CALL VDFHGHTN(1.0_JPRB, 1.0_JPRB, YDEPHLI, YDECLDP, YDECUMF, YDVDF, YDSPP, &
    & 1, 1, KLON, KLEV, PTSPHY, LLAND, &
    & PT, PQ, ZSLGSM1, PU, PV, ZCPTGZ, PQE, &
    & PAPH, PAP, PGEO, PGEOH, PBLH, &
    & ZKMFL, ZKHFL, ZKQFL, ZGP2D, ZKHVFL, ZMFLX, &
    & ZSLGUH, ZQTUH, ZUUH, ZVUH, &
    & PZINV, IINV, ICBASE, ICTOP, ZCLDBASE, PRI, PEIS, KPBLTYPE)
  ZCFM = -999.0_JPRB; ZCFH = -999.0_JPRB
  CALL VDFEXCU(YDEGWD, YDEPHY, YDSPP, 1, 1, KLON, KLEV, &
    & IINV, ICBASE, ICTOP, YDVDF%RLAM, ZZ0M, &
    & PHRLW, PHRSW, PU, PV, PT, PQ, &
    & PAPH, PGEO, PGEOH, (/0.0_JPRB/), ZCPTGZ, &
    & ZKMFL, ZKHFL, ZKQFL, ZKHVFL, ZGP2D, ZCFM, ZCFH, &
    & PZINV, PKH, PKM, PRI, ZCLDBASE, KPBLTYPE)
  ZTOFDC = -999.0_JPRB
  CALL VDFTOFDC(YDVDF, 1, 1, KLON, KLEV, PU, PV, PGEO, ZSIGF, ZTOFDC)

  WRITE(12, '(A,1X,A)') 'COL', TRIM(CNAME)
  WRITE(12, '(A,*(ES25.17))') 'SCAL ', ZKMFL(1), ZKHFL(1), ZKQFL(1), PBLH(1), PZINV(1), ZCLDBASE(1), &
    & PEIS(1), ZKHVFL(1)
  WRITE(12, '(A,6I6)') 'INT', IINV(1), ICBASE(1), ICTOP(1), KPBLTYPE(1), YDECUMF%NJKT2, YDECUMF%NJKT6
  WRITE(12, '(*(ES25.17))') PRI(1,:)
  WRITE(12, '(*(ES25.17))') ZMFLX(1,:)
  WRITE(12, '(*(ES25.17))') ZSLGUH(1,:)
  WRITE(12, '(*(ES25.17))') ZQTUH(1,:)
  WRITE(12, '(*(ES25.17))') ZUUH(1,:)
  WRITE(12, '(*(ES25.17))') ZVUH(1,:)
  WRITE(12, '(*(ES25.17))') ZCFM(1,:)
  WRITE(12, '(*(ES25.17))') ZCFH(1,:)
  WRITE(12, '(*(ES25.17))') PKH(1,:)
  WRITE(12, '(*(ES25.17))') PKM(1,:)
  WRITE(12, '(*(ES25.17))') ZTOFDC(1,:)
ENDDO
CLOSE(11); CLOSE(12)
WRITE(6, '(A)') 'DRIVER_DONE'
END PROGRAM DRIVER
