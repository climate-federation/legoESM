SUBROUTINE SURF_INQ(YDSURF, PREPUST)
  USE PARKIND1, ONLY : JPRB
  USE YOEPHY, ONLY : TSURF_STUB
  TYPE(TSURF_STUB), INTENT(IN) :: YDSURF
  REAL(KIND=JPRB), OPTIONAL, INTENT(OUT) :: PREPUST
  IF (PRESENT(PREPUST)) PREPUST = 0.0001_JPRB   ! suvexc_mod.F90:160 REPUST
END SUBROUTINE SURF_INQ

SUBROUTINE POSNAM(KULNAM, CDNAML)
  INTEGER, INTENT(IN) :: KULNAM
  CHARACTER(LEN=*), INTENT(IN) :: CDNAML
  CHARACTER(LEN=256) :: CL
  INTEGER :: IOS
  REWIND(KULNAM)
  DO
    READ(KULNAM, '(A)', IOSTAT=IOS) CL
    IF (IOS /= 0) THEN
      WRITE(0, *) 'POSNAM: group not found ', CDNAML; STOP 2
    ENDIF
    IF (INDEX(CL, '&'//TRIM(CDNAML)) > 0) THEN
      BACKSPACE(KULNAM); RETURN
    ENDIF
  ENDDO
END SUBROUTINE POSNAM

