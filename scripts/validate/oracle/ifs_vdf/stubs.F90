! Minimal stand-ins for the OpenIFS 49r1 (8f6f722) infrastructure that the
! VDF routines compiled by build.sh reference but that are not part of the
! vertical-diffusion scheme.  No physics lives here.
! PARKIND1/YOMHOOK/YOMLUN/YOMMP0/YOMDYNCORE/POSNAM/ABOR1: as sso_ifs/stubs.F90.
! YOECLDP/YOECUMF/SPP_*: as bechtold_ifs/stubs.F90, extended with the fields
! VDFEXCU/VDFHGHTN read.  SURF_INQ returns the surface library's REPUST
! (surf/module/suvexc_mod.F90:160); nothing else of the surface library is used.
MODULE PARKIND1
  INTEGER, PARAMETER :: JPIM = SELECTED_INT_KIND(9)
  INTEGER, PARAMETER :: JPIB = SELECTED_INT_KIND(12)
  INTEGER, PARAMETER :: JPRD = SELECTED_REAL_KIND(13, 300)
  INTEGER, PARAMETER :: JPRB = JPRD
  INTEGER, PARAMETER :: JPRM = SELECTED_REAL_KIND(6, 37)
  INTEGER, PARAMETER :: JPHOOK = JPRD
  INTEGER, PARAMETER :: JPLM = KIND(.TRUE.)
END MODULE PARKIND1

MODULE YOMHOOK
  USE PARKIND1, ONLY : JPHOOK
  LOGICAL :: LHOOK = .FALSE.
CONTAINS
  SUBROUTINE DR_HOOK(CDNAME, KSWITCH, PKEY)
    CHARACTER(LEN=*), INTENT(IN) :: CDNAME
    INTEGER, INTENT(IN) :: KSWITCH
    REAL(KIND=JPHOOK), INTENT(INOUT) :: PKEY
