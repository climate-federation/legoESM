! Oracle driver: OpenIFS 49r1 (8f6f722) VDFMAIN compiled unchanged, on its
! single-column prescribed-flux path (LSCMEC, LSFCFLX; REXTSHF/REXTLHF = the
! column's SHF/LHF, W m-2 downward), 49r1 defaults (LWDS = .FALSE.,
! RVDIFTS = 1.5), no tracers.  Stubs (stubs_main.F90, gen_surf_stubs.py):
! SURFEXCDRIVER returns the column's CFMSFC (surface momentum coefficient),
! USTAR**2 and the tile heat coefficients and no snow evaporation; SURFPP
! returns zeros (only the lowest-level diagnostic fluxes PDIFTS/PDIFTQ(KLEV)
! depend on it).  Same input file as driver.F90;
! PTE = PLE = PIE = PVOM = PVOL = 0, PQE = the column's PQE, PSOBETA/PSOTEU/
! PSOTEV and PUCURR/PVCURR as the stage-2 test inputs.
! Output per column: 'COL' name; 'SCAL' PZINV PBLH PVDIS PVDISG PTOFDU PTOFDV;
! 'INT' KPBLTYPE; rows PTE PQE PLE PIE PVOM PVOL PKH PKM PRI PSTRTU(0:KLEV)
! PSTRTV(0:KLEV) PDIFTS(0:KLEV) PDIFTQ(0:KLEV).
PROGRAM DRIVER_MAIN
USE PARKIND1, ONLY : JPIM, JPRB
USE YOMLUN, ONLY : NULNAM
USE YOMCST, ONLY : RG, RD, RETV
USE YOMMP0, ONLY : LSCMEC
USE YOMCT0, ONLY : LSFCFLX, REXTSHF, REXTLHF
USE YOMSFCSTUB, ONLY : SFC_CFM, SFC_KMFL, SFC_CFHTI
USE YOEPHLI, ONLY : TEPHLI
USE YOECUMF, ONLY : TECUMF
USE YOEVDF, ONLY : TVDF
USE YOEGWD, ONLY : TEGWD
USE TYPE_MODEL, ONLY : MODEL
IMPLICIT NONE
INTEGER(KIND=JPIM) :: CONST_MODE = 2
REAL(KIND=JPRB) :: CRG = -1., CRD = -1., CRCPD = -1., CRV = -1., CRLVTT = -1.
REAL(KIND=JPRB) :: PTSPHY = 900.0_JPRB
CHARACTER(LEN=512) :: INFILE = '', OUTFILE = '', CNML
NAMELIST /RUN/ CONST_MODE, CRG, CRD, CRCPD, CRV, CRLVTT, PTSPHY, INFILE, OUTFILE
TYPE(MODEL) :: YDMODEL
TYPE(TEPHLI) :: YDEPHLI
TYPE(TECUMF) :: YDECUMF
TYPE(TVDF) :: YDVDF
TYPE(TEGWD) :: YDEGWD
CHARACTER(LEN=1) :: CDCONF = 'T'
INTEGER(KIND=JPIM) :: NCOL, KLEV, IC, JLEV
CHARACTER(LEN=128) :: CNAME, CTAG
REAL(KIND=JPRB) :: ZLAND, ZSHF, ZLHF, ZUST, ZZ0M, ZSIGF, ZTILE(24), ZSFC2(8), ZDUM
REAL(KIND=JPRB), ALLOCATABLE :: ZROW(:)
#include "vm_decl.inc"
#include "vdfmain.intfb.h"

CALL GET_COMMAND_ARGUMENT(1, CNML)
OPEN(NULNAM, FILE=TRIM(CNML), STATUS='OLD', ACTION='READ')
READ(NULNAM, NML=RUN)
CALL ORACLE_SETUP(CONST_MODE, CRG, CRD, CRCPD, CRV, CRLVTT, PTSPHY, YDECUMF, YDEPHLI, YDVDF, YDEGWD)
WRITE(6, '(A,2ES25.17,L2)') 'SUVDF RVDIFTS REPQMI LWDS ', YDVDF%RVDIFTS, &
  & YDMODEL%YRML_PHY_EC%YRECND%REPQMI, YDVDF%LWDS
LSCMEC = .TRUE.; LSFCFLX = .TRUE.
YDMODEL%YRML_PHY_G%YRVDF = YDVDF
YDMODEL%YRML_PHY_EC%YREGWD = YDEGWD
YDMODEL%YRML_PHY_SLIN%YREPHLI = YDEPHLI
YDMODEL%YRML_GCONF%YRRIP%TSTEP = PTSPHY

OPEN(11, FILE=TRIM(INFILE), STATUS='OLD', ACTION='READ')
OPEN(12, FILE=TRIM(OUTFILE), STATUS='REPLACE', ACTION='WRITE')
READ(11, *) NCOL, KLEV
WRITE(12, '(2I6)') NCOL, KLEV
VM_KIDIA = 1; VM_KFDIA = 1; VM_KLON = 1; VM_KLEV = KLEV; VM_KLEVS = 4; VM_KSTEP = 0
VM_KTILES = 8; VM_KVTYPES = 1; VM_KDIAG = 1; VM_KTRAC = 0; VM_KLEVSN = 1; VM_KLEVI = 1
VM_KDHVTLS = 0; VM_KDHFTLS = 0; VM_KDHVTSS = 0; VM_KDHFTSS = 0; VM_KDHVTTS = 0; VM_KDHFTTS = 0
VM_KDHVTIS = 0; VM_KDHFTIS = 0; VM_KDHVCO2S = 0; VM_KDHFCO2S = 0; VM_KDHVVEGS = 0; VM_KDHFVEGS = 0
#include "vm_alloc.inc"
ALLOCATE(ZROW(KLEV))
DO IC = 1, NCOL
#include "vm_zero.inc"
  VM_KIDIA = 1; VM_KFDIA = 1; VM_KLON = 1; VM_KLEV = KLEV; VM_KLEVS = 4; VM_KSTEP = 0
  VM_KTILES = 8; VM_KVTYPES = 1; VM_KDIAG = 1; VM_KTRAC = 0; VM_KLEVSN = 1; VM_KLEVI = 1
  VM_PTSPHY = PTSPHY; VM_KTVL = 1; VM_KTVH = 1
  READ(11, *) CTAG, CNAME
  IF (CTAG /= 'COL') STOP 'bad column header'
  READ(11, *) ZLAND, ZSHF, ZLHF, ZUST, ZZ0M, ZSIGF
  READ(11, *) VM_PAPHM1(1,0:KLEV)
  READ(11, *) VM_PAPM1(1,:)
  READ(11, *) VM_PGEOM1(1,:)
  READ(11, *) VM_PGEOH(1,0:KLEV)
  READ(11, *) VM_PTM1(1,:)
  READ(11, *) VM_PQM1(1,:)
  READ(11, *) VM_PUM1(1,:)
  READ(11, *) VM_PVM1(1,:)
  READ(11, *) VM_PLM1(1,:)
  READ(11, *) VM_PIM1(1,:)
  READ(11, *) VM_PHRLW(1,:)
  READ(11, *) VM_PHRSW(1,:)
  READ(11, *) VM_PQE(1,:)
  READ(11, *) CTAG, ZTILE
  IF (CTAG /= 'TILE') STOP 'bad TILE record'
  READ(11, *) CTAG, ZSFC2
  IF (CTAG /= 'SFC2') STOP 'bad SFC2 record'
  READ(11, *) VM_PSOBETA(1,:)
  READ(11, *) VM_PSOTEU(1,:)
  READ(11, *) VM_PSOTEV(1,:)
  READ(11, *) ZROW
  READ(11, *) ZROW
  VM_LDLAND(1) = ZLAND > 0.5_JPRB
  VM_PLSM(1) = ZLAND
  VM_PSIGFLT(1) = ZSIGF
  VM_PZ0M(1) = ZZ0M
  VM_PFRTI(1,:) = ZTILE(1:8)
  VM_PTSKTI(1,:) = ZTILE(17:24)
  VM_PUCURR(1) = ZSFC2(2); VM_PVCURR(1) = ZSFC2(3)
  VM_PTSKM1M(1) = VM_PTM1(1,KLEV); VM_PSST(1) = VM_PTM1(1,KLEV); VM_PTICE(1) = VM_PTM1(1,KLEV)
  VM_PEMIS(1) = 1.0_JPRB
  REXTSHF = ZSHF; REXTLHF = ZLHF
  SFC_CFM(1) = ZSFC2(4); SFC_KMFL(1) = ZUST**2; SFC_CFHTI(1,:) = ZTILE(9:16)
  ! per-column NJKT* (sucumf.F90:288-298 with STPRE := this column's PAP), as driver.F90
  YDECUMF%NJKT1 = 2; YDECUMF%NJKT2 = 2; YDECUMF%NJKT8 = 2; YDECUMF%NJKT3 = KLEV-2
  DO JLEV = KLEV, 2, -1
    IF (VM_PAPM1(1,JLEV) > 350.E2_JPRB) YDECUMF%NJKT1 = JLEV
    IF (VM_PAPM1(1,JLEV) >  60.E2_JPRB) YDECUMF%NJKT2 = JLEV
    IF (VM_PAPM1(1,JLEV) > 950.E2_JPRB) YDECUMF%NJKT3 = JLEV
    IF (VM_PAPM1(1,JLEV) > 850.E2_JPRB) YDECUMF%NJKT4 = JLEV
    IF (VM_PAPM1(1,JLEV) > 500.E2_JPRB) YDECUMF%NJKT5 = JLEV
    IF (VM_PAPM1(1,JLEV) > 700.E2_JPRB) YDECUMF%NJKT6 = JLEV
    IF (VM_PAPM1(1,JLEV) > 100.E2_JPRB) YDECUMF%NJKT7 = JLEV
    IF (VM_PAPM1(1,JLEV) >   1.E2_JPRB) YDECUMF%NJKT8 = JLEV
  ENDDO
  YDECUMF%NJKT3 = MIN(KLEV-2, YDECUMF%NJKT3)
  YDMODEL%YRML_PHY_EC%YRECUMF = YDECUMF

#include "vm_call.inc"

  WRITE(12, '(A,1X,A)') 'COL', TRIM(CNAME)
  WRITE(12, '(A,*(ES25.17))') 'SCAL ', VM_PZINV(1), VM_PBLH(1), VM_PVDIS(1), VM_PVDISG(1), &
    & VM_PTOFDU(1), VM_PTOFDV(1)
  WRITE(12, '(A,I6)') 'INT', VM_KPBLTYPE(1)
  WRITE(12, '(*(ES25.17))') VM_PTE(1,:)
  WRITE(12, '(*(ES25.17))') VM_PQE(1,:)
  WRITE(12, '(*(ES25.17))') VM_PLE(1,:)
  WRITE(12, '(*(ES25.17))') VM_PIE(1,:)
  WRITE(12, '(*(ES25.17))') VM_PVOM(1,:)
  WRITE(12, '(*(ES25.17))') VM_PVOL(1,:)
  WRITE(12, '(*(ES25.17))') VM_PKH(1,:)
  WRITE(12, '(*(ES25.17))') VM_PKM(1,:)
  WRITE(12, '(*(ES25.17))') VM_PRI(1,:)
  WRITE(12, '(*(ES25.17))') VM_PSTRTU(1,:)
  WRITE(12, '(*(ES25.17))') VM_PSTRTV(1,:)
  WRITE(12, '(*(ES25.17))') VM_PDIFTS(1,:)
  WRITE(12, '(*(ES25.17))') VM_PDIFTQ(1,:)
ENDDO
CLOSE(11); CLOSE(12)
WRITE(6, '(A)') 'DRIVER_DONE'
END PROGRAM DRIVER_MAIN
