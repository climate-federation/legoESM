! Instrumentation only: writes named intermediate arrays of CUMASTRN for the
! current column (KLON=1 per call) to unit IU.  No physics.
MODULE DUMPMOD
  USE PARKIND1, ONLY : JPIM, JPRB
  IMPLICIT NONE
  INTEGER :: IU = 0
  INTEGER :: ISTAGE = 0
CONTAINS
  SUBROUTINE DUMPR2(TAG, A, KLON, K1, K2)
    CHARACTER(LEN=*), INTENT(IN) :: TAG
    INTEGER(KIND=JPIM), INTENT(IN) :: KLON, K1, K2
    REAL(KIND=JPRB), INTENT(IN) :: A(KLON, K1:K2)
    INTEGER :: JK
    IF (IU <= 0) RETURN
    WRITE(IU,'(A,1X,A,1X,I0)') 'R', TRIM(TAG), K2-K1+1
    WRITE(IU,'(4ES26.17E3)') (A(1,JK), JK=K1,K2)
  END SUBROUTINE DUMPR2
  SUBROUTINE DUMPR1(TAG, A, KLON)
    CHARACTER(LEN=*), INTENT(IN) :: TAG
    INTEGER(KIND=JPIM), INTENT(IN) :: KLON
    REAL(KIND=JPRB), INTENT(IN) :: A(KLON)
    IF (IU <= 0) RETURN
    WRITE(IU,'(A,1X,A,1X,I0)') 'R', TRIM(TAG), 1
    WRITE(IU,'(4ES26.17E3)') A(1)
  END SUBROUTINE DUMPR1
  SUBROUTINE DUMPI2(TAG, A, KLON, KLEV)
    CHARACTER(LEN=*), INTENT(IN) :: TAG
    INTEGER(KIND=JPIM), INTENT(IN) :: KLON, KLEV
    INTEGER(KIND=JPIM), INTENT(IN) :: A(KLON, KLEV)
    INTEGER :: JK
    IF (IU <= 0) RETURN
    WRITE(IU,'(A,1X,A,1X,I0)') 'I', TRIM(TAG), KLEV
    WRITE(IU,'(10I8)') (A(1,JK), JK=1,KLEV)
  END SUBROUTINE DUMPI2
  SUBROUTINE DUMPI1(TAG, A, KLON)
    CHARACTER(LEN=*), INTENT(IN) :: TAG
    INTEGER(KIND=JPIM), INTENT(IN) :: KLON
    INTEGER(KIND=JPIM), INTENT(IN) :: A(KLON)
    IF (IU <= 0) RETURN
    WRITE(IU,'(A,1X,A,1X,I0)') 'I', TRIM(TAG), 1
    WRITE(IU,'(I8)') A(1)
  END SUBROUTINE DUMPI1
  SUBROUTINE DUMPL1(TAG, A, KLON)
    CHARACTER(LEN=*), INTENT(IN) :: TAG
    INTEGER(KIND=JPIM), INTENT(IN) :: KLON
    LOGICAL, INTENT(IN) :: A(KLON)
    IF (IU <= 0) RETURN
    WRITE(IU,'(A,1X,A,1X,I0)') 'I', TRIM(TAG), 1
    IF (A(1)) THEN
      WRITE(IU,'(I8)') 1
    ELSE
      WRITE(IU,'(I8)') 0
    ENDIF
  END SUBROUTINE DUMPL1
  SUBROUTINE STAGE(TAG)
    CHARACTER(LEN=*), INTENT(IN) :: TAG
    IF (IU <= 0) RETURN
    WRITE(IU,'(A,1X,A)') 'S', TRIM(TAG)
  END SUBROUTINE STAGE
END MODULE DUMPMOD
