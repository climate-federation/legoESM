! Standalone driver: one CUMASTRN call per column (KLON=1) so the NJKT*
! level indices can be derived from each column's OWN full-level pressure
! (sucumf.F90:288-298 with STPRE := PAP of that column), which is what the
! legoESM port does with its per-column pressure thresholds.
!
! Namelist &RUN (file given as the first command-line argument):
!   CONST_MODE = 1 constants from the namelist (CRG ... CR2ES_E0; make_fixture.py
!                writes legoesm.constants / legoesm.thermo Tetens values)
!              = 2 IFS-native constants (yomcst/suphec, 8f6f722)
!   ZERO_MELT  : RLMLT = 0 (=> RLSTT = RLVTT, RALFDCP = 0)
!   ZERO_EVAP  : RCPECONS = 0 (cuflxn sub-cloud evaporation off)
!   LMFDD, LMFDUDV, LMFMID, LMFDSNOW, LMFGLAC, LMFSCV, LMFPEN : yoecumf switches
!   RTICECU_OFF: RTICECU = RTT - RTICECU_OFF
!   INFILE, OUTFILE
PROGRAM DRIVER
  USE PARKIND1, ONLY : JPIM, JPRB
  USE YOMCST, ONLY : TCST
  USE YOETHF, ONLY : TTHF
  USE YOMCHEM, ONLY : TCHEM
  USE YOM_YGFL, ONLY : TYPE_GFLD
  USE SPP_MOD, ONLY : TSPP_CONFIG
  USE MODEL_PHYSICS_ECMWF_MOD, ONLY : MODEL_PHYSICS_ECMWF_TYPE
  USE MODEL_PHYSICS_SIMPLINEAR_MOD, ONLY : MODEL_PHYSICS_SIMPLINEAR_TYPE
  USE DUMPMOD, ONLY : IU, STAGE, DUMPR1, DUMPR2, DUMPI1, DUMPL1
  IMPLICIT NONE

  INTEGER :: CONST_MODE = 1
  LOGICAL :: ZERO_MELT = .TRUE., ZERO_EVAP = .TRUE.
  LOGICAL :: LMFDD = .FALSE., LMFDUDV = .FALSE., LMFMID = .FALSE., LMFDSNOW = .FALSE.
  LOGICAL :: LMFGLAC = .FALSE., LMFSCV = .TRUE., LMFPEN = .TRUE.
  REAL(KIND=JPRB) :: RTICECU_OFF = 38.0_JPRB
  CHARACTER(LEN=512) :: INFILE = 'in.txt', OUTFILE = 'out.txt', NMLFILE
  REAL(KIND=JPRB) :: CRG = -1., CRD = -1., CRV = -1., CRCPD = -1., CRLVTT = -1., CRTT = -1.
  REAL(KIND=JPRB) :: CRA = -1., CRLMLT = -1., CR3LES = -1., CR4LES_OFF = -1., CR2ES_E0 = -1.
  NAMELIST /RUN/ CONST_MODE, ZERO_MELT, ZERO_EVAP, LMFDD, LMFDUDV, LMFMID, LMFDSNOW, &
       & LMFGLAC, LMFSCV, LMFPEN, RTICECU_OFF, INFILE, OUTFILE, &
       & CRG, CRD, CRV, CRCPD, CRLVTT, CRTT, CRA, CRLMLT, CR3LES, CR4LES_OFF, CR2ES_E0

  TYPE(TCST) :: YDCST
  TYPE(TTHF) :: YDTHF
  TYPE(TCHEM) :: YDCHEM
  TYPE(TYPE_GFLD) :: YGFL
  TYPE(TSPP_CONFIG) :: YDSPP
  TYPE(MODEL_PHYSICS_ECMWF_TYPE) :: YEC
  TYPE(MODEL_PHYSICS_SIMPLINEAR_TYPE) :: YSL

  INTEGER(KIND=JPIM), PARAMETER :: KLON = 1, KTRAC = 0
  INTEGER(KIND=JPIM) :: KLEV, NCOL, IC, JK, JLEV, ILAND
  CHARACTER(LEN=64) :: CNAME
  REAL(KIND=JPRB) :: ZAHFS, ZQHFL, ZGAW, PTSPHY, ZQS, ZDXDUM(1)
  REAL(KIND=JPRB), ALLOCATABLE :: PTEN(:,:), PQEN(:,:), PAP(:,:), PGEO(:,:), PUEN(:,:), PVEN(:,:)
  REAL(KIND=JPRB), ALLOCATABLE :: PVERVEL(:,:), PLITOT(:,:), PTENT(:,:), PTENQ(:,:), PTENTA(:,:), PTENQA(:,:)
  REAL(KIND=JPRB), ALLOCATABLE :: PAPH(:,:), PGEOH(:,:), PQSEN(:,:), PQHFL(:,:), PAHFS(:,:)
  REAL(KIND=JPRB), ALLOCATABLE :: PTENU(:,:), PTENV(:,:), PLCRIT_AER(:,:)
  REAL(KIND=JPRB), ALLOCATABLE :: PTU(:,:), PQU(:,:), PLU(:,:), PLUDE(:,:), PLUDELI(:,:,:), PSNDE(:,:,:)
  REAL(KIND=JPRB), ALLOCATABLE :: PENTH(:,:), PMFLXR(:,:), PMFLXS(:,:), PLRAIN(:,:), PRSUD(:,:,:)
  REAL(KIND=JPRB), ALLOCATABLE :: PMFU(:,:), PMFD(:,:), PMFUDE_RATE(:,:), PMFDDE_RATE(:,:), PDISS(:,:)
  REAL(KIND=JPRB), ALLOCATABLE :: PCEN(:,:,:), PTENC(:,:,:), PSCAV(:)
  REAL(KIND=JPRB) :: PGAW(1), PCUCONVCA(1), PGP2DSPP(1,1), PRAIN(1), PCAPE(1), PWMEAN(1), PVDISCU(1)
  LOGICAL :: LDLAND(1), LDCUM(1), LDCUM_LIG(1), LDSC(1), LDSHCV(1)
  INTEGER(KIND=JPIM) :: KTYPE(1), KCBOT(1), KCTOP(1), KCBOT_LIG(1), KCTOP_LIG(1), KBOTSC(1)

#include "fcttre.func.h"

  CALL GET_COMMAND_ARGUMENT(1, NMLFILE)
  OPEN(11, FILE=TRIM(NMLFILE), STATUS='OLD')
  READ(11, NML=RUN)
  CLOSE(11)
  WRITE(*, NML=RUN)

  CALL SET_CONSTANTS()

  OPEN(12, FILE=TRIM(INFILE), STATUS='OLD')
  READ(12,*) NCOL, KLEV
  ALLOCATE(PTEN(1,KLEV), PQEN(1,KLEV), PAP(1,KLEV), PGEO(1,KLEV), PUEN(1,KLEV), PVEN(1,KLEV))
  ALLOCATE(PVERVEL(1,KLEV), PLITOT(1,KLEV), PTENT(1,KLEV), PTENQ(1,KLEV), PTENTA(1,KLEV), PTENQA(1,KLEV))
  ALLOCATE(PAPH(1,KLEV+1), PGEOH(1,KLEV+1), PQSEN(1,KLEV), PQHFL(1,KLEV+1), PAHFS(1,KLEV+1))
  ALLOCATE(PTENU(1,KLEV), PTENV(1,KLEV), PLCRIT_AER(1,KLEV))
  ALLOCATE(PTU(1,KLEV), PQU(1,KLEV), PLU(1,KLEV), PLUDE(1,KLEV), PLUDELI(1,KLEV,4), PSNDE(1,KLEV,2))
  ALLOCATE(PENTH(1,KLEV), PMFLXR(1,KLEV+1), PMFLXS(1,KLEV+1), PLRAIN(1,KLEV), PRSUD(1,KLEV,2))
  ALLOCATE(PMFU(1,KLEV), PMFD(1,KLEV), PMFUDE_RATE(1,KLEV), PMFDDE_RATE(1,KLEV), PDISS(1,KLEV))
  ALLOCATE(PCEN(1,KLEV,0), PTENC(1,KLEV,0), PSCAV(0))

  IU = 13
  OPEN(IU, FILE=TRIM(OUTFILE), STATUS='REPLACE')
  WRITE(IU,'(A)') 'K RG RD RV RCPD RLVTT RTT RA RLMLT R2ES R3LES R4LES R3IES R4IES RPI'
  WRITE(IU,'(4ES26.17E3)') YDCST%RG, YDCST%RD, YDCST%RV, YDCST%RCPD, YDCST%RLVTT, &
       & YDCST%RTT, YDCST%RA, YDCST%RLMLT, YDTHF%R2ES, YDTHF%R3LES, YDTHF%R4LES, &
       & YDTHF%R3IES, YDTHF%R4IES, YDCST%RPI

  DO IC = 1, NCOL
    READ(12,*) CNAME
    READ(12,*) ILAND, ZAHFS, ZQHFL, ZGAW, PTSPHY
    READ(12,*) (PTEN(1,JK), JK=1,KLEV)
    READ(12,*) (PQEN(1,JK), JK=1,KLEV)
    READ(12,*) (PAP(1,JK), JK=1,KLEV)
    READ(12,*) (PGEO(1,JK), JK=1,KLEV)
    READ(12,*) (PUEN(1,JK), JK=1,KLEV)
    READ(12,*) (PVEN(1,JK), JK=1,KLEV)
    READ(12,*) (PVERVEL(1,JK), JK=1,KLEV)
    READ(12,*) (PLITOT(1,JK), JK=1,KLEV)
    READ(12,*) (PTENT(1,JK), JK=1,KLEV)
    READ(12,*) (PTENQ(1,JK), JK=1,KLEV)
    READ(12,*) (PTENTA(1,JK), JK=1,KLEV)
    READ(12,*) (PTENQA(1,JK), JK=1,KLEV)
    READ(12,*) (PAPH(1,JK), JK=1,KLEV+1)
    READ(12,*) (PGEOH(1,JK), JK=1,KLEV+1)

    ! per-column NJKT* (sucumf.F90:288-298 with STPRE := this column's PAP)
    YEC%YRECUMF%NJKT1 = 2; YEC%YRECUMF%NJKT2 = 2; YEC%YRECUMF%NJKT8 = 2
    YEC%YRECUMF%NJKT3 = KLEV-2
    DO JLEV = KLEV, 2, -1
      IF (PAP(1,JLEV) > 350.E2_JPRB) YEC%YRECUMF%NJKT1 = JLEV
      IF (PAP(1,JLEV) >  60.E2_JPRB) YEC%YRECUMF%NJKT2 = JLEV
      IF (PAP(1,JLEV) > 950.E2_JPRB) YEC%YRECUMF%NJKT3 = JLEV
      IF (PAP(1,JLEV) > 850.E2_JPRB) YEC%YRECUMF%NJKT4 = JLEV
      IF (PAP(1,JLEV) > 500.E2_JPRB) YEC%YRECUMF%NJKT5 = JLEV
      IF (PAP(1,JLEV) > 700.E2_JPRB) YEC%YRECUMF%NJKT6 = JLEV
      IF (PAP(1,JLEV) > 100.E2_JPRB) YEC%YRECUMF%NJKT7 = JLEV
      IF (PAP(1,JLEV) >   1.E2_JPRB) YEC%YRECUMF%NJKT8 = JLEV
    ENDDO
    YEC%YRECUMF%NJKT3 = MIN(KLEV-2, YEC%YRECUMF%NJKT3)

    ! saturation specific humidity exactly as SATUR (satur.F90, KFLAG=0 -> FOEEWM)
    DO JK = 1, KLEV
      ZQS = FOEEWM(PTEN(1,JK))/PAP(1,JK)
      ZQS = MIN(0.5_JPRB, ZQS)
      PQSEN(1,JK) = ZQS/(1.0_JPRB - YDCST%RETV*ZQS)
    ENDDO

    PQHFL = 0.0_JPRB; PAHFS = 0.0_JPRB
    PQHFL(1,KLEV+1) = ZQHFL; PAHFS(1,KLEV+1) = ZAHFS
    LDLAND(1) = (ILAND == 1)
    PGAW(1) = ZGAW
    PCUCONVCA = 1.0_JPRB; PGP2DSPP = 0.0_JPRB; PLCRIT_AER = 0.0_JPRB
    PTENU = 0.0_JPRB; PTENV = 0.0_JPRB
    LDSHCV(1) = .TRUE.
    ZDXDUM = 0.0_JPRB

    WRITE(IU,'(A,1X,A,1X,I0,1X,I0,1X,I0,1X,I0)') 'C', TRIM(CNAME), YEC%YRECUMF%NJKT1, &
         & YEC%YRECUMF%NJKT2, YEC%YRECUMF%NJKT5, YEC%YRECUMF%NJKT6
    CALL CUMASTRN &
     & (1.0_JPRB, 1.0_JPRB, YDTHF, YDCST, YSL, YEC, YGFL, &
     & YDCHEM, YDSPP, &
     & 1, 1, KLON, KLEV, ZDXDUM, .FALSE., &
     & .FALSE., LDLAND, PTSPHY, &
     & PTEN, PQEN, PUEN, PVEN, PLITOT, &
     & PVERVEL, PQSEN, PQHFL, PAHFS, &
     & PAP, PAPH, PGEO, PGEOH, PGAW, &
     & PCUCONVCA, PGP2DSPP, &
     & PTENT, PTENQ, PTENU, PTENV, PTENTA, PTENQA, &
     & LDCUM, KTYPE, KCBOT, KCTOP, &
     & LDCUM_LIG, KCBOT_LIG, KCTOP_LIG, &
     & KBOTSC, LDSC, &
     & LDSHCV, &
     & PLCRIT_AER, &
     & PTU, PQU, PLU, PLUDE, PLUDELI, PSNDE, &
     & PENTH, PMFLXR, PMFLXS, PRAIN, PLRAIN, PRSUD, &
     & PMFU, PMFD, &
     & PMFUDE_RATE, PMFDDE_RATE, PCAPE, PWMEAN, PVDISCU, PDISS, &
     & KTRAC, PCEN, PTENC, PSCAV)
    CALL STAGE('out')
    CALL DUMPR2('PTENT', PTENT, 1, 1, KLEV); CALL DUMPR2('PTENQ', PTENQ, 1, 1, KLEV)
    CALL DUMPR2('PTENU', PTENU, 1, 1, KLEV); CALL DUMPR2('PTENV', PTENV, 1, 1, KLEV)
    CALL DUMPR2('PTU', PTU, 1, 1, KLEV); CALL DUMPR2('PQU', PQU, 1, 1, KLEV)
    CALL DUMPR2('PLU', PLU, 1, 1, KLEV); CALL DUMPR2('PLUDE', PLUDE, 1, 1, KLEV)
    CALL DUMPR2('PLUDELI1', PLUDELI(:,:,1), 1, 1, KLEV)
    CALL DUMPR2('PLUDELI2', PLUDELI(:,:,2), 1, 1, KLEV)
    CALL DUMPR2('PLUDELI3', PLUDELI(:,:,3), 1, 1, KLEV)
    CALL DUMPR2('PLUDELI4', PLUDELI(:,:,4), 1, 1, KLEV)
    CALL DUMPR2('PSNDE1', PSNDE(:,:,1), 1, 1, KLEV)
    CALL DUMPR2('PSNDE2', PSNDE(:,:,2), 1, 1, KLEV)
    CALL DUMPR2('PENTH', PENTH, 1, 1, KLEV)
    CALL DUMPR2('PMFLXR', PMFLXR, 1, 1, KLEV+1); CALL DUMPR2('PMFLXS', PMFLXS, 1, 1, KLEV+1)
    CALL DUMPR1('PRAIN', PRAIN, 1); CALL DUMPR2('PLRAIN', PLRAIN, 1, 1, KLEV)
    CALL DUMPR2('PRSUD1', PRSUD(:,:,1), 1, 1, KLEV)
    CALL DUMPR2('PRSUD2', PRSUD(:,:,2), 1, 1, KLEV)
    CALL DUMPR2('PMFU', PMFU, 1, 1, KLEV); CALL DUMPR2('PMFD', PMFD, 1, 1, KLEV)
    CALL DUMPR2('PMFUDE_RATE', PMFUDE_RATE, 1, 1, KLEV)
    CALL DUMPR2('PMFDDE_RATE', PMFDDE_RATE, 1, 1, KLEV)
    CALL DUMPR1('PCAPE', PCAPE, 1); CALL DUMPR1('PWMEAN', PWMEAN, 1)
    CALL DUMPR1('PVDISCU', PVDISCU, 1); CALL DUMPR2('PDISS', PDISS, 1, 1, KLEV)
    CALL DUMPR2('PQSEN', PQSEN, 1, 1, KLEV)
    CALL DUMPL1('LDCUM', LDCUM, 1); CALL DUMPI1('KTYPE', KTYPE, 1)
    CALL DUMPI1('KCBOT', KCBOT, 1); CALL DUMPI1('KCTOP', KCTOP, 1)
    CALL DUMPI1('KBOTSC', KBOTSC, 1); CALL DUMPL1('LDSC', LDSC, 1)
    WRITE(IU,'(A)') 'E'
  ENDDO
  CLOSE(IU)
  CLOSE(12)
  WRITE(*,*) 'DRIVER_DONE', NCOL

CONTAINS

  SUBROUTINE SET_CONSTANTS()
    REAL(KIND=JPRB) :: R, RKBOL, RNAVO
    YDCST%RPI = 2.0_JPRB*ASIN(1.0_JPRB)
    IF (CONST_MODE == 1) THEN
      IF (MIN(CRG, CRD, CRV, CRCPD, CRLVTT, CRTT, CRA, CRLMLT, CR3LES, CR4LES_OFF, CR2ES_E0) <= 0.) &
           & STOP 'CONST_MODE=1 needs every CR* constant in the namelist'
      YDCST%RG = CRG
      YDCST%RD = CRD
      YDCST%RV = CRV
      YDCST%RCPD = CRCPD
      YDCST%RLVTT = CRLVTT
      YDCST%RTT = CRTT
      YDCST%RA = CRA
      YDCST%RLMLT = CRLMLT
      YDTHF%R3LES = CR3LES
      YDTHF%R4LES = YDCST%RTT - CR4LES_OFF
      YDTHF%R2ES = CR2ES_E0*YDCST%RD/YDCST%RV
    ELSE
      ! IFS yomcst.F90:508-629 / suphec.F90:231-250
      RKBOL = 1.380658E-23_JPRB
      RNAVO = 6.0221367E+23_JPRB
      R = RNAVO*RKBOL
      YDCST%RG = 9.80665_JPRB
      YDCST%RD = 1000._JPRB*R/28.9644_JPRB
      YDCST%RV = 1000._JPRB*R/18.0153_JPRB
      YDCST%RCPD = 3.5_JPRB*YDCST%RD
      YDCST%RLVTT = 2.5008E+6_JPRB
      YDCST%RTT = 273.16_JPRB
      YDCST%RA = 6371229._JPRB
      YDCST%RLMLT = 2.8345E+6_JPRB - 2.5008E+6_JPRB
      YDTHF%R3LES = 17.502_JPRB
      YDTHF%R4LES = 32.19_JPRB
      YDTHF%R2ES = 611.21_JPRB*YDCST%RD/YDCST%RV
    ENDIF
    IF (ZERO_MELT) YDCST%RLMLT = 0.0_JPRB
    YDCST%RLSTT = YDCST%RLVTT + YDCST%RLMLT
    YDCST%RETV = YDCST%RV/YDCST%RD - 1.0_JPRB
    YDTHF%R3IES = 22.587_JPRB
    YDTHF%R4IES = -0.7_JPRB
    YDTHF%R5LES = YDTHF%R3LES*(YDCST%RTT - YDTHF%R4LES)
    YDTHF%R5IES = YDTHF%R3IES*(YDCST%RTT - YDTHF%R4IES)
    YDTHF%R5ALVCP = YDTHF%R5LES*YDCST%RLVTT/YDCST%RCPD
    YDTHF%R5ALSCP = YDTHF%R5IES*YDCST%RLSTT/YDCST%RCPD
    YDTHF%RALVDCP = YDCST%RLVTT/YDCST%RCPD
    YDTHF%RALSDCP = YDCST%RLSTT/YDCST%RCPD
    YDTHF%RALFDCP = YDCST%RLMLT/YDCST%RCPD
    YDTHF%RTWAT = YDCST%RTT
    YDTHF%RTBER = YDCST%RTT - 5.0_JPRB
    YDTHF%RTBERCU = YDCST%RTT - 5.0_JPRB
    YDTHF%RTICE = YDCST%RTT - 23.0_JPRB
    YDTHF%RTICECU = YDCST%RTT - RTICECU_OFF
    YDTHF%RTWAT_RTICE_R = 1.0_JPRB/(YDTHF%RTWAT - YDTHF%RTICE)
    YDTHF%RTWAT_RTICECU_R = 1.0_JPRB/(YDTHF%RTWAT - YDTHF%RTICECU)
    YDTHF%RKOOP1 = 2.583_JPRB
    YDTHF%RKOOP2 = 0.48116E-2_JPRB

    ! yoecumf defaults, sucumf.F90:127-250 (RPLRG = RPLDARE = 1)
    ASSOCIATE(C => YEC%YRECUMF)
    C%DETRPEN = 0.75E-4_JPRB
    C%ENTRORG = 1.75E-3_JPRB
    C%ENTR_RH = 1.0_JPRB
    C%ENTSHALP = 2.0_JPRB
    C%ENTSTPC1 = 0.8_JPRB
    C%ENTSTPC2 = 2.E-4_JPRB
    C%ENTSTPC3 = 3.0_JPRB
    C%ENTRDD = 3.0E-4_JPRB
    C%RMFCMIN = 1.E-8_JPRB
    C%RMFDEPS = 0.30_JPRB
    C%RDEPTHS = 2.E4_JPRB
    C%RPRCON = 1.4E-3_JPRB
    C%RCUCOV = 0.05_JPRB
    C%RCPECONS = 5.44E-4_JPRB/YDCST%RG
    IF (ZERO_EVAP) C%RCPECONS = 0.0_JPRB
    C%RCVRFACTOR = 5.09E-3_JPRB
    C%RTAUMEL = 5._JPRB*3.6E3_JPRB*0.66_JPRB
    C%RHEBC = 0.92_JPRB
    C%RTAUA = 1.0_JPRB
    C%LMFPEN = LMFPEN
    C%LMFSCV = LMFSCV
    C%LMFMID = LMFMID
    C%LMFDD = LMFDD
    C%LMFDUDV = LMFDUDV
    C%LMFDSNOW = LMFDSNOW
    C%LMFWETB = .TRUE.
    C%LMFGLAC = LMFGLAC
    C%LSCVLIQ = .TRUE.
    C%LMFUVDIS = .TRUE.
    C%LMFENTHCONS = .FALSE.
    C%LMFCUCA = .FALSE.
    C%LMFPROFP = .FALSE.
    C%LNEWTAU = .FALSE.
    C%RXMIN = 4._JPRB
    C%RTAULIM = 1.2_JPRB
    C%RTAUFAC = 30._JPRB
    C%RMFSOLUV = 1.0_JPRB
    C%RMFSOLTQ = 1.0_JPRB
    C%RMFSOLCT = 1.0_JPRB
    C%RMFSOLRHS = 0.0_JPRB
    C%RMFADVW = 0.0_JPRB
    C%RMFADVWDD = 0.0_JPRB
    C%LMFSMOOTH = .FALSE.
    C%LMFWSTAR = .FALSE.
    C%RCAPDCYCL = 2.0_JPRB
    C%RCAPQADV = 0.8_JPRB
    C%RMINCAPE = 0.05_JPRB
    C%RMFLIA = 2.0_JPRB
    C%RMFCFL = 3.0_JPRB
    C%RUVPER = 0.3_JPRB
    C%RBASE0 = 25.E3_JPRB
    C%RMINCIN = -1000.0_JPRB
    END ASSOCIATE
  END SUBROUTINE SET_CONSTANTS

END PROGRAM DRIVER
