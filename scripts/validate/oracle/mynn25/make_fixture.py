"""Generate tests/atmosphere/oracle_fixtures/mynn25.npz by RUNNING the WRF
v4.8.0 MYNN-EDMF oracle (phys/MYNN-EDMF/module_bl_mynnedmf.F90::mynnedmf,
level-2.5 closure, WRF namelist defaults for every other option; see
mynn_driver.F90 for the exact option list).

usage:
  python make_fixture.py constants <dir>/module_model_constants.F90
  bash build.sh <WRF v4.8.0> <build> <dir>/module_model_constants.F90
  python make_fixture.py run --audit <ysu_pbl/inputs.npz> \
      --ci <WRF>/phys/MYNN-EDMF/tests/data --build <build> \
      --out tests/atmosphere/oracle_fixtures/mynn25.npz

Columns (two groups, one per vertical grid):
* ``l32``: the 20 L32 columns of the tier-2 YSU audit (this lane's column set:
  3 real MPAS checkpoint columns + 17 constructed soundings, with the audit's
  constructed surface fluxes, friction velocity and land/water flag; dt =
  1200 s as there), plus 4 variants that reach branches the 20 do not:
  an ice/supercooled-cloud copy of ``all_snow_land``, a stratocumulus copy of
  ``trop_ocean_deep`` (cloud water in the boundary layer), a strong-wind copy
  of ``neutral_windy`` (lowest-level wind 25 m/s over water: the hurricane
  tapers) and a resolved-updraft copy of ``midlat_land_summer``
  (w = 2 m/s below 1.5 km: the mass-flux shut-off).  The audit has no skin
  temperature; it is constructed from the surface heat flux with the neutral
  log law, th_sfc = th1 + hfx/(rho1*cp*ust)/karman*ln(z1/z0) (ust floored at
  0.01 m/s), ts = th_sfc*exner1.  Grid spacing dx = 100 km, except
  ``midlat_land_summer`` and its copy at 8 km (the 4-16 km grey-zone blend
  of the mixing length).
* ``l65``: records 5, 12, 20 of the MYNN-EDMF CI case ``input_clr.nc`` (land,
  clear) and 5, 9, 17 of ``input_marine_StCu.nc`` (water, stratocumulus with
  resolved updrafts), as the CI test reads them (dt = 18 s, dx = 3 km).
Specific contents are passed (the WRF driver's mixing-ratio conversion is not
called).  Each column is integrated 3 steps (driver): step 1 is the cold start
(initflag = 1), steps 2-3 carry the turbulence state.  The fixture keeps the
inputs and outputs of steps 1 and 3 and the intermediate fields of step 3 (dump
build); the generator checks that the dump build's outputs are bitwise those
of the unmodified build.  Constants handed to the oracle (its host module
module_model_constants) are legoESM's.
"""
from __future__ import annotations

import argparse
import hashlib
import tempfile
import subprocess
import sys
from pathlib import Path

import numpy as np

from legoesm import constants as C

ORACLE = dict(repo="wrf-model/WRF", tag="v4.8.0",
              sha="06d4240ae989cc3e50af412bb472df3d9048783c",
              mynn_edmf_sha="8f8e8b59021249949c04d1686edc5a02ca325627",
              files=["phys/MYNN-EDMF/module_bl_mynnedmf.F90",
                     "phys/MYNN-EDMF/WRF/module_bl_mynnedmf_common.F90",
                     "phys/ccpp_kind_types.F"])
NSTEP = 3
KEEP_STEPS = (1, 3)
DUMP_STEP = 3
LEV_IN = ("dz", "u", "v", "w", "th", "p", "exner", "rho", "sqv", "sqc", "sqi")
SFC_IN = ("dt", "dx", "xland", "ps", "ts", "ust", "hfx", "qfx", "wspd")


def write_constants(path):
    """Host constants for module_bl_mynnedmf_common (USEd from
    module_model_constants), legoESM values; the three saturation-pressure
    coefficients svp1-3 are USEd but never referenced by MYNN-EDMF."""
    vals = dict(karman=C.kappa_von_karman, g=C.g, p1000mb=C.p_ref, cp=C.c_pd, r_d=C.R_d,
                r_v=C.R_v, rcp=C.R_d / C.c_pd, xlv=C.L_v, xlf=C.L_f, xls=C.L_s,
                svp1=0.0, svp2=0.0, svp3=0.0, p608=C.R_v / C.R_d - 1.0,
                ep_2=C.R_d / C.R_v, rvovrd=C.R_v / C.R_d, cpv=C.c_pv, cliq=C.c_pw,
                cice=C.c_pi, svpt0=C.T_freeze)
    lines = ["! generated by make_fixture.py from legoesm.constants",
             "module module_model_constants", "  implicit none"]
    lines += [f"  real(8), parameter :: {k} = {float(v)!r}_8" for k, v in vals.items()]
    lines += ["end module module_model_constants", ""]
    Path(path).write_text("\n".join(lines))


def _rho(p, T, q):
    return p / (C.R_d * T * (1.0 + (C.R_v / C.R_d - 1.0) * q))


def audit_columns(src):
    """The 20 audit columns + 4 variants, bottom-up, as driver inputs."""
    names = [str(n) for n in src["names"]]
    cols = []
    for i, nm in enumerate(names):
        T = src["T"][i][::-1].astype(float)
        q = src["q"][i][::-1].astype(float)
        p = src["p_full"][i][::-1].astype(float)
        ex = (p / C.p_ref) ** (C.R_d / C.c_pd)
        zi = src["zi"][i][::-1].astype(float)
        dz = np.diff(zi)
        th = T / ex
        rho = _rho(p, T, q)
        ust = float(src["ust"][i])
        hfx = float(src["shflx"][i])
        z0 = float(src["z0"][i])
        z1 = 0.5 * dz[0]
        th_sfc = th[0] + hfx / (rho[0] * C.c_pd * max(ust, 0.01)) / C.kappa_von_karman * np.log(z1 / z0)
        cols.append(dict(name=nm, dt=float(src["dt"]), dx=100.0e3,
                         xland=float(src["xland"][i]), ps=float(src["psfc"][i]),
                         ts=th_sfc * ex[0], ust=ust, hfx=hfx, qfx=float(src["qflx"][i]),
                         wspd=float(src["wspd"][i]), dz=dz,
                         u=src["u"][i][::-1].astype(float), v=src["v"][i][::-1].astype(float),
                         w=np.zeros_like(T), th=th, p=p, exner=ex, rho=rho, sqv=q,
                         sqc=np.zeros_like(T), sqi=np.zeros_like(T)))
    by = {c["name"]: c for c in cols}
    by["midlat_land_summer"]["dx"] = 8.0e3

    def copy(base, new):
        c = {k: (v.copy() if isinstance(v, np.ndarray) else v) for k, v in by[base].items()}
        c["name"] = new
        cols.append(c)
        return c

    zc = lambda c: np.cumsum(c["dz"]) - 0.5 * c["dz"]          # full-level heights
    # ice + supercooled liquid aloft
    c = copy("all_snow_land", "all_snow_land_ice")
    z = zc(c)
    c["sqi"][(z > 3000.0) & (z < 6000.0)] = 5.0e-5
    c["sqc"][(z > 1500.0) & (z < 2500.0)] = 1.0e-4
    # stratocumulus layer: cloud water and saturated vapour in the top of the PBL
    c = copy("trop_ocean_deep", "trop_ocean_deep_stcu")
    z = zc(c)
    lay = (z > 600.0) & (z < 1100.0)
    c["sqc"][lay] = 3.0e-4
    # strong wind over water
    c = copy("neutral_windy", "neutral_windy_strong")
    c["u"] = c["u"] * (25.0 / c["u"][0])
    c["wspd"] = 25.0
    # resolved updraft in the PBL
    c = copy("midlat_land_summer", "midlat_land_summer_w")
    c["w"][zc(c) < 1500.0] = 2.0
    return cols


def ci_columns(ci_dir):
    import netCDF4
    cols = []
    for case, recs in (("clr", (5, 12, 20)), ("marine_StCu", (5, 9, 17))):
        n = netCDF4.Dataset(Path(ci_dir) / f"input_{case}.nc")
        g = lambda k, t: np.asarray(n[k][t], float).ravel()
        for t in recs:
            qv = g("QVAPOR", t); qc = g("QCLOUD", t); qi = g("QICE", t)
            cols.append(dict(
                name=f"ci_{case}_t{t}", dt=18.0, dx=3000.0, xland=g("XLAND", t)[0],
                ps=g("PSFC", t)[0], ts=g("TSK", t)[0], ust=g("UST", t)[0],
                hfx=g("HFX", t)[0], qfx=g("QFX", t)[0], wspd=g("WSPD", t)[0],
                dz=g("dz", t), u=g("U_mass", t), v=g("V_mass", t), w=g("W_mass", t),
                th=g("TH", t), p=g("PTOTAL", t), exner=g("EXNER", t), rho=g("RHO", t),
                # the CI files hold WRF mixing ratios; specific contents, as the
                # WRF driver's mynnedmf_pre_run converts them
                sqv=qv / (1.0 + qv), sqc=qc / (1.0 + qv), sqi=qi / (1.0 + qv)))
    return cols


def write_input(path, cols):
    nlev = len(cols[0]["dz"])
    with open(path, "w") as f:
        f.write(f"{len(cols)} {nlev} {NSTEP}\n")
        for c in cols:
            assert len(c["dz"]) == nlev
            f.write(" ".join(repr(float(c[k])) for k in SFC_IN) + "\n")
            for k in LEV_IN:
                f.write(" ".join(repr(float(x)) for x in c[k]) + "\n")


def parse(text):
    """{(col, step): {name: array}}"""
    out, cur = {}, None
    for line in text.splitlines():
        t = line.split()
        if not t:
            continue
        if t[0] == "step":
            cur = out.setdefault((int(t[1]) - 1, int(t[2])), {})
        elif t[0] in ("dims", "END_OK"):
            continue
        else:
            n = int(t[1])
            cur[t[0]] = np.array([float(x) for x in t[2:2 + n]])
    return out


def run(driver, cols, tmp):
    inp = Path(tmp) / "in.txt"
    write_input(inp, cols)
    r = subprocess.run([str(driver)], stdin=open(inp), capture_output=True, text=True)
    if r.returncode != 0 or "END_OK" not in r.stdout:
        sys.exit(f"oracle failed: {r.returncode}\n{r.stderr[-3000:]}")
    return parse(r.stdout)


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("constants")
    a.add_argument("path")
    b = sub.add_parser("run")
    b.add_argument("--audit", required=True)
    b.add_argument("--ci", required=True)
    b.add_argument("--build", required=True)
    b.add_argument("--out", required=True)
    args = ap.parse_args()
    if args.cmd == "constants":
        write_constants(args.path)
        return
    tmp = tempfile.mkdtemp(prefix="mynn25_oracle_")
    fix = {}
    meta = dict(ORACLE)
    meta["audit_sha256"] = hashlib.sha256(Path(args.audit).read_bytes()).hexdigest()
    groups = (("l32", audit_columns(np.load(args.audit))), ("l65", ci_columns(args.ci)))
    for g, cols in groups:
        orig = run(Path(args.build) / "orig" / "mynn_driver", cols, tmp)
        dump = run(Path(args.build) / "dump" / "mynn_driver", cols, tmp)
        for key, rec in orig.items():
            for k, v in rec.items():
                assert np.array_equal(np.asarray(dump[key][k]), np.asarray(v)), (g, key, k)
        fix[f"{g}_names"] = np.array([c["name"] for c in cols])
        for s in KEEP_STEPS:
            ks = sorted(orig[(0, s)])
            for k in ks:
                fix[f"{g}_s{s}_{k}"] = np.stack([np.atleast_1d(orig[(c, s)][k])
                                                 for c in range(len(cols))])
        for k in sorted(x for x in dump[(0, DUMP_STEP)] if x.startswith("dump_")):
            fix[f"{g}_s{DUMP_STEP}_{k}"] = np.stack([np.atleast_1d(dump[(c, DUMP_STEP)][k])
                                                     for c in range(len(cols))])
    fix["meta"] = np.array(repr(meta))
    np.savez_compressed(args.out, **fix)
    print("wrote", args.out, Path(args.out).stat().st_size, "bytes,", len(fix), "arrays")


if __name__ == "__main__":
    main()
