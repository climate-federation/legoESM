! Minimal stand-ins for the OpenIFS 49r1 modules that GWDRAG_WMS/SUGWWMS,
! O3CHEM and METHOX/SUMETHOX use but that are not part of those schemes.
! Each type carries ONLY the members those routines reference.  Values are
! the 49r1 code defaults (source line in the comment) or set by the driver.
! YOEGWWMS, YOEGWD, YOEMETH, YOMOZO and YOMCST are the real 49r1 modules.
MODULE PARKIND1
  INTEGER, PARAMETER :: JPIM = SELECTED_INT_KIND(9)
  INTEGER, PARAMETER :: JPIB = SELECTED_INT_KIND(12)
  INTEGER, PARAMETER :: JPRD = SELECTED_REAL_KIND(13, 300)
  INTEGER, PARAMETER :: JPRB = JPRD
  INTEGER, PARAMETER :: JPRM = SELECTED_REAL_KIND(6, 37)
  INTEGER, PARAMETER :: JPHOOK = JPRD
  INTEGER, PARAMETER :: JPLM = KIND(.TRUE.)
END MODULE PARKIND1

