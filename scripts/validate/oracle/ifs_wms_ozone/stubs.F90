SUBROUTINE POSNAM(KULNAM, CDNAML)
  ! Rewind and skip to the group, as the IFS POSNAM does.
  INTEGER, INTENT(IN) :: KULNAM
  CHARACTER(LEN=*), INTENT(IN) :: CDNAML
  CHARACTER(LEN=256) :: CL
  INTEGER :: IOS
  REWIND(KULNAM)
  DO
    READ(KULNAM, '(A)', IOSTAT=IOS) CL
    IF (IOS /= 0) THEN
      WRITE(0, *) 'POSNAM: group not found ', CDNAML; STOP 2
    ENDIF
    IF (INDEX(CL, '&'//TRIM(CDNAML)) > 0) THEN
      BACKSPACE(KULNAM); RETURN
    ENDIF
  ENDDO
END SUBROUTINE POSNAM

