! Oracle driver: OpenIFS 49r1 (8f6f722) non-orographic GWD (SUGWWMS +
! GWDRAG_WMS), Cariolle ozone chemistry (O3CHEM) and methane oxidation
! (SUMETHOX + METHOX), all compiled unchanged.
!
! Settings: 49r1 SUGWWMS / SUMETHOX defaults (empty NAMGWWMS / NAMMETHOX
! groups); GSSEC = 1e-12 (sugwd.F90:161); O3CHEM flags = su0phy defaults
! (stubs.F90); one launch level (KLAUNCH = 1, the 49r1 NLAUNCHLEV) at
! PTSTEP = GTPHYGWWMS, as gwdragwms_layer.F90 calls it.
! Constants: 49r1 SETUP_CONSTANTS; CONST_MODE = 1 then overwrites the module
! RG/RD/RCPD/RA the routines read with the harness namelist values
! (legoESM constants); CONST_MODE = 2 keeps the 49r1 values.
! usage: driver.x <input text dir> <output text dir> <harness namelist>
PROGRAM DRIVER
USE PARKIND1, ONLY : JPIM, JPRB
USE YOMLUN, ONLY : NULNAM
USE YOMCST, ONLY : SETUP_CONSTANTS, TCST_INIT, YRCST, RG, RD, RCPD, RA, RPI, RDAYI, RHOUR
USE YOEGWWMS, ONLY : TEGWWMS
USE YOEGWD, ONLY : TEGWD
USE YOEMETH, ONLY : RQLIM
USE YOMOZO, ONLY : TOZO
USE YOEPHY, ONLY : TEPHY
USE YOMRIP, ONLY : TRIP
USE YOMPHY2, ONLY : TPHY2
USE YOMSTA, ONLY : TSTA
USE YOMDIMV, ONLY : TDIMV
IMPLICIT NONE
CHARACTER(LEN=512) :: CIN, COUT, CNML
CHARACTER(LEN=8) :: MODE
INTEGER(KIND=JPIM) :: CONST_MODE, KLON, KLEV
REAL(KIND=JPRB) :: CRG, CRD, CRCPD, CRA, TSTEP, RDECLI, RQLIM_OVR, TEECL2
NAMELIST /HARNESS/ MODE, CONST_MODE, CRG, CRD, CRCPD, CRA, TSTEP, RDECLI, RQLIM_OVR, TEECL2
TYPE(TEGWWMS) :: YDEGWWMS
TYPE(TEGWD) :: YDEGWD
TYPE(TOZO) :: YDOZO
TYPE(TEPHY) :: YDEPHY
TYPE(TRIP) :: YDRIP
TYPE(TPHY2) :: YDPHY2
TYPE(TSTA) :: YDSTA
TYPE(TDIMV) :: YDDIMV
REAL(KIND=JPRB), ALLOCATABLE, DIMENSION(:,:) :: PT, PU, PV, PAP, PAPH, PGEO, PQ, PO3, PDELP, &
  & PTENU, PTENV, PFLUXU, PFLUXV, PTEN
REAL(KIND=JPRB), ALLOCATABLE :: PKOZO(:,:,:), PGELAT(:), PGAW(:), PPRECIP(:), PGEMU(:), PMU0(:), &
  & F1(:)

CALL GET_COMMAND_ARGUMENT(1, CIN); CALL GET_COMMAND_ARGUMENT(2, COUT); CALL GET_COMMAND_ARGUMENT(3, CNML)
OPEN(NULNAM, FILE=TRIM(CNML), STATUS='OLD', ACTION='READ')
RQLIM_OVR = -1.0_JPRB; TEECL2 = 0.0_JPRB; RDECLI = 0.0_JPRB
CALL POSNAM(NULNAM, 'HARNESS'); READ(NULNAM, NML=HARNESS)

CALL SETUP_CONSTANTS(6, 0)
WRITE(6, '(A,6ES25.17)') 'CONST_49R1 RG RD RCPD RA RPI RDAYI ', RG, RD, RCPD, RA, RPI, RDAYI
IF (CONST_MODE == 1) THEN
  YRCST%RG = CRG; YRCST%RD = CRD; YRCST%RCPD = CRCPD; YRCST%RA = CRA
  CALL TCST_INIT(YRCST)     ! copies YRCST into the PROTECTED module variables
ELSEIF (CONST_MODE /= 2) THEN
  STOP 'CONST_MODE'
ENDIF
WRITE(6, '(A,6ES25.17)') 'CONST_USED RG RD RCPD RA RPI RDAYI ', RG, RD, RCPD, RA, RPI, RDAYI
CALL WS('RHOUR', RHOUR)
KLON = NINT(SCALAR('KLON')); KLEV = NINT(SCALAR('KLEV'))

SELECT CASE (TRIM(MODE))
CASE ('WMS')
  YDDIMV%NFLEVG = KLEV
  YDRIP%TSTEP = TSTEP
  CALL R1K('STPRE', YDSTA%STPRE, KLEV)
  CALL SUGWWMS(YDSTA, YDDIMV, YDEGWWMS, YDRIP)
  YDEGWD%GSSEC = 1.E-12_JPRB                       ! sugwd.F90:161
  CALL R2('PT', PT); CALL R2('PU', PU); CALL R2('PV', PV); CALL R2('PAP', PAP)
  CALL R2('PAPH', PAPH); CALL R2('PGEO', PGEO)
  CALL R1('PGELAT', PGELAT); CALL R1('PGAW', PGAW); CALL R1('PPRECIP', PPRECIP)
  ALLOCATE(PTENU(KLON,KLEV), PTENV(KLON,KLEV), PFLUXU(KLON,KLEV+1), PFLUXV(KLON,KLEV+1))
  CALL GWDRAG_WMS(YDSTA, YDEGWD, YDEGWWMS, 1, KLON, KLON, KLEV, 1, YDEGWWMS%GTPHYGWWMS, &
    & PT, PU, PV, PAP, PAPH, PGEO, PGELAT, PGAW, PPRECIP, PTENU, PTENV, PFLUXU, PFLUXV)
  CALL WS('NLAUNCH', REAL(YDEGWWMS%NLAUNCHL(1), JPRB))
  CALL WS('GTPHYGWWMS', YDEGWWMS%GTPHYGWWMS)
  CALL W2('PTENU', PTENU); CALL W2('PTENV', PTENV)
  CALL W2('PFLUXU', PFLUXU); CALL W2('PFLUXV', PFLUXV)
CASE ('O3CHEM')
  YDPHY2%TSPHY = TSTEP
  YDRIP%RDECLI = RDECLI
  YDOZO%TEECL2 = TEECL2
  CALL R2('PAPH', PAPH); CALL R2('PAP', PAP); CALL R2('PDELP', PDELP)
  CALL R2('PT', PT); CALL R2('PO3', PO3); CALL R3('PKOZO', PKOZO, 8)
  CALL R1('PGEMU', PGEMU); CALL R1('PMU0', PMU0)
  ALLOCATE(PTEN(KLON,KLEV))
  CALL O3CHEM(YDRIP, YDEPHY, YDOZO, YDPHY2, 1, KLON, KLON, 1, KLEV, 8, PGEMU, PMU0, &
    & PAPH, PAP, PKOZO, PDELP, PT, PO3, PTEN)
  CALL W2('PTENO3', PTEN)
CASE ('METHOX')
  CALL SUMETHOX
  CALL WS('RQLIM_SUMETHOX', RQLIM)
  IF (RQLIM_OVR >= 0.0_JPRB) RQLIM = RQLIM_OVR
  CALL WS('RQLIM', RQLIM)
  CALL R2('PQ', PQ); CALL R2('PAP', PAP)
  ALLOCATE(PTEN(KLON,KLEV))
  CALL METHOX(1, KLON, KLON, KLEV, PQ, PTEN, PAP)
  CALL W2('PTENQ', PTEN)
CASE DEFAULT
  STOP 'MODE'
END SELECT
WRITE(6, *) 'DRIVER_DONE ', TRIM(MODE)

CONTAINS

  SUBROUTINE RALL(NAME, EXT, FLAT)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    INTEGER, INTENT(OUT) :: EXT(3)
    REAL(KIND=JPRB), ALLOCATABLE, INTENT(OUT) :: FLAT(:)
    INTEGER :: U, RNK, I, IOS
    OPEN(NEWUNIT=U, FILE=TRIM(CIN)//'/'//NAME//'.txt', STATUS='OLD', ACTION='READ', IOSTAT=IOS)
    IF (IOS /= 0) THEN
      WRITE(0, *) 'missing input ', NAME; STOP 4
    ENDIF
    EXT = 1
    READ(U, *) RNK; BACKSPACE(U); READ(U, *) RNK, (EXT(I), I = 1, RNK)
    ALLOCATE(FLAT(PRODUCT(EXT))); READ(U, *) FLAT; CLOSE(U)
  END SUBROUTINE RALL

  REAL(KIND=JPRB) FUNCTION SCALAR(NAME)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    INTEGER :: E(3); REAL(KIND=JPRB), ALLOCATABLE :: F(:)
    CALL RALL(NAME, E, F); SCALAR = F(1)
  END FUNCTION SCALAR

  SUBROUTINE R1(NAME, A)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), ALLOCATABLE, INTENT(OUT) :: A(:)
    CALL R1K(NAME, A, KLON)
  END SUBROUTINE R1

  SUBROUTINE R1K(NAME, A, N)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), ALLOCATABLE, INTENT(OUT) :: A(:)
    INTEGER(KIND=JPIM), INTENT(IN) :: N
    INTEGER :: E(3); REAL(KIND=JPRB), ALLOCATABLE :: F(:)
    CALL RALL(NAME, E, F); IF (E(1) /= N) STOP 'R1 SHAPE'; A = F
  END SUBROUTINE R1K

  SUBROUTINE R2(NAME, A)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), ALLOCATABLE, INTENT(OUT) :: A(:,:)
    INTEGER :: E(3); REAL(KIND=JPRB), ALLOCATABLE :: F(:)
    CALL RALL(NAME, E, F); IF (E(1) /= KLON) STOP 'R2 SHAPE'; A = RESHAPE(F, E(1:2))
  END SUBROUTINE R2

  SUBROUTINE R3(NAME, A, N3)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), ALLOCATABLE, INTENT(OUT) :: A(:,:,:)
    INTEGER, INTENT(IN) :: N3
    INTEGER :: E(3); REAL(KIND=JPRB), ALLOCATABLE :: F(:)
    CALL RALL(NAME, E, F); IF (E(1) /= KLON .OR. E(3) /= N3) STOP 'R3 SHAPE'; A = RESHAPE(F, E)
  END SUBROUTINE R3

  SUBROUTINE WOUT(NAME, F, E)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), INTENT(IN) :: F(:)
    INTEGER, INTENT(IN) :: E(:)
    INTEGER :: U, I
    OPEN(NEWUNIT=U, FILE=TRIM(COUT)//'/'//NAME//'.txt', STATUS='REPLACE', ACTION='WRITE')
    WRITE(U, *) SIZE(E), E
    DO I = 1, SIZE(F)
      WRITE(U, '(ES26.17E3)') F(I)
    ENDDO
    CLOSE(U)
  END SUBROUTINE WOUT

  SUBROUTINE WS(NAME, V)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), INTENT(IN) :: V
    CALL WOUT(NAME, [V], [1])
  END SUBROUTINE WS

  SUBROUTINE W2(NAME, A)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), INTENT(IN) :: A(:,:)
    CALL WOUT(NAME, RESHAPE(A, [SIZE(A)]), SHAPE(A))
  END SUBROUTINE W2

END PROGRAM DRIVER
