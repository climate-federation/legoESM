def mfcc_table(pgwv):
    t = np.random.default_rng(MFCC_SEED).uniform(0.0, MFCC_HI, size=(MAXH, 2 * MAXUH + 1, 2 * pgwv + 1))
    t[:, :, pgwv] = 0.0
    return t


# ---- column construction (tier-2 audit build_inputs.py) ----
def winds(p_full, au, av):
    lp = np.log(p_full)
    out = []
    for an in (au, av):
        a = np.array(an, float)
        i = np.argsort(a[:, 0])
        out.append(np.interp(lp, np.log(a[i, 0] * 100.0), a[i, 1]))
    return out


def temp_profile(p_full, ps, Ts, Ttrop, inv_dT=0.0, inv_dp=4000.0, strat_lapse=12.0):
    T = Ts * (p_full / ps) ** (constants.R_d * 6.5e-3 / constants.g)
    T = np.maximum(T, Ttrop)
    T = np.where(p_full < 10000.0, Ttrop + strat_lapse * np.log(10000.0 / p_full), T)
    return T - inv_dT * np.clip(1.0 - (ps - p_full) / inv_dp, 0.0, None)


def heating(z, kind, peak_kday):
    if kind == "none":
        return np.zeros_like(z)
    zb, zt = {"deep": (1000.0, 14000.0), "mid": (1200.0, 7500.0),
              "shallow": (400.0, 1900.0), "deep_uniform": (900.0, 11000.0)}[kind]
    h = np.where((z > zb) & (z < zt), np.sin(np.pi * (z - zb) / (zt - zb)), 0.0)
    h = np.where(z <= zb, -0.15, h)
    return peak_kday * h / DAY


def frontgf_profile(p_full, amp):
    return amp * np.exp(-((p_full - 60000.0) / 15000.0) ** 2)


