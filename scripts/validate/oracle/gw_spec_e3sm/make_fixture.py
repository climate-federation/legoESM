"""Generate tests/atmosphere/oracle_fixtures/gw_spec_e3sm.npz by RUNNING the
E3SM v3.0.1 spectral gravity-wave-drag oracle (E3SM-Project/E3SM tag v3.0.1,
SHA d4ca7d0606930f53f30eb7ff7dbb92ec83b83b84: gw_prof, gw_cm_src,
gw_beres_src, gw_oro_src, gw_drag_prof with gw_ediff, the C.-C. Chen
momentum_energy_conservation fixer and the gw_drag.F90 orographic closure,
compiled unmodified by ``build.sh``; driver ``driver.F90`` mirrors gw_init
and the gw_tend source sequence).

The oracle runs at its OWN settings: the Newtonian alpha profile interpolated
by E3SM ``lininterp`` onto ``pref_edge`` (alpha_mode 1), the level indices
kbotbg / kfront / k700 computed by E3SM's gw_init rules from ``pref_edge``
(kmode 0), and kwv = 6.28e-5 (the gw_drag.F90 parameter).  legoESM's g, R_d
and c_pd are fed to the oracle (legoESM R_d vs E3SM shr_const rair is a
repo-wide constant difference of 2.6e-5 relative, not part of this scheme).

Columns (the tier-2 audit set, oracle_audit/nonorographic_gwd_e3sm_cam
py/build_inputs.py): ``l36`` = 8 constructed soundings on the sigma L36 grid of
config/amip/amip_sundqvist_l36.yaml (sigma_top 0.002, l30_trop_logstrat) at
realistic surface pressure; ``l32`` = 3 real T/q/p columns (legoESM fixture
zm_cam6_real_zero_humidity_columns.npz, MPAS AMIP, CAM6 L32) with constructed
winds, heating and frontogenesis.  z_full, z_half and rho come from the
production helpers, as ``_make_mpas_gwd`` builds them.  ``pref_edge`` is the
coordinate at ``constants.p_ref`` (``reference_interface_pressures``).

The Beres arms use a HARNESS mfcc table (not E3SM data): uniform random
[0, 4e7) from ``numpy.random.default_rng(20261019)``, centre bin zeroed,
sized so realistic heating launches O(1e-3) Pa.  It is regenerated by the
test from the seed (its sha256 is stored) to keep the fixture small.

For datasets with a nonzero surface geopotential the oracle also runs with
dse = c_p*T + g*z (phis dropped, legoESM's convention) -> ``ptend_s_nophis``.

    bash build.sh /path/to/E3SM_v3.0.1 /tmp/gwspec_build
    python make_fixture.py --drv /tmp/gwspec_build/gw_spec_oracle \
        --out tests/atmosphere/oracle_fixtures/gw_spec_e3sm.npz
"""
