def _finish(rows, pref):
    P = lambda k: np.stack([r[k] for r in rows])
    p_half, p_full, T, q = (P(k) for k in ("p_half", "p_full", "T", "q"))
    u, v = P("u"), P("v")
    z_full, z_half = (np.asarray(x) for x in compute_heights_from_sigma(T, p_half, q_v=q))
    rho = np.asarray(compute_rho(T, p_full, q_v=q))
    return dict(names=np.array([r["name"] for r in rows]), p_half=p_half, p_full=p_full,
                T=T, q=q, u=u, v=v, z_full=z_full, z_half=z_half, rho=rho,
                netdt=np.stack([heating(z_full[i], *r["heat"]) for i, r in enumerate(rows)]),
                frontgf=np.stack([frontgf_profile(p_full[i], r["fg"]) for i, r in enumerate(rows)]),
                lat=np.array([r["lat"] for r in rows], float),
                sgh=np.full(len(rows), 300.0), lf=np.ones(len(rows)),
                phis=constants.g * np.array([r.get("zs", 0.0) for r in rows]),
                pref_edge=np.asarray(pref, float))


def build_l36():
    sc = create_sigma_coordinate(36, 0.002, dtype=jnp.float64, layout="l30_trop_logstrat")
    rows = []
    for c in L36:
        ps = c["ps"] * 100.0
        p_half = np.asarray(sc.pressure_at_half(jnp.asarray([ps])))[0]
        p_full = np.asarray(sc.pressure_at_full(jnp.asarray([ps])))[0]
        T = temp_profile(p_full, ps, c["Ts"], c["Ttrop"], c.get("inv_dT", 0.0),
                         c.get("inv_dp", 4000.0), c.get("strat_lapse", 12.0))
        qs = np.asarray(saturation_mixing_ratio(T, p_full))
        q = np.where(p_full < 10000.0, 3e-6, c["rh"] * qs / (1.0 + c["rh"] * qs))
        u, v = winds(p_full, c["u"], c["v"])
        rows.append(dict(c, p_half=p_half, p_full=p_full, T=T, q=q, u=u, v=v))
    return _finish(rows, reference_interface_pressures(sc, jnp.float64))


def build_l32():
    coord = make_cam6_l32_levels()
    fx = np.load(REAL_FX)
    rows = []
    for j, (nm, lat, au, av, heat, fg) in enumerate(L32):
        p_half = np.asarray(fx["p_half32"][j], float)
        p_full = np.asarray(coord.pressure_at_full(np.array([p_half[-1]])))[0]
        u, v = winds(p_full, au, av)
        rows.append(dict(name=nm, lat=lat, heat=heat, fg=fg, p_half=p_half, p_full=p_full,
                         T=np.asarray(fx["T32"][j], float),
                         q=np.clip(np.asarray(fx["q32"][j], float), 0, None), u=u, v=v))
    return _finish(rows, reference_interface_pressures(coord, jnp.float64))


# ---- oracle I/O (tier-2 audit harness.py, kmode 0 / alpha_mode 1) ----
def write_oracle_input(path, d, arm, mfcc):
    f = lambda a: " ".join(f"{x:.17e}" for x in np.ravel(a, order="F"))
    ncol, nlev = d["T"].shape
    srcs = arm["sources"]
    frontgfc = -1.0e300 if arm["background"] else arm.get("frontgfc", 1.0e300)
    lines = [f"{ncol} {nlev} {arm['pgwv']}",
             f(np.array([constants.g, constants.R_d, constants.c_pd, arm["dt"]])),
             f(np.array([arm["dc"], E3SM_KWV, 1.0])),
             " ".join(str(int(x)) for x in ("convective" in srcs, "frontal" in srcs,
                                            "orographic" in srcs, arm.get("efix", 0),
                                            arm["taper"])),
             f(np.array([arm.get("effgw_beres", 1.0), arm["effgw_cm"], arm.get("effgw_oro", 1.0)])),
             f(np.array([arm["taubgnd"], frontgfc, arm.get("hcf", 20.0), arm.get("hdsf", 1.0)])),
             "1 0.0", "0 -1 -1 -1", f(d["pref_edge"])]
    if "convective" in srcs:
        lines += [f"{mfcc.shape[0]} {(mfcc.shape[1] - 1) // 2}", f(mfcc)]
    dse = constants.c_pd * d["T"] + constants.g * d["z_full"] + d["phis"][:, None]
    for i in range(ncol):
        lines += [f(np.array([np.deg2rad(d["lat"][i]), d["sgh"][i], d["lf"][i]])),
                  f(d["p_half"][i]), f(d["p_full"][i]), f(d["T"][i]), f(d["u"][i]),
                  f(d["v"][i]), f(d["z_full"][i]), f(dse[i]), f(d["frontgf"][i]),
                  f(d["netdt"][i]), f(d["q"][i])]
    Path(path).write_text("\n".join(lines) + "\n")


def run_oracle(drv, d, arm, mfcc):
    with tempfile.TemporaryDirectory() as td:
        inp, out = Path(td, "in.txt"), Path(td, "out.txt")
        write_oracle_input(inp, d, arm, mfcc)
        r = subprocess.run([drv, str(inp), str(out)], capture_output=True, text=True)
        if "E3SM_SPEC_ORACLE_OK" not in r.stdout:
            raise RuntimeError(f"oracle failed: {r.stdout}\n{r.stderr}")
        rows = {}
        for line in out.read_text().splitlines():
            t = line.split()
            if t[0] in ("ptend_u", "ptend_v", "ptend_s"):
                rows.setdefault(t[0], {})[int(t[1])] = np.array([float(x) for x in t[2:]])
            elif t[0] == "kidx":
                rows["kidx"] = np.array([int(x) for x in t[1:]])
    o = {k: np.stack([v[i] for i in sorted(v)]) for k, v in rows.items() if k != "kidx"}
    o["kidx"] = rows["kidx"]
    return o


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--drv", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    data = {"l36": build_l36(), "l32": build_l32()}
    out = {}
    for ds, d in data.items():
        for k, v in d.items():
            out[f"{ds}/{k}"] = v
    meta_arms = {}
    for name, (arm, sets) in ARMS.items():
        mfcc = mfcc_table(arm["pgwv"]) if arm["mfcc"] else None
        for ds in sets:
            o = run_oracle(a.drv, data[ds], arm, mfcc)
            for k in ("ptend_u", "ptend_v", "ptend_s", "kidx"):
                out[f"{name}/{ds}/{k}"] = o[k]
            if np.any(data[ds]["phis"] != 0.0):
                # Same oracle, dse fed WITHOUT phis (legoESM's dse convention):
                # certifies the elevated columns apart from the phis round-off.
                o0 = run_oracle(a.drv, dict(data[ds], phis=0.0 * data[ds]["phis"]), arm, mfcc)
                out[f"{name}/{ds}/ptend_s_nophis"] = o0["ptend_s"]
        meta_arms[name] = dict(datasets=sets, dt=arm["dt"], ours=arm["ours"], mfcc=arm["mfcc"],
                               oracle={k: arm[k] for k in arm if k not in ("ours",)})
    tbl = mfcc_table(32)
    meta = dict(oracle=f"E3SM-Project/E3SM {E3SM_TAG} {E3SM_SHA}", kwv=E3SM_KWV,
                constants=dict(g=constants.g, R_d=constants.R_d, c_pd=constants.c_pd),
                mfcc=dict(seed=MFCC_SEED, hi=MFCC_HI, maxh=MAXH, maxuh=MAXUH, pgwv=32,
                          sha256=hashlib.sha256(tbl.tobytes()).hexdigest()),
                legoesm_sha=subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"],
                                           capture_output=True, text=True).stdout.strip(),
                gfortran=subprocess.run(["gfortran", "--version"], capture_output=True,
                                        text=True).stdout.splitlines()[0],
                arms=meta_arms)
    out["meta"] = np.array(json.dumps(meta))
    np.savez_compressed(a.out, **out)
    print("wrote", a.out, Path(a.out).stat().st_size, "bytes")
    print("FIXTURE_OK")


if __name__ == "__main__":
    main()
