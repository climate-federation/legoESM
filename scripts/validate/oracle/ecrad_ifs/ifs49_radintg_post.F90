! Harness glue between RADIATION_SCHEME and RADHEATN: the 49r1 RADINTG
! (arpifs/phys_radi/radintg.F90 at 8f6f722) statements that run on the model
! grid after the radiation call when the radiation grid IS the model grid
! (NRADRES == NSMAX: no interpolation, radintg.F90:1569 block skipped).
! Statements are copied verbatim (one block, IBEG=1, IL=KLON); each block
! carries its radintg.F90 line range. Not oracle code itself; the
! declarations are the radintg.F90 ones restricted to what these lines use.
SUBROUTINE IFS49_RADINTG_POST(KLON, KLEV, NSW, NLWOUT, LAPPROXSWUPDATE, LAPPROXLWUPDATE, &
     & ZRII0, ZAMU0, PALBD, PALBP, &
     ! radiation_scheme outputs (ZRGP slots IFRSO.. in radintg.F90:1534-1559)
     & PFRSO_IN, PFRTH_IN, PSWFC_IN, PLWFC_IN, PFRSOD_IN, PFRTED_IN, PFRSODC_IN, PFRTEDC_IN, &
     & PFDIR_IN, PCDIR_IN, PSUDU_IN, PUVDF_IN, PPARF_IN, PPARCF_IN, PTINCF_IN, PEMIT_IN, &
     & PLWDER_IN, PSWDIFFUSEBAND_IN, PSWDIRECTBAND_IN, &
     ! radintg dummy outputs (radintg.F90:20-30)
     & PEMTD, PEMTU, PTRSO, PTRSC, PEMTC, PFRTED, PTRSOD, PTRSODC, PEMTDC, PEMIT, PSUDU, &
     & PUVDF, PPARF, PPARCF, PTINCF, PFDIR, PCDIR, PLWDERIVATIVE)
USE PARKIND1, ONLY : JPIM, JPRB
IMPLICIT NONE
INTEGER(KIND=JPIM), INTENT(IN) :: KLON, KLEV, NSW, NLWOUT
LOGICAL, INTENT(IN) :: LAPPROXSWUPDATE, LAPPROXLWUPDATE
REAL(KIND=JPRB), INTENT(IN) :: ZRII0, ZAMU0(KLON), PALBD(KLON,NSW), PALBP(KLON,NSW)
REAL(KIND=JPRB), INTENT(IN) :: PFRSO_IN(KLON,KLEV+1), PFRTH_IN(KLON,KLEV+1), PSWFC_IN(KLON,KLEV+1), &
     & PLWFC_IN(KLON,KLEV+1), PFRSOD_IN(KLON), PFRTED_IN(KLON,NLWOUT), PFRSODC_IN(KLON), &
     & PFRTEDC_IN(KLON), PFDIR_IN(KLON), PCDIR_IN(KLON), PSUDU_IN(KLON), PUVDF_IN(KLON), &
     & PPARF_IN(KLON), PPARCF_IN(KLON), PTINCF_IN(KLON), PEMIT_IN(KLON), PLWDER_IN(KLON,KLEV+1), &
     & PSWDIFFUSEBAND_IN(KLON,NSW), PSWDIRECTBAND_IN(KLON,NSW)
REAL(KIND=JPRB), INTENT(OUT) :: PEMTD(KLON,KLEV+1), PEMTU(KLON,KLEV+1), PTRSO(KLON,KLEV+1), &
     & PTRSC(KLON,KLEV+1), PEMTC(KLON,KLEV+1), PFRTED(KLON,NLWOUT), PTRSOD(KLON), PTRSODC(KLON), &
     & PEMTDC(KLON), PEMIT(KLON), PSUDU(KLON), PUVDF(KLON), PPARF(KLON), PPARCF(KLON), PTINCF(KLON), &
     & PFDIR(KLON), PCDIR(KLON), PLWDERIVATIVE(KLON,KLEV+1)
! radintg.F90:414
REAL(KIND=JPRB), PARAMETER :: ZSWTOPSCALINGDEFAULT = 1.0_JPRB
REAL(KIND=JPRB) :: ZEPSILON
REAL(KIND=JPRB) :: ZFRSOD(KLON), ZFRTED(KLON,NLWOUT), ZFRSODC(KLON), ZFRTEDC(KLON), ZEMIT(KLON), &
     & ZSUDU(KLON), ZUVDF(KLON), ZPARF(KLON), ZPARCF(KLON), ZTINCF(KLON), ZFDIR(KLON), ZCDIR(KLON), &
     & ZFRSO(KLON,KLEV+1), ZSWFC(KLON,KLEV+1), ZFRTH(KLON,KLEV+1), ZLWFC(KLON,KLEV+1), &
     & ZLWDERIVATIVE(KLON,KLEV+1), ZSWDIFFUSEBAND(KLON,NSW), ZSWDIRECTBAND(KLON,NSW), &
     & ZTRSO(KLON,KLEV+1), ZEMTD(KLON,KLEV+1), ZEMTU(KLON,KLEV+1), ZTRSC(KLON,KLEV+1), &
     & ZEMTC(KLON,KLEV+1), ZTRSOD(KLON), ZTRSODC(KLON), ZEMTDC(KLON), ZSWNETCHANGE(KLON)
REAL(KIND=JPRB) :: ZBROADBANDALBEDO, ZSWDNTOP, ZSWUPTOP, ZSWDNSURF, ZSWUPSURF, ZSWDNTOPEFF, &
     & ZSWTOPSCALING, ZSWTRANSMITTANCE, ZSWREFLECTANCE, ZNEWSWNETSURF
INTEGER(KIND=JPIM) :: IL, IBEG, IEND, JL, JK

IL = KLON; IBEG = 1; IEND = KLON
! radintg.F90:484
ZEPSILON=1000._JPRB*TINY(ZEPSILON)

! radintg.F90:1870-1885 (ZRGP unpack)
ZFRSOD (1:IL)          = PFRSOD_IN(1:IL)
ZFRTED (1:IL,1:NLWOUT) = PFRTED_IN(1:IL,1:NLWOUT)
ZFRSODC(1:IL)          = PFRSODC_IN(1:IL)
ZFRTEDC(1:IL)          = PFRTEDC_IN(1:IL)
ZEMIT  (1:IL)          = PEMIT_IN(1:IL)
ZSUDU  (1:IL)          = PSUDU_IN(1:IL)
ZUVDF  (1:IL)          = PUVDF_IN(1:IL)
ZPARF  (1:IL)          = PPARF_IN(1:IL)
ZPARCF (1:IL)          = PPARCF_IN(1:IL)
ZTINCF (1:IL)          = PTINCF_IN(1:IL)
ZFDIR  (1:IL)          = PFDIR_IN(1:IL)
ZCDIR  (1:IL)          = PCDIR_IN(1:IL)
ZFRSO  (1:IL,1:KLEV+1) = PFRSO_IN(1:IL,1:KLEV+1)
ZSWFC  (1:IL,1:KLEV+1) = PSWFC_IN(1:IL,1:KLEV+1)
ZFRTH  (1:IL,1:KLEV+1) = PFRTH_IN(1:IL,1:KLEV+1)
ZLWFC  (1:IL,1:KLEV+1) = PLWFC_IN(1:IL,1:KLEV+1)

! radintg.F90:1891-1892
ZFRSOD(1:IL)  = MAX(ZFRSO(1:IL,KLEV+1), ZFRSOD(1:IL))
ZFRSODC(1:IL) = MAX(ZSWFC(1:IL,KLEV+1), ZFRSODC(1:IL))

! radintg.F90:1894-1897
IF (LAPPROXLWUPDATE) THEN
  ZLWDERIVATIVE(1:IL,1:KLEV+1)&
       & = PLWDER_IN(1:IL,1:KLEV+1)
ENDIF

! radintg.F90:1902-1988 (model-grid albedo PALBD/PALBP = the albedo radiation saw)
IF (LAPPROXSWUPDATE) THEN
  ZSWDIRECTBAND(1:IL,1:NSW)&
       & = PSWDIRECTBAND_IN(1:IL,1:NSW)
  ZSWDIFFUSEBAND(1:IL,1:NSW)&
       & = PSWDIFFUSEBAND_IN(1:IL,1:NSW)
  DO JL = 1,IL
    IF (ZFRSOD(JL) > 0.0_JPRB .AND. ZFRSO(JL,KLEV+1) > 0.0_JPRB &
         &  .AND. ZFRSOD(JL) > ZFRSO(JL,KLEV+1)) THEN
      ZBROADBANDALBEDO = ( SUM(ZSWDIRECTBAND(JL,1:NSW) *PALBP(IBEG+JL-1,1:NSW))&
           &             + SUM(ZSWDIFFUSEBAND(JL,1:NSW)*PALBD(IBEG+JL-1,1:NSW)) )&
           &           / SIGN(MAX(ABS(ZFRSOD(JL)),ZEPSILON),ZFRSOD(JL))
      ZBROADBANDALBEDO = MAX(0.0_JPRB, MIN(ZBROADBANDALBEDO, 0.9999_JPRB))
      ZSWDNTOP  = ZRII0 * ZAMU0(IBEG+JL-1)
      ZSWUPTOP  = ZSWDNTOP - ZFRSO(JL,1)
      ZSWDNSURF = ZFRSOD(JL)
      ZSWUPSURF = ZSWDNSURF - ZFRSO(JL,KLEV+1)
      ZSWTOPSCALING = (ZSWUPTOP + ZSWDNSURF - ZSWUPSURF) / ZSWDNTOP
      IF (ZSWTOPSCALING < ZSWTOPSCALINGDEFAULT) THEN
        ZSWTOPSCALING = ZSWTOPSCALINGDEFAULT
      ENDIF
      ZSWDNTOPEFF = ZSWDNTOP * ZSWTOPSCALING
      ZSWDNTOPEFF = ZSWDNTOP
      ZSWTRANSMITTANCE&
           & = (ZSWDNTOPEFF*ZSWDNSURF   - ZSWUPSURF*ZSWUPTOP)&
           & / (ZSWDNTOPEFF*ZSWDNTOPEFF - ZSWUPSURF*ZSWUPSURF)
      ZSWREFLECTANCE&
           & = (ZSWDNTOPEFF*ZSWUPTOP    - ZSWUPSURF*ZSWDNSURF)&
           & / (ZSWDNTOPEFF*ZSWDNTOPEFF - ZSWUPSURF*ZSWUPSURF)
      ZNEWSWNETSURF = ZSWDNTOPEFF * ZSWTRANSMITTANCE&
           &        * (1.0_JPRB - ZBROADBANDALBEDO)&
           &        / (1.0_JPRB - ZBROADBANDALBEDO*ZSWREFLECTANCE)
      ZSWNETCHANGE(JL) = ZNEWSWNETSURF - ZFRSO(JL, KLEV+1)
      ZFRSOD(JL) = ZNEWSWNETSURF / (1.0_JPRB - ZBROADBANDALBEDO)
    ELSE
      ZSWNETCHANGE(JL) = 0.0_JPRB
    ENDIF
  ENDDO
  DO JK=1,KLEV+1
    DO JL=1,IL
       ZFRSO(JL,JK) = ZFRSO(JL,JK) + ZSWNETCHANGE(JL)
    ENDDO
  ENDDO
ENDIF

! radintg.F90:2000-2017
DO JK=1,KLEV+1
  ZTRSO (1:IL,JK)=ZFRSO(1:IL,JK)/(ZRII0*ZAMU0(IBEG:IEND))
  ZEMTD (1:IL,JK)=ZFRTH(1:IL,JK)
  ZEMTU (1:IL,JK)=ZFRTH(1:IL,JK)
  ZTRSC (1:IL,JK)=ZSWFC(1:IL,JK)/(ZRII0*ZAMU0(IBEG:IEND))
  ZEMTC (1:IL,JK)=ZLWFC(1:IL,JK)
ENDDO
ZTRSOD(1:IL)=ZFRSOD(1:IL)/(ZRII0*ZAMU0(IBEG:IEND))
ZTRSODC(1:IL)=ZFRSODC(1:IL)/(ZRII0*ZAMU0(IBEG:IEND))
ZEMTDC(1:IL)=ZFRTEDC(1:IL)
ZEMIT (1:IL)=ZEMIT (1:IL)
ZUVDF (1:IL)=ZUVDF (1:IL)/(ZRII0*ZAMU0(IBEG:IEND))
ZPARF (1:IL)=ZPARF (1:IL)/(ZRII0*ZAMU0(IBEG:IEND))
ZPARCF(1:IL)=ZPARCF(1:IL)/(ZRII0*ZAMU0(IBEG:IEND))
ZTINCF(1:IL)=ZTINCF(1:IL)/(ZRII0*ZAMU0(IBEG:IEND))
ZFDIR (1:IL)=ZFDIR (1:IL)/(ZRII0*ZAMU0(IBEG:IEND))
ZCDIR (1:IL)=ZCDIR (1:IL)/(ZRII0*ZAMU0(IBEG:IEND))

! radintg.F90:2028-2058
DO JK=1,KLEV+1
  PTRSO(IBEG:IEND,JK)=ZTRSO(1:IL,JK)
  PTRSO(IBEG:IEND,JK)=MAX( 0.0_JPRB,MIN(1.0_JPRB,PTRSO(IBEG:IEND,JK)))
  PEMTD(IBEG:IEND,JK)=ZEMTD(1:IL,JK)
  PEMTU(IBEG:IEND,JK)=ZEMTU(1:IL,JK)
  PTRSC(IBEG:IEND,JK)=ZTRSC(1:IL,JK)
  PTRSC(IBEG:IEND,JK)=MAX( 0.0_JPRB,MIN(1.0_JPRB,PTRSC(IBEG:IEND,JK)))
  PEMTC(IBEG:IEND,JK)=ZEMTC(1:IL,JK)
  IF (LAPPROXLWUPDATE) THEN
    PLWDERIVATIVE(IBEG:IEND,JK) = MAX(0.0_JPRB,MIN(1.0_JPRB,ZLWDERIVATIVE(1:IL,JK)))
  ENDIF
ENDDO
PFRTED(IBEG:IEND,1:NLWOUT)=ZFRTED(1:IL,1:NLWOUT)
PTRSOD(IBEG:IEND)=MAX( 0.0_JPRB,MIN(1.0_JPRB,ZTRSOD(1:IL)))
PTRSODC(IBEG:IEND)=MAX( 0.0_JPRB,MIN(1.0_JPRB,ZTRSODC(1:IL)))
PEMTDC(IBEG:IEND)=ZEMTDC(1:IL)
PEMIT(IBEG:IEND) =MAX( 0.0_JPRB,MIN(1.0_JPRB,ZEMIT (1:IL)))
PSUDU(IBEG:IEND) =ZSUDU (1:IL)
PUVDF(IBEG:IEND) =MAX( 0.0_JPRB,MIN(1.0_JPRB,ZUVDF (1:IL)))
PPARF(IBEG:IEND) =MAX( 0.0_JPRB,MIN(1.0_JPRB,ZPARF (1:IL)))
PPARCF(IBEG:IEND)=MAX( 0.0_JPRB,MIN(1.0_JPRB,ZPARCF(1:IL)))
PTINCF(IBEG:IEND)=MAX( 0.0_JPRB,MIN(1.0_JPRB,ZTINCF(1:IL)))
PFDIR(IBEG:IEND) =MAX( 0.0_JPRB,MIN(1.0_JPRB,ZFDIR (1:IL)))
PCDIR(IBEG:IEND) =MAX( 0.0_JPRB,MIN(1.0_JPRB,ZCDIR (1:IL)))
END SUBROUTINE IFS49_RADINTG_POST
