"""Generate poison routines for 49r1 IFS settings types.

gfortran -finit-* does not reach derived types that carry any default
initialiser, so the harness poisons explicitly before setting the 49r1
defaults: every non-allocatable, non-pointer REAL component (scalar or
fixed-size array) of each listed type becomes NaN and every INTEGER one
-999999999, generated from the 49r1 type definition itself. A component the
driver then leaves unset shows as NaN / sentinel wherever it is read.
LOGICAL and CHARACTER components cannot be poisoned and are listed in a
comment of the generated file.

usage: python -I ifs49_poison.py <out.F90> <module.F90>:<MODULE>:<TYPE> ...
"""
import re
import sys


def comps(path, tname):
    lines = open(path).read().splitlines()
    i0 = next(k for k, l in enumerate(lines) if re.match(rf"^\s*TYPE\s*(,[^:]*)?(::)?\s*{tname}\s*$", l, re.I))
    out, cur = [], ""
    for l in lines[i0 + 1:]:
        if re.match(rf"^\s*END\s*TYPE", l, re.I) or re.match(r"^\s*CONTAINS\s*$", l, re.I):
            break
        if l.lstrip().startswith("#"):
            continue
        l = l.split("!", 1)[0].rstrip()
        if not l.strip():
            continue
        s = l.strip().lstrip("&").strip()
        cur = (cur + " " + s) if cur else s
        if cur.endswith("&"):
            cur = cur[:-1]
            continue
        out.append(cur)
        cur = ""
    return out


def main(dst, specs):
    body, notp = [], []
    for spec in specs:
        path, mod, tname = spec.split(":")
        sub = [f"SUBROUTINE IFS49_POISON_{tname}(Y)", f"USE {mod}, ONLY : {tname}",
               "USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY : IEEE_VALUE, IEEE_QUIET_NAN",
               "USE PARKIND1, ONLY : JPRB", "IMPLICIT NONE", f"TYPE({tname}), INTENT(INOUT) :: Y",
               "REAL(KIND=JPRB) :: ZNAN", "ZNAN = IEEE_VALUE(ZNAN, IEEE_QUIET_NAN)"]
        n = 0
        for s in comps(path, tname):
            if "::" not in s:
                continue
            typ, ents = s.split("::", 1)
            t = typ.strip().upper()
            if "ALLOCATABLE" in t or "POINTER" in t or "PROCEDURE" in t:
                continue
            kind = "R" if t.startswith("REAL") else "I" if t.startswith("INTEGER") else None
            parts, depth, buf = [], 0, ""
            for ch in ents:
                depth += ch in "(["
                depth -= ch in ")]"
                if ch == "," and depth == 0:
                    parts.append(buf); buf = ""
                else:
                    buf += ch
            parts.append(buf)
            for p in parts:
                p = p.split("=")[0].strip()
                if not p:
                    continue
                name = re.match(r"(\w+)", p).group(1)
                if kind is None:
                    notp.append(f"{tname}%{name}")
                    continue
                sub.append(f"Y%{name} = {'ZNAN' if kind == 'R' else '-999999999'}")
                n += 1
        if n == 0:
            sys.exit(f"no poisonable component in {tname}")
        sub.append(f"END SUBROUTINE IFS49_POISON_{tname}")
        body.append("\n".join(sub))
        print(f"{tname}: {n} components poisoned")
    with open(dst, "w") as f:
        f.write("! generated by ifs49_poison.py from the 49r1 type definitions; do not edit\n")
        f.write("! not poisonable (LOGICAL/CHARACTER/derived): " + " ".join(notp) + "\n")
        f.write("\n\n".join(body) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2:])
