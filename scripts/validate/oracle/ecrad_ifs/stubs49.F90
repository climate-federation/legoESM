! Serial stand-in for fiat MPL_MODULE (the 1.7.2 stand-in lacks MPL_RANK and
! non-real broadcasts that 49r1 easy_netcdf_read_mpi names). With one task
! every broadcast is guarded by NPROC>1 / MPL_NPROC()>1 and never runs.
MODULE MPL_MODULE
USE PARKIND1, ONLY : JPIM
IMPLICIT NONE
INTEGER(KIND=JPIM) :: MPL_RANK = 1
INTERFACE MPL_BROADCAST
  MODULE PROCEDURE MPL_BROADCAST_ANY
END INTERFACE MPL_BROADCAST
CONTAINS
SUBROUTINE MPL_BROADCAST_ANY(KBUF, KTAG, KROOT, CDSTRING, KREQUEST, KMP_TYPE)
  TYPE(*), DIMENSION(..)      :: KBUF
  INTEGER, INTENT(IN)          :: KTAG
  INTEGER, INTENT(IN), OPTIONAL :: KROOT
  CHARACTER(LEN=*), INTENT(IN), OPTIONAL :: CDSTRING
  INTEGER, INTENT(OUT), OPTIONAL :: KREQUEST
  INTEGER, INTENT(IN), OPTIONAL  :: KMP_TYPE
  CALL ABOR1('ecrad49 harness: MPL_BROADCAST called with one task')
END SUBROUTINE MPL_BROADCAST_ANY
INTEGER FUNCTION MPL_NPROC()
  MPL_NPROC = 1
END FUNCTION MPL_NPROC
INTEGER FUNCTION MPL_MYRANK()
  MPL_MYRANK = 1
END FUNCTION MPL_MYRANK
END MODULE MPL_MODULE

! easy_netcdf_read_mpi asks MPI whether it is initialised; this serial harness
! has no MPI, so the answer is "no" and every file is read by this one task.
SUBROUTINE MPI_INITIALIZED(LDFLAG, KERROR)
LOGICAL :: LDFLAG
INTEGER :: KERROR
LDFLAG = .FALSE.
KERROR = 0
END SUBROUTINE MPI_INITIALIZED
