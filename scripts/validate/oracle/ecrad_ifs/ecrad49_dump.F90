! Harness stage-dump writer for the 49r1 ecRad oracle (not oracle code).
! When ECRAD49_STAGE_DUMP names a directory, DUMP_R/DUMP_I write one array per
! file <dir>/<name>.txt: header "name kind rank lb1 ub1 ...", then the values in
! Fortran order (reals ES26.17E3). A second write of the same name aborts, so a
! multi-block run cannot silently overwrite a stage (run serial, one block).
MODULE ECRAD49_DUMP
USE PARKIND1, ONLY : JPRB, JPIM
IMPLICIT NONE
PRIVATE
PUBLIC :: DUMP_R, DUMP_I
LOGICAL :: LLINIT = .FALSE., LLON = .FALSE.
CHARACTER(LEN=1024) :: CLDIR
CONTAINS
SUBROUTINE OPENF(CDN, KU)
  CHARACTER(LEN=*), INTENT(IN) :: CDN
  INTEGER, INTENT(OUT) :: KU
  OPEN(NEWUNIT=KU, FILE=TRIM(CLDIR)//'/'//CDN//'.txt', STATUS='NEW', ACTION='WRITE')
END SUBROUTINE OPENF
LOGICAL FUNCTION ACTIVE()
  IF (.NOT. LLINIT) THEN
    CALL GET_ENVIRONMENT_VARIABLE('ECRAD49_STAGE_DUMP', CLDIR)
    LLON = LEN_TRIM(CLDIR) > 0
    LLINIT = .TRUE.
  ENDIF
  ACTIVE = LLON
END FUNCTION ACTIVE
SUBROUTINE DUMP_R(CDN, P)
  CHARACTER(LEN=*), INTENT(IN) :: CDN
  REAL(KIND=JPRB), INTENT(IN) :: P(..)
  INTEGER :: IU, J
  INTEGER :: IL(RANK(P)), IH(RANK(P))
  IF (.NOT. ACTIVE()) RETURN
  CALL OPENF(CDN, IU)
  IL = LBOUND(P); IH = UBOUND(P)
  WRITE(IU,'(A,1X,A,1X,I0,*(1X,I0))') CDN, 'r', RANK(P), (IL(J), IH(J), J=1,RANK(P))
  SELECT RANK (P)
  RANK (0); WRITE(IU,'(ES26.17E3)') P
  RANK (1); WRITE(IU,'(ES26.17E3)') P
  RANK (2); WRITE(IU,'(ES26.17E3)') P
  RANK (3); WRITE(IU,'(ES26.17E3)') P
  RANK DEFAULT; STOP 'DUMP_R: rank > 3'
  END SELECT
  CLOSE(IU)
END SUBROUTINE DUMP_R
SUBROUTINE DUMP_I(CDN, K)
  CHARACTER(LEN=*), INTENT(IN) :: CDN
  INTEGER(KIND=JPIM), INTENT(IN) :: K(..)
  INTEGER :: IU, J
  INTEGER :: IL(RANK(K)), IH(RANK(K))
  IF (.NOT. ACTIVE()) RETURN
  CALL OPENF(CDN, IU)
  IL = LBOUND(K); IH = UBOUND(K)
  WRITE(IU,'(A,1X,A,1X,I0,*(1X,I0))') CDN, 'i', RANK(K), (IL(J), IH(J), J=1,RANK(K))
  SELECT RANK (K)
  RANK (0); WRITE(IU,'(I0)') K
  RANK (1); WRITE(IU,'(I0)') K
  RANK (2); WRITE(IU,'(I0)') K
  RANK (3); WRITE(IU,'(I0)') K
  RANK DEFAULT; STOP 'DUMP_I: rank > 3'
  END SELECT
  CLOSE(IU)
END SUBROUTINE DUMP_I
END MODULE ECRAD49_DUMP
