NAMELIST /HARNESS/ NINDAT_H, NSTEP_H, TSTEP_H, NSTEPS, DMU0, DTS, CCN_LAND_MIN, CCN_LAND_MAX, &
     & CCN_SEA_MIN, CCN_SEA_MAX, LANDSEA, &
     & FULL_LEVEL, SURF_THL, CONTROL

! --- fixture fields
REAL(KIND=JPRB) :: ZLAT(KLON), ZLON(KLON), ZTS(KLON), ZMU0(KLON), ZALBD(KLON,6), ZALBP(KLON,6), &
     & ZEMISS(KLON,2), ZPH(KLON,KLEV+1), ZTH(KLON,KLEV+1), ZQ(KLON,KLEV), ZO3(KLON,KLEV), &
     & ZVMR(KLON,KLEV,8), ZCF(KLON,KLEV), ZQL(KLON,KLEV), ZQI(KLON,KLEV), ZSOLAR(1)
! --- RADIATION_SCHEME arguments
REAL(KIND=JPRB) :: ZAMU0(KLON), ZGELAM(KLON), ZGEMU(KLON), ZLSM(KLON), ZCCNL(KLON), ZCCNO(KLON), &
     & ZPF(KLON,KLEV), ZTF(KLON,KLEV), ZTHIN(KLON,KLEV+1), ZMMR(KLON,KLEV,8), ZNO2(KLON,KLEV), &
     & ZO3DP(KLON,KLEV), ZQR(KLON,KLEV), ZQS(KLON,KLEV)
REAL(KIND=JPRB), ALLOCATABLE :: ZAEROLD(:,:,:), ZAERO(:,:,:)
REAL(KIND=JPRB) :: ZFSW(KLON,KLEV+1), ZFLW(KLON,KLEV+1), ZFSWC(KLON,KLEV+1), ZFLWC(KLON,KLEV+1), &
     & ZFSWDN(KLON), ZFSWDNC(KLON), ZFLWDNC(KLON), ZFDIR(KLON), ZFDIRC(KLON), ZFDIRSUN(KLON), &
     & ZFUV(KLON), ZFPAR(KLON), ZFPARC(KLON), ZFTOA(KLON), ZEMISOUT(KLON), ZLWDER(KLON,KLEV+1)
REAL(KIND=JPRB), ALLOCATABLE :: ZFLWDN(:,:), ZSWDIFB(:,:), ZSWDIRB(:,:)
! --- direct calls of the sub-routines (same arguments as inside RADIATION_SCHEME)
REAL(KIND=JPRB) :: ZRELIQ(KLON,KLEV), ZREICE(KLON,KLEV), ZDECORR(KLON), ZDECORR_RATIO
! --- RADINTG glue outputs
REAL(KIND=JPRB) :: PEMTD(KLON,KLEV+1), PEMTU(KLON,KLEV+1), PTRSO(KLON,KLEV+1), PTRSC(KLON,KLEV+1), &
     & PEMTC(KLON,KLEV+1), PTRSOD(KLON), PTRSODC(KLON), PEMTDC(KLON), PEMIT(KLON), PSUDU(KLON), &
     & PUVDF(KLON), PPARF(KLON), PPARCF(KLON), PTINCF(KLON), PFDIRT(KLON), PCDIRT(KLON), PLWDERIV(KLON,KLEV+1)
REAL(KIND=JPRB), ALLOCATABLE :: PFRTED(:,:), ZSPEM(:,:)
! --- RADHEATN arguments
REAL(KIND=JPRB) :: ZMU0S(KLON), ZTSS(KLON), ZTE(KLON,KLEV), ZHRSW(KLON,KLEV), ZHRLW(KLON,KLEV), &
     & ZHRSC(KLON,KLEV), ZHRLC(KLON,KLEV), ZFRSO(KLON,KLEV+1), ZFRTH(KLON,KLEV+1), ZFRSOD(KLON), &
     & ZFRSODC(KLON), ZFRTHD(KLON), ZFRTHDC(KLON), ZFRSOC(KLON,2), ZFRTHC(KLON,2), ZINCSR(KLON), &
     & ZSDUR(KLON), ZDSRP(KLON), ZUVDFO(KLON), ZPARFO(KLON), ZPARCFO(KLON), ZTINCFO(KLON), &
     & ZFDIRO(KLON), ZCDIRO(KLON)
REAL(KIND=JPRB) :: ZCRAE
! --- aerosol arm (&HARNESS_AER NAERMACC=1): suecrad/radintg set-up objects
TYPE(TEAERD), SAVE :: YLEAERD
TYPE(TEAERSNK), SAVE :: YLEAERSNK
TYPE(GEOMETRY), SAVE :: YLGEOM
CHARACTER(LEN=1024) :: CAERCLIM_H = ' '
REAL(KIND=JPRB) :: ZMMR_SCALE = 1.0_JPRB

ZNAN = IEEE_VALUE(ZNAN, IEEE_QUIET_NAN)
! poison every REAL/INTEGER settings component before the 49r1 defaults are set
! (ifs49_poison.py; -finit-* does not reach types with default initialisers)
CALL IFS49_POISON_TERAD(YDMODEL%YRML_PHY_RAD%YRERAD)
CALL IFS49_POISON_TEAERATM(YDMODEL%YRML_PHY_RAD%YREAERATM)
CALL IFS49_POISON_TERDI(YDMODEL%YRML_PHY_RAD%YRERDI)
CALL IFS49_POISON_TECLDP(YDMODEL%YRML_PHY_EC%YRECLDP)
CALL IFS49_POISON_TECLD(YDMODEL%YRML_PHY_EC%YRECLD)
CALL IFS49_POISON_TEPHY(YDMODEL%YRML_PHY_EC%YREPHY)
CALL IFS49_POISON_TEPHLI(YDMODEL%YRML_PHY_SLIN%YREPHLI)
CALL IFS49_POISON_TPHY2(YDPHY2)
CALL IFS49_POISON_TPHY3(YDPHY3)
CALL IFS49_POISON_TEAERD(YLEAERD)
CALL IFS49_POISON_TEAERSNK(YLEAERSNK)
CALL GET_COMMAND_ARGUMENT(1, CMODE)

IF (TRIM(CMODE) == 'refconfig') THEN
  ! the ecRad-namelist configuration the bld49 oracle runs with, printed by
  ! the same routine after the same setup, for the RAD_CONFIG diff
  CALL GET_COMMAND_ARGUMENT(2, CNML)
  CALL REFCFG%READ(FILE_NAME=TRIM(CNML))
  CALL SETUP_RADIATION(REFCFG)
  WRITE(NULOUT,'(A)') '=== RAD_CONFIG BEGIN'
  CALL REFCFG%PRINT(IVERBOSE=5)
  WRITE(NULOUT,'(A)') '=== RAD_CONFIG END'
  WRITE(NULOUT,'(A)') '=== RAD_CONFIG_DUMP BEGIN'
  CALL IFS49_CONFIG_DUMP(REFCFG, NULOUT)
  WRITE(NULOUT,'(A)') '=== RAD_CONFIG_DUMP END'
  STOP
ENDIF
IF (TRIM(CMODE) /= 'run') STOP 'mode must be run or refconfig'
CALL GET_COMMAND_ARGUMENT(2, CIN); CALL GET_COMMAND_ARGUMENT(3, CNML)
OPEN(NULNAM, FILE=TRIM(CNML), STATUS='OLD', ACTION='READ')
CALL POSNAM(NULNAM, 'HARNESS'); READ(NULNAM, NML=HARNESS)
WRITE(NULOUT, NML=HARNESS)

! ===================== constants =====================================
CALL SUDYNCORE                           ! 49r1 sudyncore.F90 (LAPE, RPLDARE, RPLRADI...; empty &NAMDYNCORE)
CALL SETUP_CONSTANTS(NULOUT, 0)          ! yomcst.F90:408 (reads empty &NAMSCEN)
REPSCW = 1.E-12_JPRB                     ! suecrad.F90:996 (YOERDU, read by liquid_effective_radius)
REPLOG = 1.E-12_JPRB                     ! suecrad.F90:997
! suphec.F90:228-256 (YOETHF), verbatim
RVTMP2=0.0_JPRB
RHOH2O=1000.0_JPRB
R2ES=611.21_JPRB*RD/RV
R3LES=17.502_JPRB
R3IES=22.587_JPRB
R4LES=32.19_JPRB
R4IES=-0.7_JPRB
R5LES=R3LES*(RTT-R4LES)
R5IES=R3IES*(RTT-R4IES)
R5ALVCP=R5LES*RLVTT/RCPD
R5ALSCP=R5IES*RLSTT/RCPD
RALVDCP=RLVTT/RCPD
RALSDCP=RLSTT/RCPD
RALFDCP=RLMLT/RCPD
RTWAT=RTT
RTBER=RTT-5._JPRB
RTBERCU=RTT-5.0_JPRB
RTICE=RTT-23._JPRB
RTICECU=RTT-23._JPRB
RTWAT_RTICE_R=1.0_JPRB/(RTWAT-RTICE)
RTWAT_RTICECU_R=1.0_JPRB/(RTWAT-RTICECU)
RKOOP1=2.583_JPRB
RKOOP2=0.48116E-2_JPRB
ALLOCATE(YRTHF)                          ! model_mod_model_set.F90:235 points it at the model's
YRTHF = TTHF_INIT()                      ! suphec.F90:256
IF (TRIM(CONTROL) == 'nan_thf') YRTHF%R2ES = ZNAN   ! control: saturation (aerosol hydration only)

! ===================== model object ==================================
ASSOCIATE(YDERAD=>YDMODEL%YRML_PHY_RAD%YRERAD, YDERDI=>YDMODEL%YRML_PHY_RAD%YRERDI, &
     & YDEAERATM=>YDMODEL%YRML_PHY_RAD%YREAERATM, YDRAD=>YDMODEL%YRML_PHY_RAD%YRADIATION, &
     & YDEPHY=>YDMODEL%YRML_PHY_EC%YREPHY, YDECLDP=>YDMODEL%YRML_PHY_EC%YRECLDP, &
     & YDECLD=>YDMODEL%YRML_PHY_EC%YRECLD, YDGCONF=>YDMODEL%YRML_GCONF)
YRERAD => YDMODEL%YRML_PHY_RAD%YRERAD    ! model_mod_model_set.F90:150
! suecrad.F90 defaults (ECMWF: LEPHYS=T, LECMWF=T, LARPEGEF=F, LSRTM=T, LAPE=F; NAERAD empty)
YDERAD%LAPPROXLWUPDATE = .TRUE.          ! suecrad.F90:524
YDERAD%LAPPROXSWUPDATE = .TRUE.          ! :530
YDERAD%LMANNERSSWUPDATE = .TRUE.         ! :535
YDERAD%NSWWVCONTINUUM = 0                ! :562
YDERAD%NDUMPBADINPUTS = 0                ! :570
YDERAD%NDUMPINPUTS = 0                   ! :574
YDERAD%LUSEPRE2017RAD = .FALSE.          ! :627 (.NOT.LECMWF.OR.LARPEGEF)
YDERAD%NLWSCATTERING = 1                 ! :630
YDERAD%NSWGASOPTICS = 0                  ! :637
YDERAD%NLWGASOPTICS = 0                  ! :638
YDERAD%NLWSOLVER = 0                     ! :642
YDERAD%NSWSOLVER = 0                     ! :643
YDERAD%NCLOUDOVERLAP = 3                 ! :647
YDERAD%RCLOUD_SEPARATION_SCALE_TOA  = 14000.0_JPRB   ! :649
YDERAD%RCLOUD_SEPARATION_SCALE_SURF =  2500.0_JPRB   ! :650
YDERAD%NLIQOPT = 4                       ! :672 (LUSEPRE2017RAD=F)
YDERAD%NICEOPT = 3                       ! :674
YDERAD%NRADIP = 3                        ! :694
YDERAD%NRADLP = 2                        ! :695
YDERAD%RRE2DE = 0.64952_JPRB             ! :696
YDERAD%NMINICE = 1                       ! :708
YDERAD%RMINICE = 60._JPRB                ! :709
YDERAD%NDECOLAT = 2                      ! :710
YDERAD%RCADECOR = 0.75_JPRB              ! :713
YDERAD%RCBDECOR = 2.149_JPRB             ! :714
YDERAD%RCLOUD_FRAC_STD = 1.0_JPRB        ! :745
YDERAD%LFU_LW_ICE_OPTICS_BUG = .FALSE.   ! :754
YDERAD%NAERMACC = NAERMACC_ARM()         ! :778 default 1; harness arm, vote IV1
YDERAD%CAEROPTICSMODEL_DD = 'Woodward2001'   ! :795 (NACTAERO=0)
YDERAD%CAEROPTICSMODEL_OM = 'OPAC'           ! :796
YDERAD%CAEROPTICSMODEL_SU = 'GACP'           ! :797
YDERAD%CAEROPTICSMODEL_BC = 'OPAC'           ! :798
YDERAD%LCCNL = .TRUE.                    ! :839
YDERAD%LCCNO = .TRUE.                    ! :840
YDERAD%RCCNLND = 900._JPRB               ! :841
YDERAD%RCCNSEA = 50._JPRB                ! :842
YDERAD%NSW = 6                           ! :972 (LRAY=F)
YDERAD%NSOLARSPECTRUM = 0                ! :1023
YDERAD%LSPECTRALSOLARCYCLE = .FALSE.     ! :1028
! NEMISSSCHEME=0 branch, suecrad.F90:1302-1305
YDERAD%NLWEMISS = 2
YDERAD%NLWOUT   = 1
CALL YDERAD%YSPECTPLANCK%INIT(2, [ 8.0E-6_JPRB, 13.0E-6_JPRB ], [ 1,2,1 ])
YDEPHY%NALBEDOSCHEME = 2                 ! su0phy.F90:1457 (LECMWF.AND..NOT.LARPEGEF)
YDEPHY%NEMISSSCHEME = 0                  ! su0phy.F90:1464
YDEPHY%LRAD_CLOUD_INHOMOG = .FALSE.      ! su0phy.F90:1336
YDECLDP%NAERCLD = 0                      ! sucldp.F90:598
YDMODEL%YRML_PHY_SLIN%YREPHLI%LPHYLIN = .FALSE.  ! TRUE only for the OOPS linear model (model_mod_model_create.F90:283-287)
YDGCONF%YGFL%NACTAERO = 0                ! no prognostic aerosol (aerosols off, user scope)
YDGCONF%YRSPP_CONFIG%LSPP = .FALSE.      ! spp_mod.F90:61 default; stochastic physics off (A18)
YDEAERATM%LAERCCN = .FALSE.              ! su_aerw.F90:325 (no prognostic aerosol)
YDEAERATM%LAERRRTM = .FALSE.             ! su_aerw.F90:327
YDEAERATM%LAERRAD = .FALSE.              ! su_aerw.F90:309
YDEAERATM%LAERFILLCLIM = .FALSE.         ! su_aerw.F90:299
YDEAERATM%LAERVOL = .FALSE.              ! su_aerw.F90:342
CALL SURDI(YDERDI)                       ! 49r1 surdi.F90 (RRAE, RSUNDUR, ...)
YDGCONF%YRRIP%TSTEP = TSTEP_H            ! vote IV8
YDPHY2%TSPHY = TSTEP_H                   ! physics step = model step (one-time-level physics)
NINDAT = NINDAT_H                        ! vote IV8
NSTEP = NSTEP_H                          ! vote IV8

! ===================== RRTM tables (suecrad.F90:2095-2144, vote IV13) =========
CALL GET_ENVIRONMENT_VARIABLE("DATA", CDATA)  ! suecrad.F90:2112-2114
IF (CDATA == " ") STOP 'DATA must be set (ifsdata directory parent)'
CALL SURRTAB
CALL SURRTPK
CALL SURRTRF
CALL RRTM_INIT_140GP(TRIM(CDATA)//"/ifsdata")
CALL SRTM_INIT(TRIM(CDATA)//"/ifsdata", YDERAD%NSWWVCONTINUUM)

! ===================== SU_RADIATION_SCHEME ===============================
CALL SU_RADIATION_SCHEME(YDMODEL, YDERDI, YDEAERATM, YDEPHY, YDERAD, YDRAD, LDOUTPUT=.TRUE.)
WRITE(NULOUT,'(A)') '=== RAD_CONFIG BEGIN'
CALL YDRAD%RAD_CONFIG%PRINT(IVERBOSE=5)
WRITE(NULOUT,'(A)') '=== RAD_CONFIG END'
WRITE(NULOUT,'(A)') '=== RAD_CONFIG_DUMP BEGIN'
CALL IFS49_CONFIG_DUMP(YDRAD%RAD_CONFIG, NULOUT)
WRITE(NULOUT,'(A)') '=== RAD_CONFIG_DUMP END'
IF (TRIM(CONTROL) == 'refcfg') THEN
  ! cross-check: replace the SU configuration by the bld49 ecRad-namelist one
  ! (own RRTM setup, do_setup_ifsrrtm=T) and run everything else unchanged
  CALL GET_ENVIRONMENT_VARIABLE('IFS49_REFNAM', CNML)
  CALL REFCFG%READ(FILE_NAME=TRIM(CNML))
  CALL SETUP_RADIATION(REFCFG)
  YDRAD%RAD_CONFIG = REFCFG
ENDIF
CALL DUMP_I('su_nweight_uv', YDRAD%NWEIGHT_UV)
CALL DUMP_I('su_iband_uv', YDRAD%IBAND_UV(1:YDRAD%NWEIGHT_UV))
CALL DUMP_R('su_weight_uv', YDRAD%WEIGHT_UV(1:YDRAD%NWEIGHT_UV))
CALL DUMP_I('su_nweight_par', YDRAD%NWEIGHT_PAR)
CALL DUMP_I('su_iband_par', YDRAD%IBAND_PAR(1:YDRAD%NWEIGHT_PAR))
CALL DUMP_R('su_weight_par', YDRAD%WEIGHT_PAR(1:YDRAD%NWEIGHT_PAR))
CALL DUMP_R('su_trop_bg_aer_mass_ext', YDRAD%TROP_BG_AER_MASS_EXT)
CALL DUMP_R('su_strat_bg_aer_mass_ext', YDRAD%STRAT_BG_AER_MASS_EXT)
IF (YDERAD%NAERMACC == 1) CALL AER_DUMP_TABLES

! ===================== inputs ===========================================
CALL RD1('lat', ZLAT); CALL RD1('lon', ZLON); CALL RD1('skin_temperature', ZTS)
CALL RD1('cos_solar_zenith_angle', ZMU0); CALL RD1('solar_irradiance', ZSOLAR)
CALL RD2('sw_albedo', ZALBD); CALL RD2('sw_albedo_direct', ZALBP); CALL RD2('lw_emissivity', ZEMISS)
CALL RD2('pressure_hl', ZPH); CALL RD2('temperature_hl', ZTH); CALL RD2('q', ZQ); CALL RD2('o3_mmr', ZO3)
CALL RD2('co2_vmr', ZVMR(:,:,1)); CALL RD2('ch4_vmr', ZVMR(:,:,2)); CALL RD2('n2o_vmr', ZVMR(:,:,3))
CALL RD2('cfc11_vmr', ZVMR(:,:,4)); CALL RD2('cfc12_vmr', ZVMR(:,:,5)); CALL RD2('hcfc22_vmr', ZVMR(:,:,6))
CALL RD2('ccl4_vmr', ZVMR(:,:,7))
CALL RD2('cloud_fraction', ZCF); CALL RD2('q_liquid', ZQL); CALL RD2('q_ice', ZQI)
NSW = YDERAD%NSW; NLWOUT = YDERAD%NLWOUT; NLWEMISS = YDERAD%NLWEMISS
IF (NSW /= 6 .OR. NLWEMISS /= 2) STOP 'fixture albedo/emissivity bands do not match NSW/NLWEMISS'

! solar irradiance: PSOLAR_IRRADIANCE = ZRII0 = RII0*RADJUST (radintg.F90:513), RADJUST=1 (suswn.F90:1000)
YDPHY3%RII0 = ZSOLAR(1)
! curvature-corrected mu0 (radintg.F90:547-556; vote IV10)
ZCRAE=YDERDI%RRAE*(YDERDI%RRAE+2.0_JPRB)
DO JL=1,KLON
  IF (ZMU0(JL) > 1.E-10_JPRB) THEN
    ZAMU0(JL)=YDERDI%RRAE/(SQRT(ZMU0(JL)**2+ZCRAE)-ZMU0(JL))
  ELSE
    ZAMU0(JL)= YDERDI%RRAE/SQRT(ZCRAE)
  ENDIF
ENDDO
! geography (vote IV9): sine of latitude; longitude in [0,2pi)
ZGEMU = SIN(ZLAT*RPI/180.0_JPRB)
ZGELAM = MODULO(ZLON, 360.0_JPRB)*RPI/180.0_JPRB
! land-sea mask (vote IV6) and CCN (vote IV7)
DO JL=1,KLON
  SELECT CASE (TRIM(LANDSEA))
  CASE ('sea');  ZLSM(JL) = 0.0_JPRB
  CASE ('land'); ZLSM(JL) = 1.0_JPRB
  CASE ('alt');  ZLSM(JL) = REAL(MOD(JL,2), JPRB)    ! odd column index = land
  CASE DEFAULT;  STOP 'LANDSEA must be sea, land or alt'
  END SELECT
ENDDO
! column JL gets min + (max-min)*(JL-1)/(KLON-1), land and sea fields both set (vote IV7)
DO JL=1,KLON
  ZCCNL(JL) = CCN_LAND_MIN + (CCN_LAND_MAX-CCN_LAND_MIN)*REAL(JL-1,JPRB)/REAL(KLON-1,JPRB)
  ZCCNO(JL) = CCN_SEA_MIN  + (CCN_SEA_MAX -CCN_SEA_MIN )*REAL(JL-1,JPRB)/REAL(KLON-1,JPRB)
ENDDO
CALL DUMP_R('drv_in_ccn_land', ZCCNL); CALL DUMP_R('drv_in_ccn_sea', ZCCNO)
! full levels (vote IV2)
SELECT CASE (TRIM(FULL_LEVEL))
CASE ('mean')
  ZPF = 0.5_JPRB*(ZPH(:,1:KLEV)+ZPH(:,2:KLEV+1))
  ZTF = 0.5_JPRB*(ZTH(:,1:KLEV)+ZTH(:,2:KLEV+1))
CASE DEFAULT; STOP 'FULL_LEVEL must be mean'
END SELECT
! surface half-level temperature (vote IV3)
ZTHIN = ZTH
SELECT CASE (TRIM(SURF_THL))
CASE ('skin');    ZTHIN(:,KLEV+1) = ZTS
CASE ('fixture')
CASE DEFAULT; STOP 'SURF_THL must be skin or fixture'
END SELECT
! gases: VMR -> MMR with ecRad's own conversion (vote IV4), ozone as Pa*kg/kg
