SUBROUTINE RDHEAD(CDN, KU, KRANK, KSH)
  CHARACTER(LEN=*), INTENT(IN) :: CDN
  INTEGER, INTENT(OUT) :: KU, KRANK, KSH(2)
  CHARACTER(LEN=64) :: CLN
  KSH = 1
  OPEN(NEWUNIT=KU, FILE=TRIM(CIN)//'/'//CDN//'.txt', STATUS='OLD', ACTION='READ')
  READ(KU,*) CLN, KRANK
  BACKSPACE(KU)
  IF (KRANK == 0) THEN
    READ(KU,*) CLN, KRANK
  ELSE
    READ(KU,*) CLN, KRANK, KSH(1:KRANK)
  ENDIF
  IF (TRIM(CLN) /= CDN) STOP 'input header name mismatch'
END SUBROUTINE RDHEAD

SUBROUTINE RD1(CDN, P)
  CHARACTER(LEN=*), INTENT(IN) :: CDN
  REAL(KIND=JPRB), INTENT(OUT) :: P(:)
  INTEGER :: IU, IR, ISH(2)
  CALL RDHEAD(CDN, IU, IR, ISH)
  IF (IR > 1 .OR. (IR == 1 .AND. ISH(1) /= SIZE(P)) .OR. (IR == 0 .AND. SIZE(P) /= 1)) STOP 'RD1 shape'
  READ(IU,*) P
  CLOSE(IU)
END SUBROUTINE RD1

SUBROUTINE RD2(CDN, P)
  CHARACTER(LEN=*), INTENT(IN) :: CDN
  REAL(KIND=JPRB), INTENT(OUT) :: P(:,:)
  INTEGER :: IU, IR, ISH(2)
  CALL RDHEAD(CDN, IU, IR, ISH)
  IF (IR /= 2 .OR. ISH(1) /= SIZE(P,1) .OR. ISH(2) /= SIZE(P,2)) STOP 'RD2 shape'
  READ(IU,*) P
  CLOSE(IU)
END SUBROUTINE RD2

