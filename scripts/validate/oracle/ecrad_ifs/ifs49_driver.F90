! whose file names the vote that set it. Every REAL/INTEGER component of the
! settings types is poisoned (NaN / -999999999, ifs49_poison.py) before the
! defaults are set, so a member nobody sets shows in the outputs.
!
! usage: ifs49_driver.x run <input dir> <harness namelist>
!        ifs49_driver.x refconfig <ecRad namelist with directory_name set>
!   outputs: DUMP_R/DUMP_I text files in $ECRAD49_STAGE_DUMP; RAD_CONFIG
!   print between "=== RAD_CONFIG BEGIN/END" lines on stdout.
