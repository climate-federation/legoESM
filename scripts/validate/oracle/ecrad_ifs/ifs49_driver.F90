  !     only the Tegen hydration (LESO4HIS) and NVOLCVERT=2 branches: poisoned, proven unused
  ZCLON = COS(ZGELAM); ZSLON = SIN(ZGELAM)  ! GECLO/GESLO (radintg.F90:850-851)
  ZQS_X = ZNAN; ZECPO3_X = ZNAN
  ALLOCATE(ZQAERO3(KLON,KLEV,MAX(1,YAER_RAD_DESC%NCLIMATOLOGICAL)))
  CALL RADACT(YLEAERD, YDERAD, YLEAERSNK, YDRIP, YDMODEL%YRML_GCONF%YRSPP_CONFIG, 1, KLON, KLON, KLEV, &
       & 1, KLON, KLON, 0, 1, ZPH, ZGELAM, ZGEMU, ZCLON, ZSLON, ZTHIN, ZQ, ZQS_X, ZECPO3_X, &
       & ZQAER, ZQAERO3, ZQOZ)
  CALL DUMP_R('aer_radact_paer', ZQAER); CALL DUMP_R('aer_radact_paero', ZQAERO3)
  ! --- radintg.F90:1355-1430 glue (NACTAERO=0, NAERMACC=1, LRAYFM=.FALSE. su0phy.F90:1033, NPERTAER=0)
  ZAEROLD(:,1:6,:) = ZQAER(:,1:6,:)
  DO JLEV=1,KLEV
    ZAEROLD(:,5,JLEV) = YLEAERD%RCAEROS     ! NAER=1 (:1394-1398)
  ENDDO
  ICAE = 1
  DO JAERO=1,YAER_RAD_DESC%NAEROSOL
    IF (YAER_RAD_DESC%DATA(JAERO)%NSOURCE == IPROGNOSTIC) THEN
      STOP 'aerosol arm: prognostic aerosol present (NACTAERO=0 expected)'
    ELSEIF (YAER_RAD_DESC%DATA(JAERO)%NSOURCE == ICLIMATOLOGICAL) THEN
      ZAERO(:,:,JAERO) = ZQAERO3(:,:,ICAE)
      ICAE = ICAE+1
    ELSE
      ZAERO(:,:,JAERO) = 0.0_JPRB
    ENDIF
    IF (YAER_RAD_DESC%DATA(JAERO)%SCALING /= 1.0_JPRB) THEN
      ZAERO(:,:,JAERO) = ZAERO(:,:,JAERO) * YAER_RAD_DESC%DATA(JAERO)%SCALING
    ENDIF
  ENDDO
  ! control (vote B6): scale both aerosol inputs
  IF (ZMMR_SCALE /= 1.0_JPRB) THEN
    ZAERO = ZAERO*ZMMR_SCALE; ZAEROLD = ZAEROLD*ZMMR_SCALE
  ENDIF
  CALL DUMP_R('drv_in_aerosol_old', ZAEROLD); CALL DUMP_R('drv_in_aerosol', ZAERO)
  CALL DUMP_R('drv_in_mmr_scale', ZMMR_SCALE)
  IF (.NOT. ALL(IEEE_IS_FINITE(ZAEROLD(:,1,:))) .OR. .NOT. ALL(IEEE_IS_FINITE(ZAEROLD(:,6,:))) &
       & .OR. .NOT. ALL(IEEE_IS_FINITE(ZAERO))) STOP 'aerosol arm: non-finite aerosol input (poisoned member reached it)'
  END ASSOCIATE
END SUBROUTINE AER_PROFILES

