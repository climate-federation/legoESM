"""Generate IFS49_CONFIG_DUMP: write every intrinsic-type component of the
49r1 ecRad config_type (radiation_config.F90) as "name = value ...".

config%print is an incomplete instrument for the RAD_CONFIG diff (it prints
only what its verbosity branches choose), so the diff uses this dump: every
logical / integer / real / character component of config_type, scalar or
array (allocatable arrays only when allocated, prefixed by their shape).
Derived-type components (gas/cloud/aerosol optics tables, pdf sampler) are
listed by name as SKIPPED. Refuses to run if no component is found.

usage: python -I ifs49_config_dump.py <radiation_config.F90> <out.F90>
"""
import re
import sys


def main(src, dst):
    lines = open(src).read().splitlines()
    i0 = next(k for k, l in enumerate(lines) if re.match(r"^\s*type\s+config_type\s*$", l, re.I))
    i1 = next(k for k in range(i0, len(lines)) if re.match(r"^\s*contains\s*$", lines[k], re.I))
    stmts, cur = [], ""
    for l in lines[i0 + 1:i1]:
        if l.lstrip().startswith("#"):
            continue
        l = l.split("!", 1)[0].rstrip()
        if not l.strip():
            continue
        s = l.strip().lstrip("&").strip()
        cur = (cur + " " + s) if cur else s
        if cur.endswith("&"):
            cur = cur[:-1]
            continue
        stmts.append(cur)
        cur = ""
    seen, body, skipped = set(), [], []
    for s in stmts:
        if "::" not in s:
            continue
        typ, ents = s.split("::", 1)
        t = typ.strip().lower()
        kind = ("l" if t.startswith("logical") else "i" if t.startswith("integer")
                else "r" if t.startswith("real") else "c" if t.startswith("character") else None)
        alloc = "allocatable" in t or "pointer" in t
        # split entity list at top-level commas, drop initialisers
        parts, depth, buf = [], 0, ""
        for ch in ents:
            depth += ch in "(["
            depth -= ch in ")]"
            if ch == "," and depth == 0:
                parts.append(buf); buf = ""
            else:
                buf += ch
        parts.append(buf)
        for p in parts:
            p = p.split("=")[0].strip()
            if not p:
                continue
            name = re.match(r"(\w+)", p).group(1)
            if name.lower() in seen:
                continue
            seen.add(name.lower())
            if kind is None:
                skipped.append(name)
                continue
            is_arr = "(" in p or "dimension" in t
            fmt = {"l": "L2", "i": "I12", "r": "ES26.17E3", "c": "1X,A"}[kind]
            val = f"TRIM(CFG%{name})" if (kind == "c" and not is_arr) else f"CFG%{name}"
            if kind == "c" and is_arr:
                val = f"(TRIM(CFG%{name}(J)), J=1,SIZE(CFG%{name}))"
            line = f"WRITE(KU,'(A,*({fmt}))') '{name} =', {val}"
            if alloc:
                test = "ASSOCIATED" if "pointer" in t else "ALLOCATED"
                body.append(f"IF ({test}(CFG%{name})) THEN\n  WRITE(KU,'(A,*(1X,I0))') '{name} shape', SHAPE(CFG%{name})\n  {line}\n"
                            f"ELSE\n  WRITE(KU,'(A)') '{name} = (unallocated)'\nENDIF")
            else:
                body.append(line)
    if not body:
        sys.exit("no config_type components found")
    with open(dst, "w") as f:
        f.write("! generated by ifs49_config_dump.py from radiation_config.F90 (49r1); do not edit\n")
        f.write("SUBROUTINE IFS49_CONFIG_DUMP(CFG, KU)\nUSE RADIATION_CONFIG, ONLY : CONFIG_TYPE\nIMPLICIT NONE\n")
        f.write("TYPE(CONFIG_TYPE), INTENT(IN) :: CFG\nINTEGER, INTENT(IN) :: KU\nINTEGER :: J\n")
        f.write("\n".join(body) + "\n")
        for n in skipped:
            f.write(f"WRITE(KU,'(A)') '{n} = SKIPPED (derived type)'\n")
        f.write("END SUBROUTINE IFS49_CONFIG_DUMP\n")
    print(f"config_type components dumped: {len(body)}, derived-type skipped: {len(skipped)}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
