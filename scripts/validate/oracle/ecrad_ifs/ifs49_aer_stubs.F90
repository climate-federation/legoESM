! Minimal stand-ins for the OpenIFS 49r1 modules that GPHPRE and UPDECAEC USE
! (aerosol arm of the IFS-interface harness, NAERMACC=1) whose real 49r1
! versions drag in the dynamics set-up. Each type carries ONLY the members
! those two routines reference; every value is set by ifs49_driver.F90 (cited
! there) or is the cited 49r1 value below.

MODULE CODETOOLS
! SETDEFAULTL: the optional-or-default logical used by GPHPRE (gphpre.F90:LHSET..)
IMPLICIT NONE
CONTAINS
LOGICAL FUNCTION SETDEFAULTL(LDDEF, LDOPT)
  LOGICAL, INTENT(IN) :: LDDEF
  LOGICAL, OPTIONAL, INTENT(IN) :: LDOPT
  IF (PRESENT(LDOPT)) THEN
    SETDEFAULTL = LDOPT
  ELSE
    SETDEFAULTL = LDDEF
  ENDIF
END FUNCTION SETDEFAULTL
END MODULE CODETOOLS

MODULE INTDYN_MOD
! YYTXYB with the pointer indices SUPTR_TXYB(.TRUE.) sets (intdyn_mod.F90:373-380);
! GPHPRE reads them only when PXYB / the xyb outputs are requested (not here)
USE PARKIND1, ONLY : JPIM
IMPLICIT NONE
TYPE TXYB
  INTEGER(KIND=JPIM) :: M_DELP=1, M_RDELP=2, M_LNPR=3, M_ALPH=4, M_RTGR=5, M_RPRE=6, M_RPP=7, NDIM=7
END TYPE TXYB
TYPE(TXYB) :: YYTXYB
END MODULE INTDYN_MOD

MODULE YOMCVER
! TCVER members GPHPRE reads (yomcver.F90:46 et seq.); values set by the driver
USE PARKIND1, ONLY : JPIM, JPRB
IMPLICIT NONE
TYPE TCVER
  LOGICAL :: LVERTFE
  LOGICAL :: LAPRXPK
  INTEGER(KIND=JPIM) :: NDLNPR
  REAL(KIND=JPRB) :: RHYDR0
END TYPE TCVER
END MODULE YOMCVER

MODULE YOMVERT
! VP00, TOPPRES (yomvert.F90:46-47) and TVAB (yomvert.F90:49-60)
USE PARKIND1, ONLY : JPRB
IMPLICIT NONE
REAL(KIND=JPRB) :: VP00
REAL(KIND=JPRB) :: TOPPRES
TYPE TVAB
  REAL(KIND=JPRB), ALLOCATABLE :: VALH(:), VBH(:), VAH(:), VC(:), VAF(:), VBF(:), VDELA(:), VDELB(:), VRATH(:), VRATF(:)
END TYPE TVAB
END MODULE YOMVERT

MODULE GEOMETRY_MOD
! GEOMETRY members UPDECAEC reads (updecaec.F90:124: YRDIMV, YRVAB, YRCVER); TDIMV = the core build's YOMDIMV (ecRad 1.7.2 aux copy, NFLEVG)
USE YOMDIMV, ONLY : TDIMV
USE YOMVERT, ONLY : TVAB
USE YOMCVER, ONLY : TCVER
IMPLICIT NONE
TYPE GEOMETRY
  TYPE(TDIMV) :: YRDIMV
  TYPE(TVAB) :: YRVAB
  TYPE(TCVER) :: YRCVER
END TYPE GEOMETRY
END MODULE GEOMETRY_MOD
