! Minimal stand-ins for the CAM modules rrtmg_state.F90 USEs, so the CAM
! cam_cesm2_1_rel_60 file itself compiles UNMODIFIED.  Only the fields
! rrtmg_state_init / rrtmg_state_create read carry data; physconst takes
! stebol from cime shr_const_mod exactly as CAM's physconst.F90 (line 45).
! ppgrid (pcols, pver, pverp) is generated by build_cam_state.sh.
module cam_history
  use shr_kind_mod, only: r8 => shr_kind_r8
  implicit none
contains
  subroutine outfld(fname, field, idim, c)
    character(len=*), intent(in) :: fname
    real(r8), intent(in) :: field(:)
    integer, intent(in) :: idim, c
  end subroutine outfld
end module cam_history

module physconst
  use shr_kind_mod, only: r8 => shr_kind_r8
  use shr_const_mod, only: shr_const_stebol
  implicit none
  real(r8), public, parameter :: stebol = shr_const_stebol
end module physconst

module ref_pres
  use shr_kind_mod, only: r8 => shr_kind_r8
  use ppgrid, only: pverp
  implicit none
  real(r8) :: pref_edge(pverp)
end module ref_pres

module physics_types
  use shr_kind_mod, only: r8 => shr_kind_r8
  use ppgrid, only: pcols, pver, pverp
  implicit none
  type physics_state
    integer :: lchnk, ncol
    real(r8) :: t(pcols,pver), pmid(pcols,pver), lnpmid(pcols,pver)
    real(r8) :: pint(pcols,pverp), lnpint(pcols,pverp)
  end type physics_state
end module physics_types

module camsrfexch
  use shr_kind_mod, only: r8 => shr_kind_r8
  use ppgrid, only: pcols
  implicit none
  type cam_in_t
    real(r8) :: lwup(pcols)
  end type cam_in_t
end module camsrfexch

module physics_buffer
  implicit none
  type physics_buffer_desc
    integer :: unused
  end type physics_buffer_desc
end module physics_buffer

module rad_constituents
  use shr_kind_mod, only: r8 => shr_kind_r8
  use physics_types, only: physics_state
  use physics_buffer, only: physics_buffer_desc
  implicit none
contains
  subroutine rad_cnst_get_gas(icall, name, state, pbuf, mmr)
    integer, intent(in) :: icall
    character(len=*), intent(in) :: name
    type(physics_state), intent(in), target :: state
    type(physics_buffer_desc), pointer :: pbuf(:)
    real(r8), pointer :: mmr(:,:)
    nullify(mmr)
    stop 'rad_cnst_get_gas: not used by the tlev oracle'
  end subroutine rad_cnst_get_gas
end module rad_constituents
