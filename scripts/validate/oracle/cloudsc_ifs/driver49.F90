! Oracle driver: OpenIFS 49r1 CLOUDSC (arpifs/phys_ec/cloudsc.F90 at 8f6f722)
! on the CLOUDSC-dwarf input set (text export of input.h5, one file per dataset).
!
! Settings: YDECLDP from 49r1's own SUCLDP after su0phy's RCLDTOPP default
! (su0phy.F90:1343); empty NAMCLDP/NAMSCEN namelists, i.e. 49r1 code defaults.
! Constants: 49r1 SETUP_CONSTANTS runs (SUCLDP reads its module RG/RTT/RPI);
! the YRCST/YRTHF members CLOUDSC reads are then overwritten with the file's
! values (vote V7a) and every difference is printed.
! Inputs the file lacks get the votes' values (V2-V5, user picks 2-3):
!   NCLDTOP via a monotone STPRE crossing RCLDTOPP between levels 14 and 15;
!   PLUDE = PLUDELI = 0; PEIS = 0; KCTOP = KPBLTYPE = 0; PDYNR = PDYNS = 0;
!   PSNDE: 49r1 slot 1 (rain) = 0, slot 2 (snow) = file PSNDE (all zero);
!   PGEOM hydrostatic from the file's T, q, p with zero surface geopotential;
!   PGAW from the namelist (unused at defaults; control run changes it);
!   LDDIAG = .FALSE., PGP2DSPP = 0, SPP off.
! usage: driver49.x <input text dir> <output text dir> <harness namelist>
PROGRAM DRIVER49
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY : IEEE_VALUE, IEEE_QUIET_NAN
USE PARKIND1, ONLY : JPIM, JPRB
USE YOMLUN, ONLY : NULNAM
USE YOMCST, ONLY : YRCST, SETUP_CONSTANTS, RG_MOD => RG, RTT_MOD => RTT, RPI_MOD => RPI
USE YOETHF, ONLY : YRTHF, TTHF
USE YOECLDP, ONLY : TECLDP, NCLV
USE YOEPHLI, ONLY : TEPHLI
USE YOERAD, ONLY : TERAD
USE YOEPHY, ONLY : TEPHY
USE YOECUMF, ONLY : TECUMF
USE YOEVDF, ONLY : TVDF
USE SPP_MOD, ONLY : TSPP_CONFIG
USE YOMSTA, ONLY : TSTA
USE YOMDIMV, ONLY : TDIMV
USE YOMPHY2, ONLY : TPHY2
IMPLICIT NONE
CHARACTER(LEN=512) :: CIN, COUT, CNML
INTEGER(KIND=JPIM) :: KLON, KLEV, KFLDX, JK, JL
REAL(KIND=JPRB) :: ZNAN
REAL(KIND=JPRB) :: PTSPHY, RCLOUD_FRAC_STD, PGAW_VALUE, PGEOM_SCALE
NAMELIST /HARNESS/ RCLOUD_FRAC_STD, PGAW_VALUE, PGEOM_SCALE
TYPE(TECLDP), TARGET :: YDECLDP
TYPE(TEPHLI) :: YDEPHLI
TYPE(TERAD) :: YDERAD
TYPE(TEPHY) :: YDEPHY
TYPE(TECUMF) :: YDECUMF
TYPE(TVDF) :: YDVDF
TYPE(TSPP_CONFIG) :: YDSPP
TYPE(TSTA) :: YDSTA
TYPE(TDIMV) :: YDDIMV
TYPE(TPHY2) :: YDPHY2
REAL(KIND=JPRB), ALLOCATABLE, DIMENSION(:,:) :: PT, PQ, TCT, TCQ, TCA, TLT, TLQ, TLA, PVFA, PVFL, PVFI, &
  & PDYNA, PDYNL, PDYNI, PDYNR, PDYNS, PHRSW, PHRLW, PVERVEL, PAP, PAPH, PGEOM, PLU, PLUDE, &
  & PMFU, PMFD, PA, PLCRIT, PICRIT, PRE_ICE, PCCN, PNICE, PCOVPTOT, PFSD, PGP2DSPP, &
  & PFSQLF, PFSQIF, PFCQNNG, PFCQLNG, PFSQRF, PFSQSF, PFCQRNG, PFCQSNG, PFSQLTUR, PFSQITUR, &
  & PFPLSL, PFPLSN, PFHPSL, PFHPSN, ZPHI
REAL(KIND=JPRB), ALLOCATABLE :: TCC(:,:,:), TLC(:,:,:), PCLV(:,:,:), PLUDELI(:,:,:), PSNDE(:,:,:), PEXTRA(:,:,:)
REAL(KIND=JPRB), ALLOCATABLE :: PLSM(:), PGAW(:), PEIS(:), PRAINFRAC(:), F1(:)
LOGICAL, ALLOCATABLE :: LDCUM(:)
INTEGER(KIND=JPIM), ALLOCATABLE :: KCTOP(:), KTYPE(:), KPBLTYPE(:)
LOGICAL :: LDSLPHY

CALL GET_COMMAND_ARGUMENT(1, CIN); CALL GET_COMMAND_ARGUMENT(2, COUT); CALL GET_COMMAND_ARGUMENT(3, CNML)
OPEN(NULNAM, FILE=TRIM(CNML), STATUS='OLD', ACTION='READ')
CALL POSNAM(NULNAM, 'HARNESS'); READ(NULNAM, NML=HARNESS)

KLON = NINT(SCALAR('KLON')); KLEV = NINT(SCALAR('KLEV')); KFLDX = MAX(1, NINT(SCALAR('KFLDX')))
PTSPHY = SCALAR('PTSPHY')

! --- constants: 49r1 setup, then file values into the structures CLOUDSC reads
CALL SETUP_CONSTANTS(6, 0)
CALL CHK('RG', RG_MOD); CALL CHK('RTT', RTT_MOD)
WRITE(6, '(A,ES25.17)') 'CONST_MODULE RPI (no file value) ', RPI_MOD
CALL SETC('RG', YRCST%RG); CALL SETC('RD', YRCST%RD); CALL SETC('RCPD', YRCST%RCPD)
CALL SETC('RETV', YRCST%RETV); CALL SETC('RLVTT', YRCST%RLVTT); CALL SETC('RLSTT', YRCST%RLSTT)
CALL SETC('RLMLT', YRCST%RLMLT); CALL SETC('RTT', YRCST%RTT); CALL SETC('RV', YRCST%RV)
ALLOCATE(YRTHF)
CALL SETF('R2ES', YRTHF%R2ES); CALL SETF('R3LES', YRTHF%R3LES); CALL SETF('R3IES', YRTHF%R3IES)
CALL SETF('R4LES', YRTHF%R4LES); CALL SETF('R4IES', YRTHF%R4IES); CALL SETF('R5LES', YRTHF%R5LES)
CALL SETF('R5IES', YRTHF%R5IES); CALL SETF('R5ALVCP', YRTHF%R5ALVCP); CALL SETF('R5ALSCP', YRTHF%R5ALSCP)
CALL SETF('RALVDCP', YRTHF%RALVDCP); CALL SETF('RALSDCP', YRTHF%RALSDCP); CALL SETF('RALFDCP', YRTHF%RALFDCP)
CALL SETF('RTWAT', YRTHF%RTWAT); CALL SETF('RTICE', YRTHF%RTICE); CALL SETF('RTICECU', YRTHF%RTICECU)
CALL SETF('RTWAT_RTICE_R', YRTHF%RTWAT_RTICE_R); CALL SETF('RTWAT_RTICECU_R', YRTHF%RTWAT_RTICECU_R)
CALL SETF('RKOOP1', YRTHF%RKOOP1); CALL SETF('RKOOP2', YRTHF%RKOOP2)
WRITE(6, '(A,2ES25.17)') 'CONST RA/RPI used by CLOUDSC (49r1 setup, no file value) ', YRCST%RA, YRCST%RPI

! --- cloud-scheme settings: su0phy default, then 49r1 SUCLDP
YDECLDP%RCLDTOPP = 100.0_JPRB                    ! su0phy.F90:1343
YDDIMV%NFLEVG = KLEV
YDPHY2%TSPHY = PTSPHY
ALLOCATE(YDSTA%STPRE(KLEV))
DO JK = 1, KLEV                                  ! vote V2a: crosses RCLDTOPP between 14 and 15
  YDSTA%STPRE(JK) = YDECLDP%RCLDTOPP * REAL(JK, JPRB) / 14.5_JPRB
ENDDO
CALL SUCLDP(YDSTA, YDDIMV, YDPHY2, YDECLDP)
WRITE(6, '(A,I4,A,I4)') 'NCLDTOP 49r1=', YDECLDP%NCLDTOP, ' file=', NINT(SCALAR('YRECLDP_NCLDTOP'))
IF (YDECLDP%NCLDTOP /= NINT(SCALAR('YRECLDP_NCLDTOP'))) STOP 'NCLDTOP MISMATCH'
YDERAD%RCLOUD_FRAC_STD = RCLOUD_FRAC_STD
CALL DUMP_ECLDP(TRIM(COUT)//'/settings_49r1.txt')

! --- fields
CALL R2('PT', PT); CALL R2('PQ', PQ)
CALL R2('TENDENCY_TMP_T', TCT); CALL R2('TENDENCY_TMP_Q', TCQ); CALL R2('TENDENCY_TMP_A', TCA)
CALL R3('TENDENCY_TMP_CLD', TCC)
CALL R2('PVFA', PVFA); CALL R2('PVFL', PVFL); CALL R2('PVFI', PVFI)
CALL R2('PDYNA', PDYNA); CALL R2('PDYNL', PDYNL); CALL R2('PDYNI', PDYNI)
CALL R2('PHRSW', PHRSW); CALL R2('PHRLW', PHRLW); CALL R2('PVERVEL', PVERVEL)
CALL R2('PAP', PAP); CALL R2('PAPH', PAPH)
CALL R2('PLU', PLU); CALL R2('PLUDE', PLUDE); CALL R2('PMFU', PMFU); CALL R2('PMFD', PMFD)
CALL R2('PA', PA); CALL R3('PCLV', PCLV)
CALL R2('PLCRIT_AER', PLCRIT); CALL R2('PICRIT_AER', PICRIT); CALL R2('PRE_ICE', PRE_ICE)
CALL R2('PCCN', PCCN); CALL R2('PNICE', PNICE)
CALL R1('PLSM', PLSM); CALL R1('KTYPE', F1); KTYPE = NINT(F1, JPIM)
CALL R1('LDCUM', F1); LDCUM = F1 > 0
LDSLPHY = SCALAR('LDSLPHY') > 0
ALLOCATE(PDYNR(KLON,KLEV), PDYNS(KLON,KLEV), PGEOM(KLON,KLEV), ZPHI(KLON,KLEV+1))
PDYNR = 0; PDYNS = 0
ALLOCATE(PLUDELI(KLON,KLEV,4), PSNDE(KLON,KLEV,2), PGAW(KLON), PEIS(KLON), KCTOP(KLON), KPBLTYPE(KLON))
PLUDE = 0; PLUDELI = 0                            ! vote V3c
CALL R2('PSNDE', PCOVPTOT); PSNDE(:,:,1) = 0; PSNDE(:,:,2) = PCOVPTOT   ! dwarf PSNDE = snow; 49r1 slot 1 rain, 2 snow
PEIS = 0; KCTOP = 0; KPBLTYPE = 0                 ! vote V4b / user pick 2
PGAW = PGAW_VALUE                                 ! vote V5a
! hydrostatic geopotential, zero surface geopotential (pick 2; unused by 49r1 CLOUDSC)
ZPHI(:,KLEV+1) = 0
DO JK = KLEV, 1, -1
  ZPHI(:,JK) = ZPHI(:,JK+1) + YRCST%RD*PT(:,JK)*(1.0_JPRB+YRCST%RETV*PQ(:,JK))*LOG(PAPH(:,JK+1)/MAX(PAPH(:,JK),1.0_JPRB))
  PGEOM(:,JK) = PGEOM_SCALE * 0.5_JPRB*(ZPHI(:,JK)+ZPHI(:,JK+1))
ENDDO
ALLOCATE(PGP2DSPP(KLON,1)); PGP2DSPP = 0
ALLOCATE(TLT(KLON,KLEV), TLQ(KLON,KLEV), TLA(KLON,KLEV), TLC(KLON,KLEV,NCLV))
ALLOCATE(PFSD(KLON,KLEV), PRAINFRAC(KLON), PEXTRA(KLON,KLEV,KFLDX))
DEALLOCATE(PCOVPTOT); ALLOCATE(PCOVPTOT(KLON,KLEV))
ALLOCATE(PFSQLF(KLON,KLEV+1), PFSQIF(KLON,KLEV+1), PFCQNNG(KLON,KLEV+1), PFCQLNG(KLON,KLEV+1), &
  & PFSQRF(KLON,KLEV+1), PFSQSF(KLON,KLEV+1), PFCQRNG(KLON,KLEV+1), PFCQSNG(KLON,KLEV+1), &
  & PFSQLTUR(KLON,KLEV+1), PFSQITUR(KLON,KLEV+1), PFPLSL(KLON,KLEV+1), PFPLSN(KLON,KLEV+1), &
  & PFHPSL(KLON,KLEV+1), PFHPSN(KLON,KLEV+1))
PEXTRA = 0
! Regions CLOUDSC does not define (TLC(:,:,NCLV), PCOVPTOT above NCLDTOP, PFSD with
! LRAD_CLOUD_INHOMOG off) come out as NaN, so a scorer must mask them explicitly.
ZNAN = IEEE_VALUE(ZNAN, IEEE_QUIET_NAN)
TLT = ZNAN; TLQ = ZNAN; TLA = ZNAN; TLC = ZNAN; PCOVPTOT = ZNAN; PFSD = ZNAN; PRAINFRAC = ZNAN
PFSQLF = ZNAN; PFSQIF = ZNAN; PFCQNNG = ZNAN; PFCQLNG = ZNAN; PFSQRF = ZNAN; PFSQSF = ZNAN
PFCQRNG = ZNAN; PFCQSNG = ZNAN; PFSQLTUR = ZNAN; PFSQITUR = ZNAN; PFPLSL = ZNAN; PFPLSN = ZNAN
PFHPSL = ZNAN; PFHPSN = ZNAN

CALL CLOUDSC(YDECLDP, YDECUMF, YDEPHLI, YDERAD, YDEPHY, YDVDF, YDSPP, &
  & 1, KLON, KLON, KLEV, .FALSE., PTSPHY, PT, PQ, TCT, TCQ, TCA, TCC, TLT, TLQ, TLA, TLC, &
  & PVFA, PVFL, PVFI, PDYNA, PDYNL, PDYNI, PDYNR, PDYNS, PHRSW, PHRLW, PVERVEL, PAP, PAPH, PGEOM, &
  & PLSM, PGAW, LDCUM, KCTOP, KTYPE, KPBLTYPE, PEIS, PLU, PLUDE, PLUDELI, PSNDE, PMFU, PMFD, PGP2DSPP, &
  & LDSLPHY, PA, PCLV, PLCRIT, PICRIT, PRE_ICE, PCCN, PNICE, PCOVPTOT, PFSD, PRAINFRAC, &
  & PFSQLF, PFSQIF, PFCQNNG, PFCQLNG, PFSQRF, PFSQSF, PFCQRNG, PFCQSNG, PFSQLTUR, PFSQITUR, &
  & PFPLSL, PFPLSN, PFHPSL, PFHPSN, PEXTRA, KFLDX)

CALL W2('TENDENCY_LOC_T', TLT); CALL W2('TENDENCY_LOC_Q', TLQ); CALL W2('TENDENCY_LOC_A', TLA)
CALL W3('TENDENCY_LOC_CLD', TLC); CALL W2('PLUDE', PLUDE); CALL W2('PCOVPTOT', PCOVPTOT)
CALL W2('PFSD', PFSD); CALL W1('PRAINFRAC_TOPRFZ', PRAINFRAC); CALL W1('PEIS', PEIS)
CALL W2('PFSQLF', PFSQLF); CALL W2('PFSQIF', PFSQIF); CALL W2('PFCQNNG', PFCQNNG); CALL W2('PFCQLNG', PFCQLNG)
CALL W2('PFSQRF', PFSQRF); CALL W2('PFSQSF', PFSQSF); CALL W2('PFCQRNG', PFCQRNG); CALL W2('PFCQSNG', PFCQSNG)
CALL W2('PFSQLTUR', PFSQLTUR); CALL W2('PFSQITUR', PFSQITUR); CALL W2('PFPLSL', PFPLSL); CALL W2('PFPLSN', PFPLSN)
CALL W2('PFHPSL', PFHPSL); CALL W2('PFHPSN', PFHPSN)
WRITE(6, *) 'DRIVER49_DONE'

CONTAINS

  SUBROUTINE RALL(NAME, EXT, FLAT)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    INTEGER, INTENT(OUT) :: EXT(3)
    REAL(KIND=JPRB), ALLOCATABLE, INTENT(OUT) :: FLAT(:)
    INTEGER :: U, RNK, I, IOS
    OPEN(NEWUNIT=U, FILE=TRIM(CIN)//'/'//NAME//'.txt', STATUS='OLD', ACTION='READ', IOSTAT=IOS)
    IF (IOS /= 0) THEN
      WRITE(0, *) 'missing input ', NAME; STOP 4
    ENDIF
    EXT = 1
    READ(U, *) RNK; BACKSPACE(U); READ(U, *) RNK, (EXT(I), I = 1, RNK)
    ALLOCATE(FLAT(PRODUCT(EXT))); READ(U, *) FLAT; CLOSE(U)
  END SUBROUTINE RALL

  REAL(KIND=JPRB) FUNCTION SCALAR(NAME)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    INTEGER :: E(3); REAL(KIND=JPRB), ALLOCATABLE :: F(:)
    CALL RALL(NAME, E, F); SCALAR = F(1)
  END FUNCTION SCALAR

  SUBROUTINE R1(NAME, A)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), ALLOCATABLE, INTENT(OUT) :: A(:)
    INTEGER :: E(3); REAL(KIND=JPRB), ALLOCATABLE :: F(:)
    CALL RALL(NAME, E, F); IF (E(1) /= KLON) STOP 'R1 SHAPE'; A = F
  END SUBROUTINE R1

  SUBROUTINE R2(NAME, A)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), ALLOCATABLE, INTENT(OUT) :: A(:,:)
    INTEGER :: E(3); REAL(KIND=JPRB), ALLOCATABLE :: F(:)
    CALL RALL(NAME, E, F); IF (E(1) /= KLON) STOP 'R2 SHAPE'; A = RESHAPE(F, E(1:2))
  END SUBROUTINE R2

  SUBROUTINE R3(NAME, A)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), ALLOCATABLE, INTENT(OUT) :: A(:,:,:)
    INTEGER :: E(3); REAL(KIND=JPRB), ALLOCATABLE :: F(:)
    CALL RALL(NAME, E, F); IF (E(1) /= KLON .OR. E(3) /= NCLV) STOP 'R3 SHAPE'; A = RESHAPE(F, E)
  END SUBROUTINE R3

  SUBROUTINE SETC(NAME, V)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), INTENT(INOUT) :: V
    REAL(KIND=JPRB) :: FV
    FV = SCALAR(NAME)
    IF (FV /= V) WRITE(6, '(A,A,2ES25.17)') 'CONST_DIFF 49r1_setup->file ', NAME, V, FV
    V = FV
  END SUBROUTINE SETC

  SUBROUTINE SETF(NAME, V)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), INTENT(OUT) :: V
    V = SCALAR(NAME)
  END SUBROUTINE SETF

  SUBROUTINE CHK(NAME, V)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), INTENT(IN) :: V
    IF (SCALAR(NAME) /= V) WRITE(6, '(A,A,2ES25.17)') 'CONST_MODULE_DIFF (used by SUCLDP) ', NAME, V, SCALAR(NAME)
  END SUBROUTINE CHK

  SUBROUTINE WOUT(NAME, F, E)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), INTENT(IN) :: F(:)
    INTEGER, INTENT(IN) :: E(:)
    INTEGER :: U, I
    OPEN(NEWUNIT=U, FILE=TRIM(COUT)//'/'//NAME//'.txt', STATUS='REPLACE', ACTION='WRITE')
    WRITE(U, *) SIZE(E), E
    DO I = 1, SIZE(F)
      WRITE(U, '(ES26.17E3)') F(I)
    ENDDO
    CLOSE(U)
  END SUBROUTINE WOUT

  SUBROUTINE W1(NAME, A)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), INTENT(IN) :: A(:)
    CALL WOUT(NAME, A, SHAPE(A))
  END SUBROUTINE W1

  SUBROUTINE W2(NAME, A)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), INTENT(IN) :: A(:,:)
    CALL WOUT(NAME, RESHAPE(A, [SIZE(A)]), SHAPE(A))
  END SUBROUTINE W2

  SUBROUTINE W3(NAME, A)
    CHARACTER(LEN=*), INTENT(IN) :: NAME
    REAL(KIND=JPRB), INTENT(IN) :: A(:,:,:)
    CALL WOUT(NAME, RESHAPE(A, [SIZE(A)]), SHAPE(A))
  END SUBROUTINE W3

  SUBROUTINE DUMP_ECLDP(PATH)
    CHARACTER(LEN=*), INTENT(IN) :: PATH
    INTEGER :: U
    OPEN(NEWUNIT=U, FILE=PATH, STATUS='REPLACE', ACTION='WRITE')
    CALL YDECLDP%PRINT(0, U)
    CLOSE(U)
  END SUBROUTINE DUMP_ECLDP

END PROGRAM DRIVER49
