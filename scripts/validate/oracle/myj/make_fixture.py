"""Generate tests/atmosphere/oracle_fixtures/myj.npz by RUNNING the WRF v4.8.0
MYJ PBL oracle (phys/module_bl_myjpbl.F::MYJPBL, one column, LOWLYR=1, QCI
present; see myj_driver.F90).

usage:
  python make_fixture.py constants <dir>/module_model_constants.F90
  bash build.sh <WRF v4.8.0> <build> <dir>/module_model_constants.F90
  python make_fixture.py run --audit <ysu_pbl/inputs.npz> --build <build> \
      --wrf <WRF v4.8.0> --out tests/atmosphere/oracle_fixtures/myj.npz

Columns: the 20 L32 columns of the tier-2 YSU audit (also the MYNN oracle's
column set; dt = 1200 s), plus 5 variants that reach branches the 20 do not:
cloud water in the top of the boundary layer (``trop_ocean_deep_stcu``), cloud
ice and supercooled water aloft (``all_snow_land_ice``), snow cover on land
(``all_snow_land_snowcover``: the sublimation-heat factor) and a nonzero
counter-gradient increment (``desert_high_lcl_ct``: the inversion DTH+CT
path).  MYJSFC is not run: its outputs are constructed from the audit's
surface fluxes with neutral exchange, AKMS = AKHS = ust^2/wspd,
THZ0 = th1 + shflx/(rho1*cp*AKHS), QZ0 = q1 + qflx/(rho1*AKHS) (THZ0 = th1,
QZ0 = q1 where AKHS = 0), TSK = THZ0/(1e5/psfc)^(R_d/cp), ELFLX = lhflx,
CHKLOWQ = 1, UZ0 = VZ0 = 0, CT = 0.  Moisture is passed as WRF mixing ratios
(audit specific humidity q -> q/(1-q)).  Each column runs 3 steps (driver);
the fixture keeps inputs and outputs of steps 1 and 3.  Constants handed to
the oracle (its host module module_model_constants): physical ones from
legoesm.constants, MYJ scheme constants at WRF's values.
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np

from legoesm import constants as C

ORACLE = dict(repo="wrf-model/WRF", tag="v4.8.0",
              sha="06d4240ae989cc3e50af412bb472df3d9048783c",
              files=["phys/module_bl_myjpbl.F"])
NSTEP = 3
KEEP_STEPS = (1, 3)
# WRF share/module_model_constants.F scheme constants used by MYJPBL
WRF_SCHEME = dict(epsq2=0.2, pq0=379.90516, a2=17.2693882, a3=273.16, a4=35.86)
SFC_IN = ("dt", "xland", "ht", "ust", "akhs", "akms", "thz0", "qz0", "uz0", "vz0", "ct",
          "chklowq", "elflx", "tsk", "qsfc", "snow", "sice", "znt")
LEV_IN = ("dz", "u", "v", "th", "exner", "pmid", "qv", "qcw", "qci")


def write_constants(path):
    p608 = C.R_v / C.R_d - 1.0
    vals = dict(g=C.g, r_d=C.R_d, r_v=C.R_v, cp=C.c_pd, xlv=C.L_v, xls=C.L_s,  # latent-ok: WRF MYJ oracle constant
                ep_1=p608, p608=p608, **WRF_SCHEME)
    lines = ["! generated by make_fixture.py: physical constants from legoesm.constants,",
             "! MYJ scheme constants at WRF v4.8.0 share/module_model_constants.F values",
             "module module_model_constants", "  implicit none"]
    lines += [f"  real(8), parameter :: {k} = {float(v)!r}_8" for k, v in vals.items()]
    lines += ["end module module_model_constants", ""]
    Path(path).write_text("\n".join(lines))


def audit_columns(src):
    """The 20 audit columns + 5 variants, bottom-up, as driver inputs."""
    capa = C.R_d / C.c_pd
    cols = []
    for i, nm in enumerate(str(n) for n in src["names"]):
        T = src["T"][i][::-1].astype(float)
        q = src["q"][i][::-1].astype(float)
        p = src["p_full"][i][::-1].astype(float)
        pint = src["p_half"][i][::-1].astype(float)
        zi = src["zi"][i][::-1].astype(float)
        ex = (p / C.p_ref) ** capa
        th = T / ex
        rho1 = p[0] / (C.R_d * T[0] * (1.0 + (C.R_v / C.R_d - 1.0) * q[0]))
        ust = float(src["ust"][i])
        wspd = float(src["wspd"][i])
        ak = ust * ust / wspd
        psfc = pint[0]
        thz0 = th[0] + (float(src["shflx"][i]) / (rho1 * C.c_pd * ak) if ak > 0.0 else 0.0)
        qz0 = q[0] + (float(src["qflx"][i]) / (rho1 * ak) if ak > 0.0 else 0.0)
        cols.append(dict(
            name=nm, dt=float(src["dt"]), xland=float(src["xland"][i]), ht=zi[0], ust=ust,
            akhs=ak, akms=ak, thz0=thz0, qz0=qz0, uz0=0.0, vz0=0.0, ct=0.0, chklowq=1.0,
            elflx=float(src["lhflx"][i]), tsk=thz0 / (1.0e5 / psfc) ** capa, qsfc=qz0,
            snow=0.0, sice=0.0, znt=float(src["z0"][i]),
            dz=np.diff(zi), u=src["u"][i][::-1].astype(float),
            v=src["v"][i][::-1].astype(float), th=th, exner=ex, pmid=p,
            qv=q / (1.0 - q), qcw=np.zeros_like(T), qci=np.zeros_like(T), pint=pint))
    by = {c["name"]: c for c in cols}

    def copy(base, new):
        c = {k: (v.copy() if isinstance(v, np.ndarray) else v) for k, v in by[base].items()}
        c["name"] = new
        cols.append(c)
        return c

    zc = lambda c: np.cumsum(c["dz"]) - 0.5 * c["dz"]          # full-level heights AGL
    c = copy("trop_ocean_deep", "trop_ocean_deep_stcu")
    c["qcw"][(zc(c) > 600.0) & (zc(c) < 1100.0)] = 3.0e-4
    c = copy("all_snow_land", "all_snow_land_ice")
    c["qci"][(zc(c) > 3000.0) & (zc(c) < 6000.0)] = 5.0e-5
    c["qcw"][(zc(c) > 1500.0) & (zc(c) < 2500.0)] = 1.0e-4
    c = copy("all_snow_land", "all_snow_land_snowcover")
    c["snow"] = 0.05
    c = copy("desert_high_lcl", "desert_high_lcl_ct")
    c["ct"] = 0.5
    c = copy("trop_ocean_deep", "trop_ocean_deep_uz0")      # surface velocity (vote Z13)
    c["uz0"], c["vz0"] = 1.0, -0.5
    return cols


def write_input(path, cols):
    nlev = len(cols[0]["dz"])
    with open(path, "w") as f:
        f.write(f"{len(cols)} {nlev} {NSTEP}\n")
        for c in cols:
            assert len(c["dz"]) == nlev and len(c["pint"]) == nlev + 1
            f.write(" ".join(repr(float(c[k])) for k in SFC_IN) + "\n")
            for k in LEV_IN + ("pint",):
                f.write(" ".join(repr(float(x)) for x in c[k]) + "\n")


def parse(text):
    """{(col, step): {name: array}}"""
    out, cur = {}, None
    for line in text.splitlines():
        t = line.split()
        if not t or t[0] in ("dims", "END_OK"):
            continue
        if t[0] == "step":
            cur = out.setdefault((int(t[1]) - 1, int(t[2])), {})
        else:
            n = int(t[1])
            cur[t[0]] = np.array([float(x) for x in t[2:2 + n]])
    return out


def run(driver, cols, tmp):
    inp = Path(tmp) / "in.txt"
    write_input(inp, cols)
    r = subprocess.run([str(driver)], stdin=open(inp), capture_output=True, text=True)
    if r.returncode != 0 or "END_OK" not in r.stdout:
        sys.exit(f"oracle failed: {r.returncode}\n{r.stderr[-3000:]}")
    return parse(r.stdout)


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("constants")
    a.add_argument("path")
    b = sub.add_parser("run")
    b.add_argument("--audit", required=True)
    b.add_argument("--build", required=True)
    b.add_argument("--out", required=True)
    b.add_argument("--wrf", required=True, help="WRF checkout the oracle was built from")
    args = ap.parse_args()
    if args.cmd == "constants":
        write_constants(args.path)
        return
    cols = audit_columns(np.load(args.audit))
    driver = Path(args.build) / "myj_driver"
    rec = run(driver, cols, tempfile.mkdtemp(prefix="myj_oracle_"))
    again = run(driver, cols, tempfile.mkdtemp(prefix="myj_oracle_"))
    for key, r in rec.items():                       # bitwise rerun
        for k, v in r.items():
            assert np.array_equal(again[key][k], v), (key, k)
    src = Path(args.wrf) / ORACLE["files"][0]
    built = (Path(args.build) / "module_bl_myjpbl.F").read_bytes()
    assert built == src.read_bytes(), "build copy differs from the WRF source"
    meta = dict(ORACLE, audit_sha256=hashlib.sha256(Path(args.audit).read_bytes()).hexdigest(),
                source_sha256=hashlib.sha256(src.read_bytes()).hexdigest(),
                driver_sha256=hashlib.sha256(driver.read_bytes()).hexdigest())
    fix = {"names": np.array([c["name"] for c in cols]), "meta": np.array(repr(meta))}
    for s in KEEP_STEPS:
        for k in sorted(rec[(0, s)]):
            fix[f"s{s}_{k}"] = np.stack([np.atleast_1d(rec[(c, s)][k]) for c in range(len(cols))])
    np.savez_compressed(args.out, **fix)
    print("wrote", args.out, Path(args.out).stat().st_size, "bytes,", len(fix), "arrays")


if __name__ == "__main__":
    main()
