! Single-column driver for OpenIFS CUMASTRN (8f6f722), native IFS constants.
! usage: ifs_cumastrn.x <inputs.txt> <dump.txt>
! Setup mirrors the IFS call tree: SETUP_CONSTANTS (YOMCST), the YOETHF
! block of SUPHEC (included verbatim from the extracted source), SUCUMF,
! SUCLDP, the SUPHLI defaults that CUMASTRN reads, then PQSEN from SATUR
! exactly as CUCALLN does.  Port-matched switches (user decision): no
! downdraughts, no momentum transport, no dissipation heating, no
! mid-level convection.  Inputs not carried by the port are filled as
! decided (vertical velocity 0, grid-area weight from the port's dx,
! shallow allowed, aerosol / CA inputs 0, surface fluxes on the surface
! half level only in the IFS sign convention, positive downward).

MODULE DRV_SETUP
USE PARKIND1, ONLY : JPIM, JPRB
IMPLICIT NONE
CONTAINS
SUBROUTINE SET_THF
USE YOMCST, ONLY : RD, RV, RCPD, RLVTT, RLSTT, RLMLT, RTT
USE YOETHF
#include "suphec_thf_block.inc"
END SUBROUTINE SET_THF
SUBROUTINE SET_PHLI(YDEPHLI)
USE YOEPHLI, ONLY : TEPHLI
USE YOETHF, ONLY : RTWAT, RTICE
TYPE(TEPHLI), INTENT(INOUT) :: YDEPHLI
ASSOCIATE(LPHYLIN=>YDEPHLI%LPHYLIN, RLPTRC=>YDEPHLI%RLPTRC)
#include "suphli_block.inc"
END ASSOCIATE
END SUBROUTINE SET_PHLI
END MODULE DRV_SETUP

PROGRAM IFS_CUMASTRN_DRIVER
USE PARKIND1, ONLY : JPIM, JPRB
USE YOMLUN, ONLY : NULNAM, NULOUT
USE YOMDYNCORE, ONLY : RPLRG, RPLDARE, RPLRADI, RCORIOI, LAPE
USE YOMCST, ONLY : SETUP_CONSTANTS, YRCST, RA, RPI, RLVTT, RD, RV, RETV, RTT
USE YOETHF, ONLY : TTHF, TTHF_INIT
USE YOMSTA, ONLY : TSTA
USE YOMDIMV, ONLY : TDIMV
USE YOMPHY2, ONLY : TPHY2
USE MODEL_PHYSICS_ECMWF_MOD, ONLY : MODEL_PHYSICS_ECMWF_TYPE
USE MODEL_PHYSICS_SIMPLINEAR_MOD, ONLY : MODEL_PHYSICS_SIMPLINEAR_TYPE
USE YOM_YGFL, ONLY : TYPE_GFLD
USE YOMCHEM, ONLY : TCHEM
USE SPP_MOD, ONLY : TSPP_CONFIG
USE DRV_SETUP, ONLY : SET_THF, SET_PHLI
USE CU_ALL, ONLY : CUMASTRN, SATUR
USE TDBG
IMPLICIT NONE
INTEGER(KIND=JPIM), PARAMETER :: KLON = 1, KTRAC = 0
INTEGER(KIND=JPIM) :: KLEV, JK
CHARACTER(LEN=512) :: CIN, COUT
REAL(KIND=JPRB) :: ZDT, ZDXIN, ZSHF, ZLHF
REAL(KIND=JPRB), ALLOCATABLE, DIMENSION(:,:) :: PTEN, PQEN, PUEN, PVEN, PLITOT, PVERVEL, PQSEN, &
 & PQHFL, PAHFS, PAP, PAPH, PGEO, PGEOH, PTENT, PTENQ, PTENU, PTENV, PTENTA, PTENQA, PLCRIT_AER, &
 & PTU, PQU, PLU, PLUDE, PENTH, PMFLXR, PMFLXS, PLRAIN, PMFU, PMFD, PMFUDE_RATE, PMFDDE_RATE, PDISS
REAL(KIND=JPRB), ALLOCATABLE :: PLUDELI(:,:,:), PSNDE(:,:,:), PRSUD(:,:,:), PCEN(:,:,:), PTENC(:,:,:)
REAL(KIND=JPRB), ALLOCATABLE :: PGP2DSPP(:,:)
REAL(KIND=JPRB) :: PGAW(KLON), PCUCONVCA(KLON), PDX(KLON), PRAIN(KLON), PCAPE(KLON), PWMEAN(KLON), &
 & PVDISCU(KLON), PSCAV(1)
LOGICAL :: LDLAND(KLON), LDCUM(KLON), LDCUM_LIG(KLON), LDSC(KLON), LDSHCV(KLON)
INTEGER(KIND=JPIM) :: KTYPE(KLON), KCBOT(KLON), KCTOP(KLON), KCBOT_LIG(KLON), KCTOP_LIG(KLON), KBOTSC(KLON)
TYPE(TTHF) :: YDTHF
TYPE(TSTA) :: YDSTA
TYPE(TDIMV) :: YDDIMV
TYPE(TPHY2) :: YDPHY2
TYPE(MODEL_PHYSICS_ECMWF_TYPE) :: YDEC
TYPE(MODEL_PHYSICS_SIMPLINEAR_TYPE) :: YDSL
TYPE(TYPE_GFLD) :: YGFL
TYPE(TCHEM) :: YDCHEM
TYPE(TSPP_CONFIG) :: YDSPP

CALL GET_COMMAND_ARGUMENT(1, CIN)
CALL GET_COMMAND_ARGUMENT(2, COUT)
OPEN(10, FILE=TRIM(CIN), STATUS='OLD', ACTION='READ')
READ(10, *) KLEV
IF (KLEV > NDK) STOP 'KLEV > NDK'
READ(10, *) ZDT, ZDXIN, ZSHF, ZLHF
ALLOCATE(PTEN(KLON,KLEV), PQEN(KLON,KLEV), PUEN(KLON,KLEV), PVEN(KLON,KLEV), PLITOT(KLON,KLEV), &
 & PVERVEL(KLON,KLEV), PQSEN(KLON,KLEV), PQHFL(KLON,KLEV+1), PAHFS(KLON,KLEV+1), PAP(KLON,KLEV), &
 & PAPH(KLON,KLEV+1), PGEO(KLON,KLEV), PGEOH(KLON,KLEV+1), PTENT(KLON,KLEV), PTENQ(KLON,KLEV), &
 & PTENU(KLON,KLEV), PTENV(KLON,KLEV), PTENTA(KLON,KLEV), PTENQA(KLON,KLEV), PLCRIT_AER(KLON,KLEV), &
 & PTU(KLON,KLEV), PQU(KLON,KLEV), PLU(KLON,KLEV), PLUDE(KLON,KLEV), PENTH(KLON,KLEV), &
 & PMFLXR(KLON,KLEV+1), PMFLXS(KLON,KLEV+1), PLRAIN(KLON,KLEV), PMFU(KLON,KLEV), PMFD(KLON,KLEV), &
 & PMFUDE_RATE(KLON,KLEV), PMFDDE_RATE(KLON,KLEV), PDISS(KLON,KLEV))
ALLOCATE(PLUDELI(KLON,KLEV,4), PSNDE(KLON,KLEV,2), PRSUD(KLON,KLEV,2), PCEN(KLON,KLEV,1), PTENC(KLON,KLEV,1))
READ(10, *) PTEN(1,:)
READ(10, *) PQEN(1,:)
READ(10, *) PUEN(1,:)
READ(10, *) PVEN(1,:)
READ(10, *) PAP(1,:)
READ(10, *) PAPH(1,:)
READ(10, *) PGEO(1,:)
READ(10, *) PGEOH(1,:)
READ(10, *) PTENT(1,:)
READ(10, *) PTENQ(1,:)
READ(10, *) PTENTA(1,:)
READ(10, *) PTENQA(1,:)
CLOSE(10)

! Earth: no planet rescaling (SUDYNCORE values for the real planet)
RPLRG = 1.0_JPRB; RPLDARE = 1.0_JPRB; RPLRADI = 1.0_JPRB; RCORIOI = 1.0_JPRB; LAPE = .FALSE.
OPEN(NULNAM, FILE='harness_namelist.nml', STATUS='REPLACE')
WRITE(NULNAM, '(A)') '&NAMSCEN /', '&NAMCUMF /', '&NAMCLDP /'
REWIND(NULNAM)
CALL SETUP_CONSTANTS(NULOUT, 0)
CALL SET_THF
YDTHF = TTHF_INIT()
YDDIMV%NFLEVG = KLEV
ALLOCATE(YDSTA%STPRE(KLEV), YDSTA%STPREH(0:KLEV))
YDSTA%STPRE(:) = PAP(1,:)
YDSTA%STPREH(0:KLEV) = PAPH(1,:)
YDPHY2%TSPHY = ZDT
CALL SUCUMF(YDSTA, YDDIMV, YDEC%YRECUMF)
CALL SUCLDP(YDSTA, YDDIMV, YDPHY2, YDEC%YRECLDP)
CALL SET_PHLI(YDSL%YREPHLI)
! port-matched switches (user decision 1a)
YDEC%YRECUMF%LMFDD = .FALSE.
YDEC%YRECUMF%LMFDUDV = .FALSE.
YDEC%YRECUMF%LMFUVDIS = .FALSE.
YDEC%YRECUMF%LMFMID = .FALSE.
YDEC%YREPHY%LEPCLD = .TRUE.
YDEC%YREPHY%LMFTRAC = .FALSE.
YDEC%YREPHY%LMFSCAV = .FALSE.
YDEC%YREPHY%LELIGHT = .FALSE.
YDSL%YRPHNC%LENCLD2 = .FALSE.
YDSL%YRPHNC%LEPCLD2 = .FALSE.
YDSPP%SM%NRFTOTAL = 1
ALLOCATE(PGP2DSPP(KLON,1)); PGP2DSPP = 0.0_JPRB

PLITOT = 0.0_JPRB; PVERVEL = 0.0_JPRB
PQHFL = 0.0_JPRB; PAHFS = 0.0_JPRB
PAHFS(1,KLEV+1) = ZSHF
PQHFL(1,KLEV+1) = ZLHF / RLVTT
PDX(1) = ZDXIN
PGAW(1) = (ZDXIN / (2.0_JPRB * RA))**2 / RPI    ! so that 2*RA*SQRT(RPI*PGAW) = dx (cumastrn :728)
PCUCONVCA = 0.0_JPRB; PLCRIT_AER = 0.0_JPRB
LDLAND = .FALSE.; LDSHCV = .TRUE.
PTENU = 0.0_JPRB; PTENV = 0.0_JPRB; PCEN = 0.0_JPRB; PTENC = 0.0_JPRB; PSCAV = 0.0_JPRB
PQSEN(1,:) = PQEN(1,:)
CALL SATUR(YDTHF, YRCST, 1, 1, KLON, YDEC%YRECUMF%NJKT2, KLEV, YDSL%YREPHLI%LPHYLIN, PAP, PTEN, PQSEN, 1)

CALL CUMASTRN(RPLDARE, RPLRG, YDTHF, YRCST, YDSL, YDEC, YGFL, YDCHEM, YDSPP, &
 & 1, 1, KLON, KLEV, PDX, .FALSE., &
 & .FALSE., LDLAND, ZDT, &
 & PTEN, PQEN, PUEN, PVEN, PLITOT, &
 & PVERVEL, PQSEN, PQHFL, PAHFS, &
 & PAP, PAPH, PGEO, PGEOH, PGAW, &
 & PCUCONVCA, PGP2DSPP, &
 & PTENT, PTENQ, PTENU, PTENV, PTENTA, PTENQA, &
 & LDCUM, KTYPE, KCBOT, KCTOP, &
 & LDCUM_LIG, KCBOT_LIG, KCTOP_LIG, &
 & KBOTSC, LDSC, LDSHCV, PLCRIT_AER, &
 & PTU, PQU, PLU, PLUDE, PLUDELI, PSNDE, &
 & PENTH, PMFLXR, PMFLXS, PRAIN, PLRAIN, PRSUD, &
 & PMFU, PMFD, PMFUDE_RATE, PMFDDE_RATE, PCAPE, PWMEAN, PVDISCU, PDISS, &
 & KTRAC, PCEN(:,:,1:0), PTENC(:,:,1:0), PSCAV(1:0))

OPEN(11, FILE=TRIM(COUT), STATUS='REPLACE')
WRITE(11, '(A,I0)') 'KLEV ', KLEV
WRITE(11, '(A,5ES25.16E3)') 'CONST rlvtt rd rv retv rtt', RLVTT, RD, RV, RETV, RTT
WRITE(11, '(A,4I6,L3)') 'FG ktype_fg ktype_rc kcbot kctop ldcum_fg', DBG_KTYPE_FG(1), DBG_KTYPE_RC(1), &
 & DBG_KCBOT(1), DBG_KCTOP(1), DBG_LDCUM_FG(1)
WRITE(11, '(A,3ES25.16E3)') 'MB zmfub_fg zmfub1 zdhpbl', DBG_ZMFUB_FG(1), DBG_ZMFUB1(1), DBG_ZDHPBL(1)
WRITE(11, '(A,L3,3I6)') 'OUT ldcum ktype kcbot kctop', LDCUM(1), KTYPE(1), KCBOT(1), KCTOP(1)
WRITE(11, '(A)') 'LEV qsen mfu_asc mfus_asc mful_asc lude_asc dmfup_asc mfu dT_dt dq_dt'
DO JK = 1, KLEV
  WRITE(11, '(I5,9ES25.16E3)') JK, PQSEN(1,JK), DBG_MFU_ASC(1,JK), DBG_MFUS_ASC(1,JK), DBG_MFUL_ASC(1,JK), &
   & DBG_LUDE_ASC(1,JK), DBG_DMFUP_ASC(1,JK), PMFU(1,JK), PTENT(1,JK), PTENQ(1,JK)
ENDDO
CLOSE(11)
WRITE(*, '(A)') 'DRIVER_OK'
END PROGRAM IFS_CUMASTRN_DRIVER
